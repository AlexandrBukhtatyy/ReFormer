/**
 * Контракт компонента-рендерера массива: готовые элементы + мутации обычными колбэками.
 *
 * Объявлен в ui-kit НАМЕРЕННО, а не импортирован из `@reformer/renderer-react`: дизайн-система
 * не должна зависеть от рендерера (см. `ArrayItemSlot`/`ArrayComponentProps` там же — типы
 * структурно совместимы, TS сматчит их по форме без номинальной связи).
 *
 * Компонент, реализующий этот контракт, — «humble object»: он не подписывается на модель,
 * не вызывает хуков рендерера и не знает про сигналы. Отсюда два следствия: его можно
 * отрисовать любым рендерером (в т.ч. чужим) и протестировать на фейковых `items` без формы.
 *
 * @module ui-kit/lib/array-slot
 */
import type { Key, ReactNode } from 'react';

/** Один готовый к отрисовке элемент массива. */
export interface ArrayItemSlot {
  /** Стабильный React-ключ элемента. */
  key: Key;
  /** Живой индекс в массиве — для `onRemove(index)` / `onMove(index, …)`. */
  index: number;
  /** Данные элемента — для меток вида `itemLabel(model, index)`. */
  model?: unknown;
  /** Отрендеренное содержимое элемента. */
  children: ReactNode;
}

/** Общие props компонента-рендерера массива: элементы + мутации. */
export interface ArrayComponentProps {
  /** Отрендеренные элементы массива в порядке следования. */
  items?: ArrayItemSlot[];
  /** Добавить элемент (значение нового элемента резолвит вызывающая сторона). */
  onAdd?: () => void;
  /** Удалить элемент по индексу. */
  onRemove?: (index: number) => void;
  /** Переместить элемент (реордер). */
  onMove?: (from: number, to: number) => void;
}
