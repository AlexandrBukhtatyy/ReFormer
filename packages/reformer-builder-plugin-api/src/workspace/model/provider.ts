/**
 * Провайдер модели документа — единственное место, где кто-то знает, что внутри файла.
 *
 * Host держит машинерию документа: буфер, признак изменённости, историю, состояние вида,
 * переключение между двумя видами документа. Знания о формате в нём нет и быть не может:
 * разбор схемы формы — предметная логика, и в платформе она означала бы, что второй формат
 * (или второй продукт поверх той же платформы) придётся вносить правкой ядра.
 *
 * Поэтому провайдер — **вклад плагина**, а точка расширения объявлена здесь только затем,
 * чтобы у вклада было типизированное имя. Провайдер для схемы формы регистрирует
 * `plugins/editor-schema/`; появится другой формат — придёт со своим плагином.
 *
 * ## Регистрация на тип ресурса, а не на редактор
 *
 * {@link DocumentModelProvider.applies} отвечает про РЕСУРС. Если бы провайдер вносился
 * вместе с редактором, у одного файла оказалось бы две модели — своя у Monaco и своя
 * у структурного редактора, — и они разошлись бы на первой же правке. Одна модель
 * на документ означает, что оба редактора правят одно и то же.
 *
 * ## Чего здесь намеренно нет
 *
 * Нет `NodeId` из домена: {@link NodeId} — просто строка, и Host не проверяет ни форму,
 * ни уникальность. Выдача идентификаторов принадлежит провайдеру (`ensureNodeIds` живёт
 * в `lib/form-model`, куда платформе ходу нет), а ядру они нужны ровно как адреса выделения
 * и цели диагностик.
 *
 * Здесь ОБЪЯВЛЕНИЯ. Синхронная проба и выбор провайдера по ресурсу живут в оболочке билдера:
 * первое — деталь пути открытия документа, второе — решение, которое принимает она, а не плагин.
 *
 * @module @reformer/builder-plugin-api/workspace/model/provider
 */

import { defineExtensionPoint } from '../../primitives/extension-point.js';
import type { ResourceRef } from '../../primitives/resource.js';

/**
 * Адрес узла внутри модели.
 *
 * Для Host — непрозрачная строка. Домен выдаёт восемь символов base36 и кладёт их в `$nodeId`,
 * но проверять это здесь означало бы, что платформа знает формат: следующий провайдер
 * с другой схемой идентификаторов не смог бы существовать, ничего при этом не нарушив.
 */
export type NodeId = string;

/**
 * Проба содержимого — чтобы кандидаты читали ресурс ОДИН раз на всех.
 *
 * Форма совпадает с `EditorProbe` из вклада редактора (см. `plugin-and-shell.md`) намеренно:
 * один и тот же объект передаётся и в `canOpen` редактора, и в {@link DocumentModelProvider.applies},
 * а структурная совместимость держит их одним типом без общей зависимости.
 */
export interface EditorProbe {
  /** Текст ресурса; читается один раз и переиспользуется всеми кандидатами. */
  text(): Promise<string>;
}

/**
 * Описание правки модели.
 *
 * Сериализуемость обязательна: то же самое описание уходит в журнал операций (фундамент
 * под совместную работу и под разбор хода ассистента), а значит в `params` не должно быть
 * ни функций, ни ссылок на узлы модели — только данные.
 */
export interface EditOp {
  /** `'insert' | 'move' | 'set-prop' | …` — словарь принадлежит провайдеру, не ядру. */
  readonly type: string;
  readonly target?: NodeId;
  readonly params?: Record<string, unknown>;
}

/** Результат применения операции к модели. */
export interface ApplyResult<M> {
  readonly model: M;
  /** Операция, отменяющая эту. Ядру нужна не для Ctrl+Z (там снимки), а для журнала. */
  readonly inverse: EditOp;
  /** Куда переехало выделение: узел мог сместиться или родиться. */
  readonly focus?: NodeId;
}

/**
 * Разбор, печать и правка одного формата.
 *
 * `parse`, `print` и `apply` — синхронные и чистые. Это не стилистика: на синхронности
 * `apply` стоит гейт ассистента (ход проверяется до применения, а не после), а на чистоте —
 * отмена через снимки: если бы `apply` мутировала модель, снимок перестал бы быть снимком.
 *
 * `apply` ОБЯЗАНА сохранять неизменённые поддеревья по ссылке. Разбор каждый раз даёт новый
 * объект целиком, и именно поэтому документ с моделью не пересобирается из текста на каждое
 * действие: structural sharing — то, на чём держится и отмена, и сравнение, и перерисовка.
 */
export interface DocumentModelProvider<M> {
  /** Уникален среди провайдеров; попадает в диагностику разбора. */
  readonly id: string;
  /**
   * Берётся ли этот провайдер за такой ресурс.
   *
   * Решение по одному лишь расширению не годится: `.json` бывает и схемой формы, и конфигом
   * пакета. Провайдеру, которому нужно содержимое, проба на пути открытия отдаёт его
   * синхронно: оболочка кладёт туда уже прочитанный текст, и сузить тип можно `'peek' in probe`.
   */
  applies(ref: ResourceRef, probe: EditorProbe): boolean;
  /** @throws если текст не разбирается — это НЕ авария, а состояние расхождения. */
  parse(text: string): M;
  print(model: M): string;
  apply(model: M, op: EditOp): ApplyResult<M>;
  /**
   * Где в тексте лежит каждый узел модели: идентификатор узла → путь в дереве печати
   * (ключи объектов и индексы массивов).
   *
   * Нужен текстовому редактору, чтобы подчеркнуть находку на узле, у которого в тексте нет
   * своего идентификатора. Спрашивается у провайдера, а не выводится оболочкой: путь узла —
   * знание о формате. Необязателен: без него такие находки остаются без места в тексте.
   * Зовётся часто — на каждую публикацию находок, — поэтому ответ стоит запоминать по модели.
   */
  nodePaths?(model: M): ReadonlyMap<NodeId, readonly (string | number)[]>;
}

/**
 * Точка расширения провайдеров модели.
 *
 * Тип вклада — `DocumentModelProvider<unknown>`: ядро не параметризуется моделью, потому что
 * держит их разом несколько и ни об одной ничего не знает. Типизированный доступ появляется
 * там, где провайдер известен, — у самого плагина.
 */
export const DocumentModelPoint =
  defineExtensionPoint<DocumentModelProvider<unknown>>('document.model');
