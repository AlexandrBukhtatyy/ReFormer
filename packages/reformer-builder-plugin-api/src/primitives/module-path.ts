/**
 * Нормализация пути внутри набора файлов модуля: плагина или сайдкаров формы.
 *
 * Отдельно от `normalizePath` ресурсов — у них разный ответ на побег за корень. Адрес ресурса
 * за корнем источника — ошибка программы, и там бросают. Путь модуля за корнем набора файлов —
 * это то, что написал автор плагина или формы (`"main": "../../secrets.ts"`), и ответ на него
 * обязан быть ДАННЫМИ: разбор манифеста превращает его в отказ с объяснением, линковщик —
 * в ненайденный модуль. Бросок здесь уронил бы разбор чужого каталога целиком.
 *
 * Одна функция на линковщик, разбор манифеста и сборку плагина: разойдись они, валидатор
 * пропускал бы точку входа, которую оболочка отвергнет.
 *
 * @module @reformer/builder-plugin-api/primitives/module-path
 */

/**
 * Нормализует путь: убирает `.`, схлопывает `..`, приводит разделители к `/`.
 *
 * Возвращает `undefined`, если путь вылез за корень набора файлов. Это не педантизм: набор
 * файлов — весь мир исполняемого кода, и `../../../etc` обязан быть отказом, а не промахом.
 */
export function normalizeModulePath(path: string): string | undefined {
  const out: string[] = [];
  for (const segment of path.replace(/\\/g, '/').split('/')) {
    if (segment === '' || segment === '.') continue;
    if (segment === '..') {
      if (out.length === 0) return undefined;
      out.pop();
      continue;
    }
    out.push(segment);
  }
  return out.join('/');
}
