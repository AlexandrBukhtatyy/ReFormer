/**
 * Контекст применимости — снимок состояния, по которому команда решает, доступна ли она сейчас.
 *
 * Проектируется раньше реестра, и это не порядок изложения. Вторая причина монолитности
 * обработчика клавиш в v1 — охранные условия («фокус в поле ввода», «курсор на канвасе»,
 * «не на кнопке»). Реестр команд сам по себе их не убирает, он их прячет: условия просто
 * переезжают внутрь десятка `enabled`. Убирает их только явный снимок состояния, общий для
 * всех команд, — вот этот.
 *
 * Почему сюда входит режим превью: условие «курсор на канвасе» невозможно выразить, не
 * обращаясь одновременно к режиму поверхности. Проверка по коду v1 дала отрицательный ответ,
 * поэтому режим входит в контекст сразу — иначе контракт пришлось бы ломать на первом же
 * редакторе.
 *
 * Ни одно поле не знает предметной области: `activeResourceKind` и `previewMode` —
 * непрозрачные строки, их смысл задаёт плагин, Host только переносит значение от источника
 * к предикату.
 *
 * @module shell/platform/primitives/when-context
 */

/**
 * Куда направлен фокус.
 *
 * Различение `editable` от остальных несущее: именно на нём стоит правило «сочетание
 * пропускается, если фокус в поле ввода» — то самое, из-за которого v1 не разбирается на части.
 *
 * - `editable` — поле ввода, текстовый редактор, `contenteditable`;
 * - `canvas` — поверхность превью;
 * - `tree` — дерево ресурсов;
 * - `panel` — прочий интерфейс оболочки;
 * - `none` — фокуса нет ни на чём осмысленном (например, на `body`).
 */
export type FocusTarget = 'editable' | 'control' | 'canvas' | 'tree' | 'panel' | 'none';

/** Состояние, в котором вычисляется применимость команды. Только чтение, только снимок. */
export interface WhenContext {
  /** Куда направлен фокус: поле ввода, канвас, дерево, панель. */
  readonly focus: FocusTarget;
  /** Идентификатор активного редактора; `null`, если открытых вкладок нет. */
  readonly activeEditorId: string | null;
  /**
   * Вид активного ресурса — непрозрачная строка от плагина документа
   * (`form.schema`, `markdown`, …). Host её не интерпретирует, только сравнивает.
   */
  readonly activeResourceKind: string | null;
  /** Есть ли выделение — в дереве, на канвасе или в редакторе; что именно, знает редактор. */
  readonly hasSelection: boolean;
  /**
   * Режим поверхности превью; `null` — превью не активно.
   *
   * Без этого поля не выражается «курсор на канвасе»: одного `focus === 'canvas'` мало,
   * потому что в режиме взаимодействия тот же фокус означает противоположное.
   */
  readonly previewMode: string | null;
}

/**
 * Нейтральный контекст: ничего не в фокусе, ничего не открыто, ничего не выделено.
 *
 * Нужен там, где реального контекста ещё нет: реестр команд без поставщика контекста,
 * тесты, вызов команды из кода при старте. Значение заморожено — им можно делиться.
 */
export const NEUTRAL_WHEN_CONTEXT: WhenContext = Object.freeze({
  focus: 'none',
  activeEditorId: null,
  activeResourceKind: null,
  hasSelection: false,
  previewMode: null,
});

/**
 * Собирает контекст из нейтрального и переданных отличий.
 *
 * Существует ради одного свойства: добавление поля в {@link WhenContext} не должно ломать
 * каждое место, где контекст собирается. Поставщики контекста в оболочке и тесты указывают
 * только то, что для них значимо.
 */
export function whenContext(patch: Partial<WhenContext> = {}): WhenContext {
  return Object.freeze({ ...NEUTRAL_WHEN_CONTEXT, ...patch });
}
