/**
 * Сервис — единственная точка доступа к реализации, общей для всей платформы.
 *
 * Токен вместо строкового ключа нужен ради одного свойства: строка требует приведения типа
 * на каждом получении, и расхождение между тем, что положили, и тем, во что привели,
 * всплывает не в месте ошибки, а в вызывающем коде спустя несколько слоёв. Токен несёт тип
 * с собой — `get` возвращает уже нужный тип, `register` не даёт положить чужую реализацию.
 *
 * ## Правило доступности: `require` — для Host, `get` — для плагинов
 *
 * Сервисы Host существуют всегда: их регистрирует запуск оболочки до активации плагинов,
 * и если их нет — сломана сборка, а не сценарий. Для них `require`, потому что вызывающему
 * нечего делать с `undefined`, кроме как проверить и упасть чуть дальше от причины.
 *
 * Сервисы плагинов могут отсутствовать — плагин выключен, не установлен, снят на лету.
 * Для них только `get`, и отсутствие обрабатывается как штатная деградация: возможности нет,
 * приложение работает. Это прямое следствие принципа «приложение обязано работать без
 * необязательных частей»: если отсутствие плагина роняет вызывающего, принцип нарушен.
 *
 * ## Один токен — одна реализация
 *
 * Сервис — слот на одну реализацию. Если реализаций должно быть много (панели, валидаторы,
 * цели генерации), это не сервис, а точка расширения — см. `./extension-point`.
 *
 * Здесь ОБЪЯВЛЕНИЕ, а не реестр: реализация (`createServiceRegistry`) живёт в оболочке
 * билдера. Плагину она не нужна и не должна быть доступна — реестр приходит к нему полем
 * контекста, то есть по правилам, а не по импорту.
 *
 * @module @reformer/builder-plugin-api/primitives/service
 */

import type { Disposable } from './disposable';

/**
 * Типизированная ссылка на сервис.
 *
 * Сравнивается и хранится **по `id`**, а не по идентичности объекта. Это осознанно:
 * плагины из каталога проекта грузятся собственным линкером, и один и тот же модуль
 * с объявлением токена может оказаться в памяти дважды. При ключе по объекту второй
 * экземпляр токена не нашёл бы уже зарегистрированный сервис, а диагностика выглядела бы
 * как «сервис есть, но не находится» — худший вид отказа.
 */
export interface ServiceToken<T> {
  readonly id: string;
  /**
   * Только для вывода типов, в рантайме поля нет.
   *
   * Без него `ServiceToken<A>` и `ServiceToken<B>` структурно одинаковы, и компилятор
   * молча пропустил бы `register(tokenA, implB)`.
   */
  readonly __type?: T;
}

/**
 * Объявляет токен сервиса.
 *
 * `id` попадает в сообщения об ошибках и в ключ реестра, поэтому он обязан быть
 * непустым и осмысленным: `reformer.workspace`, а не `ws`.
 */
export function defineService<T>(id: string): ServiceToken<T> {
  if (id.trim() === '') {
    throw new Error('defineService: идентификатор сервиса не может быть пустым');
  }
  return Object.freeze({ id });
}

/**
 * Слот занят или освобождён.
 *
 * Нагрузка — только идентификатор и факт: реализацию подписчик берёт `get`, потому что между
 * уведомлением и чтением слот мог смениться ещё раз, и переданная в событии ссылка была бы
 * устаревшей ровно в том сценарии, ради которого уведомление и заведено (перезагрузка плагина
 * снимает регистрацию и ставит новую).
 */
export interface ServiceChange {
  readonly id: string;
  /** `true` — слот занят, `false` — освобождён. */
  readonly present: boolean;
}

export interface ServiceRegistry {
  /**
   * Занимает слот токена.
   *
   * Бросает, если слот уже занят: действующая реализация иначе зависела бы от порядка
   * активации, а он объявлен незначимым. `dispose()` освобождает слот — после него токен
   * снова можно зарегистрировать.
   */
  register<T>(token: ServiceToken<T>, impl: T): Disposable;
  /** `undefined`, если сервиса нет. Вызывающий обязан деградировать, а не падать. */
  get<T>(token: ServiceToken<T>): T | undefined;
  /** Бросает с внятным сообщением. Только для сервисов Host — см. правило доступности. */
  require<T>(token: ServiceToken<T>): T;
  /**
   * Слот заняли или освободили.
   *
   * Заведено для одного проверяемого случая: **наблюдать за появлением провайдера нечем**.
   * Правило «сервис ищется в момент использования» закрывает команды и обработчики — они
   * спрашивают реестр тогда, когда их позвали, — но не закрывает того, кто обязан ОТРЕАГИРОВАТЬ
   * на появление службы: перерисовать панель, доставшую наконец своего провайдера, или снять
   * деградацию. Без уведомления такому потребителю остаётся опрос по таймеру.
   *
   * Подписчик не должен полагаться на порядок и обязан быть дешёвым: доставка синхронная,
   * внутри `register`/`dispose`. Его исключение не выходит наружу — оно бы превратило отказ
   * наблюдателя в отказ регистрации, то есть уронило бы активацию чужого плагина.
   */
  onDidChange(listener: (event: ServiceChange) => void): Disposable;
}
