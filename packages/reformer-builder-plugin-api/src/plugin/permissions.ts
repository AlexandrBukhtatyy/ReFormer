/**
 * Права плагина: что он объявляет в манифесте и что человек ему подтверждает.
 *
 * ## Почему поле появилось только сейчас
 *
 * «`permissions` не вводим» — решение, записанное в `plugin-and-shell.md` и действовавшее до
 * этого модуля. Довод был не в том, что права не нужны, а в том, что **поле, которое ничего
 * не принуждает, создаёт ложное ощущение границы**: объявленное намерение, которое никто
 * не проверяет, хуже честного «включённый плагин может всё».
 *
 * Принуждение появилось вместе с первой привилегированной службой. Реестр служб отдаёт её
 * только тому, кому право подтверждено, и отказ — не совет, а отсутствие объекта. Поэтому
 * список здесь **закрытый и растёт ровно по одному имени на одну такую службу**: право,
 * за которым не стоит запертой двери, — это снова то самое ложное ощущение.
 *
 * ## Что право НЕ значит
 *
 * Оно не про безопасность исполнения: плагин работает в том же realm, что оболочка, и код,
 * который человек включил, может дотянуться до чего угодно своими руками. Граница здесь одна,
 * и она названа в `plugin-and-shell.md`: плагин включается ЯВНО. Права сужают не возможности
 * кода, а поверхность платформы — то, что оболочка подаёт ему сама, по адресу из контракта.
 *
 * @module @reformer/builder-plugin-api/plugin/permissions
 */

/**
 * Все права, которые оболочка умеет принуждать.
 *
 * - **`workspace.save`** — вынести написанное НАРУЖУ, в источник проекта. Единственная
 *   операция с таким свойством: все остальные пути записи упираются в рабочую копию, и до
 *   источника мимо сохранения не дотянуться физически. Отсюда и первое право: дверь ровно
 *   одна, охранять её дешевле, чем объяснять, почему её нет.
 * - **`workspace.resources`** — менять записи проекта: создать, переименовать, перенести,
 *   удалить, скопировать, открыть другой каталог. То же свойство, что у сохранения: действие
 *   выходит за пределы рабочей копии, и отменить его нашими силами нельзя. Право заведено
 *   вместе со службой `reformer.workspace.resources`, а не «на будущее»: до неё эти операции
 *   существовали только портом композиции, то есть для внешнего плагина их не было вовсе,
 *   и запирать было нечего.
 * - **`plugins.manage`** — распоряжаться ОСТАЛЬНЫМИ плагинами: включать, выключать,
 *   перезагружать, ставить из npm. Самое сильное из трёх, и это надо называть вслух:
 *   включить плагин значит исполнить чужой код, то есть обладатель права решает за человека
 *   то, что человек привык решать сам. Отдельным правом оно и заведено — чтобы вопрос
 *   задавался отдельно и заметно, а не приезжал довеском к работе с файлами.
 */
export const PLUGIN_PERMISSIONS = Object.freeze([
  'workspace.save',
  'workspace.resources',
  'plugins.manage',
] as const);

/** Право плагина — имя из {@link PLUGIN_PERMISSIONS}. */
export type PluginPermission = (typeof PLUGIN_PERMISSIONS)[number];

/** Знает ли оболочка такое право. Разбор манифеста отвергает незнакомые, а не игнорирует. */
export function isPluginPermission(value: string): value is PluginPermission {
  return (PLUGIN_PERMISSIONS as readonly string[]).includes(value);
}
