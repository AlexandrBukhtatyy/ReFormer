/**
 * Скоуп стилей плагина: атрибут на контейнере, под который оболочка переписывает таблицу стилей
 * плагина (`styles` манифеста, `"isolation": "scoped"`).
 *
 * Панели и вклады плагина оболочка помечает сама (`PluginScope`). Отдельно скоуп нужен тому, кто
 * рисует содержимое ДРУГОГО плагина: превью рисует компоненты кита, пришедшего плагином, и стили
 * этого кита должны действовать только внутри контейнера, помеченного скоупом его владельца, —
 * а не перекрашивать остальной интерфейс билдера.
 *
 * Изоляция — гигиена, а не граница безопасности: код плагина исполняется в том же realm.
 *
 * @module @reformer/builder-plugin-api/ui/plugin-scope
 */

/** Атрибут скоупа. Литерал один на платформу: вторая его запись разошлась бы с первой молча. */
export const PLUGIN_SCOPE_ATTRIBUTE = 'data-rb-plugin';

/** Атрибуты контейнера, внутри которого действуют стили плагина `pluginId`. */
export function pluginScopeAttributes(pluginId: string): {
  readonly [PLUGIN_SCOPE_ATTRIBUTE]: string;
} {
  return { [PLUGIN_SCOPE_ATTRIBUTE]: pluginId };
}
