/**
 * Перевод как React-значение: строка, которая меняется вместе с языком.
 *
 * ## Зачем хук, если есть `t`
 *
 * `i18n.t(key)` отвечает на вопрос «как это звучит СЕЙЧАС» и ничего не обещает про потом.
 * React о смене языка не знает: локаль живёт в службе, вне дерева, и компонент, позвавший
 * `t` при отрисовке, останется на прежних строках до следующей причины перерисоваться —
 * то есть до случайного щелчка. Хук подписывает компонент на смену локали и тем превращает
 * «как звучит сейчас» в «как звучит».
 *
 * ## Почему возвращается функция, а не строка
 *
 * Ключей в панели обычно десяток, и хук на каждый означал бы десять подписок на одно событие
 * плюс правило «вызывать одинаковое число раз» на каждое условие в разметке. Возвращается
 * переводчик, а перерисовку вызывает подписка внутри.
 *
 * Ссылка на переводчика меняется ВМЕСТЕ с локалью и только с ней: иначе он не годился бы
 * в зависимости `useMemo`/`useCallback` — всё, что им посчитано из строк, пересчитывалось бы
 * на каждой отрисовке родителя.
 *
 * ## Почему здесь, а не в плагине
 *
 * Это единственный способ для плагина показать переведённую строку реактивно, а плагину
 * доступен только контракт. Раньше такой хук вёз КАЖДЫЙ порт (`useTranslate` есть у превью,
 * у ассистента, у файлов, у markdown) — по копии на плагин, все с одинаковым телом: службы
 * локализации в SDK не было. Теперь она есть полем контекста, и копии не нужны.
 *
 * @module @reformer/builder-plugin-api/ui/useTranslate
 */

import { useMemo } from 'react';
import type { PluginI18n } from '../services/i18n.js';
import { useLocale } from './useLocale.js';

/** Перевод: ключ и параметры сообщения. Совпадает по форме с `PluginI18n.t`. */
export type Translate = (key: string, params?: Record<string, unknown>) => string;

export function useTranslate(
  i18n: Pick<PluginI18n, 'locale' | 't' | 'onDidChangeLocale'>
): Translate {
  // Подписка на смену локали: значение нужно не переводчику, а перерисовке.
  const locale = useLocale(i18n);
  return useMemo<Translate>(() => {
    // Локаль здесь — МЕТКА ВЕРСИИ, а не данные: в теле она не участвует, но её смена обязана
    // дать новую ссылку, иначе посчитанное потребителем из строк осталось бы на прежнем языке.
    void locale;
    return (key, params) => i18n.t(key, params);
  }, [i18n, locale]);
}
