/**
 * Служба китов — один ответ на «какой кит активен» для всех стеков и плагинов.
 *
 * ## Почему служба, а не значение
 *
 * Палитра рисует компоненты активного кита, превью резолвит их, валидатор сверяет имена с его
 * каталогом, тема RJSF строится по нему же. Если у каждого свой ответ, валидатор ругается на
 * компонент, который человек только что поставил из палитры. Поэтому ответ держит одна служба,
 * и находят её по возможности {@link KitsCapability}.
 *
 * ## Служба нейтральна
 *
 * Она отдаёт кит так, как его поставил кит: сырой каталог и дескриптор. Что из каталога следует
 * для конкретного стека (узлы по умолчанию, синтетика палитры, тема), стек выводит сам — служба
 * не знает ни одного стека, иначе второй стек пришлось бы вносить её правкой.
 *
 * ## Синхронные читатели
 *
 * Все читатели зовутся из отрисовки и не ждут: у ленивого кита до загрузки каталог ПУСТ
 * (шапка кита есть, записей нет). Переход «пусто → загружено» приходит тем же
 * {@link KitsService.onDidChange}, что и смена кита: для читателя это одно «показанное устарело».
 * Между сменами читатели возвращают те же ссылки — на этом стоит `useSyncExternalStore`.
 *
 * @module @reformer/builder-plugin-api/kits/service
 */

import type { ComponentType, ReactNode } from 'react';
import type { Disposable } from '../primitives/disposable.js';
import { defineCapability } from '../primitives/capability.js';
import type { CatalogJson, KitNamespace } from './catalog.js';
import type { KitDescriptor } from './descriptor.js';

/**
 * Откуда кит: встроен в сборку билдера или внесён плагином.
 *
 * Различие несущее. Стили кита-плагина действуют только внутри скоупа его владельца, и рамка
 * превью ставит этот скоуп; компоненты встроенного кита оболочка и так отдаёт своим реестром
 * модулей, а кита-плагина — только через его пространство имён.
 */
export type KitOrigin =
  | { readonly kind: 'builtin' }
  | { readonly kind: 'plugin'; readonly pluginId: string };

/** Кит в списке доступных: всё, что нужно переключателю, и ничего из каталога. */
export interface KitSummary {
  readonly id: string;
  readonly label: string;
  readonly package: string;
  readonly version: string;
  readonly active: boolean;
  readonly origin: KitOrigin;
}

/** Пропсы рамки кита: поддерево, которое надо нарисовать в окружении активного кита. */
export interface KitFrameProps {
  readonly children?: ReactNode;
}

export interface KitsService {
  /** Идентификатор активного кита. */
  activeId(): string;
  /** Откуда активный кит. */
  activeOrigin(): KitOrigin;
  /**
   * Дескриптор активного кита по его сырому каталогу. До загрузки ленивого каталога — дескриптор
   * пустого каталога: личность кита та же, всё выводимое из записей пусто.
   */
  descriptor(): KitDescriptor;
  /** Сырой каталог активного кита — как его поставил кит. До загрузки — без записей. */
  catalogJson(): CatalogJson;
  /** Между чем можно выбирать: встроенные первыми, затем внесённые плагинами. */
  available(): readonly KitSummary[];
  /**
   * Делает кит активным и сохраняет выбор. Активным он становится СРАЗУ, а промис относится
   * к записи в настройки — переключатель не ждёт хранилище. Незнакомый кит — отказ.
   */
  activate(id: string): Promise<void>;
  /**
   * Активный кит сменился ИЛИ его каталог доехал. Нагрузки нет: подписчик перечитывает то,
   * что ему нужно.
   */
  onDidChange(cb: () => void): Disposable;
  /** Изменился список доступных: плагин внёс кит или его выключили. */
  onDidChangeAvailable(cb: () => void): Disposable;
  /**
   * Пространство имён активного кита либо `null`: кит его не объявил или оно ещё едет. Первый
   * вызов заводит загрузку — синхронный читатель ждать не может.
   */
  namespace(): KitNamespace | null;
  /** Пространство имён доехало — «кит тот же, но теперь он есть». */
  onDidLoadNamespace(cb: () => void): Disposable;
  /**
   * Рамка активного кита: скоуп стилей плагина-владельца и провайдер кита
   * (`kit.adapters.provider`). Стек, рисующий форму компонентами кита, кладёт её внутрь.
   *
   * Компонент стабилен на всё время жизни службы и сам следит за сменой кита: пересоздавать
   * его значило бы размонтировать форму на каждое переключение.
   */
  readonly Frame: ComponentType<KitFrameProps>;
}

/**
 * Возможность «активный кит».
 *
 * `2.0.0` — мажор: служба стала нейтральной. Проекция каталога под ReFormer (`catalog()`
 * с узлами по умолчанию) ушла к стеку, а служба отдаёт сырой каталог, происхождение кита,
 * рамку и список, меняющийся по мере того, как плагины вносят киты.
 */
export const KitsCapability = defineCapability<KitsService>({
  id: 'reformer.kit.catalog',
  version: '2.0.0',
});
