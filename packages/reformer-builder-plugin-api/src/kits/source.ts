/**
 * Источник кита — то, чем плагин ставит кит в билдер: каталог, шапка и пространство имён.
 *
 * ## Точка, а не параметр реестра
 *
 * Раньше кит подключался правкой композиции: список китов реестр получал параметром, и кит
 * из каталога плагинов проекта попасть туда не мог. Точка расширения делает кит обычным вкладом:
 * плагин вносит источник, реестр китов его подхватывает, выключение плагина кит снимает.
 *
 * ## Каталог может приехать позже кита
 *
 * Каталог настоящей дизайн-системы весит сотни килобайт, а нужен не раньше, чем открыт файл
 * формы. Поэтому он отдаётся значением ИЛИ загрузчиком, а пространство имён — только загрузчиком:
 * это сами компоненты, самая тяжёлая часть кита.
 *
 * @module @reformer/builder-plugin-api/kits/source
 */

import { defineExtensionPoint } from '../primitives/extension-point.js';
import type { CatalogJson, KitDescriptorJson, KitNamespace } from './catalog.js';

/**
 * Загрузчик каталога. Реестр зовёт его не более одного раза на кит и сам держит результат,
 * поэтому возвращать один и тот же промис загрузчик не обязан.
 */
export type CatalogLoader = () => Promise<CatalogJson>;

/**
 * Кит на входе реестра.
 *
 * ## Ленивый кит представляется ДО загрузки
 *
 * Список китов обязан быть готов раньше, чем загружен хоть один каталог, а идентификатор — ключ
 * выбора, попадающий в настройки. Поэтому источник с загрузчиком объявляет шапку ({@link kit})
 * заранее, а реестр после загрузки сверяет её с каталогом: иначе ключ выбора менялся бы
 * под ногами.
 */
export interface KitSource {
  /** Каталог по контракту `component-catalog.schema.json` — значением либо загрузчиком. */
  readonly catalog: CatalogJson | CatalogLoader;
  /**
   * Шапка кита: чем он представляется, пока каталога нет. После загрузки действует блок `kit`
   * самого каталога; каталог, назвавший себя иначе, чем шапка, реестр отвергнет. У источника со
   * значением шапку можно не давать — идентификатор берётся из каталога.
   */
  readonly kit?: KitDescriptorJson;
  /**
   * Пространство имён кита — сами компоненты. Только загрузчиком: нужно лишь тому, кто рисует
   * форму по-настоящему. Без него превью рисует подписанные заглушки.
   *
   * Объявляет его КИТ, а не превью: «чем рисовать `Input`» — утверждение дизайн-системы о себе.
   */
  readonly namespace?: () => Promise<KitNamespace>;
}

/**
 * Точка источников китов. Вклад — {@link KitSource}; идентификатор вклада на выбор не влияет,
 * ключ кита — его собственный `id`.
 */
export const KitSourcePoint = defineExtensionPoint<KitSource>('reformer.kit.source');

/**
 * Идентификатор, которым источник представляется до загрузки каталога: шапка, иначе блок
 * `kit` каталога-значения. `undefined` — кит себя не назвал, и реестр его не примет.
 */
export function declaredKitId(source: KitSource): string | undefined {
  const fromHeader = source.kit?.id;
  if (fromHeader !== undefined && fromHeader !== '') return fromHeader;
  if (typeof source.catalog === 'function') return undefined;
  const fromCatalog = source.catalog.kit?.id;
  return fromCatalog !== undefined && fromCatalog !== '' ? fromCatalog : undefined;
}
