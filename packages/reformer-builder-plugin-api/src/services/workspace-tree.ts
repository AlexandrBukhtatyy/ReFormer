/**
 * Дерево проекта — как возможность оболочки: готовая панель и то, что в ней выделено.
 *
 * ## Зачем
 *
 * Навигация по ресурсам не предметна: дерево, его раскрытие, выделение набора, перетаскивание
 * и контекстное меню строки живут в оболочке целиком. А вот МЕСТО для дерева — решение
 * предметное: показывать ли его, в каком слоте, под каким названием и значком. Принимает его
 * плагин, и раньше тело панели приезжало к нему портом, который собирала композиция, — то есть
 * внести дерево мог только встроенный плагин. Возможность отдаёт то же самое любому.
 *
 * ## Почему компонент, а не данные
 *
 * Отдать дерево данными значило бы заставить каждого, кто его показывает, заново написать
 * виртуализацию, клавиатуру и перетаскивание — и получить несколько деревьев, ведущих себя
 * по-разному. Компонент один; плагин решает, где он стоит.
 *
 * ## Выделение
 *
 * {@link WorkspaceTreeService.selection} нужен командам, вызванным С КЛАВИШИ: у пункта меню
 * цель приходит аргументом, а у клавиши аргументов нет вовсе, и «к чему применить» знает только
 * дерево. Правило «набор, если фокус внутри него, иначе одна строка» — платформенное.
 *
 * Корень проекта спрашивают не здесь, а у `WorkspaceFilesService.projectRoot()`.
 *
 * @module @reformer/builder-plugin-api/services/workspace-tree
 */

import type { ComponentType } from 'react';
import { defineCapability, type Capability } from '../primitives/capability.js';
import type { ResourceRef } from '../primitives/resource.js';

export interface WorkspaceTreeService {
  /**
   * Тело панели с деревом проекта. Ссылка стабильна на всё время жизни оболочки.
   *
   * Без открытого проекта панель пуста — это состояние, а не отказ.
   */
  readonly Panel: ComponentType<{ panelId: string }>;
  /**
   * Что выделено в дереве — набор, если щёлкнули по его строке, иначе одна строка.
   * Без проекта и без выделения — пустой список.
   */
  selection(): readonly ResourceRef[];
}

/**
 * Возможность «дерево проекта». Провайдер — оболочка.
 *
 * Версия `1.0.0` — исходная.
 */
export const WorkspaceTreeCapability: Capability<WorkspaceTreeService> =
  defineCapability<WorkspaceTreeService>({ id: 'reformer.workspace.tree', version: '1.0.0' });
