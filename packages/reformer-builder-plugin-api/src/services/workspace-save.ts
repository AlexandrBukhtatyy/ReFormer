/**
 * Сохранение рабочей копии в источник — первая служба, которую оболочка отдаёт НЕ ВСЕМ.
 *
 * ## Почему именно она
 *
 * Все прочие пути записи упираются в рабочую копию: `DocumentsService.writeText`,
 * `WorkspaceFilesService`, запись сайдкаров — всё это правит копию внутри браузера, и до файлов
 * человека мимо сохранения не дотянуться физически. `save` — единственное исключение, то есть
 * единственная дверь наружу. Пока политики прав не было, служба существовать не могла вовсе:
 * отдать её через реестр значило раздать эту дверь каждому включённому плагину. Поэтому
 * генерация кода и шаблоны получали сохранение ПОРТОМ, от композиции.
 *
 * ## Что изменилось
 *
 * Появилось принуждение: возможность отдаётся только тому, кто объявил право
 * `workspace.save` в манифесте и кому человек его подтвердил. Отказ — отсутствие объекта
 * (`capabilities.get` вернёт `undefined`, `require` откажет), а не совет не делать.
 *
 * Объём — ровно одна операция и ни членом больше: «сохранить набор адресов». Расхождения
 * с источником сюда не попадают — их показывает диалог слияния, и знает о них тот, кто
 * его открывает.
 *
 * @module @reformer/builder-plugin-api/services/workspace-save
 */

import { defineCapability, type Capability } from '../primitives/capability.js';
import type { ResourceId } from '../primitives/resource.js';

export interface WorkspaceSaveService {
  /**
   * Сохраняет перечисленные ресурсы в источник проекта.
   *
   * `false` — проекта нет или хотя бы один ресурс не сохранился. Причины по одному ресурсу
   * наружу не отдаются: показать их некому, кроме рабочей области, а она о них знает и так.
   */
  save(ids: readonly ResourceId[]): Promise<boolean>;
}

/**
 * Возможность «сохранить в источник». Привилегированная: оболочка сверяет право
 * `workspace.save` перед тем, как отдать её плагину.
 */
export const WorkspaceSaveCapability: Capability<WorkspaceSaveService> =
  defineCapability<WorkspaceSaveService>({ id: 'reformer.workspace.save', version: '1.0.0' });

/** Токен службы — ТОТ ЖЕ объект: возможность расширяет токен, второго реестра нет. */
export const WorkspaceSaveServiceToken = WorkspaceSaveCapability;
