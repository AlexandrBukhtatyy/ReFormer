/**
 * Сохранение рабочей копии в источник — первая служба, которую оболочка отдаёт НЕ ВСЕМ.
 *
 * ## Почему именно она
 *
 * Все прочие пути записи упираются в рабочую копию: `DocumentsService.writeText`,
 * `WorkspaceFilesService`, запись сайдкаров — всё это правит копию внутри браузера, и до файлов
 * человека мимо сохранения не дотянуться физически. `save` — единственное исключение, то есть
 * единственная дверь наружу. Пока политики прав не было, служба существовать не могла вовсе:
 * отдать её через реестр значило раздать эту дверь каждому включённому плагину. Поэтому
 * генерация кода и шаблоны получали сохранение ПОРТОМ, от композиции.
 *
 * ## Что изменилось
 *
 * Появилось принуждение: возможность отдаётся только тому, кто объявил право
 * `workspace.save` в манифесте и кому человек его подтвердил. Отказ — отсутствие объекта
 * (`capabilities.get` вернёт `undefined`, `require` откажет), а не совет не делать.
 *
 * Объём — сохранение и ничего сверх: набор адресов, всё изменённое и вопрос «есть ли что
 * сохранять». Расхождения с источником сюда не попадают — их показывает диалог слияния,
 * и знает о них тот, кто его открывает.
 *
 * @module @reformer/builder-plugin-api/services/workspace-save
 */

import { defineCapability, type Capability } from '../primitives/capability.js';
import type { ResourceId } from '../primitives/resource.js';

/** Что сохранить сверх названных ресурсов. */
export interface WorkspaceSaveOptions {
  /**
   * Вместе с документом — изменения его сопутствующих файлов (`DocumentModelProvider.companionsDir`).
   *
   * Просит только сохранение от лица человека. Плагин, сохраняющий записанные им файлы, этого
   * не просит: чужие несохранённые правки рядом с ними — не его решение.
   */
  readonly companions?: boolean;
  /**
   * Сохранить несохранённое ВНУТРИ названных ресурсов: у каталога — все изменённые файлы под
   * ним на любой глубине, у файла — он сам, если изменён. Неизменённое пропускается без отказа:
   * сохранить каталог, в котором нечего сохранять, — пустая операция, а не ошибка.
   *
   * Просит сохранение выделенного в дереве проекта: человек выделяет каталог формы, а не
   * перечисляет её файлы, и список изменённого у плагина нет. Без флага каталог в списке —
   * отказ (`false`): сам по себе он не файл, и сохранять у него нечего.
   */
  readonly nested?: boolean;
}

export interface WorkspaceSaveService {
  /**
   * Сохраняет перечисленные ресурсы в источник проекта.
   *
   * `false` — проекта нет или хотя бы один ресурс не сохранился. Причины по одному ресурсу
   * наружу не отдаются: показать их некому, кроме рабочей области, а она о них знает и так.
   */
  save(ids: readonly ResourceId[], options?: WorkspaceSaveOptions): Promise<boolean>;
  /**
   * Сохраняет всё изменённое. `false` — проекта нет или что-то не сохранилось.
   *
   * Отдельный глагол, а не «`save` со списком всех изменённых»: списка изменённого у плагина
   * нет, и собирать его ради одной команды значило бы отдать наружу устройство рабочей копии.
   */
  saveAll(): Promise<boolean>;
  /**
   * Есть ли несохранённые правки. Без аргумента — во всей рабочей области; со списком — в этих
   * ресурсах и под ними, по тому же правилу, что {@link WorkspaceSaveOptions.nested}: им пункт
   * «Сохранить выбранное» гасит себя там, где сохранять нечего. Без проекта — `false`.
   */
  isDirty(ids?: readonly ResourceId[]): boolean;
}

/**
 * Возможность «сохранить в источник». Привилегированная: оболочка сверяет право
 * `workspace.save` перед тем, как отдать её плагину.
 *
 * `1.1.0` — минор: {@link WorkspaceSaveService.saveAll} и {@link WorkspaceSaveService.isDirty}.
 * `1.2.0` — минор: {@link WorkspaceSaveOptions.companions}.
 * `1.3.0` — минор: {@link WorkspaceSaveOptions.nested} и список адресов
 *   у {@link WorkspaceSaveService.isDirty}.
 */
export const WorkspaceSaveCapability: Capability<WorkspaceSaveService> =
  defineCapability<WorkspaceSaveService>({ id: 'reformer.workspace.save', version: '1.3.0' });

/** Токен службы — ТОТ ЖЕ объект: возможность расширяет токен, второго реестра нет. */
export const WorkspaceSaveServiceToken = WorkspaceSaveCapability;
