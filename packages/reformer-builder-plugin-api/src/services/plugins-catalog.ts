/**
 * Каталог плагинов: список и распоряжение им — включить, выключить, перезагрузить.
 *
 * ## Почему это привилегированная служба, а не порт композиции
 *
 * Портом она была ровно потому, что «управлять списком исполняемого кода — привилегия
 * композиции, и раздавать её каждому плагину значило бы отдать границу доверия тому, кого
 * она держит». Довод верен, а вывод из него был слишком широким: порт не раздаёт — он
 * ОТРЕЗАЕТ. Собрать порт внешнему плагину некому, поэтому распоряжаться плагинами мог
 * только встроенный, и никакого решения человек при этом не принимал.
 *
 * Со службой и правом решение появляется: плагин объявляет `plugins.manage` в манифесте,
 * человек подтверждает — и тогда получает объект. Не подтвердил — `get` отдаёт `undefined`,
 * и это не совет, а отсутствие двери.
 *
 * ## Что это право значит на самом деле
 *
 * Оно сильнее остальных, и это надо называть вслух: тот, кому его дали, может включить
 * ЛЮБОЙ плагин каталога, то есть исполнить чужой код без отдельного согласия человека.
 * Право не превращает плагин в песочницу и не делает его безопасным — граница доверия
 * у нас одна и в другом месте (плагин включается явно). Оно делает видимым то, что раньше
 * было невыразимо: «этот плагин распоряжается остальными».
 *
 * @module @reformer/builder-plugin-api/services/plugins-catalog
 */

import { defineCapability, type Capability } from '../primitives/capability.js';

/** Состояние строки каталога: найден-выключен, работает, не грузится. */
export type ManagedPluginState = 'disabled' | 'enabled' | 'failed';

/** Плагин каталога в объёме, нужном тому, кто им распоряжается. */
export interface ManagedPlugin {
  readonly id: string;
  readonly name: string;
  readonly version?: string;
  readonly state: ManagedPluginState;
  /** Помечен «в разработке»: файлы наблюдаются, плагин перезагружается после правки. */
  readonly dev: boolean;
  /** Слой, из которого взят плагин: каталог проекта или установленное из npm. */
  readonly layer?: 'project' | 'installed';
  /** Почему `failed`. Текста достаточно: код разбора нужен спискам оболочки, а не отсюда. */
  readonly problem?: { readonly message: string };
}

export interface PluginsCatalogService {
  /** Снимок списка. Живого списка здесь нет намеренно: подписка — дело того, кто рисует. */
  list(): readonly ManagedPlugin[];
  /** Загружает и активирует. Для упавшего это и есть «попробовать снова». */
  enable(id: string): Promise<boolean>;
  /** Снимает вклады, помнит решение человека. */
  disable(id: string): void;
  /** Снимает вклады, перечитывает файлы, поднимает заново. */
  reload(id: string): Promise<boolean>;
  /** Ставит или снимает пометку «в разработке». */
  setDev(id: string, on: boolean): void;
  /** Перечитывает каталог: так в списке появляется только что созданный плагин. */
  refresh(): Promise<unknown>;

  /**
   * Ставит плагин из npm, спросив имя пакета у человека.
   *
   * Необязателен, и это названная деградация: сборка без установки (профиль без неё,
   * окружение без OPFS) обязана работать, а тот, кто рисует список, — не показывать
   * действие, которое ничего не сделает. Имя пакета спрашивает ОБОЛОЧКА: диалоги — её
   * служба, и плагин не должен получать её ради одного поля ввода.
   */
  install?(): Promise<void>;
  /** Убирает установленный плагин целиком. Плагина из каталога проекта не касается. */
  uninstall?(id: string): Promise<void>;
  /**
   * Переключает установленный плагин на другую уже скачанную версию.
   *
   * Откат существует ради одного случая, зато обязательного: новая версия сломала работу.
   * Прошлые версии остаются на диске, поэтому операция не ходит в сеть и работает без неё.
   */
  rollback?(id: string): Promise<void>;
}

/**
 * Возможность «каталог плагинов». Привилегированная: право `plugins.manage`.
 *
 * Провайдер — оболочка. Версия `1.0.0` — исходная; растит её тот, кто меняет интерфейс.
 */
export const PluginsCatalogCapability: Capability<PluginsCatalogService> =
  defineCapability<PluginsCatalogService>({ id: 'reformer.plugins.catalog', version: '1.0.0' });

/** Токен службы — ТОТ ЖЕ объект: возможность расширяет токен, второго реестра нет. */
export const PluginsCatalogServiceToken = PluginsCatalogCapability;
