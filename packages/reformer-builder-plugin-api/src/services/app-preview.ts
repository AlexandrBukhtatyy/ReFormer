/**
 * Превью приложением: адреса, по которым запущенное приложение показывает себя и одну свою форму.
 *
 * ## Зачем это возможность, а не знание плагина
 *
 * Билдер, встроенный в приложение, об устройстве приложения не знает ничего — и не должен: форму
 * в превью рисует само приложение, в отдельном документе (рамке), а обновляет её его же
 * dev-сервер после записи файлов на диск. От билдера при этом нужно ровно одно: АДРЕС, по
 * которому это показать. Адрес знает оболочка, встроенная в приложение, — она в нём живёт;
 * плагин, рисующий панель превью, получает его отсюда и остаётся нейтральным.
 *
 * ## Возможность необязательная
 *
 * Регистрирует её только оболочка, встроенная в приложение. В самостоятельном билдере её нет,
 * и это законная сборка: там форму рисует сам билдер. Поэтому плагин не объявляет её
 * в `requires`, а спрашивает реестр служб при активации и без неё ничего не вносит.
 *
 * ## Два адреса и ничего больше
 *
 * Страница и одна форма — всё, что билдер вправе знать о приложении. Маршруты, реестр
 * компонентов, источники данных сюда не попадают: это уже сотрудничество с конкретным
 * приложением, и ему место в отдельном плагине, а не в контракте превью.
 *
 * @module @reformer/builder-plugin-api/services/app-preview
 */

import { defineCapability, type Capability } from '../primitives/capability.js';
import type { Disposable } from '../primitives/disposable.js';

/**
 * Имя окна рамки, в которой показывается приложение.
 *
 * Приложение в рамке — то же самое приложение с тем же встроенным билдером, и без этого имени
 * оно показало бы кнопку билдера внутри собственного превью. Имя окна — единственный признак,
 * который переживает переходы внутри рамки и не требует договорённостей с маршрутизатором
 * приложения: рамку называет тот, кто её рисует, а компонент билдера в приложении его читает.
 */
export const APP_PREVIEW_FRAME_NAME = 'reformer-builder-preview';

/** Адреса запущенного приложения — в объёме, нужном панели превью. */
export interface AppPreviewService {
  /**
   * Адрес страницы приложения, с которой включили режим билдера. С него начинается вид
   * «приложение целиком»; дальше человек ходит по приложению сам.
   */
  pageUrl(): string;

  /**
   * Адрес, по которому приложение рисует ОДНУ форму без остальной страницы.
   *
   * @param modulePath Путь модуля формы от корня открытого проекта (`src/forms/contact/index.tsx`).
   * Существует ли такой файл, проверяет спрашивающий: у него есть рабочая область, а здесь —
   * только адресная арифметика.
   */
  formUrl(modulePath: string): string;

  /**
   * Файлы проекта записаны на диск — запущенное приложение сейчас изменится.
   *
   * Рамке превью этого мало узнать от самого приложения. Его dev-сервер обновляет модули
   * «на лету», сохраняя состояние компонентов, а собранная форма — как раз состояние: правка
   * схемы приезжает, форма остаётся прежней. Поэтому после записи рамку перезагружают, а не
   * ждут, что приложение перерисуется само.
   *
   * Событие — про запись в ИСТОЧНИК, а не про правку рабочей копии: несохранённого приложение
   * не видит вовсе.
   */
  onDidWriteSource(cb: () => void): Disposable;
}

/** Возможность «превью приложением». Даёт её оболочка, встроенная в приложение. */
export const AppPreviewCapability: Capability<AppPreviewService> =
  defineCapability<AppPreviewService>({
    id: 'reformer.app.preview',
    version: '1.0.0',
  });
