/**
 * Профили состава: из чего собрано приложение и на что его можно пересобрать.
 *
 * Здесь ОБЪЯВЛЕНИЕ. Сами профили, их разрешение и сборка состава живут в приложении билдера,
 * а не в оболочке и не в плагине: плагин видит только имена — ровно столько, сколько нужно,
 * чтобы показать человеку выбор.
 *
 * ## Почему смена — это перезапуск
 *
 * Состав плагинов фиксируется при сборке приложения, до активации первого плагина: набор вкладов
 * и служб не может зависеть от того, что успело загрузиться. Поэтому {@link
 * ApplicationProfilesService.select} не «переключает» состав, а запоминает выбор и перезапускает
 * приложение — следующая сборка прочитает выбор раньше, чем начнёт собираться.
 *
 * ## Три имени, а не одно
 *
 * «Что собрано», «что задал тот, кто разворачивает билдер» и «что выбрал человек» — разные вещи,
 * и расходятся они штатно: конфиг запуска называет один профиль, человек выбрал другой, а
 * несобравшийся выбор откатывается назад. Служба отдаёт первое и второе; третье читается как
 * их разница, и вернуть его к конфигу — `select(launch().id)`.
 *
 * @module @reformer/builder-plugin-api/services/application-profiles
 */

import { defineService } from '../primitives/service.js';

/** Профиль в объёме, нужном для выбора: имя для кода и имя для человека. */
export interface ApplicationProfileInfo {
  /** Идентификатор профиля — тот же, что в `preset` конфига запуска. */
  readonly id: string;
  /** Имя для человека. Не ключ словаря: профиль описан данными конфига, а не плагином. */
  readonly name: string;
}

export interface ApplicationProfilesService {
  /**
   * Профиль, из которого приложение собрано НА САМОМ ДЕЛЕ. Не «что написано в конфиге»:
   * неизвестное имя и несобравшийся состав откатываются на другой профиль, и здесь — он.
   */
  current(): ApplicationProfileInfo;
  /** Профиль конфига запуска — к нему возвращает отказ от собственного выбора. */
  launch(): ApplicationProfileInfo;
  /**
   * Профили, между которыми можно переключаться. Меньше двух — переключать не между чем:
   * так организация закрепляет состав. {@link current} в списке может и не быть — например,
   * свой профиль организации, не предложенный к выбору.
   */
  offered(): readonly ApplicationProfileInfo[];
  /**
   * Запоминает выбор и перезапускает приложение, если выбран не тот профиль, что собран.
   *
   * `launch().id` снимает выбор — приложение снова следует конфигу запуска. Отвергается
   * исключением: имя не из {@link offered} и не `launch().id`; выбор не удалось сохранить
   * (перезапуск тогда ничего бы не сменил и выглядел бы как поломка).
   */
  select(id: string): Promise<void>;
}

export const ApplicationProfilesServiceToken = defineService<ApplicationProfilesService>(
  'reformer.application.profiles'
);
