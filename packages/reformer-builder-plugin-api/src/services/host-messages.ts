/**
 * Словарь оболочки — на чтение, для тех, кто показывает чужие находки.
 *
 * ## Зачем
 *
 * Коды диагностик переводятся ОДНИМ словарём (`errors.<code>` у оболочки), а не словарём
 * каждого плагина: одна и та же ошибка обязана звучать одинаково в подчёркивании редактора кода,
 * на узле канваса и строкой в панели проблем. Раньше перевод доезжал до редакторов портами,
 * которые собирала оболочка, — внешний редактор перевести код находки не мог вовсе и показывал
 * сам код. Заголовки быстрых исправлений (`QuickFix.titleKey`) — ключи того же словаря.
 *
 * ## Почему только чтение
 *
 * Словарь принадлежит оболочке. Плагин вносит строки в СВОЁ пространство имён (`ctx.i18n`),
 * а здесь только спрашивает — метода `contribute` в типе нет, и это граница, а не забывчивость.
 *
 * Форма совместима с `useTranslate` из SDK: реактивный перевод строится тем же хуком, что и для
 * словаря плагина.
 *
 * @module @reformer/builder-plugin-api/services/host-messages
 */

import { defineCapability, type Capability } from '../primitives/capability.js';
import type { PluginI18n } from './i18n.js';

/** Словарь оболочки: локаль, перевод ключа без приставки плагина, смена локали. */
export type HostMessagesService = Pick<PluginI18n, 'locale' | 't' | 'onDidChangeLocale'>;

/**
 * Возможность «словарь оболочки». Провайдер — оболочка.
 *
 * Версия `1.0.0` — исходная.
 */
export const HostMessagesCapability: Capability<HostMessagesService> =
  defineCapability<HostMessagesService>({ id: 'reformer.host.messages', version: '1.0.0' });
