/**
 * Словарь плагина: его строки в ЕГО пространстве имён.
 *
 * Пространство имён — ОТДЕЛЬНОЕ ИЗМЕРЕНИЕ каталога, а не префикс в ключе. Разница видна
 * на идентификаторах с точкой: плагин `acme`, внёсший ключ `sub.title`, при хранении «плоским
 * префиксом» занял бы `acme.sub.title` — то есть ключ `title` плагина `acme.sub`. Отдельное
 * измерение делает такое пересечение невыразимым.
 *
 * Ключ — семантический (`files.panel.title`), а не английская строка: тогда ни одна локаль
 * не оказывается «главной», и правка `en` не ломает ключи. Промах виден маркером `⟦…⟧`,
 * а не молчаливым возвратом ключа: `files.panel.title` в интерфейсе неотличим от задуманного
 * текста и до баг-репорта не доживает.
 *
 * Здесь только ВИД для плагина. Сам сервис (`createI18nService`), его корневой интерфейс
 * и загрузка словарей живут в оболочке билдера: язык у приложения один, и распоряжается им она.
 *
 * @module @reformer/builder-plugin-api/services/i18n
 */

import type { Disposable } from '../primitives/disposable.js';

/** Вид сервиса для плагина: ключи автоматически префиксуются его идентификатором. */
export interface PluginI18n {
  /**
   * Действующая локаль — та же, что у корня: у вида своей быть не может.
   *
   * Нужна не для показа, а для перерисовки: снимок для `useSyncExternalStore` обязан меняться
   * вместе с языком, иначе панель плагина осталась бы на прежних строках до следующей правки
   * своего состояния (см. `ui/useTranslate`).
   */
  readonly locale: string;
  t(key: string, params?: Record<string, unknown>): string;
  /**
   * Локаль сменилась. Тот же канал, что у корня: подписка идёт НАПРЯМУЮ к нему, потому что
   * язык у приложения один, а вид — всего лишь пространство имён ключей.
   */
  onDidChangeLocale(cb: (locale: string) => void): Disposable;
  /**
   * Регистрирует словарь в пространстве имён плагина.
   *
   * Повторный вызов для той же локали **дополняет** словарь, а не заменяет его: плагин вправе
   * везти словарь по частям — например, догружать раздел вместе с панелью.
   *
   * Бросает, если сообщение не разбирается, называя ключ. Ни одно сообщение этого вызова
   * при этом не регистрируется.
   */
  contribute(locale: string, messages: Readonly<Record<string, string>>): void;
}

/** Разделитель владельца и ключа в ключе с владельцем. */
const OWNER_SEPARATOR = ':';

/**
 * Ключ сообщения, текст которого лежит в словаре плагина-владельца: `<plugin-id>:<key>`.
 *
 * Нужен там, где строку переводит НЕ плагин, а тот, кто показывает, — уведомления и находки.
 * Показывающий общий на всех, и без владельца он знал бы только свой словарь: стек, пришедший
 * плагином, либо писал бы в словарь оболочки (которой его строки не принадлежат), либо
 * показывал бы маркер промаха. Ключ с владельцем переводится словарём владельца, голый — словарём
 * оболочки, как раньше.
 */
export function pluginMessageKey(pluginId: string, key: string): string {
  return `${pluginId}${OWNER_SEPARATOR}${key}`;
}

/** Владелец ключа (`null` — оболочка) и сам ключ без владельца. */
export function splitMessageKey(key: string): {
  readonly pluginId: string | null;
  readonly key: string;
} {
  const at = key.indexOf(OWNER_SEPARATOR);
  return at <= 0
    ? { pluginId: null, key }
    : { pluginId: key.slice(0, at), key: key.slice(at + OWNER_SEPARATOR.length) };
}
