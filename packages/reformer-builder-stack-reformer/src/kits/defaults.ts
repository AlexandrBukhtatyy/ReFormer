/**
 * Запасные значения ReFormer для вызовов, у которых нет дескриптора активного кита.
 *
 * Контракт кита живёт в SDK (`@reformer/builder-plugin-api`), и всё, что кит рассказывает о себе,
 * приходит из его каталога. Здесь — только то, что стеку ReFormer нужно и без кита:
 *
 * - **листья** для узла по умолчанию и обхода дерева, когда вызывающий дескриптора не передал
 *   (инструменты ассистента строят узлы без него). Совпадают с листьями встроенного кита: без
 *   дескриптора стек ведёт себя так, как вёл бы со встроенным китом;
 * - **ключи инфраструктуры** реестра renderer-json — имена, которыми схемы адресуют обёртку поля,
 *   границу загрузки и список. Это ключи РЕЕСТРА, а не экспорты кита: какими символами кит их
 *   поставляет, говорит `descriptor.infra`.
 *
 * Модуль — лист графа: без импортов, поэтому его можно тянуть из любого слоя стека без циклов.
 *
 * @module @reformer/builder-stack-reformer/kits/defaults
 */

/**
 * Листья по умолчанию: самодостаточный визуал, детей не держат. Тот же набор объявляет о себе
 * встроенный кит (`leaf: true` в его каталоге).
 */
export const LEAF_COMPONENT_NAMES: ReadonlySet<string> = new Set([
  'Icon',
  'Separator',
  'Spinner',
  'Skeleton',
  'Progress',
  'Tree',
]);

/**
 * Ключи инфраструктуры в реестре renderer-json: обёртка поля (`FIELD_WRAPPER`), граница
 * асинхронной загрузки и обёртка списка, которой схемы адресуют повторяющиеся узлы
 * (`{ array, component: '$component(List)', item.$template }`).
 *
 * `Wizard`/`Step` сюда не входят: они палитровые (синтетические записи каталога).
 */
export const INFRA_NAMES = ['FormField', 'AsyncBoundary', 'List'] as const;
