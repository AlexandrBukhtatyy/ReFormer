/**
 * `useFormBundle` — стабильность формы между рендерами, арминг живой валидации и снятие сборки
 * при размонтировании.
 *
 * Общий хук для всех фабрик семейства (`createForm`, `createReactForm`, `createJsonForm`):
 * пакеты рендера реэкспортируют его как `useReactForm` / `useJsonForm`, чтобы вызов читался в
 * терминах своего слоя.
 *
 * Фабрика вызывается РОВНО один раз — ленивым инициализатором `useState`. `useMemo` для этого не
 * годится: React вправе сбросить его кэш и пересобрать форму, потеряв введённое.
 *
 * ## Снятие сборки
 *
 * Сборкой владеет хук: её собрала его фабрика, значит, освобождать её больше некому. Без снятия
 * поведение формы (`compute`, `enableWhen`, …), подписки нод и идущие проверки жили после
 * размонтирования компонента.
 *
 * Снятие откладывается на микрозадачу и отменяется, если эффект запустился снова. StrictMode в
 * разработке (и Fast Refresh) размонтирует эффекты и тут же монтирует их над ТОЙ ЖЕ сборкой:
 * синхронный `dispose()` в очистке снял бы поведение и ноды живой формы, а вернуть их нечем —
 * переармировать умеет только контроллер живой проверки. Настоящее размонтирование повторного
 * запуска не даёт, и сборка снимается сразу после коммита.
 *
 * Очистка эффектов в React — не всегда размонтирование: скрытый `<Activity>` снимает эффекты и
 * хранит состояние. Если сборку успели снять, а эффект запустился снова (поддерево показали),
 * хук собирает новую сборку той же фабрикой: снятая форма не оживает, а мёртвая хуже свежей.
 * Введённое в скрытую форму при этом не сохраняется.
 *
 * @module platforms/react/hooks/use-form-bundle
 */

import { useEffect, useRef, useState } from 'react';
import type { FormValidationController } from '../../../form/validation/strategy';

/** Минимум, который хук ожидает от бандла: контроллер живой валидации и снятие — оба опционально. */
export interface FormBundleLike {
  validation?: { controller: FormValidationController };
  /** Снять сборку: поведение, подписки нод, живую проверку. Есть у всех фабрик семейства. */
  dispose?(): void;
}

/**
 * Собрать форму один раз и держать её стабильной; живую стратегию валидации армировать в эффекте
 * (не при SSR — там эффекты не выполняются); при размонтировании снять сборку.
 *
 * @typeParam B - Тип бандла конкретной фабрики.
 * @param factory - Фабрика бандла, обычно `() => createForm({…})`. Сборкой владеет хук: при
 *   размонтировании он вызывает её `dispose()`, поэтому фабрика должна собирать НОВУЮ форму, а не
 *   возвращать чужую, живущую дольше компонента.
 * @returns Стабильный бандл.
 *
 * @example
 * ```tsx
 * const credit = useFormBundle(() => createForm<CreditForm>({ model: createCreditModel() }));
 * ```
 *
 * @remarks
 * Передавайте именно фабрику: `useState` трактует функцию как ленивый инициализатор, а некоторые
 * части бандла сами являются функциями (`RenderSchemaProxy`), поэтому `useFormBundle(bundle.render)`
 * вызвал бы её вместо сохранения.
 *
 * Сборка снимается микрозадачей после размонтирования, а не в самой очистке эффекта (см. шапку
 * модуля): код, который сразу после размонтирования пишет в модель, ещё видит живое поведение.
 */
export function useFormBundle<B extends FormBundleLike>(factory: () => B): B {
  const [bundle, setBundle] = useState(factory);
  // Фабрика первого рендера: ею же собирается замена снятой сборки. Новая фабрика на ререндере
  // бандл не пересобирает — как и раньше.
  const [build] = useState(() => factory);
  /** Снятие, заказанное последней очисткой; повторный запуск эффекта над той же сборкой его отменяет. */
  const pending = useRef<{ bundle: B; cancelled: boolean; done: boolean } | null>(null);

  useEffect(() => {
    const previous = pending.current;
    if (previous?.bundle === bundle && previous.done) {
      // Сборку уже сняли, а эффект запустился снова — поддерево показали после скрытия. Замена
      // ставится из колбэка, как ответ внешней системы, а не телом эффекта: синхронный setState
      // здесь — лишний каскадный рендер. Если поддерево успели скрыть раньше, замена отменяется,
      // а билет остаётся — следующий показ попробует снова.
      let live = true;
      queueMicrotask(() => {
        if (live) setBundle(build());
      });
      return () => {
        live = false;
      };
    }
    pending.current = null;
    if (previous?.bundle === bundle) previous.cancelled = true;
    const stop = bundle.validation?.controller.start();
    return () => {
      stop?.();
      const disposal = { bundle, cancelled: false, done: false };
      pending.current = disposal;
      queueMicrotask(() => {
        if (disposal.cancelled) return;
        bundle.dispose?.();
        disposal.done = true;
      });
    };
  }, [bundle, build]);

  return bundle;
}
