/**
 * Признак «инструмент ничего не нашёл».
 *
 * Инструменты отвечают markdown-текстом для модели, а не структурой, и тупик выглядит как
 * обычный ответ — иногда довольно длинный: `find_recipe` при промахе печатает СПИСОК доступных
 * рецептов и алиасов. Отличить его от находки по длине или непустоте нельзя.
 *
 * Пока единственным потребителем был eval-харнесс, маркеры жили у него: там они защищали замер
 * от ложных попаданий (слабое ожидание вроде `["cross"]` совпадало со словом `cross` в списке
 * алиасов, и тупик засчитывался как решённая задача). Теперь их читает и фасад консумента,
 * которому надо решить, продолжать ли каскад, — и держать два списка в разных местах значило
 * бы, что первый же новый вид тупика узнает только один из них.
 *
 * Связь с текстами ответов хрупкая по своей природе. Она закреплена тестом
 * (`tests/empty-answer.test.ts`): каждый маркер обязан быть началом реального ответа хотя бы
 * одного инструмента.
 *
 * @module reformer-mcp/core/tools/empty-answer
 */

/** Начала ответов, которые означают «сервер ничего не нашёл». */
export const EMPTY_MARKERS = [
  // Найден тестом, а не вычитан из кода: фасад принимал этот ответ за находку и обрывал
  // каскад на первом же шаге, когда правило не сработало.
  'No decision rule matched',
  'No recipe found',
  'No curated recipe is registered',
  'No documentation sections matched',
  'No public symbols',
  'Symbol "',
  'Section "',
] as const;

/** `true`, если ответ — тупик, а не находка. */
export function isEmptyAnswer(text: string): boolean {
  const head = String(text).trimStart();
  return EMPTY_MARKERS.some((m) => head.startsWith(m));
}
