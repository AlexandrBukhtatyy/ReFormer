/**
 * Порт для текста постановки задачи («спеки»).
 *
 * Ссылка на спеку намеренно строка, а не путь: в CLI это путь на диске, в браузере — имя
 * файла, который пользователь бросил в панель, и содержимое уже лежит в памяти. Инструментам
 * (`plan_form`, `generate_form`) знать разницу незачем — им нужен текст.
 *
 * @module reformer-mcp/core/spec/source
 */

export interface SpecSource {
  /** Текст спеки по ссылке; `null` — недоступна. */
  read(ref: string): string | null;
  /**
   * Относительно чего резолвится ссылка — для сообщения «не найдено».
   *
   * Живёт в порте, а не в инструменте: рабочий каталог знает платформа, а ядру знать про
   * `process` нельзя (гейт `check:no-node-globals` это и поймал).
   */
  describe?(): string;
}

/** Источник-заглушка для сред, где спеку взять неоткуда. */
export const EMPTY_SPEC_SOURCE: SpecSource = { read: () => null };
