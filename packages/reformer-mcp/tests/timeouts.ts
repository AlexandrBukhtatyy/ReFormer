/**
 * Таймаут для тестов, которые разбирают TypeScript-AST всех пакетов.
 *
 * Зачем явно. Такой тест в изоляции занимает ~350 мс, но `vitest` гоняет файлы параллельными
 * воркерами, и каждый парсит заново (кэш парсера — на процесс). Под нагрузкой (например,
 * когда рядом идёт сборка монорепо) замерено 6-7 секунд, то есть выше дефолтных 5 000 мс —
 * и четыре теста разом падали по таймауту, хотя ни один инвариант не был нарушен.
 *
 * Дефолт поднимать глобально нельзя: он маскировал бы по-настоящему медленные тесты в
 * остальных файлах. Поэтому цена названа поимённо там, где она есть, — это и документация
 * тоже: тест с этим таймаутом заведомо тяжёлый.
 *
 * Убрать можно будет вместе с самим разбором AST: он остался только как фолбэк для пакетов
 * без `llms-index.json` (см. src/index/symbols.ts).
 */
export const AST_HEAVY_TIMEOUT_MS = 30_000;
