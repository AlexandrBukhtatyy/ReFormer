/**
 * Мост к dev-серверу приложения: то, что о странице знает только сборщик.
 *
 * Клиент билдера — обычный React, без единого обращения к сборщику: его компилирует приложение
 * своими настройками, и рассчитывать на `import.meta.hot` или на типы сборщика он не вправе.
 * А одна вещь нужна именно от dev-сервера — узнать, что он собрался перезагрузить страницу
 * (`./reload-hold`).
 *
 * Поэтому связь перевёрнута: плагин Vite (`vite/plugin.mjs`) кладёт на страницу приложения
 * маленький модуль, который заводит на глобальном объекте мост и пересылает в него события
 * dev-сервера. Клиент мост читает. Нет моста — плагин не подключён: билдера на этом сервере
 * нет, и компонент рисует одно приложение.
 *
 * Ключ — `Symbol.for`: модуль плагина и клиент не импортируют друг друга, и общего у них
 * только это имя.
 *
 * @module client/host-bridge
 */

import type { ReloadRequest } from './reload-hold';

/** Имя моста на глобальном объекте — то же, что в модуле, который кладёт плагин Vite. */
export const HOST_BRIDGE_KEY = Symbol.for('reformer.builder.host');

export interface HostBridge {
  /**
   * Dev-сервер просит перезагрузить страницу. Обещание, которое не завершается, перезагрузку
   * останавливает; `undefined` — пропускает.
   */
  beforeReload: ((request: ReloadRequest) => Promise<void> | undefined) | null;
}

/** Мост этой страницы либо `undefined`, если плагин билдера к dev-серверу не подключён. */
export function hostBridge(): HostBridge | undefined {
  return (globalThis as { [HOST_BRIDGE_KEY]?: HostBridge })[HOST_BRIDGE_KEY];
}
