/**
 * Модель того, что производит генерация: файл, его класс и данные, из которых он печатается.
 *
 * ## Почему это `lib/`, а не плагин
 *
 * Печать текста из схемы — чистая функция домена: одна и та же схема с одним и тем же китом
 * обязана дать один и тот же байт. Состояния здесь нет вовсе, поэтому по правилу раскладки
 * («чистое и без состояния — в `lib/`, состояние и жизненный цикл — в плагине») эмиссия живёт
 * тут, а РЕШЕНИЕ, какие файлы производить, — в `plugins/codegen`, где оно выражено вкладами.
 *
 * Второй потребитель у этой библиотеки появляется сразу: `plugins/templates` печатает
 * встроенные шаблоны теми же эмиттерами. В v1 для этого лежало 900 строк «рыб»
 * (`app/form-templates.ts`, `app/wizard-templates.ts`), которые повторяли вывод кодогена
 * руками — и расходились с ним при каждой правке эмиттера. Плагины друг друга не импортируют,
 * поэтому единственное место, где такой общий код может лежать, — `lib/`.
 *
 * @module lib/codegen/types
 */

/**
 * Класс файла: перезаписывать при повторной генерации или нет.
 *
 * `derived` — производное схемы; правки в нём обречены и потому перезаписываются молча.
 * `user` — то, что дописывает человек под свой бэкенд; пишется один раз.
 *
 * Третьего класса нет намеренно: «user-файл, который всё-таки производится из правил»
 * (`validation.ts`, `form.behavior.ts`, `renderer.behavior.ts`) — не класс файла, а свойство
 * ЦЕЛИ, и живёт оно у цели (`CodegenTarget.regenerable` в плагине). В v1 это был третий
 * литеральный набор имён в `codegen/deliver.ts`, который надо было держать синхронным с
 * четвёртым в `codegen/regenerate.ts`.
 */
export type FileClass = 'derived' | 'user';

/** Один сгенерированный файл. Путь — относительно каталога модуля формы. */
export interface GeneratedFile {
  readonly path: string;
  readonly content: string;
  readonly cls: FileClass;
}

/**
 * Мок-данные формы: начальные значения модели и значения источников.
 *
 * Форма совпадает с `PreviewMock` плагина превью, и это не совпадение: артефакт один и тот же —
 * авторские данные формы. Копия типа здесь потому, что `lib/` не может импортировать плагин,
 * а плагины — друг друга. Оба места ждут переезда артефакта в общий контракт.
 */
export interface FormMock {
  readonly model: Record<string, unknown>;
  readonly dataSources: Record<string, unknown>;
}
