/**
 * Шаблонизатор кодогенерации: единственный настроенный экземпляр Eta.
 *
 * ## Почему Eta, а не Handlebars, который уже есть в монорепо
 *
 * У Handlebars разделители `{{ }}`, а мы печатаем TSX, где `settings={{ fieldWrapper: FormField }}`
 * — обычная запись, а не выражение шаблона. В `packages/reformer-mcp` этот стык уже оплачен:
 * strict-режим разобрал JSX как выражение, промпт `start-here` отдавал клиенту JSON-RPC -32603,
 * и чинят это до сих пор рукописный пре-лексер, отдельный шаг CI и снапшот-тест. Разделители
 * Handlebars сменить нельзя. `<%` в валидном TS/TSX невозможен — ни один тип, оператор или
 * JSX-тег не начинается с `<` `%`.
 *
 * ## Почему `eta/core`, а не `eta`
 *
 * Корневой вход — это `class Eta extends EtaCore` ПЛЮС поля `readFile`/`resolvePath`, которые
 * тянут `node:fs` и `node:path`. В браузере это либо ошибка сборки, либо полифилл. На `eta/core`
 * оба поля равны `null`, поэтому поиск включений идёт сразу во внутренний стор — тот, что
 * заполняет `loadTemplate`. Файловой системы у шаблонов нет вовсе, и это не ограничение, а
 * требование: шаблон пользователя приезжает из источника проекта, а не с диска.
 *
 * ## Экземпляр один
 *
 * Кэш скомпилированных функций и стор включений живут В ЭКЗЕМПЛЯРЕ. Второй экземпляр означал бы
 * второй стор, то есть партиал, зарегистрированный одним, невидим другому — и отказ выглядел бы
 * как «включение не найдено» в шаблоне, который заведомо правильный.
 *
 * @module lib/codegen/render
 */

import { Eta } from 'eta/core';

const eta = new Eta({
  // Умолчание — `true`. Оно превратило бы `&&` в `&amp;&amp;`, а `<div>` в `&lt;div&gt;`:
  // мы печатаем КОД, а не HTML. Самая важная строка модуля, поэтому она же закреплена тестом.
  autoEscape: false,
  // Данные видны как `it`, а не разложены в область видимости: `with` — ошибка в strict-режиме,
  // а явный префикс к тому же делает вид шаблона читаемым без знания контракта.
  useWith: false,
  varName: 'it',
  tags: ['<%', '%>'],
  // Обрезки НЕТ — вопреки умолчанию Eta (`[false, 'nl']`), и это осознанный отказ от него.
  //
  // Умолчание снимает перевод строки сразу за КАЖДЫМ закрывающим тегом, а не только за
  // управляющим. То есть обычная подстановка в конце строки — `# <%= it.names.title %>` —
  // молча съедает перенос, и заголовок слипается со следующим абзацем. Отказ при этом
  // невидим в шаблоне: там перенос стоит на месте.
  //
  // Форматтера у нас нет (prettier не подключён намеренно), поэтому пробелы значащие, а
  // шаблоны пишет в том числе человек со стороны. Цена буквальности — `-%>` на управляющих
  // строках; цена умолчания — класс отказов «перенос пропал, а почему, не видно».
  autoTrim: [false, false],
  // Съел бы отступы — а отступ в генерируемом коде значащий.
  rmWhitespace: false,
  // Кэш по имени: шаблон компилируется один раз на своё содержимое (см. `loadOnce`).
  cache: true,
  // Ошибка исполнения печатается с номером строки и окном ±3 строки вокруг сбойной. Для
  // ШАБЛОНОВ ПОЛЬЗОВАТЕЛЯ это не удобство, а условие ремонтопригодности: без окна сообщение
  // выглядит как «Cannot read properties of undefined» без единого указания, где именно.
  debug: true,
});

/**
 * Что уже загружено и с каким исходником.
 *
 * Ключ — имя, значение — ТЕКСТ. Сверка по тексту, а не флагом «загружен», потому что
 * пользовательские шаблоны перечитываются: после правки файла имя то же, а тело другое, и
 * кэш отдал бы прежнюю скомпилированную функцию.
 */
const loaded = new Map<string, string>();

function loadOnce(name: string, source: string): void {
  if (loaded.get(name) === source) return;
  eta.loadTemplate(name, source);
  loaded.set(name, source);
}

/**
 * Зарегистрировать включение под именем — то, что шаблон зовёт как `include("имя", it)`.
 *
 * Отдельное имя вместо `renderTemplate` ради читаемости места вызова: партиал регистрируют
 * один раз при сборке, а рендерят его не здесь.
 */
export function registerPartial(name: string, source: string): void {
  loadOnce(name, source);
}

/**
 * Напечатать шаблон.
 *
 * Имя обязательно и не косметично: под ним шаблон лежит в кэше, и оно же попадает в сообщение
 * об ошибке. `renderString` имени не принимает — поэтому здесь `loadTemplate` + `render`,
 * а не однострочный вызов.
 *
 * Бросок наружу НЕ перехватывается: у `generateModule` уже есть путь «отказ цели — это запись
 * в отчёте», и сообщение Eta с окном строк доедет до панели как есть.
 */
export function renderTemplate(name: string, source: string, view: object): string {
  loadOnce(name, source);
  return eta.render(name, view);
}
