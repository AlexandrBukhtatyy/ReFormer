/**
 * Контракт канала к модели.
 *
 * Собственный интерфейс, а не тип из SDK, по двум причинам: адаптер конкретного SDK становится
 * заменяемым (и удаляемым) файлом, а тесты цикла получают сценарный провайдер без сети и ключей.
 *
 * Цикл вызовов держит ПРОВАЙДЕР: у современных SDK он встроен (`stopWhen`), и воспроизводить его
 * поверх — значит бороться с библиотекой. Наш код владеет исполнением инструментов ({@link AiToolDef.execute}),
 * то есть тем, что действительно должно оставаться под контролем редактора.
 *
 * @module reformer-builder/agent/providers/types
 */

import type { ToolOutcome } from '../core/types';

/** Реплика диалога. */
export interface AiMessage {
  role: 'user' | 'assistant';
  content: string;
}

/** Инструмент, отдаваемый модели. */
export interface AiToolDef {
  name: string;
  description: string;
  /** JSON Schema аргументов. */
  inputSchema: object;
  /**
   * Не меняет форму. Нужен провайдеру, чтобы схлопывать повторные ЧТЕНИЯ в накопленном контексте:
   * ответ пишущего инструмента устареть не может — он говорит о своей правке и ни о чём больше.
   */
  readOnly: boolean;
  /** Исполнение на стороне редактора. Провайдер отдаёт модели только `outcome.text`. */
  execute(args: unknown): Promise<ToolOutcome>;
}

/** Запрос к модели. */
export interface AiRequest {
  system: string;
  messages: readonly AiMessage[];
  tools: readonly AiToolDef[];
  /**
   * Предел шагов «модель → инструмент → модель» за один ход; `undefined` — без предела.
   *
   * Без предела ход идёт, пока модель не скажет, что закончила. Останавливают его в этом случае
   * только кнопка «Остановить» и таймаут потока — а предел, выставленный «на всякий случай»,
   * обрывал работу на середине формы и выдавал недоделанное за результат.
   */
  maxSteps?: number;
  /**
   * Потолок входных токенов на весь ход; `undefined` — без потолка.
   *
   * Считать шаги — плохая мера стоимости: цена шага растёт вместе с диалогом, и двадцать шагов в
   * начале хода стоят кратно меньше двадцати в конце. На платном канале ограничивать надо то, за
   * что платят, поэтому предел выражен в токенах, а не в вызовах.
   */
  maxInputTokens?: number;
}

/**
 * Расход токенов на одном шаге.
 *
 * Нужен не для счёта денег, а как единственный объективный измеритель оптимизаций: «стало быстрее»
 * на глаз неотличимо от «модель в этот раз сходила удачнее». Все поля необязательны — локальные
 * серверы сообщают в лучшем случае суммарный вход, и отсутствие цифры это не ошибка.
 *
 * `cachedInputTokens` — единственное доказательство, что кэш префикса реально сработал: без него
 * «включили кэширование» проверяется только счётом в биллинге через сутки.
 */
export interface AiUsage {
  inputTokens?: number;
  cachedInputTokens?: number;
  cacheWriteTokens?: number;
  outputTokens?: number;
}

/**
 * Чем именно кончился ход.
 *
 * Существует потому, что `reason: 'complete'` отвечает на вопрос «дошли ли до конца потока», а не
 * «закончила ли модель работу». Локальный сервер, замолчавший на переполнении окна, закрывает поток
 * штатно и причины не сообщает вовсе — снаружи это неотличимо от законченной работы, и ход с
 * недоделанной формой выглядел как успешный.
 *
 * Поля необязательны все: провайдер, который ничего не сообщил, не должен выдумывать за себя
 * причину — отсутствие цифры честнее выдуманной.
 */
export interface AiStop {
  /** Унифицированная причина провайдера: `stop`, `length`, `tool-calls`, `other`… */
  reason?: string;
  /**
   * Причина в том виде, в каком её назвал сервер. У локальных серверов она информативнее
   * унифицированной: та схлопывает в `other` и «модель договорила», и «сервер молча закрыл поток».
   */
  raw?: string;
  /**
   * Имя инструмента, вызов которого модель начала и не дописала.
   *
   * Единственный признак обрыва, который виден ВСЕГДА, чем бы провайдер ни назвал причину:
   * аргументы инструмента приходят потоком, и незакрытый вызов означает, что вывод кончился
   * посреди JSON. Правка при этом не применяется вовсе — пакет всё-или-ничего.
   */
  truncatedCall?: string;
  /**
   * Ход кончился, не сказав ни слова и не вызвав ни одного инструмента.
   *
   * Второй признак обрыва — и для локального канала главный. Оборванный JSON аргументов у него
   * до нас не доходит (сервер добирает вызов из накопленного и падает разбор, что видно как
   * ошибка инструмента), зато обрыв ДО вызова выглядит именно так: пришло одно рассуждение, а
   * потом поток закрылся. По протоколу пустой ответ — аномалия: модель либо отвечает, либо
   * зовёт инструмент, поэтому пустота здесь не осторожная догадка, а надёжный признак.
   */
  emptyFinish?: boolean;
}

/** Событие потока. */
export type AiEvent =
  | { type: 'delta'; text: string }
  /**
   * Ход рассуждения модели. Отдельно от `delta` намеренно: это черновик мысли, а не ответ — в
   * ленту он идёт свёрнутым и в историю диалога не возвращается. Но и терять его нельзя: у
   * think-моделей весь поток до первого инструмента приходит именно сюда, и без него панель
   * выглядит зависшей, а обрыв на пределе длины — беспричинным.
   */
  | { type: 'reasoning'; text: string }
  | { type: 'tool_call'; id: string; name: string; args: unknown }
  | { type: 'tool_result'; id: string; result: ToolOutcome }
  /** Шаг закончен: расход токенов. Провайдер, не сообщающий его, просто не шлёт событие. */
  | { type: 'step_usage'; usage: AiUsage }
  | { type: 'error'; message: string; retryable: boolean }
  | { type: 'done'; reason: 'complete' | 'aborted' | 'error'; stop?: AiStop };

/** Возможности канала. */
export interface AiCapabilities {
  streaming: boolean;
  /**
   * Умеет ли модель вызывать инструменты. Без этого правки схемы невозможны в принципе, и такой
   * провайдер не предлагается как канал редактирования — молчаливый отказ был бы хуже.
   */
  tools: boolean;
  images: boolean;
  /** Коды языков; отсутствие нужного — основание предупредить пользователя. */
  languages: readonly string[];
}

/** Результат проверки доступности. */
export interface AiDetection {
  available: boolean;
  reason?: string;
}

/** Канал к модели. */
export interface AiProvider {
  readonly id: string;
  readonly displayName: string;
  /** Где исполняется запрос: влияет на предупреждения интерфейса о том, куда уходит текст. */
  readonly origin: 'browser' | 'loopback';
  detect(): Promise<AiDetection>;
  capabilities(): AiCapabilities;
  stream(req: AiRequest, signal?: AbortSignal): AsyncIterable<AiEvent>;
}
