/**
 * Контракты слоя `agent/core` — машиночитаемая поверхность операций редактора.
 *
 * Слой намеренно НЕ знает ни про React, ни про `store/`: инструмент получает схему во входе и
 * возвращает новую схему в выходе. Это даёт два свойства, ради которых слой и разделён:
 *  - его можно покрыть юнитами принятыми в проекте средствами (`environment: 'node'`,
 *    `include: ['src/**\/*.test.ts']` — `.tsx`-тестов в билдере нет);
 *  - ход агента правит ЧЕРНОВИК, а не активную вкладку, поэтому применение результата —
 *    один `editorActions.replaceSchema`, то есть ровно одна запись undo.
 *
 * Адресация узлов — JSON Pointer (RFC 6901) поверх существующих `toPointer`/`fromPointer`
 * (`model/paths`), см. {@link module:reformer-builder/agent/core/node-ref}.
 *
 * @module reformer-builder/agent/core/types
 */

import type { JsonFormSchema } from '@reformer/renderer-json';
import type { FormRules } from '../../model/rules';

/**
 * Бюджет текста ответа инструмента (символы). Ограничение не протокольное, а экономическое:
 * ответ инструмента уходит в контекст модели на КАЖДОМ шаге цикла, поэтому дайджест обязан быть
 * дешевле полного JSON — иначе смысл дайджеста теряется. Реестр обрезает превышение.
 */
export const TOOL_TEXT_BUDGET = 1500;

/** Бюджет имени инструмента (символы). Проверяется тестом, а не в рантайме. */
export const TOOL_NAME_BUDGET = 30;

/** Бюджет описания инструмента (символы). Проверяется тестом, а не в рантайме. */
export const TOOL_DESCRIPTION_BUDGET = 500;

/**
 * Бюджет ВСЕЙ поверхности инструментов: имена, описания и схемы аргументов вместе (символы).
 *
 * Отдельно от {@link TOOL_DESCRIPTION_BUDGET} потому, что дорого не отдельное описание, а сумма:
 * поверхность уходит в запрос ЦЕЛИКОМ на каждом шаге, а шагов за ход десятки. Тринадцать
 * инструментов, каждый из которых честно уложился в свои 500 символов, вместе стоят дороже
 * системного промпта вчетверо.
 *
 * Число — храповик, а не цель: оно равно достигнутому размеру и его СНИЖАЮТ по мере сжатия схем.
 * Поднимать нельзя — рост поверхности обязан быть осознанным решением, а не побочным эффектом
 * очередного уточнения в описании.
 *
 * Второй случай, когда число не изменилось при добавлении инструмента: справка по библиотеке
 * (`ask_reformer`, 368 символов) вошла за счёт сжатия остальных описаний на 366 — убрано то,
 * что модель уже знает из системного промпта или из описания самого инструмента. Потолок при
 * этом опустился с 7700 до фактического размера: место, освобождённое один раз, не должно
 * молча превратиться в запас под следующую правку.
 *
 * Осознанных повышений за всю историю три.
 *
 * Первое — пакетные аргументы (`nodes[]`, `refs[]`, `props{}`): прибавили около трёхсот
 * символов КАЖДОМУ запросу, но убрали из эталонной задачи одиннадцать обращений к модели, а
 * каждое обращение несёт весь контекст целиком. Размен выгоден примерно на два порядка.
 *
 * Второе — правила формы (`set_form_rules`, 1259 символов, потолок 7686 → 8946). Здесь размен
 * не в шагах, а в том, что происходит БЕЗ инструмента, и это измерено живым прогоном
 * (gemma4:26b, отчёт — docs/mcp-eval/builder-rules.md). На просьбу «сделай email обязательным»
 * агент без него зовёт `set_node_prop`, ход завершается как успешный, форма выглядит
 * изменённой — а валидации нет. Отказ был бы дешевле: ложное «готово» пользователь обнаружит
 * у себя, а не в редакторе. С инструментом выбор верен 4/4, включая две задачи, где правила
 * трогать НЕ надо, — то есть плата за него не растеклась на соседние ходы.
 *
 * Третье — поведение UI (`set_render_rules`, 971 символ, потолок 8946 → 9917). Размен снова не в
 * шагах: без инструмента у агента НЕТ способа задать условную видимость, событие узла или
 * динамический проп — правил render-слоя не принимал ни один инструмент, потому что селектором
 * никто не управлял. Замер на `qwen3.8:27b` (`agent/core/render-rules-eval.test.ts`, отчёт —
 * docs/mcp-eval/builder-render-rules.md): выбор верен 4/4, причём в обеих НЕцелевых задачах новый
 * инструмент не вызывался вовсе — то есть плата за поверхность не растеклась на соседние ходы.
 */
export const TOOL_SURFACE_BUDGET = 9917;

/**
 * Бюджет системного промпта (символы) — вторая половина постоянной части запроса.
 *
 * Тот же храповик, что и у поверхности: промпт отправляется на каждом шаге, поэтому строка,
 * добавленная «на всякий случай», умножается на число шагов и на число ходов.
 *
 * С одной оговоркой, которой нет у поверхности: часть промпта — не текст, а КАТАЛОГ. Имена всех
 * полей кита перечислены поимённо намеренно (первый `list_components` становится необязательным,
 * см. `prompt.ts`), поэтому промпт растёт вместе с китом, а не только с правками этого файла.
 * Значит и двигать константу можно ровно по этой причине: 4000 → 4100 понадобилось, когда в кит
 * приехали `ComboboxTree` и `ComboboxTreeMulti`. Для прозы храповик прежний — сжимать, а не
 * поднимать.
 */
export const PROMPT_BUDGET = 4100;

/**
 * Код ошибки инструмента. Коды существуют, чтобы модель чинилась САМА: по коду и `suggestions`
 * она понимает, что именно поправить, вместо «что-то пошло не так».
 */
export type ToolErrorCode =
  /** Имени нет в каталоге. `suggestions` — похожие имена. */
  | 'UNKNOWN_COMPONENT'
  /** `componentProps` не прошли схему компонента. */
  | 'INVALID_PROPS'
  /** Указатель никуда не ведёт либо ведёт не в тот узел (проверка `expect`). */
  | 'STALE_POINTER'
  /** Родитель не принимает детей либо слот не существует. */
  | 'INVALID_PARENT'
  /** Результат не прошёл строгий гейт валидации. */
  | 'SCHEMA_INVALID'
  /** Аргументы вызова не соответствуют `inputSchema`. */
  | 'INVALID_PARAMS'
  /** Инструмента с таким именем нет. `suggestions` — похожие имена. */
  | 'UNKNOWN_TOOL'
  /** Инструмент бросил исключение. Цикл продолжается: модель получает ошибку и пробует иначе. */
  | 'TOOL_FAILED';

/** Структурированная ошибка инструмента. */
export interface ToolError {
  code: ToolErrorCode;
  message: string;
  /** Кандидаты на замену (имена компонентов, имена инструментов). */
  suggestions?: string[];
}

/** Вид операции для списка изменений в предпросмотре. */
export type ChangeOpKind = 'add' | 'update' | 'remove' | 'move';

/** Одна операция хода агента — строка списка изменений в предпросмотре. */
export interface ChangeOp {
  kind: ChangeOpKind;
  /** Указатель затронутого узла ПОСЛЕ операции. */
  ref: string;
  /** Человекочитаемое описание: «Email (Input)», «Email → обязательное». */
  summary: string;
}

/** Вход инструмента: черновик хода и база, от которой считается diff. */
export interface ToolContext {
  /** Схема черновика — то, что инструмент читает и правит. НЕ схема активной вкладки. */
  readonly draft: JsonFormSchema;
  /** Схема на начало хода: база для diff и для проверки конфликта при применении. */
  readonly base: JsonFormSchema;
  /**
   * Правила формы черновика (валидация, поведение, видимость).
   *
   * Отдельно от схемы, а не внутри неё, потому что контракт `@reformer/renderer-json` закрыт:
   * `additionalProperties: false` и на корне, и в `meta`. См. `model/rules`.
   */
  readonly rules: FormRules;
}

/** Результат вызова инструмента. */
export interface ToolOutcome {
  ok: boolean;
  /** Текст для модели. Реестр обрезает до {@link TOOL_TEXT_BUDGET}. */
  text: string;
  /** Новая схема черновика. Есть только у write-инструментов при `ok: true`. */
  schema?: JsonFormSchema;
  /** Новые правила формы. Есть только у инструментов, правящих правила, при `ok: true`. */
  rules?: FormRules;
  /**
   * Строки для списка изменений. Есть только у write-инструментов при `ok: true`.
   *
   * Список, а не одна операция: инструменты принимают пакет (несколько узлов за вызов), а
   * предпросмотр обязан показывать каждую правку отдельной строкой — «добавлено 12 полей» одной
   * строкой невозможно ни проверить, ни отменить осмысленно.
   */
  ops?: readonly ChangeOp[];
  /** Заполнено при `ok: false`. */
  error?: ToolError;
}

/** Одна операция редактора, описанная машиночитаемо. */
export interface AgentTool<P = never> {
  /** Идентификатор вызова, snake_case. */
  readonly name: string;
  /** Для чего инструмент и когда его выбирать. */
  readonly description: string;
  /** JSON Schema аргументов — сырой объект, как в инструментах `@reformer/mcp` (без zod). */
  readonly inputSchema: object;
  /** Не меняет схему. Определяет, попадёт ли вызов в список изменений. */
  readonly readOnly: boolean;
  /**
   * Выполнить операцию.
   *
   * Возвращать промис разрешено, но нежелательно: ответ инструмента уходит в контекст модели
   * на каждом шаге, и асинхронный шаг задерживает весь ход. Асинхронность оправдана там, где
   * данные физически не в памяти — например, справка по библиотеке грузит корпус лениво.
   */
  run(params: P, ctx: ToolContext): ToolOutcome | Promise<ToolOutcome>;
}

/** Успешный ответ read-only инструмента. */
export function ok(text: string): ToolOutcome {
  return { ok: true, text };
}

/** Ответ с ошибкой. */
export function fail(code: ToolErrorCode, message: string, suggestions?: string[]): ToolOutcome {
  return {
    ok: false,
    text: suggestions?.length ? `${message} Did you mean: ${suggestions.join(', ')}.` : message,
    error: { code, message, ...(suggestions?.length ? { suggestions } : {}) },
  };
}
