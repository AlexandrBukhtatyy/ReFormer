/**
 * Встроенный кит — тот, с которым инструмент открывается «из коробки».
 *
 * Каталог берётся из САМОГО ПАКЕТА (`@reformer/ui-kit/catalog` — это его
 * `component-catalog.json`), а не из копии в билдере. Копия отстала бы от кита ровно на одно
 * обновление: компонент в ките есть, в палитре его нет, и виноватого не найти. Здесь же
 * рассинхронизация невыразима — источник один, и он в зависимостях.
 *
 * Импорт внешнего пакета из плагина законен: плагину запрещено видеть `@/shell` и соседние
 * плагины, а библиотеки — нет. Именно так плагин и должен поставлять предметное знание.
 *
 * ## Почему динамический импорт, а не статический
 *
 * Цена измерена: каталог весит **864 кБ**, и статический импорт клал их в главный чанк —
 * 1497 кБ raw / 362 кБ gzip против 659 / 212 без него. Платили все и сразу, а нужен каталог
 * не раньше, чем открыт файл формы. Динамический импорт уводит его в собственный чанк, и
 * оболочка стартует, не дожидаясь дизайн-системы.
 *
 * ## Почему шапка
 *
 * Каталог ленивый, а представиться кит обязан ДО загрузки: список китов и ключ выбора нужны
 * раньше, чем приедет каталог. Раньше шапки не было, и личность встроенного кита достраивали
 * таблицы «неявного кита» билдера; теперь кит называет себя сам — в каталоге, — а шапка
 * повторяет ровно имя, подпись и пакет. Служба сверяет имя шапки с загруженным каталогом, так
 * что разойтись они не могут молча.
 *
 * ## Почему приведение типа
 *
 * JSON приходит в TypeScript структурным литеральным типом, и он ЧУЖОЙ контракту
 * {@link CatalogJson}: `role` в нём выведется как `string`, а не как объединение ролей.
 * Проверять его по-настоящему умеет проверка контракта (ajv по `component-catalog.schema.json`),
 * а не компилятор, поэтому приведение здесь — честная граница «данные снаружи», локализованная
 * в одном месте, а не рассыпанная по потребителям.
 *
 * @module plugins/kits/registry/builtin
 */

import type {
  CatalogJson,
  CatalogLoader,
  KitNamespace,
  KitSource,
} from '@reformer/builder-plugin-api';

/** Загрузчик каталога встроенного кита. Отдельный чанк — в этом весь смысл. */
export const loadBuiltinCatalog: CatalogLoader = () =>
  import('@reformer/ui-kit/catalog').then((module) => module.default as unknown as CatalogJson);

/**
 * Поля кита за подпутём: в главный вход они не входят из-за своих зависимостей
 * (`react-day-picker`, `cmdk`, `input-otp`), но каталог называет их полями формы наравне
 * с остальными. Без них палитра предлагала бы поле, которое превью рисует заглушкой, а тема RJSF
 * оставляла бы дату стандартному виджету (ReFormer-9r8q).
 *
 * Только поля: `chart`, `carousel` и прочие подпути форме не нужны, и грузить их ради неё незачем.
 */
const loadFieldSubpaths = (): Promise<readonly object[]> =>
  Promise.all([
    import('@reformer/ui-kit/calendar'),
    import('@reformer/ui-kit/combobox'),
    import('@reformer/ui-kit/date-picker'),
    import('@reformer/ui-kit/input-otp'),
  ]);

/**
 * Компоненты встроенного кита — самый крупный чанк приложения, поэтому тоже загрузчиком: нужен он
 * только тому, кто рисует форму по-настоящему.
 *
 * Главный вход ложится последним: одноимённый экспорт из него побеждает подпуть.
 */
export const loadBuiltinNamespace = async (): Promise<KitNamespace> => {
  const [main, subpaths] = await Promise.all([import('@reformer/ui-kit'), loadFieldSubpaths()]);
  return Object.freeze(Object.assign({}, ...subpaths, main)) as KitNamespace;
};

/** Встроенный кит: шапка для списка до загрузки, каталог и компоненты — загрузчиками. */
export const BUILTIN_KIT: KitSource = Object.freeze({
  kit: Object.freeze({
    id: 'reformer-ui-kit',
    label: 'ReFormer UI Kit',
    package: '@reformer/ui-kit',
  }),
  catalog: loadBuiltinCatalog,
  namespace: loadBuiltinNamespace,
});
