/**
 * Порт платформы для управления плагинами каталога: ровно то, чем пользуется палитра.
 *
 * ## Почему порт, а не импорт
 *
 * Плагин видит платформу только через `@reformer/builder-plugin-api` (проверяется линтером), а каталога плагинов
 * в `@reformer/builder-plugin-api` нет и не будет: управлять списком исполняемого кода — привилегия композиции,
 * и раздавать её каждому плагину значило бы отдать границу доверия тому, кого она держит.
 * Поэтому недостающее приходит ПАРАМЕТРОМ — тем же приёмом, что у плагинов файлов и китов.
 *
 * Типы здесь — СТРУКТУРНЫЕ надмножества платформенных: `ProjectPluginCatalog` присваивается
 * в {@link PluginManagerHost} как есть, и совместимость проверяется компиляцией в месте
 * подстановки (`application/composer/builtin-plugins.ts`). Отдельного адаптера в композиции нет:
 * порт совпадает с каталогом по форме, и переходник был бы файлом из одних делегаций.
 *
 * ## Почему этим занимается ПЛАГИН
 *
 * У корневого реестра вкладов нет `contribute` — точки расширения заполняются только
 * плагинами, и это правило проверяется отсутствием пути (см. `primitives/extension-point`).
 * Пункты палитры «включить/выключить/перезагрузить» — вклад, значит их вносит плагин;
 * то, что предмет вклада — сами плагины, ничего в правиле не меняет.
 *
 * @module plugins/plugin-manager/host
 */

/**
 * Перевод в пространстве имён плагина. Функция, а не хук: пункты палитры собираются
 * в момент запроса, а не в отрисовке (см. одноимённый тип у плагина китов).
 */
export type Translate = (key: string, params?: Record<string, unknown>) => string;

/** Состояние строки — то же, что у каталога: найден-выключен, работает, не грузится. */
export type ManagedPluginState = 'disabled' | 'enabled' | 'failed';

/** Строка списка в объёме, нужном пунктам палитры. */
export interface ManagedPlugin {
  readonly id: string;
  readonly name: string;
  readonly version?: string;
  readonly state: ManagedPluginState;
  /** Помечен «в разработке»: наблюдается, перезагружается при правке файлов. */
  readonly dev: boolean;
  /** Слой, из которого взят плагин: каталог проекта или установленное из npm. */
  readonly layer?: 'project' | 'installed';
  /** Почему `failed`. Достаточно текста — код разбора палитре ни к чему. */
  readonly problem?: { readonly message: string };
}

export interface PluginManagerHost {
  /** Снимок списка плагинов каталога проекта. */
  list(): readonly ManagedPlugin[];
  /** Загружает и активирует. Для упавшего это и есть «попробовать снова». */
  enable(id: string): Promise<boolean>;
  /** Снимает вклады, помнит решение человека. */
  disable(id: string): void;
  /** Снимает вклады, перечитывает файлы, поднимает заново. */
  reload(id: string): Promise<boolean>;
  /** Ставит или снимает пометку «в разработке». */
  setDev(id: string, on: boolean): void;
  /** Перечитывает каталог проекта: так в списке появляется только что созданный плагин. */
  refresh(): Promise<unknown>;
  /**
   * Ставит плагин из npm, спросив имя пакета у человека.
   *
   * Имя спрашивает КОМПОЗИЦИЯ, а не палитра: диалоги — служба оболочки, и плагин не должен
   * получать её ради одного поля ввода. Пункт палитры выражает намерение, остальное
   * происходит там, где для этого есть средства.
   *
   * Необязателен намеренно: сборка без установки из реестра (профиль без неё, окружение без
   * OPFS) обязана работать, а палитра — не показывать пункт, который ничего не сделает.
   */
  install?(): Promise<void>;
  /** Убирает установленный плагин целиком. Плагина из каталога проекта не касается. */
  uninstall?(id: string): Promise<void>;
  /**
   * Переключает установленный плагин на другую уже скачанную версию.
   *
   * Откат существует ради одного случая, зато обязательного: новая версия сломала работу.
   * Скачивать для этого заново нечего — прошлые версии остаются на диске, — поэтому операция
   * не ходит в сеть вовсе и работает без неё.
   */
  rollback?(id: string): Promise<void>;
}
