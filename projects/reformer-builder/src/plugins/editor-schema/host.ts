/**
 * Порт платформы для редактора схемы формы: ровно то, чем он пользуется, и ничего сверх.
 *
 * ## Почему порт, а не импорт
 *
 * Плагин видит платформу только через `@/sdk` (проверяется линтером), а в `@/sdk` сегодня нет
 * ни точки `document.model`, ни рабочей области, ни сервиса локализации. Недостающее приходит
 * ПАРАМЕТРОМ — тем же приёмом, каким объявляет свою потребность `plugins/files/host`:
 * потребность объявляет потребитель, а удовлетворяет её композиция.
 *
 * Типы здесь СТРУКТУРНЫЕ копии платформенных, и это не второй контракт, а его сужение: каждая
 * обязана быть присваиваемой настоящей ({@link SchemaModelProviderSpec} →
 * `DocumentModelProvider<unknown>`). Проверяется это компиляцией в одном месте — там, где
 * композиция подставляет настоящую точку расширения.
 *
 * ## Чего в порту нет
 *
 * Реестров, оболочки, чужих документов, буфера. Раньше здесь были три глагола над текстом
 * (прочитать, подписаться на смену, записать) — и ровно из них плагин был вынужден собрать
 * копию модельного документа: историю, отсев собственного эха, состояние расхождения.
 * Теперь композиция отдаёт готовую ручку ({@link SchemaModelHandle}), и текст из порта ушёл
 * целиком: редактор схемы правит модель, а буфер по ней перерисовывает платформа.
 *
 * Сохранение в источник — по-прежнему не его дело, и способа его вызвать здесь нет.
 *
 * @module plugins/editor-schema/host
 */

import type { ComponentType } from 'react';
import type { JsonFormSchema } from '@reformer/renderer-json';
import type { CatalogEntry } from '@/lib/catalog/types';
import type { FormRules } from '@/lib/form-model/rules';
import type {
  Diagnostic,
  Disposable,
  DocumentModelProvider,
  EditOp,
  NodeId,
  ResourceId,
  ResourceRef,
} from '@/sdk';

/**
 * Типизированное имя точки расширения — структурная копия `host/primitives/extension-point`.
 *
 * Эта копия остаётся, и осознанно: она описывает не модель, а САМ реестр, поэтому разойтись
 * с платформой по смыслу не может — `__type` существует только для вывода типов, а ключом
 * служит `id`. Копии, которые пришлось снять, были другого сорта: они описывали предметную
 * область (модель документа), и у платформы на неё своё, более широкое мнение.
 */
export interface ExtensionPointRef<T> {
  readonly id: string;
  readonly __type?: T;
}

/**
 * Точка провайдеров модели и словарь правок — НАСТОЯЩИЕ, из `@/sdk`.
 *
 * Здесь были структурные копии `ExtensionPointRef`, `EditOp`, `ApplyResult` и
 * `DocumentModelProvider`. Они появились потому, что `@/sdk` точки модели не отдавал,
 * и немедленно разошлись с оригиналом: копия описывала точку СВОЕЙ модели, а настоящая
 * точка держит `DocumentModelProvider<unknown>` — ядро моделей не различает, потому что
 * держит их разом несколько. Компилятор поймал это на композиции, в единственном месте,
 * где обе стороны встречаются.
 *
 * Провайдер конкретной модели вносится в общую точку без приведения: методы в TypeScript
 * бивариантны, поэтому провайдер `JsonFormSchema` годится там, где ждут `unknown`.
 */
export type { ApplyResult, EditOp, NodeId } from '@/sdk';

/** Провайдер модели схемы формы: тот же контракт платформы, суженный до своей модели. */
export type SchemaModelProviderSpec = DocumentModelProvider<JsonFormSchema>;

/** Согласован ли буфер с моделью. Структурная копия `DocumentSyncState` платформы. */
export type SyncState = 'synced' | 'diverged';

/** Что вызвало смену состояния модельного документа. */
export type SchemaModelChangeReason = 'apply' | 'parse' | 'undo' | 'redo' | 'selection';

/**
 * Модельный документ — в объёме, нужном редактору схемы.
 *
 * Читающее лицо: модель, выделение, состояние согласованности. Здесь нет ни `getText`,
 * ни записи в буфер — редактор схемы правит МОДЕЛЬ, а буфер по ней перерисовывает платформа,
 * откладывая перерисовку, пока в текстовом редакторе печатает человек. Отдельного канала
 * записи у плагина нет, и это граница прав, а не неудобство.
 */
export interface SchemaModelDocument {
  readonly ref: ResourceRef;
  /** Последняя валидная модель. В расхождении — та, что была до поломки буфера. */
  getModel(): JsonFormSchema;
  getSyncState(): SyncState;
  /** `undefined`, когда согласовано. Текста для человека тут нет — только сообщение разбора. */
  getParseFailure(): { readonly message: string } | undefined;
  getSelection(): readonly NodeId[];
  onDidChangeModel(cb: (change: { readonly reason: SchemaModelChangeReason }) => void): Disposable;
}

/** Отказ применить операцию. Не исключение: оба случая — нормальные состояния, а не аварии. */
export type SchemaApplyOutcome =
  | { readonly status: 'applied'; readonly inverse: EditOp; readonly focus?: NodeId }
  | {
      readonly status: 'rejected';
      readonly reason: 'diverged' | 'provider-error';
      readonly error?: unknown;
    };

/**
 * Ручка модельного документа — пишущее лицо: правка операциями, история, выделение.
 *
 * Структурная копия `ModelDocumentHandle<JsonFormSchema>` платформы, суженная до того,
 * чем редактор пользуется. Здесь нет `flush` и `dispose`: перерисовку буфера по уходу фокуса
 * заказывает текстовый редактор, а время жизни ручки принадлежит тому, кто открыл документ.
 */
export interface SchemaModelHandle {
  readonly document: SchemaModelDocument;
  /** `mergeKey` — ключ схлопывания истории, обычно `свойство@узел` (см. `./ops`). */
  apply(op: EditOp, options?: { readonly mergeKey?: string }): SchemaApplyOutcome;
  setSelection(selection: readonly NodeId[]): void;
  undo(): boolean;
  redo(): boolean;
  /** Ответит ли `undo` согласием: расхождение учитывается платформой здесь же. */
  canUndo(): boolean;
  canRedo(): boolean;
}

/** Перевод в пространстве имён плагина. */
export type Translate = (key: string, params?: Record<string, unknown>) => string;

/**
 * Служба диагностик — в объёме «читать и следить».
 *
 * Сужение намеренное: публикует находки валидатор, а редактор их только показывает.
 * Настоящая служба объявлена в `@/sdk`, поэтому плагин берёт её из `ctx.services` сам
 * и через порт композиции она не идёт — но принимает её редактор вот в этом объёме,
 * а не целиком: право писать в общий свод у него отсутствует не по договорённости,
 * а потому, что метода нет в типе.
 */
export interface SchemaDiagnostics {
  get(resource: ResourceId): readonly Diagnostic[];
  onDidChange(cb: (resource: ResourceId) => void): Disposable;
}

/**
 * Приёмник словарей — вид сервиса локализации для плагина (`PluginI18n.contribute`).
 *
 * В `PluginContext` его нет, поэтому словарь регистрирует не `activate`, а тот, кто этот
 * приёмник даст. Необязателен: без него плагин работает, а строки показываются маркерами
 * промаха — ровно так, как задумано в i18n.
 */
export interface MessageSink {
  contribute(locale: string, messages: Readonly<Record<string, string>>): void;
}

/**
 * Правила формы САЙДКАРОМ: их держит не схема, а тот, кто их и так хранит.
 *
 * `JsonFormSchema` — закрытый контракт рендерера (`additionalProperties: false`), положить
 * правила внутрь нельзя, поэтому они живут рядом отдельным файлом. Редактору схемы они нужны
 * ровно за одним: быстрое исправление «убрать осиротевшее правило» обязано его убрать.
 * Читать и писать — потому что снятие правила выражается только заменой списка целиком.
 *
 * Отдельного канала истории у сайдкара нет: `Ctrl+Z` в редакторе отменяет правку СХЕМЫ,
 * а не удаление правила. Это ограничение названо, а не спрятано: исправление предлагают,
 * но не применяют само (см. `validator-schema/check`.`orphanRules`), — и решение стереть
 * принимает человек.
 */
export interface SchemaRulesPort {
  /** Правила документа; `null` — сайдкара у этого документа нет. */
  get(id: ResourceId): FormRules | null;
  /** Записывает правила документа целиком. */
  set(id: ResourceId, rules: FormRules): void;
}

/**
 * Что живой вид даёт поверхности, которая рисует форму.
 *
 * Структурная копия части `PreviewContext` — самая опасная в этом файле, потому что описывает
 * ПРЕДМЕТНОЕ (урок Э6: такие копии разъезжаются). Смягчено тем, что копия сведена к пяти членам,
 * а всё остальное — адрес документа, мок-данные, хранилище введённых значений, имя источника
 * находок — достраивает композиция, там же, где обе стороны встречаются и где расхождение
 * поймает компилятор.
 *
 * Схема идёт ОТСЮДА, а не из буфера документа: редактор правит модель, а буфер по ней
 * перерисовывается с задержкой, пока в текстовом редакторе печатают. Возьми поверхность схему
 * из буфера — форма отставала бы от канваса ровно на эту задержку.
 */
export interface LiveSurfaceContext {
  /** Разобранная схема; `null` — буфер не разбирается. Ссылка обязана быть стабильной. */
  schema(): JsonFormSchema | null;
  onDidChangeSchema(cb: () => void): Disposable;
  selection(): readonly NodeId[];
  onDidChangeSelection(cb: () => void): Disposable;
  /** Обратная связь хит-теста поверхности: она сообщает, куда ткнули. */
  select(ids: readonly NodeId[]): void;
  /** Находки сборки — уже сведёнными строками: словарь превью встраивающему не принадлежит. */
  report?(messages: readonly string[]): void;
}

/**
 * Чем нарисована форма — в объёме, которым живой вид принимает решения.
 *
 * Возможностей здесь три из пяти, и отобраны они по тому, на что живой вид РЕАГИРУЕТ:
 * без `hitTest` и `sameRealm` он не вешает обработчиков вовсе (чужой realm читать нечем),
 * а `executesCode` отвечает на вопрос человека «почему моя валидация молчит».
 */
export interface LiveSurfaceInfo {
  readonly id: string;
  /** Уже переведённое имя: словарь превью живому виду не принадлежит. */
  readonly title: string;
  readonly hitTest: boolean;
  readonly sameRealm: boolean;
  readonly executesCode: boolean;
  /** Уже переведённая причина, по которой выбрана не самая способная поверхность. */
  readonly notice: string | null;
}

/**
 * Живой рендер формы — чужая поверхность, отданная редактору схемы композицией.
 *
 * Тот же приём и та же причина, что у {@link SchemaEditorHost.TextEditor}: рисовать форму умеет
 * плагин превью, а импортировать его отсюда нельзя. Композиция читает точку расширения
 * `preview.surface`, применяет к ней общее правило выбора и отдаёт сюда результат — поэтому
 * форма в редакторе и форма в панели превью нарисованы ОДНОЙ поверхностью, а не двумя похожими.
 */
export interface LivePreviewPort {
  /** Есть ли кому рисовать вовсе: плагин превью могли выключить. */
  available(): boolean;
  /** Чем будет нарисован этот документ; `null` — показывать нечем. */
  chosen(documentId: ResourceId): LiveSurfaceInfo | null;
  /**
   * Смонтировать форму в элемент; `null` — не за что было взяться.
   *
   * Элемент создаёт вызывающий и отдаёт целиком: поверхность рисует в него своим корнем React.
   */
  mount(documentId: ResourceId, element: HTMLElement, ctx: LiveSurfaceContext): Disposable | null;
  /**
   * Состав поверхностей или выбор человека для ЭТОГО документа изменились.
   *
   * Документом, а не общим потоком: выбор поверхности принадлежит документу, и подписка
   * без адреса не узнала бы о его смене — а это ровно то, что человек делает в панели превью,
   * ожидая, что форма в редакторе изменится вместе с ней.
   */
  onDidChange(documentId: ResourceId, cb: () => void): Disposable;
}

/** Всё, что редактор схемы получает от композиции. */
export interface SchemaEditorHost {
  /**
   * Реактивный перевод. Хук, а не функция: локаль меняется, и компонент обязан
   * перерисоваться — подписку на смену локали держит композиция.
   */
  useTranslate(): Translate;

  /**
   * Перевод кода диагностики словарём **Host**, а не плагина.
   *
   * То же разделение, что в порту Monaco, и по той же причине: метку на узле рисует
   * канвас, но владеет текстом тот, кто завёл код, — а коды лежат общим списком
   * (`errors.<code>` в словаре Host), потому что одна и та же ошибка обязана выглядеть
   * одинаково на канвасе, в редакторе и в панели проблем. **Ключ передаётся голым
   * кодом**, без приставки: её ставит композиция.
   *
   * Необязателен: без него метка покажет сам код. Читаемо для разработчика, но не для
   * человека — композиции стоит его дать той же строкой, что у Monaco.
   */
  useDiagnosticMessage?(): Translate;

  /**
   * Ручка модельного документа открытой вкладки.
   *
   * `null` означает три разных вещи, и редактору они одинаковы: вкладка ещё открывается,
   * вкладку закрыли, документ текстовый (провайдер за него не взялся или первый разбор
   * не удался). Во всех трёх случаях править нечего.
   *
   * Модель, история и запись буфера принадлежат платформе — здесь их СПРАШИВАЮТ, а не
   * повторяют. Ровно это и есть разница с прежним сеансом плагина.
   */
  modelOf(id: ResourceId): SchemaModelHandle | null;

  /**
   * Адрес активной вкладки; `null` — открытых нет.
   *
   * Нужен командам, вызванным из палитры или с клавиши: у кнопки в полосе вкладок документ
   * приходит аргументом, а у палитры аргументов нет вовсе.
   */
  activeDocument?(): ResourceId | null;

  /**
   * Тело редактора кода — для показа схемы исходником.
   *
   * Компонент, а не флаг: плагин не выбирает редактор и не знает, чей он (`plugins/**`
   * не импортируют друг друга). Композиция подставляет то же тело, которым правится обычная
   * code-вкладка, поэтому «показать текстом» — это тот же самый редактор, а не его копия.
   *
   * Отсутствие означает, что режима исходника нет вовсе: кнопка не рисуется.
   */
  readonly TextEditor?: ComponentType<{ documentId: ResourceId }>;

  /**
   * Каталог активного кита.
   *
   * Функция, а не список: кит переключают, и палитра с инспектором обязаны показывать тот
   * каталог, который действует СЕЙЧАС, а не тот, что был на активации плагина.
   */
  /**
   * Каталог активного кита. Читается на КАЖДЫЙ вызов, а не захватывается: кит переключают,
   * и кроме того каталог грузится лениво — до загрузки он честно пуст.
   */
  catalog(): readonly CatalogEntry[];
  /**
   * Подписка на смену каталога: кит переключили либо ленивый каталог догрузился.
   *
   * Обязательна, а не удобна. Без неё панели читают каталог в отрисовке и переход
   * «пусто → загружено» до них не доходит: React не знает, что снаружи что-то изменилось.
   * Сегодня это незаметно только по совпадению — плагин китов заказывает загрузку при
   * активации, задолго до того как человек откроет первый файл формы. На первом же
   * переключении кита в рантайме палитра осталась бы от прежнего.
   */
  onCatalogChange(cb: () => void): Disposable;

  /** Порядок разделов палитры из конфига клиента; без него — умолчание домена. */
  categoryOrder?(): readonly string[] | undefined;

  /**
   * Перевод ключа словарём **Host** БЕЗ приставки — для подписей быстрых исправлений.
   *
   * Отдельно от {@link useDiagnosticMessage}, хотя словарь тот же: тот приписывает `errors.`,
   * потому что получает голый код находки, а `QuickFix.titleKey` — уже полный ключ
   * (`quickfix.replace-component`). Приписать ему приставку значило бы промахнуться мимо
   * словаря, а завести подписи в словаре плагина — получить две разные фразы для одного
   * исправления: на канвасе и в панели проблем.
   *
   * Необязателен: без него на кнопке виден сам ключ. Читаемо для разработчика, но не для
   * человека, — композиции стоит его дать той же строкой, что и остальным портам.
   */
  useQuickFixTitle?(): Translate;

  /**
   * Живой рендер формы.
   *
   * Отсутствие означает, что четвёртого представления нет вовсе: кнопка не рисуется, а
   * запомненное предпочтение «показывать формой» падает на дерево. Так и бывает — плагин
   * превью выключаемый.
   */
  readonly live?: LivePreviewPort;

  /**
   * Правила-сайдкар открытых документов.
   *
   * Необязателен, и от него зависит, будет ли вообще зарегистрирована команда `rules.remove`
   * (см. `./commands`): чинить осиротевшее правило, не имея правил, нечем.
   */
  readonly rules?: SchemaRulesPort;
}
