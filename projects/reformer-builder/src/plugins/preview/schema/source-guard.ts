/**
 * Запрет исполнения по источнику — то самое место, где решается, можно ли монтировать
 * компилирующую поверхность.
 *
 * Правило контракта Э8 дословно: **поверхность с `executesCode: true` не монтируется, если
 * у источника документа `capabilities.executesCode === false`**. Умолчание для всего, кроме
 * локальной файловой системы, — `false`.
 *
 * ## Почему это отдельный модуль, а не проверка внутри поверхности
 *
 * Проверку обязан выполнять тот, кто МОНТИРУЕТ, а не тот, кого монтируют: поверхность, которая
 * проверяет себя сама, защищает ровно себя, а точка расширения открыта для чужих вкладов.
 * Ровно так же устроен загрузчик плагинов: `host/plugin/loader` отказывает ДО того, как код
 * плагина коснулся линковщика, а не внутри самого плагина.
 *
 * ## Отказ ВИДЕН
 *
 * Функция возвращает данные, а не бросает и не молчит. Тихая подмена режима хуже отказа:
 * пользователь будет думать, что видит результат своего кода, а увидит форму без сайдкаров.
 * Поэтому причина отказа доезжает до интерфейса отдельным полем и показывается словами —
 * см. {@link '../surface/selection'}, где отказ превращается в откат на более бедную поверхность.
 *
 * ## Неизвестный источник — это отказ
 *
 * `null` (источника нет, проект закрыт, документ уже закрыли) трактуется как запрет. Обратное
 * означало бы, что дырой в учёте источников открывается исполнение кода, и обнаружилась бы она
 * не здесь, а в чужом коде, который исполнился.
 *
 * @module plugins/preview/schema/source-guard
 */

import type { PreviewCapabilities } from '../contract';
import type { PreviewSourceCapabilities } from '../host';

/** Почему поверхность не монтируется. Причины различаются, потому что чинятся по-разному. */
export type PreviewRefusalReason =
  /** Источник объявил `executesCode: false` — код оттуда не исполняется. */
  | 'source-forbids-code'
  /** Источник неизвестен: проект закрыт или документ уже закрыт. */
  | 'source-unknown';

/** Решение о монтировании. */
export type MountDecision =
  | { readonly allowed: true }
  | { readonly allowed: false; readonly reason: PreviewRefusalReason };

const ALLOWED: MountDecision = Object.freeze({ allowed: true });

/**
 * Можно ли смонтировать поверхность с такими возможностями над документом такого источника.
 *
 * Чистая функция от двух наборов признаков — ни документа, ни рабочей области здесь нет
 * намеренно: решение зависит ровно от двух вещей, и всё остальное в сигнатуре было бы
 * приглашением проверить заодно что-нибудь ещё.
 *
 * Поверхность, не исполняющая код, монтируется ВСЕГДА, в том числе при неизвестном источнике:
 * каркас и рантайм ничего не исполняют, и запрещать их значило бы оставлять человека без
 * превью вовсе там, где оно безопасно.
 */
export function canMountSurface(
  capabilities: PreviewCapabilities,
  source: PreviewSourceCapabilities | null
): MountDecision {
  if (!capabilities.executesCode) return ALLOWED;
  if (source === null) return { allowed: false, reason: 'source-unknown' };
  if (!source.executesCode) return { allowed: false, reason: 'source-forbids-code' };
  return ALLOWED;
}

/** Ключ сообщения об отказе в словаре плагина. Текст — дело словаря, соответствие — этого модуля. */
export function refusalMessageKey(reason: PreviewRefusalReason): string {
  return `refusal.${reason}`;
}
