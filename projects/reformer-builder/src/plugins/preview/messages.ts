/**
 * Словарь плагина: локаль → ключ → сообщение.
 *
 * Словари везёт плагин: имя поверхности разрешается в пространстве имён ВНЁСШЕГО её плагина,
 * поэтому одинаковый ключ у двух плагинов — два разных сообщения, и словарь Host для них
 * невыразим. Читает эти строки не сам плагин — своего интерфейса у него нет, — а живой вид
 * редактора схемы, которому композиция даёт уже переведённое (см. `app/live-surface`).
 *
 * Файлы JSON, а не литералы в `.ts`: словарь правит переводчик, а не автор кода, и формат,
 * в котором нельзя случайно написать выражение, для этого лучше.
 *
 * @module plugins/preview/messages
 */

import en from './locales/en.json';
import ru from './locales/ru.json';

/** Локаль → ключ (без пространства имён) → сообщение. */
export const PREVIEW_MESSAGES: Readonly<Record<string, Readonly<Record<string, string>>>> =
  Object.freeze({ ru, en });
