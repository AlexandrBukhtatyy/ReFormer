/**
 * Перенос введённых значений в пересобранную форму.
 *
 * ## Почему переносим значения, а не саму модель
 *
 * Соблазн очевиден: отдать `createJsonForm` прежнюю `FormModel` и ничего не терять. Так нельзя.
 * Модель строит дерево сигналов из НАЧАЛЬНЫХ значений, и `resolveSignalAt` ищет узел по этому
 * дереву; на путь, которого в нём нет, она отвечает `undefined`, а рендерер пишет
 * «No form node for signal …» и рисует пустоту. Модель, созданная под старую схему, не умеет
 * отращивать листья под новую — а в конструкторе схема меняется каждую секунду.
 *
 * Поэтому переносится СОДЕРЖИМОЕ: новая форма собирается своими начальными значениями, а поверх
 * ложится то из прежних, чему в новой форме есть место.
 *
 * ## Правила переноса, и почему они такие
 *
 * - **ключ есть только в новых** — берётся новое: поле только что добавили, и у него свой дефолт;
 * - **ключ есть только в прежних** — отбрасывается: путь из схемы убрали, значению негде жить;
 * - **оба объекта** — рекурсия: группа полей переносится по полю, а не целиком;
 * - **оба массива** — берётся прежний ЦЕЛИКОМ: человек добавил три элемента, и они его, а не
 *   мока. Слияние по индексам здесь было бы хуже: при перестановке элементов оно перемешало бы
 *   значения между ними;
 * - **типы разошлись** — берётся новое. Поле переделали из строки в число, и старая строка
 *   не значение, а мусор, который контрол не покажет.
 *
 * Функция чистая и ничего не мутирует: `previous` приходит из живой модели, и правка на месте
 * означала бы правку формы, которую прямо сейчас показывают.
 *
 * @module plugins/preview/runtime/carry
 */

/** Форма данных модели превью: она приходит из схемы, и сузить её нечем. */
type Shape = Record<string, unknown>;

function isPlainObject(value: unknown): value is Shape {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * Начальные значения новой формы с перенесённым содержимым прежней.
 *
 * `base` — то, что новая форма получила бы без переноса (мок плюс `model.ts`); `previous` —
 * снимок модели прежней формы. `undefined` означает «переносить нечего», и тогда `base`
 * возвращается ТОЙ ЖЕ ссылкой: лишний объект здесь стоил бы пересборки на ровном месте.
 */
export function carryValues(base: Shape, previous: Shape | undefined): Shape {
  if (previous === undefined) return base;

  const out: Shape = {};
  for (const [key, next] of Object.entries(base)) {
    if (!Object.hasOwn(previous, key)) {
      out[key] = next;
      continue;
    }
    const kept = previous[key];
    if (isPlainObject(next) && isPlainObject(kept)) {
      out[key] = carryValues(next, kept);
    } else if (Array.isArray(next) && Array.isArray(kept)) {
      out[key] = kept;
    } else if (sameKind(next, kept)) {
      out[key] = kept;
    } else {
      out[key] = next;
    }
  }
  return out;
}

/**
 * Одного ли рода значения.
 *
 * `typeof` мало: `null` и объект неразличимы, а массив и объект — тем более. Оба этих случая
 * до сюда доходят (поле без значения в моке — это `null`), и спутать их значило бы положить
 * в контрол то, чего он не ждёт.
 */
function sameKind(a: unknown, b: unknown): boolean {
  if (a === null || b === null) return a === b;
  if (Array.isArray(a) !== Array.isArray(b)) return false;
  return typeof a === typeof b;
}
