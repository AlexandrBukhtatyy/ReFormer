/**
 * Порт платформы для предпросмотра markdown: ровно то, чем он пользуется, и ничего сверх.
 *
 * Плагин видит платформу только через `@/sdk` (проверяется линтером), а рабочей области,
 * вкладок и чужих редакторов в ней нет. Недостающее приходит ПАРАМЕТРОМ — тем же приёмом,
 * которым порт объявляют плагины файлов и Monaco: потребность объявляет потребитель,
 * а удовлетворяет её композиция.
 *
 * ## Редактор кода приходит сюда, а не импортируется
 *
 * Режим «рядом» показывает исходник слева и рендер справа. Исходник умеет рисовать плагин
 * Monaco, но `plugins/**` не импортируют друг друга — это правило слоёв, а не неудобство.
 * Поэтому редактор внедряется компонентом ({@link MarkdownHost.TextEditor}) — ровно так же,
 * как диалог слияния получает свой редактор пропом. Композиция подставляет тот же самый
 * `Body` редактора Monaco, что рисует обычную code-вкладку, поэтому «рядом» и «код» — это
 * буквально один и тот же редактор, а не его урезанная копия.
 *
 * Без порта режим «рядом» просто отсутствует: {@link availableViews} его не покажет.
 *
 * @module plugins/editor-markdown/host
 */

import type { ComponentType } from 'react';
import type { Disposable, ResourceId, ResourceRef } from '@/sdk';

/** Перевод в пространстве имён плагина. */
export type Translate = (key: string, params?: Record<string, unknown>) => string;

/** Открытый документ в объёме, нужном предпросмотру: текст и его изменения. */
export interface MarkdownDocument {
  readonly ref: ResourceRef;
  getText(): string;
  onDidChangeContent(cb: (text: string) => void): Disposable;
}

/** Всё, что предпросмотр получает от композиции. */
export interface MarkdownHost {
  /**
   * Реактивный перевод. Хук, а не функция: локаль меняется, и компонент обязан
   * перерисоваться — подписку на смену локали держит композиция.
   */
  useTranslate(): Translate;

  /**
   * Адрес активной вкладки или `null`.
   *
   * Нужен командам, вызванным ИЗ ПАЛИТРЫ или с клавиши: у кнопки в строке вкладок документ
   * приходит аргументом, а у палитры аргументов нет вовсе.
   */
  activeDocument?(): ResourceId | null;

  /** Документ открытой вкладки или `null`, если она ещё открывается. */
  documentOf(id: ResourceId): MarkdownDocument | null;

  /**
   * Байты ресурса — для картинок предпросмотра.
   *
   * Байты, а не текст: картинка в проекте это `.png`, и чтение её текстом портит содержимое
   * молча. `null` — файла нет; для предпросмотра это обычный случай (опечатка в ссылке),
   * а не сбой, поэтому отказом он не выражается.
   */
  readBytes(id: ResourceId): Promise<Uint8Array | null>;

  /**
   * Адрес ресурса по пути ОТ КОРНЯ ИСТОЧНИКА того же документа.
   *
   * Сам путь считает плагин (`resolveRelativePath`), потому что правила markdown знает он.
   * Собрать из пути адрес может только платформа: разбор `ResourceId` — её дело.
   */
  resourceAt(document: MarkdownDocument, projectPath: string): ResourceId;

  /**
   * Открыть ресурс вкладкой — переход по ссылке на соседний файл.
   *
   * Необязателен: без него ссылки внутри проекта остаются текстом, и это видно на глаз,
   * а не выглядит поломкой.
   */
  openResource?(id: ResourceId): void;

  /**
   * Тело текстового редактора для режима «рядом».
   *
   * Компонент, а не флаг: плагин не выбирает редактор и не знает, чей он. Отсутствие
   * означает, что режима «рядом» нет — см. `./view`.
   */
  readonly TextEditor?: ComponentType<{ documentId: ResourceId }>;
}
