/**
 * Порт редактора Monaco: ровно то, чем пользуется тело редактора, и ничего сверх.
 *
 * ## Зачем порт, если всё есть в контексте
 *
 * Тело редактора пишется против ЭТОГО интерфейса, а не против пяти служб и точки расширения:
 * тест подставляет порт целиком, а компонент не знает, из чего он собран. Собирает его сам
 * плагин — из служб SDK (`./host-from-context`). Раньше порт собирала оболочка и ради этого
 * импортировала плагин; теперь оболочка о плагине не знает.
 *
 * Типы здесь — сужения контрактов SDK до нужного редактору: настоящий `Document` присваивается
 * в {@link MonacoDocument}, настоящая `DiagnosticsService` — в {@link MonacoDiagnostics}.
 * Совместимость проверяется компиляцией там, где порт собирается.
 *
 * ## Чего в порту нет
 *
 * Реестров, оболочки, источника, модели документа. Редактор не открывает чужих документов,
 * не сохраняет в источник и не правит модель: правка идёт **в буфер через рабочую область**,
 * а что с ней сделает провайдер модели — не его дело (см. `docs/editors-and-preview.md`).
 *
 * @module plugins/base/editor-monaco/host
 */

import type {
  Diagnostic,
  Disposable,
  DocumentNodeAnchor,
  JsonSchemaHint,
  ResourceId,
  ResourceRef,
  TextCompletion,
  TextStringSite,
} from '@reformer/builder-plugin-api';

/** Перевод: ключ и параметры сообщения. Совпадает по форме с `I18nService.t`. */
export type Translate = (key: string, params?: Record<string, unknown>) => string;

/**
 * Открытый документ — в объёме, нужном текстовому редактору.
 *
 * `getText` — то, что уйдёт в файл при сохранении. Записать в него можно только через
 * {@link MonacoHost.writeText}, то есть через рабочую область: отдельного канала записи
 * у плагина нет, и это граница прав, а не неудобство.
 *
 * `kind` здесь НЕ объявлен намеренно. Для текстового редактора модельный документ ничем
 * не отличается от обычного: он правит буфер, а перерисовку буфера по модели откладывает
 * рабочая область по признаку фокуса (см. `focus.ts`). Знай Monaco про два вида документа,
 * ему пришлось бы решать за платформу, что истина.
 */
export interface MonacoDocument {
  readonly ref: ResourceRef;
  getText(): string;
  onDidChangeContent(cb: (text: string) => void): Disposable;
}

/** Служба диагностик — в объёме «читать и следить». Публикует не редактор, а валидаторы. */
export interface MonacoDiagnostics {
  get(resource: ResourceId): readonly Diagnostic[];
  onDidChange(cb: (resource: ResourceId) => void): Disposable;
}

/** Приёмник словаря: `PluginI18n.contribute` в объёме, которым пользуется плагин. */
export interface MessageSink {
  contribute(locale: string, messages: Readonly<Record<string, string>>): void;
}

/** Всё, что редактор получает от оболочки. Собирает порт сам плагин — `./host-from-context`. */
export interface MonacoHost {
  /**
   * Реактивный перевод в пространстве имён плагина. Хук, а не функция: локаль меняется,
   * и компонент обязан перерисоваться — подписку на смену локали держит композиция.
   */
  useTranslate(): Translate;

  /**
   * Перевод кода диагностики словарём **Host**, а не плагина.
   *
   * Разделение то же, что у заголовков команд в плагине файлов: строку рисует редактор,
   * но владеет ею тот, кто завёл код, — а коды диагностик лежат общим списком
   * (`errors.<code>` в словаре Host), потому что одна и та же ошибка обязана выглядеть
   * одинаково в редакторе, в панели проблем и в логе.
   *
   * **Ключ передаётся голым кодом** (`schema.unknown-component`), без префикса: приставку
   * `errors.` ставит реализация. Иначе редактор знал бы раскладку чужого словаря, и её
   * изменение чинилось бы правкой всех, кто диагностику показывает, — а показывать её
   * будут ещё панель проблем и подсказка на файле в дереве.
   */
  useDiagnosticMessage(): Translate;

  /** Документ открытой вкладки или `null`, если её уже закрыли. */
  documentOf(id: ResourceId): MonacoDocument | null;

  /** Пишет в рабочую копию. В источник не пишет ничего и никогда — для этого есть `save`. */
  writeText(id: ResourceId, text: string): Promise<void>;

  /** Читается ли такой ресурс текстом. Правило платформенное — таблица медиатипов у неё. */
  isTextual(mediaType: string): boolean;

  /** Свод диагностик документа: подписка и чтение. */
  readonly diagnostics: MonacoDiagnostics;

  /**
   * Где узлы модели документа: идентификатор → путь значения в JSON от корня файла.
   *
   * Нужен разметке диагностик у документа, в тексте которого идентификаторы ещё не записаны
   * (они попадают в файл при первом сохранении, а форма из кодогена не сохранялась ни разу).
   * Модель их уже выдала — в памяти, — и путь узла в ней совпадает с путём объекта в тексте.
   * Перевод «путь → диапазон» редактор делает сам по своему тексту (`diagnostics/node-ranges`).
   *
   * `null` — у документа нет модели (текстовый, чужого вида) или она не согласована с буфером:
   * пути расходящейся модели указывали бы на объекты, которых в тексте уже нет.
   *
   * Необязателен: без него узлы без идентификатора остаются в нерешённых, как было.
   */
  locateNodes?(id: ResourceId): ReadonlyMap<string, readonly (string | number)[]> | null;

  /**
   * Как узел записан в тексте документа: ключ идентификатора и «говорящий» ключ.
   *
   * Знание формата — отвечает провайдер модели, как и на {@link locateNodes}. У файла части
   * составного документа отвечает провайдер документа, в который он входит. `null` — модели
   * нет или формат ключей не объявил: узлы тогда находятся только по пути.
   *
   * Необязателен: без него редактор не находит в тексте ни одного идентификатора.
   */
  nodeAnchorFor?(id: ResourceId): DocumentNodeAnchor | null;

  /**
   * JSON Schema формата документа — для подсказок: ключи, допустимые значения, описания.
   *
   * Отвечает провайдер модели документа, как и на {@link locateNodes}: схема — знание о формате.
   * `null` — у документа нет модели или провайдер схемы не даёт. Проверкой схема не служит:
   * `validate: false` в языковой службе остаётся, находки идут общим сводом.
   */
  jsonSchemaFor?(id: ResourceId): JsonSchemaHint | null;

  /** Схема документа устарела (сменился кит) — спросить {@link jsonSchemaFor} заново. */
  onDidChangeJsonSchema?(id: ResourceId, cb: () => void): Disposable;

  /**
   * Подсказки в строковом значении под курсором — то, что зависит от содержимого документа
   * (пути модели). Пустой список — подсказывать нечего.
   */
  completeString?(id: ResourceId, site: TextStringSite): readonly TextCompletion[];

  /**
   * Выполнить отложенную перерисовку буфера по модели. Зовётся на уходе фокуса.
   *
   * Необязателен: у документа без провайдера модели откладывать нечего, и композиция
   * вправе его не давать. Соответствует `ModelDocumentHandle.flush`.
   */
  flush?(id: ResourceId): void | Promise<void>;
}
