/**
 * Порт платформы для ассистента: ровно то, чем он пользуется, и ничего сверх.
 *
 * ## Почему порт, а не импорт
 *
 * Плагин видит платформу только через `@/sdk` (проверяется линтером), а рабочей области и
 * сервиса локализации там нет — это состав сданной поверхности, а не упущение. Недостающее
 * приходит ПАРАМЕТРОМ, тем же приёмом, что у `plugins/editor-monaco/host.ts` и
 * `plugins/files/host.ts`: потребность объявляет потребитель, а удовлетворяет её композиция.
 *
 * Типы здесь СТРУКТУРНЫЕ копии платформенных и обязаны быть их сужением: настоящий `Document`
 * присваивается в {@link AiDocument}. Проверяется это компиляцией в одном месте — там, где
 * `app/ai-host` подставляет настоящие объекты Host.
 *
 * ## Чего в порту нет
 *
 * Реестров, оболочки, источника, модели документа, сохранения. Всё, что ассистент делает с
 * рабочей областью, выражено тремя глаголами: узнать активную вкладку, прочитать её буфер,
 * записать в него. **Записать — значит `Workspace.writeText`**, тот же путь, которым правит
 * человек: отдельного канала записи у ассистента нет, и это граница прав, а не неудобство.
 *
 * ## Почему переводов два
 *
 * `useTranslate` — хук для панели: локаль меняется, и компонент обязан перерисоваться.
 * {@link AiHost.translate} — обычная функция для МОСТА: замечание к ходу («правки не
 * применены — форма закрыта») пишется в ленту вне React, там хука быть не может, а строка
 * обязана быть переведённой в момент записи. Разные вызывающие, разные формы одного сервиса.
 *
 * @module plugins/ai/host
 */

import type { CatalogEntry } from '@/lib/catalog/types';
import type { Disposable, ResourceId, ResourceRef } from '@/sdk';
import type { PackageFiles } from './knowledge';

/** Перевод: ключ и параметры сообщения. Совпадает по форме с `I18nService.t`. */
export type Translate = (key: string, params?: Record<string, unknown>) => string;

/**
 * Открытый документ — в объёме, нужном ассистенту.
 *
 * `getText` — то, что лежит в рабочей копии СЕЙЧАС. Оно же основание для проверки конфликта:
 * ход длится минуты, и за это время текст могли поправить руками.
 *
 * Записать в документ можно только через {@link AiHost.writeText}, то есть через рабочую
 * область.
 */
export interface AiDocument {
  readonly ref: ResourceRef;
  getText(): string;
  onDidChangeContent(cb: (text: string) => void): Disposable;
}

/**
 * Пометка правки для журнала — структурная копия `WriteOptions` рабочей области.
 *
 * СУЖЕНА до двух происхождений из трёх: `'external'` означает правку, пришедшую извне
 * приложения, и назвать её ассистенту нечем и незачем. Сужение параметра законно и проверяется
 * компилятором в одном месте — там, где `app/ai-host` подставляет настоящую рабочую область:
 * функция, принимающая БОЛЬШЕ, присваивается той, что принимает меньше.
 */
export interface WriteMark {
  readonly origin?: 'user' | 'agent';
  /** Логический шаг: ход ассистента отменяется целиком, даже если записей в буфер было две. */
  readonly txId?: string;
}

/** Приёмник словаря: `PluginI18n.contribute` в объёме, которым пользуется плагин. */
export interface MessageSink {
  contribute(locale: string, messages: Readonly<Record<string, string>>): void;
}

/** Всё, что ассистент получает от композиции. */
export interface AiHost {
  /** Реактивный перевод для панели. Подписку на смену локали держит композиция. */
  useTranslate(): Translate;
  /** Перевод для моста — см. «Почему переводов два» в шапке модуля. */
  translate: Translate;

  /** Идентификатор активной вкладки или `null`. */
  activeResource(): ResourceId | null;
  /** Документ открытой вкладки или `null`, если её уже закрыли. */
  documentOf(id: ResourceId): AiDocument | null;
  /**
   * Пишет в рабочую копию. В источник не пишет ничего и никогда — для этого есть `save`.
   *
   * `options` — пометка для журнала, и ассистент ей ПОЛЬЗУЕТСЯ: своя запись уходит с
   * `origin: 'agent'` (см. `./apply`). Без пометки журнал считал бы автором человека, и
   * ход ассистента был бы неотличим от правки руками — то есть аудит терял бы главное.
   */
  writeText(id: ResourceId, text: string, options?: WriteMark): Promise<void>;

  /**
   * Каталог активного кита.
   *
   * Функция, а не список: кит переключают, и ход обязан идти против того каталога, который
   * действует СЕЙЧАС, а не против того, что был на активации плагина.
   */
  catalog(): readonly CatalogEntry[];

  /**
   * Чтение файлов открытого проекта — источник корпуса знаний о версиях, которые стоят у
   * пользователя. `undefined` (или функция, вернувшая `undefined`) — проекта нет, останется
   * вшитый корпус.
   */
  projectFiles?(): PackageFiles | undefined;
}
