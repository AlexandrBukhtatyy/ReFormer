/**
 * Кто сейчас печатает — единственный вопрос, от которого зависит перерисовка буфера.
 *
 * ## Зачем реестр, а не флаг в компоненте
 *
 * Ответ «в фокусе ли текстовый редактор ЭТОГО документа» нужен двоим, и оба вне React:
 *
 * - **рабочей области** — `createModelDocument({ isTextEditorFocused })` откладывает
 *   перерисовку буфера из `print(model)`, пока человек печатает (иначе ход ассистента
 *   затрёт набранное на полуслове);
 * - **самому редактору** — внешняя правка буфера применяется по тому же правилу.
 *
 * Флаг внутри компонента виден только React'у, а спрашивают его из документа, который
 * про React не знает. Поэтому состояние живёт в маленьком реестре: компонент его пишет,
 * платформа читает функцией.
 *
 * ## Почему ключ — документ, а не «редактор вообще»
 *
 * Вкладок много, буфер у каждой свой. Один общий флаг означал бы, что набор в одной вкладке
 * замораживает перерисовку во всех остальных, — и ход ассистента в соседнем файле повис бы
 * до ухода фокуса отсюда.
 *
 * Реестр намеренно ничего не знает ни про Monaco, ни про DOM: это `Map` с двумя операциями,
 * и проверяется он в `node` целиком.
 *
 * @module plugins/editor-monaco/sync/focus
 */

import type { ResourceId } from '@/sdk';

export interface MonacoFocusRegistry {
  /** В фокусе ли текстовый редактор этого документа. */
  isFocused(id: ResourceId): boolean;
  /** Сообщает о смене фокуса. `false` снимает запись, а не хранит её: пустая карта дешевле. */
  setFocused(id: ResourceId, focused: boolean): void;
  /** Есть ли фокус хоть где-нибудь. Нужно диагностике и тестам. */
  hasFocus(): boolean;
}

/**
 * Создаёт реестр фокуса.
 *
 * Один на приложение: его создаёт композиция, отдаёт плагину и им же отвечает рабочей области.
 * Два реестра означали бы два разных ответа на один вопрос.
 */
export function createFocusRegistry(): MonacoFocusRegistry {
  const focused = new Set<ResourceId>();
  return {
    isFocused: (id) => focused.has(id),
    setFocused(id, value) {
      if (value) focused.add(id);
      else focused.delete(id);
    },
    hasFocus: () => focused.size > 0,
  };
}
