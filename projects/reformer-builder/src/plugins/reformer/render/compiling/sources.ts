/**
 * Какие файлы составляют форму — то самое ПРЕДМЕТНОЕ знание, ради которого `plugins/base/preview`
 * существует отдельно от `host/modules`.
 *
 * Платформа умеет транспилировать и линковать любой набор «путь → исходник» и не знает, что
 * такое форма. Здесь — знание: сайдкары лежат в каталоге схемы (у визарда — ещё и в
 * `steps/<шаг>/`), исполняются только `.ts`/`.tsx`, страница-обёртка, фикстура и тесты
 * не исполняются никогда.
 *
 * ## Почему `fixture.ts` исключена
 *
 * Она лежит в каталоге формы, но сайдкаром не является: фикстура ПОДСТАВЛЯЕТ модули формы
 * (`./api`), а сайдкары их импортируют. В одном графе `api.ts` исполнился бы дважды — раз как
 * импорт фикстуры, раз как импорт сайдкара, — и форма получила бы два разных объекта под одним
 * именем (разбор — в `./fixture`). Графы собираются врозь, и разделяет их только имя файла.
 *
 * ## Читается рабочая КОПИЯ, а не источник
 *
 * Это то, ради чего рабочая копия вообще существует. Буфер редактора и есть файл: правка,
 * не сохранённая на диск, обязана попасть в превью — иначе «поменял валидацию, ничего
 * не изменилось» становится нормой. В v1 путей чтения было два, с правилом приоритета,
 * и форма, собранная в билдере, живого превью не получала вовсе, потому что файлов у неё
 * не существовало.
 *
 * ## Почему `index.tsx` исключён
 *
 * Это страница-обёртка примера: она монтирует форму в приложение, тянет роутер и layout.
 * Исполнить её в превью значит смонтировать приложение внутрь приложения. Сайдкары, которые
 * она импортирует, превью и так найдёт — они лежат рядом.
 *
 * Исключается только КОРНЕВОЙ `index.ts(x)`: `steps/index.ts` визарда — не страница, а
 * агрегатор шагов, и без него `validation.ts` не собрал бы ни одного правила шага.
 *
 * @module plugins/reformer/render/compiling/sources
 */

import { isFixturePath } from '@/plugins/reformer/core/form-fixture';
import type { ResourceRef } from '@reformer/builder-plugin-api';

/** Расширения, которые превью исполняет. */
const EXECUTABLE = /\.tsx?$/;
/** Объявления типов: исполнять нечего, а транспилятор на них ругаться права не имеет. */
const DECLARATION = /\.d\.tsx?$/;
/** Тесты и спеки: они про сайдкары, а не сайдкары. */
const TESTS = /\.(test|spec)\.tsx?$/;
/** Страница-обёртка примера — только в корне каталога формы. */
const PAGE_ENTRY: ReadonlySet<string> = new Set(['index.ts', 'index.tsx']);

/** Последний сегмент пути. */
function baseName(path: string): string {
  return path.slice(path.lastIndexOf('/') + 1);
}

/**
 * Исполняется ли этот файл каталога формы.
 *
 * Принимает путь ОТ КАТАЛОГА ФОРМЫ (`validation.ts`, `steps/kontakty/validation.ts`). Фильтры
 * расширений, тестов и фикстуры — по базовому имени: тест в папке шага такой же тест.
 * Страница-обёртка — только в корне (см. модуль).
 *
 * Решение по ИМЕНИ, а не по содержимому: список файлов известен раньше, чем их текст, и читать
 * весь каталог ради отбора значило бы платить чтением за файлы, которые всё равно отбросим.
 */
export function isExecutableSidecar(path: string): boolean {
  const name = baseName(path);
  const nested = path.includes('/');
  // Схема шага визарда (`steps/<шаг>/form.schema.json`) — данные, которые импортирует агрегатор
  // шагов. Корневая схема — нет: её превью берёт из модели редактора, а не из файла.
  if (nested && name.endsWith('.json')) return true;
  if (!EXECUTABLE.test(name)) return false;
  if (DECLARATION.test(name)) return false;
  if (TESTS.test(name)) return false;
  if (isFixturePath(name)) return false;
  return nested || !PAGE_ENTRY.has(name);
}

/**
 * Сайдкары среди соседей документа — один уровень, без обхода.
 *
 * Каталоги отбрасываются: обход вглубь делает `readSidecars` (`./read`), когда порт
 * умеет листинг, а этот отбор — запасной путь для порта, у которого есть только соседи.
 */
export function selectSidecars(refs: readonly ResourceRef[]): readonly ResourceRef[] {
  return refs.filter((ref) => ref.kind === 'file' && isExecutableSidecar(ref.name));
}
