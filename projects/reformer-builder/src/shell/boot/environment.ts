/**
 * Окружение оболочки: то, что сборка делает не с собой, а с местом, где она запущена.
 *
 * ## Зачем это порт
 *
 * Сборка (`./boot`) одна, а мест запуска два: своя вкладка браузера и страница чужого
 * приложения, внутри которого билдер открыт оверлеем. Почти всё у них общее — службы, реестры,
 * проект, слои плагинов. Различается только отношение к ДОКУМЕНТУ и ИСТОЧНИКУ: во вкладке билдер
 * хозяин — пишет заголовок, вешает класс темы на корень, вправе перезагрузить страницу и снести
 * хранилище; в чужом приложении он гость, и каждое из этих действий портит хозяину жизнь.
 *
 * Флаги режима в `boot` дали бы то же поведение, но размазали бы вопрос «чей это документ» по
 * десятку условий. Порт собирает ответ в одном объекте: сборка спрашивает окружение, а кто
 * отвечает — решает тот, кто её вызывает.
 *
 * ## Необязательное значит «этого здесь делать нельзя»
 *
 * Метода нет — действия нет, и всё, что от него зависит, не появляется вовсе: без `reload`
 * не предлагается смена профиля состава, без `purgeStorage` не регистрируется команда «Очистить
 * кэш». Это тот же приём, которым необязательны службы у `ShellHost`: отсутствие — законная
 * сборка, а не поломка.
 *
 * ## Умолчание — вкладка браузера
 *
 * `boot` без окружения ведёт себя как всегда: {@link createBrowserTabEnvironment}. Умолчание
 * живёт здесь, а не у оболочки вкладки, потому что сборке нельзя импортировать оболочки, а
 * десяток вызывающих (тесты сборки, тесты доменов-плагинов) окружения не называют.
 *
 * @module shell/boot/environment
 */

import type { ServiceRegistry } from '@reformer/builder-plugin-api/internal';
import type { ThemeRoot } from '@/shell/platform/services/theme';
import {
  browserPurgeEnvironment,
  purgeOriginStorage,
  type PurgeReport,
} from '@/shell/platform/workspace/storage/purge';

/**
 * Что приложение держит в хранилище источника.
 *
 * Состав хранилищ знает сборка — она их завела; окружение решает лишь, можно ли их сносить.
 * Поэтому список приходит параметром, а не лежит в окружении.
 */
export interface KnownStorage {
  /** Базы IndexedDB — запасной путь на движки без перечисления баз. */
  readonly databases: readonly string[];
}

export interface ShellEnvironment {
  /**
   * Заголовок документа; `undefined` — вернуть тот, что был до билдера.
   *
   * Метода нет у оболочки без своей вкладки: заголовок страницы принадлежит приложению.
   */
  applyTitle?(title: string | undefined): void;

  /**
   * Куда служба темы ставит класс тёмной темы. `null` — никуда: тема считается, но документ
   * не трогается (среда без DOM, либо оболочка применяет тему сама и на своих условиях).
   */
  readonly themeRoot: ThemeRoot | null;

  /**
   * Перезапуск приложения. Нужен смене профиля состава и очистке хранилища.
   *
   * Нет метода — нет и обоих действий: перезагрузить чужую страницу билдер не вправе.
   */
  readonly reload?: () => void;

  /**
   * Снести хранилища источника (OPFS, IndexedDB, Cache Storage, `*Storage`).
   *
   * Источник у встроенного билдера общий с приложением, и «очистить кэш билдера» там означало
   * бы «стереть данные приложения» — поэтому метод есть только у оболочки со своим источником.
   */
  purgeStorage?(known: KnownStorage): Promise<PurgeReport>;

  /**
   * Возможности, которые оболочка добавляет от себя. Зовётся один раз, после служб Host и до
   * активации плагинов: плагин спрашивает реестр при активации и обязан уже застать ответ.
   */
  registerCapabilities?(services: ServiceRegistry): void;
}

/**
 * Окружение «своя вкладка браузера» — историческое и единственное до встраивания.
 *
 * Обращения к `document` и `window` стоят там же и так же, как стояли в `boot`: заголовок
 * и корень темы читаются при создании (оно происходит в начале сборки), а перезапуск зовёт
 * `window` в момент вызова. Тесты сборки подменяют оба глобала и полагаются на это.
 */
export function createBrowserTabEnvironment(): ShellEnvironment {
  const hasDocument = typeof document !== 'undefined';
  /** Титул до конфига — то, что написано в index.html; к нему возвращаемся без конфига. */
  const builtinTitle = hasDocument ? document.title : '';

  return {
    applyTitle(title) {
      if (typeof document === 'undefined') return;
      document.title = title ?? builtinTitle;
    },
    themeRoot: hasDocument ? document.documentElement : null,
    reload() {
      window.location.reload();
    },
    purgeStorage: (known) =>
      purgeOriginStorage(browserPurgeEnvironment({ knownDatabases: known.databases })),
  };
}
