/**
 * Форма композиции: всё, что оболочка ЗНАЕТ о составе приложения, — а знает она только форму.
 *
 * Оболочка собирает приложение, но не решает, из каких плагинов оно состоит. «ReFormer Builder»
 * — это конкретный набор, и набор живёт в `application/`, вне оболочки. Здесь объявлена одна
 * лишь ПОТРЕБНОСТЬ — две фазы, которые `boot` обязан откуда-то получить, — а удовлетворяет её
 * тот, кто приложение собирает, и передаёт ПАРАМЕТРОМ (`BootOptions.application`).
 *
 * Это тот же приём, которым устроены порты плагинов: потребность объявляет ПОТРЕБИТЕЛЬ, а не
 * поставщик. Плагин файлов объявляет `FilesHost` и получает реализацию от композиции, ничего
 * не зная о платформе; оболочка объявляет {@link ApplicationComposition} и получает состав,
 * ничего не зная о плагинах. Зависимость развёрнута в обе стороны одинаково и по одной причине:
 * тот, кто объявляет, обязан оставаться заменяемым.
 *
 * Почему не «список плагинов параметром»: состав — это не массив, а ДВЕ фазы (см.
 * {@link ApplicationComposition}), и каждая из них ещё и функция от опций, потому что порты
 * собирает `boot`. Передать готовый массив можно было бы только после того, как опции собраны,
 * то есть строкой ниже по тому же файлу, — и никакого разворота зависимости не вышло бы.
 *
 * Обратная сторона, которую надо принять: {@link BuiltinPluginsOptions} живут ЗДЕСЬ, в оболочке,
 * а не рядом с составом. Они и есть то, что оболочка УМЕЕТ ДАТЬ, — порты, собранные ею из
 * платформы; состав их только тратит. Уедь тип в `application/`, `boot` импортировал бы оттуда
 * хотя бы его — и разворот остался бы на бумаге.
 *
 * @module shell/boot/composition
 */

import type { CapabilityProvider } from '@reformer/builder-plugin-api/internal';
import type {
  CapabilityDeclaration,
  PluginPermission,
} from '@reformer/builder-plugin-api/internal';
import type { Plugin } from '@reformer/builder-plugin-api/internal';

// Порты и настройки встроенных — только ТИПЫ, до единого. `verbatimModuleSyntax` стирает такой
// импорт целиком, графа он не создаёт: ни один барель плагина отсюда в стартовый граф не едет,
// и ленивые шестеро остаются отдельными файлами. Стережёт это храповик в тесте состава.
import type { FilesHost } from '@/plugins/files';
import type { MonacoHost } from '@/plugins/editor-monaco';
import type { KitsPluginOptions } from '@/plugins/kits';
import type { PreviewHost } from '@/plugins/preview-runtime';
import type { MarkdownHost } from '@/plugins/editor-markdown';
import type { SchemaEditorHost } from '@/plugins/editor-schema';
import type { CodegenGaps } from '@/plugins/codegen';
import type { TemplatesGaps } from '@/plugins/templates';

/**
 * Состав приложения — двумя фазами, ровно теми, что нужны запуску.
 *
 * Две фазы, а не один список, потому что `boot` регистрирует статических СИНХРОННО (их значения
 * нужны ему тут же, при сборке), а ленивых дожидается внутри `ready` — до первой отрисовки, но
 * уже асинхронно. Один метод, возвращающий `Promise`, отложил бы вместе с ленивыми и статических,
 * то есть саму отрисовку.
 *
 * Что попадает в какую фазу и почему — знает тот, кто композицию поставляет. Оболочке этот вопрос
 * не задаётся и задан быть не может: ответ на него — литеральные `import()`, а литерал обязан
 * лежать там же, где список.
 */
/**
 * Плагин вместе с тем, что он ОБЪЯВИЛ снаружи своего кода.
 *
 * Пара, а не поле {@link Plugin}, по той же причине, по которой объявление приходит вторым
 * аргументом в `PluginRegistry.register`: источник у него другой — манифест у плагина
 * каталога, карта состава у встроенного, — и читается оно ДО того, как код плагина исполнится.
 * Поле внутри плагина означало бы, что объявление известно только после загрузки, то есть
 * ровно тогда, когда проверять его уже поздно.
 *
 * Необязательное `provides` — это «ничего не обещал», а не «обещал пустое»: таких
 * встроенных большинство.
 */
export interface ComposedPlugin {
  readonly plugin: Plugin;
  readonly provides?: readonly CapabilityDeclaration[];
  /**
   * Права, объявленные манифестом встроенного плагина.
   *
   * У встроенного они НЕ спрашиваются: его код приехал вместе с приложением, и спрашивать
   * разрешения на то, что человек уже установил, — театр. Объявление здесь всё равно нужно,
   * и по двум причинам: привратник служб один на всех (без прав привилегированная служба
   * не видна и встроенному), а список прав в манифесте — то, чем встроенный объясняет себя
   * в списке плагинов ровно так же, как внешний.
   */
  readonly permissions?: readonly PluginPermission[];
}

export interface ApplicationComposition {
  /** Плагины стартового графа: регистрируются синхронно, при сборке приложения. */
  eager(options: BuiltinPluginsOptions): readonly ComposedPlugin[];
  /** Плагины, приезжающие своим файлом: их дожидается `ready`, тоже до первой отрисовки. */
  lazy(options: BuiltinPluginsOptions): Promise<readonly ComposedPlugin[]>;
  /**
   * Что этот состав ОБЪЯВЛЯЕТ — возможности встроенных плагинов с версиями и владельцами.
   *
   * Данные, а не функция, и в этом всё дело: ни одного плагина этот список не тянет — он
   * собирается из объявлений карты состава, то есть из литералов. Поэтому он есть у обеих
   * фаз сразу, включая ленивую, чьих файлов в стартовом графе нет.
   *
   * Нужен он одному потребителю — каталогу плагинов проекта: чтобы отказать внешнему плагину
   * с невыполнимым `requires` ДО загрузки его кода, надо знать, что даёт остальное приложение,
   * а реестр служб на этот вопрос ещё не отвечает (в нём пусто до активации) и НИКОГДА
   * не ответит про версии — он хранит реализацию, а не паспорт.
   */
  readonly capabilities: readonly CapabilityProvider[];
}

/**
 * Что оболочка УМЕЕТ ДАТЬ составу: порты и настройки встроенных.
 *
 * Словарей здесь больше нет ни у одного плагина: каждый регистрирует свой сам, полем
 * контекста (`ctx.i18n`), и пространство имён ему подставляет сборка контекста, а не
 * композиция. Раньше это было невозможно — поля в контексте не было, — и композиция раздавала
 * виды `forPlugin(id)` по одному на плагин.
 */
export interface BuiltinPluginsOptions {
  /** Порт платформы для плагина файлов. */
  readonly files: FilesHost;
  /** Порт платформы для редактора Monaco. */
  readonly monaco: MonacoHost;
  /**
   * Порт предпросмотра markdown.
   *
   * Отдельный плагин, а не режим редактора Monaco: «этот файл показывают рендером» —
   * предметное знание о формате, и держать его внутри редактора кода значило бы, что
   * выключение markdown требует правки чужого плагина.
   */
  readonly markdown: MarkdownHost;
  /** Порт платформы для визуального редактора схемы. */
  readonly schema: SchemaEditorHost;
  /**
   * Настройки плагина китов.
   *
   * Киты вносятся плагином, а не композицией, потому что «какой кит активен» — это
   * состояние, которое читают трое: валидатор (с чем сверять), палитра (что предлагать)
   * и инспектор (какие свойства у компонента). Сервис — единственный способ отдать одно
   * состояние троим, не заводя его копию у каждого.
   */
  readonly kits: Pick<KitsPluginOptions, 'settings' | 'sources'>;
  /**
   * Порт платформы для превью. Его берут двое: превью-хост — адрес документа и права
   * источника, чтобы выбрать поверхность, — и поверхности стека ReFormer, которым нужны кит,
   * загрузчик модулей и соседние файлы формы. Порт хоста — подмножество этого.
   */
  readonly preview: PreviewHost;
  /**
   * То, чего генерации кода и шаблонам не хватает в возможностях: сохранение в источник.
   *
   * Не порты: рабочую область оба плагина собирают сами, из служб контекста. Здесь остаётся
   * единственная операция, выносящая написанное НАРУЖУ, — её нельзя отдать плагину каталога
   * без политики прав (см. `shell/boot/ports/workspace-save`).
   */
  readonly codegen: CodegenGaps;
  /** То же самое у шаблонов форм: сохранение и ничего сверх. */
  readonly templates: TemplatesGaps;
}
