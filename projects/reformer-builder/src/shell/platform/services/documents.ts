/**
 * Служба документов — рабочая область в том объёме, который нужен редактору.
 *
 * Заведена ради дыры, которую нельзя закрыть ни одним именем из `@/sdk`: там нет ни одного
 * способа прочитать или записать текст документа. Встроенные редакторы получают рабочую
 * область ПОРТАМИ (`MonacoHost.documentOf/writeText`, `AiHost`, `FilesHost`), а порт собирает
 * композиция — плагину из каталога проекта его никто не соберёт. Тело внешнего редактора
 * получает `documentId` и не может сделать с ним ничего. Служба — это тот же объём, что у
 * портов, но по адресу, который виден через `ctx.services`.
 *
 * ## Почему служба, а не поле контекста
 *
 * **На момент активации плагина рабочей области ещё нет** — она появляется, когда человек
 * открыл проект, то есть заведомо позже, а `activate` только регистрирует. Поле пришлось бы
 * объявить необязательным и всё равно проверять на каждом обращении (`sdk/index.ts`, раздел
 * «Сервисы платформы»; `docs/plugin-and-shell.md`, «`workspace` в контексте НЕТ»). Служба
 * же существует с запуска и без проекта отвечает как порты: `null`, `false`, отказ записи.
 * Плагин спрашивает {@link DocumentsService.hasProject} или деградирует по ответу —
 * так же, как с любой другой службой, которой «ещё нет».
 *
 * ## Почему запись — только в рабочую копию
 *
 * {@link DocumentsService.writeText} — это `Workspace.writeText`, и ничего сверх него:
 * единственный путь наружу — `save`, а его здесь НЕТ. Это граница прав рабочей области
 * (`workspace/workspace.ts`, «`writeText` пишет в рабочую копию»): ассистент, интерфейс
 * и внешний редактор ходят одной дверью и потому не нуждаются в отдельных правах — до
 * источника мимо сохранения не дотянуться физически. Пометка {@link WriteOptions} прав
 * не даёт, она называет автора уже разрешённой записи ради журнала. Дать службе `save`
 * значило бы открыть плагину каталога вторую дверь, которую пришлось бы охранять политиками.
 *
 * ## Что здесь есть и чего нет
 *
 * Есть ровно то, без чего редактор не редактор: текущий документ вкладки, активный ресурс,
 * запись текста, открытие вкладки и ОДНО уведомление «что-то изменилось». Изменение ТЕКСТА
 * сюда не входит — за ним следят по самому документу ({@link Document.onDidChangeContent}),
 * а служба сообщает о смене проекта и о вкладках (открытие, закрытие, активация). Одно
 * уведомление без нагрузки, а не три — потому что читать всё равно придётся снимок:
 * форма `onDidChange` + `activeResource()` ложится в `useSyncExternalStore` без переходника.
 *
 * Нет дерева, операций над записями, сохранения и диагностик: у каждого из них свой
 * владелец, и складывать их в одну службу значило бы повторить порт файлов под другим именем.
 * Ближайшая соседка — `./workspace-files`: что в рабочей области ЛЕЖИТ и где (существование,
 * листинг каталога, чтение текста, путевая арифметика). Граница между ними проведена
 * по правам: писать можно только здесь, и только в рабочую копию.
 *
 * ## Порты переедут сюда
 *
 * Сегодня служба дублирует по смыслу `documentOf`/`writeText` трёх портов. Это переходное
 * состояние: по плану (Фаза 5, «Порты → capabilities») встроенные плагины перейдут на неё
 * по одному, и порты потеряют эти методы. До тех пор истина одна — `project.get()` на каждый
 * вызов — и расхождение исключено тем, что оба пути читают её одинаково.
 *
 * @module shell/platform/services/documents
 */

import type { Disposable } from '@/shell/platform/primitives/disposable';
import type { ResourceId } from '@/shell/platform/primitives/resource';
import { defineCapability, type Capability } from '@/shell/platform/primitives/capability';
import type { Document } from '@/shell/platform/workspace/document';
import type { WriteOptions } from '@/shell/platform/workspace/workspace';

/**
 * Чем править открытие вкладки.
 *
 * Объявлено здесь, а не взято у хранилища вкладок: служба лежит НИЖЕ интерфейса и на его
 * состояние ссылаться не должна. Совместимость с настоящими опциями вкладки проверяет
 * компиляция порта — там значение уходит в `documents.open` без приведения.
 */
export interface OpenDocumentOptions {
  /**
   * Временная вкладка (`true` по умолчанию, как у щелчка в дереве): следующая такая же
   * займёт её место. `false` — закрепить: человек пришёл править, а не посмотреть.
   */
  readonly preview?: boolean;
}

export interface DocumentsService {
  /** Открыт ли проект. Без него остальное отвечает `null` и отказом — см. шапку. */
  hasProject(): boolean;
  /** Ресурс активной вкладки; `null` без проекта и без вкладок. */
  activeResource(): ResourceId | null;
  /**
   * Ресурсы ВСЕХ открытых вкладок, в порядке вкладок. Без проекта — пусто.
   *
   * Не то же, что {@link activeResource}, и нужен тем, чьё состояние живёт дольше активной
   * вкладки: превью помнит значения формы и находки сборки, пока открыт хоть один файл её
   * каталога, и «хоть один» из активного не выводится — активным в этот миг бывает файл
   * из совсем другого места.
   *
   * Список, а не событие «вкладку закрыли»: у хранилища вкладок событие одно — «снимок
   * сменился», — и сведение по снимку не пропускает закрытие, случившееся мимо уведомления
   * (смена проекта закрывает все вкладки разом).
   */
  openDocuments(): readonly ResourceId[];
  /**
   * Документ открытой вкладки. Настоящий {@link Document}, а не копия: `getText()` — то,
   * что уйдёт в файл при сохранении, а {@link Document.onDidChangeContent} — единственный
   * способ узнать о правке текста (в том числе чужой: ассистента, слияния, отката).
   */
  documentOf(id: ResourceId): Document | null;
  /**
   * Записывает текст в рабочую копию. Без проекта — отказ обещанием, а не тишина:
   * правка, ушедшая в никуда, выглядит как сохранённая.
   *
   * Третий аргумент обязателен к пробросу до рабочей области: без него ход ассистента
   * попадает в журнал как правка человека.
   */
  writeText(id: ResourceId, text: string, options?: WriteOptions): Promise<void>;
  /** Открывает вкладку и делает её активной. Без проекта — отказ, как у записи. */
  open(id: ResourceId, options?: OpenDocumentOptions): Promise<void>;
  /**
   * Выполнить отложенную перерисовку буфера по модели. Зовётся на уходе фокуса.
   *
   * Нужен редактору модельного документа, и без него контракт редактора не закрывается. Пока
   * человек печатает, платформа откладывает перерисовку буфера из модели — она спрашивает
   * реестр фокуса (`TextEditorFocusToken`), в который редактор и пишет. Снятый фокус и есть
   * тот момент, когда откладывать больше не из-за чего, поэтому порядок несущий: сперва
   * `setFocused(id, false)`, потом `flush(id)`.
   *
   * У текстового документа модели нет и откладывать нечего: вызов безвреден.
   */
  flush(id: ResourceId): void | Promise<void>;

  /**
   * Сменился проект или вкладки: открытие, закрытие, активация. Нагрузки нет намеренно —
   * подписчик перечитывает снимок ({@link activeResource}, {@link documentOf}).
   */
  onDidChange(cb: () => void): Disposable;
}

/**
 * Рабочая область как ВОЗМОЖНОСТЬ: токен службы плюс версия контракта.
 *
 * Провайдер — сама оболочка, а не плагин (`services/host-capabilities`): служба существует
 * с запуска, потому что без неё редактор из каталога проекта не редактор, и ставить её
 * появление в зависимость от состава плагинов значило бы, что профиль без превью отнимает
 * у внешнего редактора текст документа.
 *
 * Идентификатор ПРЕЖНИЙ — `shell.documents`, хотя RFC зовёт эту возможность
 * `reformer.workspace`: смена `id` службы — это миграция сохранённых данных и чужих
 * манифестов, и она отложена целиком в фазу 7 плана v4 (там же переименование `kits.active`).
 *
 * Версия `1.0.0` — исходная: {@link DocumentsService} на момент объявления, вместе
 * с `openDocuments`. Растит её тот, кто интерфейс меняет: минор — добавленный метод,
 * мажор — удалённый или сменивший смысл.
 */
export const DocumentsCapability: Capability<DocumentsService> = defineCapability<DocumentsService>(
  { id: 'reformer.workspace', version: '1.0.0' }
);

/**
 * Токен службы. ТОТ ЖЕ объект, что {@link DocumentsCapability}: возможность расширяет токен,
 * второго реестра нет (`primitives/capability`). Имя оставлено — им пользуется `@/sdk`
 * и каждый плагин, который уже берёт службу.
 */
export const DocumentsServiceToken = DocumentsCapability;
