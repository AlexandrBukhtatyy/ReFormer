/**
 * Контракт валидатора: два уровня проверки и то, что валидатор про документ знает.
 *
 * ## Почему уровня два, а не один
 *
 * Разделение вынужденное и обосновано измерением, а не вкусом. Структурная валидация схемы
 * в v1 синхронная, и на ней стоит **гейт ассистента**: ход проверяется ДО применения, иначе
 * ассистент правит модель, а узнаёт о поломке следующим сообщением. Сделать всю валидацию
 * асинхронной означает сделать асинхронным цикл ассистента — 9.7k строк чистого синхронного
 * кода, у которого нет ни одной другой причины ждать.
 *
 * Поэтому:
 *
 * ```text
 * validate()       синхронный, дешёвый    на нём стоит гейт: ход не применяется, пока не прошёл
 * validateAsync()  с задержкой, отменяемый результат вливается отдельным источником, когда придёт
 * ```
 *
 * Оба необязательны: валидатор вправе иметь только быстрый уровень (так устроен валидатор схемы)
 * или только дорогой (так будет устроена проверка типов — первый потребитель пула воркеров).
 *
 * ## Два уровня публикуются под РАЗНЫМИ источниками
 *
 * `DiagnosticsService.publish` замещает результаты источника целиком. Под общим именем поздний
 * дорогой результат стирал бы находки быстрого, хотя тот проверял другое. Имена считает
 * оркестратор ({@link fastSource} / {@link asyncSource}), а не валидатор: это бухгалтерия
 * службы диагностик, и забыть её не должно быть возможно.
 *
 * ## Чего в контексте нет
 *
 * Нет схемы формы, нет узлов, нет правил: Host не знает, что внутри документа. Валидатору
 * достаётся текст и — если документ модельный и его модель согласована с буфером — сама модель
 * как `unknown`. Сузить её до своего типа обязан тот, кто этот тип объявил, то есть плагин.
 *
 * @module shell/platform/services/validation/types
 */

import { defineExtensionPoint } from '@/shell/platform/primitives/extension-point';
import type { ResourceId, ResourceRef } from '@/shell/platform/primitives/resource';
import type { Diagnostic } from '@/shell/platform/services/diagnostics/types';
import type { DocumentKind } from '@/shell/platform/workspace/document';

/**
 * То, что валидатор знает о документе, ещё ничего не прочитав.
 *
 * Ровно три поля, и все три — из уже открытого документа (`Document` присваивается сюда
 * структурно). Методов здесь нет намеренно: {@link ValidatorContribution.applies} обязан
 * отвечать по адресу и виду, а не по содержимому — иначе выбор валидаторов стоил бы разбора
 * текста на каждой правке, причём каждому кандидату своего.
 */
export interface DocumentRef {
  readonly id: ResourceId;
  readonly ref: ResourceRef;
  readonly kind: DocumentKind;
}

/**
 * Что валидатору дают на проход.
 *
 * `text()` и `model()` — методы, а не поля: контекст переживает один проход, но проход бывает
 * отложенным (дорогой уровень), и читать состояние надо в момент чтения, а не в момент сборки
 * контекста.
 */
export interface ValidateContext {
  readonly doc: DocumentRef;

  /** Текст буфера — ровно то, что видит человек и что уйдёт в файл при сохранении. */
  text(): string;

  /**
   * Модель документа, **согласованная с буфером**, либо `undefined`.
   *
   * `undefined` означает одно из трёх: документ текстовый (провайдера модели нет), буфер
   * не разобрался (расхождение), или модель есть, но она устарела. Все три случая для
   * валидатора одинаковы: доверять можно только тексту, и если ему нужна структура — он
   * разбирает текст сам и сам отвечает за ошибку разбора.
   *
   * Отдавать УСТАРЕВШУЮ модель было бы хуже, чем не отдавать ничего: диагностика указывала бы
   * на узлы, которых в тексте перед человеком уже нет.
   */
  model(): unknown;
}

/**
 * Вклад валидатора.
 *
 * Оба метода необязательны, но хотя бы один обязан быть — вклад без обоих просто ничего
 * не делает, и оркестратор его молча пропускает.
 */
export interface ValidatorContribution {
  /**
   * Уникален среди валидаторов: он же — имя источника в службе диагностик, по которому
   * замещаются прошлые находки.
   */
  readonly id: string;

  /** Берётся ли этот валидатор за такой документ. Синхронный и дешёвый — см. {@link DocumentRef}. */
  applies(doc: DocumentRef): boolean;

  /**
   * Быстрая проверка. **СИНХРОННАЯ** — на ней стоит гейт ассистента.
   *
   * Возвращает полный список своих находок: не «что изменилось», а «что я вижу сейчас».
   * Пустой массив — законный ответ «чисто», и именно он снимает исправленную ошибку.
   */
  validate?(ctx: ValidateContext): readonly Diagnostic[];

  /**
   * Дорогая проверка: запускается с задержкой, отменяется следующей правкой, результат
   * вливается отдельным источником.
   *
   * Обязана уважать `signal`: оркестратор отменённый результат **отбросит**, но работу,
   * которую валидатор продолжает делать в отменённом проходе, за него никто не остановит.
   */
  validateAsync?(ctx: ValidateContext, signal: AbortSignal): Promise<readonly Diagnostic[]>;
}

/**
 * Точка расширения валидаторов.
 *
 * Заполняется только плагинами: разбор и проверка содержимого — предметное знание, и в Host
 * оно означало бы, что второй формат придётся вносить правкой ядра.
 */
export const ValidatorPoint = defineExtensionPoint<ValidatorContribution>('validator');

/**
 * Суффикс источника дорогого уровня.
 *
 * Видимый, а не скрытый: имя источника попадает в интерфейс и в лог, и «почему у меня два
 * источника от одного валидатора» должно читаться из самого имени.
 */
export const ASYNC_SOURCE_SUFFIX = '#async';

/** Имя источника быстрого уровня — сам идентификатор валидатора. */
export function fastSource(validatorId: string): string {
  return validatorId;
}

/** Имя источника дорогого уровня — идентификатор плюс {@link ASYNC_SOURCE_SUFFIX}. */
export function asyncSource(validatorId: string): string {
  return `${validatorId}${ASYNC_SOURCE_SUFFIX}`;
}
