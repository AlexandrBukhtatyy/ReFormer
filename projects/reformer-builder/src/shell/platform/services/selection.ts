/**
 * Служба выделения — общий адрес того, что человек выбрал внутри документа.
 *
 * Заведена ради дыры, которую нельзя закрыть внутри плагина: превью умеет выбрать узел
 * кликом, редактор схемы держит выделение в своих сеансах, а канала между ними нет —
 * `src/plugins/**` не импортируют друг друга, и это правило, а не недосмотр. Пишет сюда
 * кто угодно, читает кто угодно; знакомы стороны только через `ResourceId` и {@link NodeId}.
 *
 * ## Служба, а не событие в шине
 *
 * Решение принято по одному признаку, а не по вкусу: **выделение — это состояние, а не факт.**
 * Различие проверяемое, и проверка звучит так: «что должен увидеть тот, кто подписался ПОСЛЕ
 * того, как всё уже произошло». У факта правильный ответ — ничего (события в шине не
 * переигрывают), у состояния — текущее значение.
 *
 * Здесь правильный ответ второй, и это не теория: панель превью и редактор схемы монтируются
 * в разное время и в произвольном порядке — превью нижним доком, редактор при открытии вкладки.
 * Событие означало бы, что редактор, открытый после клика по превью, не знает о выделении
 * вовсе и узнает о нём только со следующего клика. Со службой он читает {@link
 * SelectionService.get} при монтировании и оказывается прав сразу. Поздний подписчик — не
 * краевой случай, а обычный порядок событий, и он покрыт тестом.
 *
 * Событие при этом никуда не девается — оно внутри: {@link SelectionService.onDidChange}
 * рассылает «выделение такого-то ресурса изменилось». Разница ровно в том, что рядом с
 * рассылкой лежит значение, которое можно спросить.
 *
 * ## Выделение принадлежит РЕСУРСУ
 *
 * Ключ — `ResourceId`, а не «выделение приложения». Две открытые формы держат каждая своё,
 * и переключение вкладки не должно ни стирать чужое, ни показывать его. Единственное
 * выделение на приложение пришлось бы гасить при каждом переключении вкладки, то есть
 * решать за плагины, когда их состояние умирает.
 *
 * ## Чистка мёртвых адресов сюда НЕ входит
 *
 * Это тот же водораздел, который уже проведён для модели документа (см. журнал решений,
 * «Э2 закрыт по-настоящему»): платформа выделение ХРАНИТ и ПЕРЕНОСИТ, а «жив ли ещё такой
 * узел» отвечает только разбор формата. Для службы {@link NodeId} — непрозрачная строка:
 * она не знает ни формы адреса, ни того, где его искать, и любая её попытка «прибраться»
 * была бы догадкой о чужом формате.
 *
 * Поэтому чистит тот, кто правит документ: применил операцию — вычислил живых — записал
 * очищенный список сюда. Служба при этом гарантирует ровно одно: записанное вернётся тем же.
 *
 * ## Пустой список снимает запись
 *
 * Как у `publish` службы диагностик: «ничего не выбрано» — это отсутствие записи, а не запись
 * с пустым списком. Иначе карта росла бы на каждый файл, который когда-либо открывали, а
 * «выделения нет» имело бы два неразличимых представления.
 *
 * Служба выделения — реализация объявленного канала.
 *
 * Объявление службы и токен живут в пакете `@reformer/builder-plugin-api`.
 *
 * @module shell/platform/services/selection
 */

import { createEventBus } from '@/shell/platform/primitives/event';
import { defineEvent } from '@reformer/builder-plugin-api/internal';
import type { ResourceId } from '@reformer/builder-plugin-api/internal';
import type { NodeId } from '@reformer/builder-plugin-api/internal';
import { type SelectionService } from '@reformer/builder-plugin-api/internal';

const SelectionDidChange = defineEvent<ResourceId>('selection.didChange');

/** Общее пустое выделение: одна ссылка на все ресурсы без записи — см. требование к `get`. */
const EMPTY: readonly NodeId[] = Object.freeze([]);

/** Совпадают ли выделения по содержимому и порядку. */
function sameSelection(a: readonly NodeId[], b: readonly NodeId[]): boolean {
  return a === b || (a.length === b.length && a.every((id, index) => id === b[index]));
}

/**
 * Создаёт службу выделения.
 *
 * Состояние только в памяти и между сессиями не переживает: выделение — это «где человек
 * сейчас», а восстановленное из хранилища оно указывало бы на узлы файла, который за это
 * время мог измениться кем угодно. Восстановить его дешевле кликом, чем разбираться,
 * почему подсвечено не то.
 */
export function createSelectionService(): SelectionService {
  const byResource = new Map<ResourceId, readonly NodeId[]>();
  const bus = createEventBus();

  return {
    get: (resource) => byResource.get(resource) ?? EMPTY,

    set(resource, ids) {
      const current = byResource.get(resource);

      if (ids.length === 0) {
        if (current === undefined) return;
        byResource.delete(resource);
        bus.emit(SelectionDidChange, resource);
        return;
      }

      if (current !== undefined && sameSelection(current, ids)) return;
      // Копия: список принадлежит вызывающему, и он вправе переиспользовать свой массив
      // (редактор схемы держит выделение в снимке сеанса и правит его на месте).
      byResource.set(resource, Object.freeze([...ids]));
      bus.emit(SelectionDidChange, resource);
    },

    onDidChange: (cb) => bus.on(SelectionDidChange, cb),

    forget(resource) {
      if (!byResource.delete(resource)) return;
      bus.emit(SelectionDidChange, resource);
    },
  };
}
