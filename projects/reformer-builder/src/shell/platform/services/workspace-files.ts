/**
 * Записи рабочей области: что в ней лежит и где — но НЕ как её править.
 *
 * ## Почему отдельно от службы документов
 *
 * Служба документов (`./documents`) отвечает про ОТКРЫТОЕ: что во вкладках, что активно,
 * какой текст в рабочей копии и как его туда записать. Эта — про то, что в рабочей области
 * есть вообще: существует ли ресурс, что лежит в каталоге, как из одного адреса получить
 * соседний. Вопросы разные, и потребители у них разные: редактору хватает документов,
 * а генерации кода нужно разложить файлы рядом со схемой, которую никто не открывал.
 *
 * Разделение проведено по ПРАВАМ, а не по удобству. Шапка службы документов прямо
 * отказывается складывать в себя дерево и операции над записями — «получился бы порт файлов
 * под другим именем», — и это верно: две службы с разными правами лучше одной, которую
 * придётся охранять по методу.
 *
 * ## Чего здесь НЕТ и почему
 *
 * **Записи.** Писать в рабочую копию можно ровно одной дверью — `DocumentsService.writeText`, —
 * и второй здесь нет намеренно: пометка происхождения (`origin: 'agent'`) живёт у той двери,
 * и второй путь означал бы записи, не попавшие в журнал как чужие.
 *
 * **Сохранения.** `save` выносит написанное НАРУЖУ, в источник, и это единственная операция
 * рабочей области, которую нельзя отдать плагину каталога без политики прав (её ещё нет).
 * Пока политики нет, сохранение остаётся названной дырой в порту генерации кода — не потому,
 * что его забыли, а потому, что дверь наружу не открывают «на будущее».
 *
 * **Дерева.** `list` — ОДИН уровень каталога, а не обход: дерево проекта рисует панель файлов,
 * и второй его обход из плагина означал бы второй ответ на вопрос «что в проекте».
 *
 * ## Путевая арифметика — здесь, и только здесь
 *
 * Адрес ресурса для плагина непрозрачен (`primitives/resource-path`): разбирать его самому
 * нельзя, иначе плагин начнёт различать источники, у которых внутри путь, и источники,
 * у которых внутри ответ сервера. Поэтому вопросы «чей это каталог», «что рядом» и «где
 * корень проекта» — методы службы. Семья из трёх вопросов живёт в одном месте: раздели их
 * между двумя службами, и через полгода никто не вспомнит, по какому правилу делили.
 *
 * @module shell/platform/services/workspace-files
 */

import { defineCapability, type Capability } from '@/shell/platform/primitives/capability';
import type { ResourceId, ResourceRef } from '@/shell/platform/primitives/resource';

export interface WorkspaceFilesService {
  /**
   * Каталог, в котором лежит ресурс. Для ресурса в корне источника — сам корень.
   *
   * Нужен каждому, чьё состояние принадлежит КАТАЛОГУ, а не файлу: у превью значения формы
   * и находки сборки общие на форму и её сайдкары.
   */
  parentOf(id: ResourceId): ResourceId;
  /** Адрес внутри каталога: `resolve(dir, 'validation.ts')`. Сегменты приписываются по одному. */
  resolve(dir: ResourceId, ...segments: readonly string[]): ResourceId;
  /**
   * Адрес по пути ОТ КОРНЯ ИСТОЧНИКА, в котором лежит опорный ресурс.
   *
   * Нужен импортам и ссылкам вида `src/forms/credit`: они записаны от корня проекта,
   * а опорой служит любой ресурс того же источника.
   */
  fromRoot(anchor: ResourceId, path: string): ResourceId;
  /**
   * Корень открытого проекта или `null`, если проекта нет.
   *
   * Отдельный вопрос, а не «parentOf до упора»: корень знает рабочая область, и подниматься
   * к нему перебором значило бы гадать, где остановиться.
   */
  projectRoot(): ResourceId | null;
  /**
   * Есть ли такой ресурс. Отказ источника — это `false`, а не исключение: спрашивают об этом,
   * чтобы не затереть чужой файл, и «не знаю» здесь хуже, чем «нет».
   */
  exists(id: ResourceId): Promise<boolean>;
  /** Один уровень каталога. Отказ листинга — пустой список: «здесь ничего не нашлось». */
  list(dir: ResourceId): Promise<readonly ResourceRef[]>;
  /** Текст ресурса из рабочей копии; `null` — нет проекта, нет ресурса или он не читается текстом. */
  readText(id: ResourceId): Promise<string | null>;
  /**
   * Примет ли ИСТОЧНИК этого ресурса запись. Без проекта — `false`.
   *
   * Не то же, что «есть ли право у плагина»: право одно на всех и выражено самой дверью
   * записи. Это вопрос к источнику — каталог мог быть открыт только на чтение, — и задают
   * его ДО работы: генерация обязана сказать «сюда писать нельзя» до первого напечатанного
   * файла, а не после половины.
   */
  canWrite(id: ResourceId): boolean;
  /**
   * Перечитать каталог: в нём появились или исчезли записи мимо интерфейса.
   *
   * Дерево проекта читает уровни ЛЕНИВО и помнит прочитанное, поэтому каталог, созданный
   * записью плагина, сам в нём не появится. Это не «сбросить кэш на всякий случай»: зовёт
   * это тот, кто ТОЛЬКО ЧТО записал, и знает, куда именно.
   */
  refresh(dir: ResourceId): Promise<void>;
}

/**
 * Возможность «записи рабочей области».
 *
 * Провайдер — оболочка (`./host-capabilities`): рабочая область существует с запуска и
 * отвечает без проекта — `null`, `false`, пустым списком, — как и служба документов рядом.
 *
 * Версия `1.0.0` — исходная. Растит её тот, кто интерфейс меняет.
 */
export const WorkspaceFilesCapability: Capability<WorkspaceFilesService> =
  defineCapability<WorkspaceFilesService>({ id: 'shell.workspaceFiles', version: '1.0.0' });

/** Токен службы — ТОТ ЖЕ объект: возможность расширяет токен, второго реестра нет. */
export const WorkspaceFilesServiceToken = WorkspaceFilesCapability;
