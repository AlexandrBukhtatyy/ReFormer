/**
 * Что даёт САМА оболочка — список возможностей, у которых провайдер не плагин.
 *
 * ## Зачем список, если службы и так регистрируются
 *
 * Проверка требований идёт ДО загрузки чужого кода, а до неё реестр служб пуст: он хранит
 * реализации, а появляются они при запуске. Резолвер (`application/resolver/capability-resolver`)
 * поэтому читает не реестр, а ОБЪЯВЛЕНИЯ — и собирает их с частей состава, то есть с плагинов.
 * Оболочка плагином не является, и без этого списка её возможности были бы для резолвера
 * невидимы: внешний плагин с `requires: shell.documents@^1` получал бы отказ «никто
 * не предоставляет» ровно у той службы, которая заведена для него же.
 *
 * ## Почему провайдер — оболочка, а не какой-нибудь плагин
 *
 * Все трое — разделяемое состояние рабочей области, у которого читателей больше одного и
 * ни один из них не главный: текст документа нужен любому редактору, фокус обязан писать
 * каждый текстовый редактор, снимок вида — каждый вид. Отдай мы их плагину, состав без
 * этого плагина отнимал бы у остальных не его возможности, а общие. К тому же порядок:
 * рабочая область собирается раньше первой активации, и надстройка модели документа
 * спрашивает фокус до того, как хоть один плагин поднялся.
 *
 * Список и регистрация обязаны совпадать. Совпадение проверяется не комментарием,
 * а интеграционным тестом на настоящем запуске (`shell/boot/integration/host-capabilities`):
 * объявленное здесь и отсутствующее в реестре — это та же ложь резолверу, ради которой
 * заведена проверка `provides-unregistered` у плагинов.
 *
 * @module shell/platform/services/host-capabilities
 */

import type { Capability } from '@/shell/platform/primitives/capability';
import { EditorViewStatesCapability } from '@/shell/platform/workspace/model/editor-view-states';
import { TextEditorFocusCapability } from '@/shell/platform/workspace/model/text-editor-focus';
import { DocumentsCapability } from './documents';
import { WorkspaceFilesCapability } from './workspace-files';

/**
 * Имя провайдера в диагностике.
 *
 * С точкой и без совпадения с идентификатором плагина: строка попадает в сообщения вида
 * «её объявляет плагин «builder.host»», и человек должен понимать, что включать нечего —
 * возможность даёт сам инструмент.
 */
export const HOST_PROVIDER_ID = 'builder.host';

/**
 * Возможности оболочки. Порядок — от самой общей к самой узкой, он ни на что не влияет.
 *
 * `Capability<unknown>` намеренно: список нужен как ОБЪЯВЛЕНИЯ (идентификатор и версия),
 * и типы реализаций здесь ничего не решают — их проверяет `services.register` в месте
 * регистрации, где токен известен точно.
 */
export const HOST_CAPABILITIES: readonly Capability<unknown>[] = Object.freeze([
  DocumentsCapability,
  WorkspaceFilesCapability,
  TextEditorFocusCapability,
  EditorViewStatesCapability,
]);
