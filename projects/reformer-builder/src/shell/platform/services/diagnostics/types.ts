/**
 * Форма диагностики: во что валидатор облекает найденную проблему.
 *
 * Два свойства, из которых следует всё остальное:
 *
 * **У диагностики ровно одна цель.** Не «и диапазон, и узел». Синтаксическая ошибка адресуется
 * диапазоном, потому что узла ещё нет — текст не разобрался. Структурная адресуется
 * идентификатором узла, потому что он не съезжает при вставке соседей, а путь съезжает.
 * Двойная адресация означала бы, что валидатор обязан посчитать оба адреса, и один из них
 * (диапазон структурной ошибки) он вычислял бы симуляцией печати — то есть врал бы.
 * Перевод «узел → диапазон» делает тот, кто рисует, по тексту, который сейчас в редакторе.
 *
 * Узловая цель при этом умеет СУЖАТЬСЯ до свойства внутри узла ({@link DiagnosticTarget.within}),
 * и это не вторая адресация: адрес по-прежнему один — узел, — а путь отсчитывается ОТ НЕГО
 * и потому съезжает не больше, чем сам идентификатор. Запрет на путь в находке — про путь
 * УЗЛА от корня документа: тот двигается вставкой соседа где угодно выше и потому спрашивается
 * у модели в момент показа. Путь ВНУТРИ узла двигается только вместе со своим узлом, а из
 * текста его не восстановить: про то, что виноват именно `readOnly`, знает валидатор и никто
 * больше. Без сужения «у компонента нет свойства readOnly» подчёркивало бы `$nodeId` —
 * единственное место узла, которое к ошибке не относится.
 *
 * Правило для потребителя: **уточнение можно игнорировать**. Кто читает только `kind`
 * и `nodeId`, остаётся прав — поэтому поле и необязательное, а не отдельный вид цели:
 * новый вид молча выпал бы из проверок `kind === 'node'` в панели проблем и на канвасе.
 *
 * **Сообщение — это код и параметры, а не готовая строка.** По коду ассистент чинится сам,
 * по переведённой фразе не может. И одна ошибка выглядит одинаково в интерфейсе, в логе
 * и в тесте, потому что переводится в момент показа, а не в момент возникновения.
 *
 * @module shell/platform/services/diagnostics/types
 */

/**
 * Полуинтервал `[start, end)` в тексте ресурса, **в кодовых единицах UTF-16**.
 *
 * Единицы названы намеренно и совпадают с `TextEdit.offset` из журнала изменений: JavaScript
 * и Monaco считают именно так, и потребитель, решивший, что это байты или кодовые точки,
 * сломается на первом эмодзи. Смещения, а не «строка/колонка», потому что смещение — это то,
 * что отдаёт разбор с позициями, и то, что Monaco переводит в позицию одним вызовом;
 * обратный перевод потребовал бы считать начала строк и разъезжался бы на разных переводах
 * строки.
 */
export interface TextRange {
  readonly start: number;
  readonly end: number;
}

/**
 * Что подчеркнуть у свойства, на которое показывает `within` узловой цели.
 *
 * `name` — токен имени вместе с кавычками, он всегда короткий. `value` — само значение,
 * и только там, где виновато ОНО: `$component(Inpit)`, «must be boolean». Значение-поддерево
 * при этом не подчёркивается — см. заметку о выборе места в `editor-monaco/diagnostics`.
 */
export type NodePart = 'name' | 'value';

/** Куда показывает диагностика. Ровно один вариант — см. заголовок модуля. */
export type DiagnosticTarget =
  | {
      readonly kind: 'node';
      readonly nodeId: string;
      /**
       * Уточнение места ВНУТРИ узла: путь от самого узла до свойства-виновника
       * (`['componentProps', 'readOnly']`). Отсутствует или пуст — находка о узле целиком.
       *
       * Это по-прежнему ОДНА цель, а не вторая: адресом остаётся узел, путь лишь сужает место
       * внутри него. И он не съезжает ровно по той причине, по которой не съезжает
       * идентификатор: он отсчитывается ОТ УЗЛА, поэтому вставка соседей где угодно в документе
       * его не двигает. Абсолютный путь в находку класть по-прежнему нельзя — он устаревает
       * вместе с показом.
       *
       * Перевод «путь → диапазон» остаётся за тем, кто РИСУЕТ: свойство ищется в тексте,
       * который сейчас в редакторе. Не нашлось — подчёркивается узел, как и раньше.
       */
      readonly within?: readonly (string | number)[];
      /** Что подчеркнуть у найденного свойства. По умолчанию — имя: оно всегда коротко. */
      readonly at?: NodePart;
    }
  | { readonly kind: 'range'; readonly range: TextRange }
  /** Проблема всего ресурса: файл не читается, схема не того вида. */
  | { readonly kind: 'resource' }
  /**
   * Проблема ресурса, которой НЕТ в его тексте: она в приложенном файле, который этот ресурс
   * тянет за собой, — для формы это сайдкар правил.
   *
   * Ресурс остаётся адресом, потому что через него проблема и чинится: команда правки правил
   * получает адрес СХЕМЫ, а файл правил находит по нему сама. Но подчеркнуть в схеме нечего —
   * правило указывает на поле, которого в ней нет, в том и находка. `resource` тут не годится:
   * он означает «ошибка уровня документа», и рисующий ставит на неё маркер первой строки —
   * то есть на `{` файла, к которому находка не относится.
   *
   * Отдельный вид, а не флаг у `resource`, потому что все, кто различает цели, должны решить
   * заново: рисующий — не ставить маркер, канвас — посчитать в неразмещённые (как и `resource`),
   * панель проблем — показать строку без бейджа узла. Проверка `kind !== 'node'` даёт всё это
   * сама, а `switch` у рисующего заставит компилятор напомнить.
   */
  | { readonly kind: 'attached' };

/**
 * Готовое исправление: ассистент получает не только «что не так», но и «чем чинить»,
 * и чинит той же командой, что и человек.
 */
export interface QuickFix {
  /** Ключ i18n подписи. */
  readonly titleKey: string;
  readonly commandId: string;
  readonly args?: unknown;
}

export type DiagnosticSeverity = 'error' | 'warning' | 'info';

/**
 * Порядок строгости: чем больше, тем строже.
 *
 * Живёт рядом со словарём, а не у каждого потребителя. Сравнивать строгости нужно всем,
 * кто показывает диагностику — дереву (какой тон у значка), канвасу (метка на узле),
 * панели проблем (что показать первым), — а плагины не видят друг друга и завели бы по
 * копии. Копии совпадали бы «по договорённости», то есть до первой правки словаря.
 */
export const SEVERITY_RANK: Readonly<Record<DiagnosticSeverity, number>> = Object.freeze({
  error: 3,
  warning: 2,
  info: 1,
});

export interface Diagnostic {
  /** Идентификатор валидатора. По нему `publish` замещает прошлый результат. */
  readonly source: string;
  readonly severity: DiagnosticSeverity;
  /** Ключ i18n: `errors.<code>`. Не текст. */
  readonly code: string;
  readonly params?: Record<string, unknown>;
  readonly target: DiagnosticTarget;
  readonly fixes?: readonly QuickFix[];
}
