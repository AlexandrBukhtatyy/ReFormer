/**
 * Версия ПРИЛОЖЕНИЯ — билдера, — а не контракта плагинов.
 *
 * Две версии в системе, и путать их дорого. `BUILDER_API_VERSION` (пакет контракта) отвечает
 * на вопрос «какие имена доступны плагину»; эта — на вопрос «какое приложение их подаёт».
 * Расходятся они по построению: контракт растёт, когда меняется поверхность плагина,
 * а билдер выпускается по своим причинам — исправления, интерфейс, сборка.
 *
 * Читается из `package.json`, а не из `define` в конфиге сборки: конфигов у билдера три
 * (`vite`, `vitest`, `vitest.browser`), и `define` пришлось бы держать в каждом. Забыть
 * один означало бы получить в тестах `undefined` там, где в приложении версия есть, —
 * то есть проверять не то, что работает. Импорт одинаково виден всем троим, а сборка
 * оставляет от `package.json` ровно это поле.
 *
 * @module shell/platform/version
 */

import { version } from '../../../package.json';

/** Версия сборки билдера: то, против чего проверяется `compatibility.builder` манифеста. */
export const BUILDER_VERSION: string = version;
