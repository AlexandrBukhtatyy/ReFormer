/**
 * Контейнер поддерева плагина: узел, к которому привязаны его стили.
 *
 * Таблица стилей плагина переписывается под селектор контейнера (см. `plugin/styles`), поэтому
 * без узла с атрибутом `data-rb-plugin` не совпадает НИ ОДНО её правило — то есть CSS плагина
 * не применяется вовсе, молча и целиком. Этот компонент и есть недостающий узел.
 *
 * ## Почему своя обёртка, а не атрибут на узле оболочки
 *
 * Узлы оболочки общие, а контейнер обязан принадлежать одному плагину. В центре панели слота
 * `editor.main` рисуются СОСЕДЯМИ в одном `div`, и приходят они от разных плагинов — один
 * родитель не может нести два разных идентификатора. Там, где панель в доке одна (`aside`
 * левого дока), атрибут пришлось бы пересчитывать на каждую смену активной вкладки, а каркасный
 * узел оболочки получил бы принадлежность плагину, которой у него нет.
 *
 * Обёртка вокруг каждого тела отвечает на вопрос «чей это узел» там, где ответ известен
 * достоверно, — у самого вклада (`Contribution.pluginId`, его проставляет реестр, а не вносящий).
 * Значение вклада для этого не годится: `PanelContribution.id` — имя панели, а не имя владельца.
 *
 * ## Почему `display: contents`
 *
 * Обёртка обязана быть предком и не обязана быть боксом. Тела вкладов живут внутри флекс-колонок
 * оболочки (`flex min-h-0 flex-1`) и растягиваются по ним сами; настоящий `div` посередине стал
 * бы флекс-элементом ВМЕСТО тела, и панель схлопнулась бы по содержимому — то есть изоляция
 * стилей чинилась бы ценой сломанной раскладки. `display: contents` убирает бокс, оставляя
 * элемент в дереве: селекторы потомков совпадают, раскладка не меняется.
 *
 * Цена у этого своя, и её лучше назвать здесь. Раз бокса нет, правила, которые КРАСЯТ сам
 * контейнер (фон, отступы, рамка — в том числе доставшиеся ему от `html`/`body`/`:root`, которые
 * `plugin/styles` заменяет селектором контейнера), не рисуют ничего; наследуемые свойства —
 * шрифт, цвет, размер — проходят сквозь него насквозь, и ради них замена и делалась.
 *
 * Вторая цена уже названа в шапке `plugin/styles` и этой обёрткой не снимается: узел, ушедший
 * порталом в `document.body`, оказывается ВНЕ контейнера и остаётся без стилей плагина. Лечится
 * это контейнером портала внутри поддерева, а не отменой изоляции.
 *
 * @module shell/platform/ui/chrome/PluginScope
 */

import type { ReactElement, ReactNode } from 'react';
import { PLUGIN_SCOPE_ATTRIBUTE } from '@/shell/platform/plugin/styles';

export interface PluginScopeProps {
  /**
   * Владелец поддерева.
   *
   * Берётся из вклада (`Contribution.pluginId`), а не из его значения: первое проставляет
   * реестр, и подделать его вносящий не может — второе плагин пишет сам.
   */
  readonly pluginId: string;
  readonly children: ReactNode;
}

/**
 * Оборачивает тело вклада контейнером со скоупом стилей.
 *
 * Имя атрибута берётся из `plugin/styles`, а не пишется литералом: селектор и разметка обязаны
 * расходиться только вместе. Второй литерал `data-rb-plugin` в проекте означал бы, что их можно
 * рассинхронизировать правкой одного файла — и узнать об этом по пропавшим стилям.
 */
export function PluginScope({ pluginId, children }: PluginScopeProps): ReactElement {
  return (
    <div {...{ [PLUGIN_SCOPE_ATTRIBUTE]: pluginId }} className="contents">
      {children}
    </div>
  );
}
