/**
 * Хеш содержимого для ключей кэша сборки.
 *
 * ## Почему SHA-256, а не FNV из `lib/codegen/marker`
 *
 * Тот хеш отвечает на вопрос «текст правили?» — там коллизия означает пропущенную правку
 * в файле, который человек видит глазами и может перегенерировать. Здесь коллизия означает
 * ИСПОЛНЕНИЕ ЧУЖОГО КОДА: два разных исходника с одним ключом дали бы форме модуль соседней
 * формы, и проявилось бы это как необъяснимое поведение, а не как ошибка. 32 бита FNV на такое
 * не рассчитаны; `crypto.subtle` рассчитан.
 *
 * ## Почему асинхронно и почему это не мешает
 *
 * `crypto.subtle.digest` асинхронен по устройству. Это ровно то ограничение, которое уже решено
 * в загрузке кода: всё асинхронное случается в фазе прогрева, до линковки, потому что `require`
 * внутри модуля синхронен. Хеши считаются там же.
 *
 * ## Недоступность — не ошибка
 *
 * `crypto.subtle` существует только в защищённом контексте (https или localhost). В обычном http
 * его нет вовсе, и это законный режим работы: кэш просто выключается, а сборка идёт как раньше.
 * Своей реализации SHA-256 здесь нет и не будет — она была бы медленнее транспиляции, ради
 * ускорения которой кэш и заводится.
 *
 * @module shell/platform/modules/digest
 */

/**
 * Склейка частей ключа — длиной, а не разделителем.
 *
 * Разделитель пришлось бы выбирать из символов, которых «не бывает в исходниках», и он бы
 * ошибся: `['a b','c']` и `['a','b c']` при склейке пробелом дают одну строку, то есть два
 * РАЗНЫХ набора получили бы один ключ. Нулевой байт от этого спасает, но делает сам исходник
 * бинарным для `grep` и `git diff`.
 *
 * Длина-префикс не требует запрещать ни одного символа: `2:ab1:c` и `1:a2:bc` различаются
 * по построению, что бы ни лежало внутри частей.
 */
function joinParts(parts: readonly string[]): string {
  let out = '';
  for (const part of parts) out += `${part.length}:${part}`;
  return out;
}

/**
 * Доступно ли хеширование в этом окружении.
 *
 * Вызывающий обязан деградировать, а не падать: без хеша нет ключа, без ключа нет кэша,
 * а без кэша сборка работает — просто медленнее.
 */
export function digestAvailable(): boolean {
  try {
    return typeof globalThis.crypto?.subtle?.digest === 'function';
  } catch {
    // Обращение к `crypto` в отдельных окружениях само бросает.
    return false;
  }
}

/** Байты в hex. Отдельно, потому что читается это чаще, чем пишется. */
function toHex(buffer: ArrayBuffer): string {
  const bytes = new Uint8Array(buffer);
  let out = '';
  for (const byte of bytes) out += byte.toString(16).padStart(2, '0');
  return out;
}

/**
 * SHA-256 от склейки частей, в hex.
 *
 * @throws если {@link digestAvailable} отвечает `false` — вызывающий обязан спросить заранее.
 */
export async function digestHex(parts: readonly string[]): Promise<string> {
  const bytes = new TextEncoder().encode(joinParts(parts));
  const hash = await globalThis.crypto.subtle.digest('SHA-256', bytes);
  return toHex(hash);
}
