/**
 * Какие модули оболочки просит набор файлов: чтение импортов без разбора кода.
 *
 * Нужно это одному — прогреву. Ленивый модуль обязан быть загружен ДО линковки (`require`
 * внутри модуля синхронен), а греть всё подряд стало неверно, когда в реестр приехали подпути
 * кита: за пятнадцатью из них стоят свои зависимости, и форма с одним полем тянула бы `recharts`
 * с `cmdk` заодно. Значит нужен ответ на вопрос «что этому набору понадобится», и единственный
 * источник ответа — его же исходники.
 *
 * ## Почему регулярками, а не разбором
 *
 * Линковщик резолвит только ЛИТЕРАЛЬНЫЕ спецификаторы — иначе `require` было бы нечем ответить
 * синхронно, — поэтому вычисляемых имён здесь не бывает по построению, и разбор AST дал бы
 * ровно те же строки ценой транспиляции всего набора до прогрева. Пропуск в другую сторону
 * (строка, похожая на импорт, в комментарии или тексте) безвреден: лишний спецификатор — это
 * лишний прогретый модуль, а не ошибка. Промах же виден словами: `resolve` отвечает «не
 * прогрет», а не `undefined`.
 *
 * @module shell/platform/modules/specifiers
 */

/**
 * Формы, которыми модуль называют: статический импорт и реэкспорт, `require`, динамический
 * `import()`. Спецификатор — всегда строковый литерал, см. шапку модуля.
 */
const PATTERNS: readonly RegExp[] = [
  /(?:^|[\s;}])(?:import|export)\s[^;'"]*?from\s*['"]([^'"]+)['"]/g,
  /(?:^|[\s;}=(,])import\s*['"]([^'"]+)['"]/g,
  /\brequire\s*\(\s*['"]([^'"]+)['"]\s*\)/g,
  /\bimport\s*\(\s*['"]([^'"]+)['"]\s*\)/g,
];

/** Спецификатор пакета — не путь: относительные и абсолютные резолвит линковщик, не реестр. */
function isBare(specifier: string): boolean {
  return !specifier.startsWith('.') && !specifier.startsWith('/');
}

/**
 * Собирает bare-спецификаторы, упомянутые набором файлов.
 *
 * @param files путь → исходник; ровно то, что уходит в загрузку
 */
export function collectBareSpecifiers(files: ReadonlyMap<string, string>): readonly string[] {
  const found = new Set<string>();
  for (const source of files.values()) {
    for (const pattern of PATTERNS) {
      // Регулярка с `g` несёт состояние между вызовами — сбрасываем явно, иначе второй файл
      // читался бы с середины первого.
      pattern.lastIndex = 0;
      let match: RegExpExecArray | null;
      while ((match = pattern.exec(source)) !== null) {
        const specifier = match[1];
        if (specifier !== undefined && isBare(specifier)) found.add(specifier);
      }
    }
  }
  return [...found].sort();
}
