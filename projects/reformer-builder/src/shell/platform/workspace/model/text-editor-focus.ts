/**
 * Кто сейчас печатает — единственный вопрос, от которого зависит перерисовка буфера.
 *
 * ## Почему платформа, а не плагин редактора
 *
 * Читает реестр рабочая область: `attachDocumentModel({ isTextEditorFocused })` откладывает
 * перерисовку буфера из `print(model)`, пока человек печатает, — иначе ход ассистента или
 * структурная правка затирают набранное на полуслове. Читатель один, и он НИЖЕ любого
 * плагина: надстройка модели собирается при открытии документа, раньше, чем какой-либо
 * редактор его нарисовал.
 *
 * Пока реестр жил в плагине Monaco, ответ «печатает ли человек» знал только Monaco. Любой
 * другой текстовый редактор — второй встроенный или внешний из каталога проекта — в реестр
 * не писал, рабочая область считала документ свободным и переписывала буфер под руками:
 * без единой ошибки, просто набранное исчезало. Дотянуться до реестра внешний плагин не мог
 * в принципе — `plugins/**` не импортируют друг друга. Поэтому реестр — часть платформы,
 * а плагину виден через `ctx.services` токеном {@link TextEditorFocusToken}: писать в него
 * ОБЯЗАН каждый текстовый редактор, а не тот, в чьём каталоге файл когда-то лежал.
 *
 * ## Контракт редактора
 *
 * - `setFocused(id, true)` — текстовое поле документа получило фокус;
 * - `setFocused(id, false)` — потеряло, и ПОТОМ просьба к рабочей области догнать буфер
 *   моделью (`flush` ручки документа; у Monaco это `MonacoHost.flush`).
 *
 * Порядок несущий: `flush` сам спрашивает этот реестр и при живом фокусе отложит перерисовку
 * снова — редактор, зовущий его до `setFocused(id, false)`, оставит буфер отставшим до
 * следующего повода. Образец — обработчики `onDidFocusEditorText`/`onDidBlurEditorText`
 * в `plugins/editor-monaco/ui/MonacoEditor.tsx`.
 *
 * ## Зачем реестр, а не флаг в компоненте
 *
 * Ответ «в фокусе ли текстовый редактор ЭТОГО документа» нужен двоим, и оба вне React:
 * рабочей области (см. выше) и самому редактору — внешняя правка буфера применяется по тому
 * же правилу. Флаг внутри компонента виден только React'у, а спрашивают его из документа,
 * который про React не знает. Поэтому состояние живёт в маленьком реестре: редактор его
 * пишет, платформа читает функцией.
 *
 * ## Почему ключ — документ, а не «редактор вообще»
 *
 * Вкладок много, буфер у каждой свой. Один общий флаг означал бы, что набор в одной вкладке
 * замораживает перерисовку во всех остальных, — и ход ассистента в соседнем файле повис бы
 * до ухода фокуса отсюда.
 *
 * Реестр намеренно ничего не знает ни про конкретный редактор, ни про DOM: это `Set`
 * с двумя операциями, и проверяется он в `node` целиком.
 *
 * @module shell/platform/workspace/model/text-editor-focus
 */

import type { ResourceId } from '@reformer/builder-plugin-api/internal';
import { defineCapability, type Capability } from '@/shell/platform/primitives/capability';

export interface TextEditorFocusRegistry {
  /** В фокусе ли текстовый редактор этого документа. */
  isFocused(id: ResourceId): boolean;
  /** Сообщает о смене фокуса. `false` снимает запись, а не хранит её: пустая карта дешевле. */
  setFocused(id: ResourceId, focused: boolean): void;
  /** Есть ли фокус хоть где-нибудь. Нужно диагностике и тестам. */
  hasFocus(): boolean;
}

/**
 * Возможность «кто сейчас печатает»: токен службы плюс версия контракта.
 *
 * Провайдер — оболочка (`services/host-capabilities`), а не редактор, и это то же решение,
 * что у самого реестра: писать в него обязан КАЖДЫЙ текстовый редактор, поэтому принадлежать
 * он не может ни одному. Регистрируется до активации плагинов, поэтому редактор вправе взять
 * его `require` прямо в `activate` — правило «сервис ищется в момент использования»
 * (`plugin/types.ts`) касается сервисов ЧУЖИХ плагинов, а не платформы.
 *
 * Идентификатор ПРЕЖНИЙ — `shell.textEditorFocus`; переименование в `reformer.editor.focus`
 * (как зовёт RFC) идёт общей миграцией идентификаторов в фазе 7 плана v4.
 */
export const TextEditorFocusCapability: Capability<TextEditorFocusRegistry> =
  defineCapability<TextEditorFocusRegistry>({
    id: 'reformer.editor.focus',
    version: '1.0.0',
  });

/** Токен службы — ТОТ ЖЕ объект: возможность расширяет токен, второго реестра нет. */
export const TextEditorFocusToken = TextEditorFocusCapability;

/**
 * Создаёт реестр фокуса.
 *
 * Один на приложение: его создаёт композиция, регистрирует службой и им же отвечает рабочей
 * области. Два реестра означали бы два разных ответа на один вопрос — и ровно ту потерю
 * набранного, ради которой реестр переехал в платформу.
 */
export function createTextEditorFocusRegistry(): TextEditorFocusRegistry {
  const focused = new Set<ResourceId>();
  return {
    isFocused: (id) => focused.has(id),
    setFocused(id, value) {
      if (value) focused.add(id);
      else focused.delete(id);
    },
    hasFocus: () => focused.size > 0,
  };
}
