/**
 * Оболочка «своя вкладка браузера»: билдер — единственное, что есть в документе.
 *
 * Здесь то, что у самостоятельного билдера своё: он сам заводит корень React, сам решает, когда
 * рисовать, и сам восстанавливает последний проект. Окружение у него — вкладка браузера
 * (`shell/boot/environment`, умолчание сборки): заголовок, тема документа, перезагрузка
 * и очистка хранилища принадлежат ему.
 *
 * Состава приложения оболочка не знает, как и сборка: собранное приложение приходит параметром
 * от входа (`main.tsx`), который один соединяет состав с оболочкой.
 *
 * @module shell/standalone/mount
 */

import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import type { BuilderApp } from '@/shell/boot/boot';
import { BuilderRoot } from '@/shell/boot/BuilderRoot';

export interface StandaloneMountOptions {
  readonly app: BuilderApp;
  /** Элемент, который билдер занимает целиком. */
  readonly container: HTMLElement;
  /** Первый кадр оболочки — отметка, к которой сводится замер запуска. */
  readonly onFirstFrame?: () => void;
}

/** Рисует собранное приложение в свой корень и поднимает последний проект. */
export function mountStandaloneShell(options: StandaloneMountOptions): void {
  const { app } = options;
  const root = createRoot(options.container);

  // Отрисовка ждёт `ready` — шаги 2–3 последовательности запуска (настройки, словари, плагины).
  // Это не «загрузочный экран»: обе вещи читаются оболочкой **один раз** при монтировании —
  // раскладка панелей и словарь локали, — поэтому отрисовка раньше означала бы не «быстрее»,
  // а «сохранённые размеры не применились и вместо строк маркеры промаха».
  //
  // Отказ уже обработан внутри `boot`, поэтому `then` здесь один и без ветки ошибки:
  // приложение обязано открыться даже с недогруженными настройками.
  void app.ready.then(() => {
    root.render(
      <StrictMode>
        <BuilderRoot app={app} />
      </StrictMode>
    );

    // Первый кадр — всё, что до него, человек ждёт перед пустым окном.
    requestAnimationFrame(() => {
      options.onFirstFrame?.();
    });

    // Шаг 5: восстановление последнего проекта — ПОСЛЕ отрисовки и не блокируя её. Оно ждёт
    // IndexedDB и, возможно, разрешения на каталог, а «проект не открыт» — это нормальное
    // состояние интерфейса, которое обязано быть видно сразу.
    void app.restore();
  });
}
