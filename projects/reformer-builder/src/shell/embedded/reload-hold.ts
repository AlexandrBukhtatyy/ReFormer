/**
 * Перезагрузки страницы от dev-сервера — отложены, пока открыт билдер.
 *
 * ## Откуда они берутся
 *
 * Билдер пишет файл на диск, dev-сервер приложения видит правку и обновляет модули «на лету».
 * Когда обновить не получается (у изменённого модуля нет принимающей границы — типичный случай
 * для формы, которую ещё нигде не подключили), сервер рассылает «перезагрузить страницу» ВСЕМ
 * открытым документам. Рамкам превью это и нужно. А страница, на которой открыт сам билдер,
 * перезагрузилась бы вместе с ним на каждое сохранение.
 *
 * ## Что делается
 *
 * Пока билдер открыт, перезагрузка этой страницы, вызванная правкой ФАЙЛА, не выполняется,
 * а запоминается: под оверлеем приложение скрыто, и свежим оно обязано стать к моменту, когда
 * его снова покажут. Поэтому отложенная перезагрузка происходит при выключении режима.
 *
 * Перезагрузку без названного файла (сервер пересобрал зависимости, перезапустился) пропускаем
 * как есть: после неё прежние модули сервер уже не отдаёт, и удерживать страницу значило бы
 * оставить её сломанной.
 *
 * ## Только под Vite и только из исходников
 *
 * Механизм — событие клиента Vite `vite:beforeFullReload`: клиент ждёт его обработчиков, и
 * обработчик, который не завершается, перезагрузку останавливает. `import.meta.hot` существует
 * лишь в модуле, который обработал Vite; в любой другой сборке его нет, и модуль ничего
 * не делает — страница перезагружается как обычно, а билдер восстанавливает режим, проект
 * и вкладки сам.
 *
 * @module shell/embedded/reload-hold
 */

/** Просьба сервера перезагрузить страницу — в объёме, который нужен решению. */
export interface ReloadRequest {
  /** Файл модуля, правка которого не обновилась «на лету». */
  readonly triggeredBy?: string;
  /** Кому адресована перезагрузка: путь изменённой страницы либо `*` — «всем». */
  readonly path?: string;
}

/**
 * Вызвана ли перезагрузка правкой файла проекта.
 *
 * Причину сервер называет двумя способами: файлом модуля, который не обновился «на лету»,
 * либо путём изменённой страницы (правка `index.html` приходит без файла-причины).
 * Перезагрузка «всем» без названного файла — не правка: сервер пересобрал зависимости.
 */
function causedByFileEdit(request: ReloadRequest): boolean {
  return request.triggeredBy !== undefined || (request.path !== undefined && request.path !== '*');
}

export interface ReloadHold {
  /**
   * Начинает удерживать перезагрузки. Возвращает «отпустить»: если за время удержания
   * перезагрузка откладывалась, она выполняется сейчас.
   */
  hold(reload: () => void): () => void;
  /**
   * Сервер просит перезагрузить страницу.
   *
   * @returns Обещание, которое не завершится, если перезагрузку надо остановить; иначе `undefined`.
   */
  intercept(request: ReloadRequest): Promise<void> | undefined;
}

export function createReloadHold(): ReloadHold {
  let holding = false;
  let postponed = false;

  return {
    hold(reload) {
      holding = true;
      return () => {
        holding = false;
        if (!postponed) return;
        postponed = false;
        reload();
      };
    },

    intercept(request) {
      if (!holding || !causedByFileEdit(request)) return undefined;
      postponed = true;
      // Не завершается намеренно: клиент Vite ждёт обработчиков перед перезагрузкой.
      return new Promise<void>(() => {});
    },
  };
}

const pageHold = createReloadHold();

if (import.meta.hot) {
  import.meta.hot.on('vite:beforeFullReload', (payload) => pageHold.intercept(payload));
}

/** Удерживает перезагрузки этой страницы — см. {@link ReloadHold.hold}. */
export function holdReloads(): () => void {
  return pageHold.hold(() => {
    window.location.reload();
  });
}
