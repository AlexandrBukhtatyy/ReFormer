/**
 * Выбранный пользователем кит. Хранится в `localStorage` — там же, где остальные предпочтения
 * оболочки (раскладка панелей): выбор кита это именно предпочтение UI, а не данные проекта.
 *
 * Почему не IndexedDB: значение нужно ПРЯМО на бутстрапе, до импорта графа приложения, и
 * синхронное чтение здесь заметно проще асинхронного. IndexedDB в билдере несёт то, что не влезает
 * в localStorage (handle каталога, шаблоны, черновики вкладок) — одна строка туда не просится.
 *
 * Смена кита — с перезагрузкой страницы: каталог, реестр превью и монако-диагностика мемоизируются
 * на графе модулей, и надёжнее пересоздать граф целиком, чем инвалидировать четыре кэша и все
 * React-мемо, закрывшиеся над каталогом.
 *
 * @module reformer-builder/kits/selection
 */

const STORAGE_KEY = 'reformer-builder:active-kit';

/** id выбранного кита или `null`, если пользователь не выбирал (или хранилище недоступно). */
export function getSelectedKitId(): string | null {
  try {
    return localStorage.getItem(STORAGE_KEY);
  } catch {
    // Приватный режим / отключённое хранилище — не повод падать на бутстрапе.
    return null;
  }
}

/** Запомнить выбор (без перезагрузки — её инициирует вызывающий). */
export function storeSelectedKitId(id: string): void {
  try {
    localStorage.setItem(STORAGE_KEY, id);
  } catch {
    /* не сохранится — переживём, кит применится на эту сессию */
  }
}

/** Забыть выбор (тесты, откат после несовместимого кита). */
export function clearSelectedKitId(): void {
  try {
    localStorage.removeItem(STORAGE_KEY);
  } catch {
    /* нечего забывать */
  }
}
