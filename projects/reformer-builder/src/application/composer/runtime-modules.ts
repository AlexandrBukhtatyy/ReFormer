/**
 * Модули, которые состав отдаёт исполняемому коду, — собранные по каталогу `../runtime`.
 *
 * Имён пакетов здесь нет ни одного, и это то же правило, что у карты плагинов
 * (`./builtin-plugins`): состав знает, КАК найти, а не ЧТО найдёт. Какие пакеты импортирует
 * код формы и как нарезан кит — знание приложения «конструктор форм», и лежит оно списками
 * в `application/runtime`, по файлу на тему. Плагинам, которым эти пакеты нужны, они достаются
 * внешними модулями: плагины собраны отдельно от билдера и своих копий не везут. Новый набор
 * пакетов — новый файл в каталоге, без правки этого модуля и без правки оболочки.
 *
 * Раньше списки лежали у встроенных плагинов (превью-хост, киты). Плагины уехали в плагины
 * приложения, а списки остались у приложения: поставить общий модуль в защищённый реестр может
 * только тот, кто реестр создаёт.
 *
 * ## Соглашение файла
 *
 * Два необязательных экспорта: `modules` — пары «спецификатор, объект экспортов», и
 * `lazyModules` — пары «спецификатор, загрузчик». Загрузчик — обычная функция с `import()`;
 * в обещание реестра (`lazyBuiltin`) её оборачивают здесь — список остаётся простым перечнем.
 *
 * ## Обход — НЕ отложенный, и стартовый граф от этого не растёт
 *
 * Реестр модулей создаётся ДО загрузки плагинов, а защищённый слот занимается только при
 * создании — поэтому списки нужны сразу. Файл со списком статически импортирует лишь то, что
 * и так лежит в стартовом графе билдера. Всё тяжёлое в нём — `import()` и остаётся отдельным
 * чанком.
 *
 * ## Один набор на все профили
 *
 * Модули берутся из ВСЕХ файлов каталога, каким бы ни был собранный профиль. Набор —
 * обещание сборщику внешнего плагина (`PLUGIN_RUNTIME_MODULES` пакета контракта): всё из него
 * плагин держит внешним, и профиль, отдавший меньше, уронил бы плагин, собранный «правильно».
 * Совпадение стережёт тест сборки (`shell/boot/integration/plugin-modules.test`).
 *
 * Один спецификатор в двух файлах — отказ на старте: реестр не принимает слот дважды.
 *
 * @module application/composer/runtime-modules
 */

import type { ComposedModule } from '@/shell/boot/composition';
import { lazyBuiltin } from '@/shell/platform/modules/registry';

/** Что может объявить файл каталога `../runtime`. */
interface RuntimeModulesFile {
  readonly modules?: readonly (readonly [string, unknown])[];
  readonly lazyModules?: readonly (readonly [string, () => Promise<unknown>])[];
}

const FILES = import.meta.glob<RuntimeModulesFile>(['../runtime/*.ts', '!../runtime/*.test.ts'], {
  eager: true,
});

/** Модули всех списков. Порядок — по пути файла: детерминирован, но на поведение не влияет. */
export const RUNTIME_MODULES: readonly ComposedModule[] = Object.freeze(
  Object.keys(FILES)
    .sort()
    .flatMap((file): ComposedModule[] => {
      const declared = FILES[file];
      return [
        ...(declared?.modules ?? []),
        ...(declared?.lazyModules ?? []).map(
          ([specifier, load]): ComposedModule => [specifier, lazyBuiltin(load)]
        ),
      ];
    })
);
