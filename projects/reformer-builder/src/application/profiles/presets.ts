/**
 * Профили, кроме полного: чем механизм состава проверяется и чем он пользуется.
 *
 * Заведены они ради проверок — «оболочка поднимается без превью и редактора схемы» можно
 * утверждать только на составе, где их нет, — но живут не в тестовом каталоге, и это
 * решение. Профиль выбирается конфигом запуска (`preset`), а значит доступен снаружи;
 * профиль, существующий только в тесте, проверял бы резолвер, но не проверял бы путь
 * «строка в конфиге → собранное приложение», то есть ровно то, ради чего фаза затевалась.
 *
 * ## Почему именно эти два
 *
 * {@link minimalProfile} — нижняя граница работоспособного инструмента: дерево файлов,
 * редактор кода и валидатор схемы. Всё, что за этой границей, обязано ДЕГРАДИРОВАТЬ
 * названно: без превью нет живого вида, без редактора схемы `.json` открывается текстом.
 * Это и проверяет интеграционный тест сборки (`shell/boot/integration/minimal-profile`).
 *
 * {@link aiBuilderProfile} — тот же минимум плюс ассистент, и он здесь ради `extends`:
 * наследование даёт смысл только тогда, когда база и надстройка живут порознь. Заодно
 * это единственный профиль, у которого собственный список короче унаследованного, —
 * то есть проверка того, что склейка идёт «основа, потом своё», а не наоборот.
 *
 * @module application/profiles/presets
 */

import { defineProfile } from './profile';

export const MINIMAL_PROFILE_ID = 'minimal';
export const AI_BUILDER_PROFILE_ID = 'ai-builder';

export const minimalProfile = defineProfile({
  id: MINIMAL_PROFILE_ID,
  name: 'Минимальный',
  plugins: ['files', 'editor-monaco', 'validator-schema'],
});

export const aiBuilderProfile = defineProfile({
  id: AI_BUILDER_PROFILE_ID,
  name: 'Минимальный с ассистентом',
  extends: MINIMAL_PROFILE_ID,
  plugins: ['ai'],
});
