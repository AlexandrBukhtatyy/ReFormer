/**
 * Профиль приложения: состав, названный ДАННЫМИ.
 *
 * Профиль — это список имён плагинов, и только он. Ни одной фабрики, ни одного `import`
 * из `@/plugins` здесь быть не может, и это не стилистика: барель ленивого плагина,
 * импортированный ради его константы-идентификатора, возвращает плагин в стартовый граф
 * целиком (храповик в `composer/builtin-plugins.test`). Поэтому имена написаны строками —
 * а сверяет их с картой встроенных резолвер, на каждое разрешение профиля.
 *
 * Отсюда же ответ, почему {@link ApplicationProfile.plugins} — `readonly string[]`, а не
 * объединение известных идентификаторов. Объединение поймало бы опечатку в профиле, но не
 * поймало бы её в конфиге запуска (`plugins.enable` приходит из JSON), — то есть проверка
 * всё равно нужна в рантайме, а тип лишь создал бы вторую, наполовину работающую. Одна
 * проверка в одном месте честнее двух.
 *
 * ## `extends` — ИМЕНЕМ, а не ссылкой на профиль
 *
 * Ссылка на значение выглядит проще и дешевле, но у неё две цены. Первая: профиль перестаёт
 * быть данными — он начинает импортировать другой модуль, и сериализовать его (конфиг, CLI,
 * будущий реестр профилей) уже нельзя. Вторая: круг наследования становится невыразимым
 * в типах, но по-прежнему выразимым в коде, — и вместо внятного отказа получается зависание.
 * Имя плюс поиск по реестру (`./registry`) даёт и то, и другое: отказ на неизвестного
 * родителя и названный круг.
 *
 * @module application/profiles/profile
 */

export interface ApplicationProfile {
  /**
   * Идентификатор профиля: им профиль называют в конфиге запуска (`preset`) и в `extends`.
   * Он же — единственное, чем круг наследования отличается от честной цепочки.
   */
  readonly id: string;
  /** Человекочитаемое имя. Живёт для диагностики и будущего выбора профиля глазами. */
  readonly name: string;
  /**
   * Плагины профиля — именами из карты встроенных (`composer/builtin-plugins`).
   *
   * Порядок сохраняется резолвером и доходит до состава: он ни на что не влияет по контракту
   * рантайма плагинов, но остаётся тем, в каком порядке их видно в диагностике.
   */
  readonly plugins: readonly string[];
  /** Профиль-основа: его список идёт ПЕРЕД своим. Цепочка любой длины, круги отвергаются. */
  readonly extends?: string;
  /**
   * Выбор провайдера: идентификатор возможности → идентификатор плагина.
   *
   * Нужен там, где одну возможность объявили двое: слот службы один, и «возьмём любого»
   * сделало бы состав зависимым от порядка карты. Это вопрос к человеку, и отвечает на него
   * профиль — то есть данные, а не код.
   *
   * Наследуется как список плагинов: запись наследника перекрывает запись основы по ключу.
   * Выбор, называющий плагина, который эту возможность не объявляет, ОТВЕРГАЕТСЯ сборкой
   * состава (`composer/compose`): молчаливое «тогда оставим как есть» пряталось бы ровно
   * до первого запуска — а профиль пишет человек, как и имя плагина рядом.
   */
  readonly providers?: Readonly<Record<string, string>>;
}

/**
 * Объявляет профиль.
 *
 * Функция, а не литерал с аннотацией типа, ради одного свойства: результат ЗАМОРОЖЕН вместе
 * со списком. Профиль — общее значение, живущее всё время работы приложения, и правка его
 * списка на ходу означала бы, что состав одного приложения меняется из другого места; при
 * `readonly` в типе такая правка — всего лишь `as`, а при `Object.freeze` её нет вовсе.
 */
export function defineProfile(profile: ApplicationProfile): ApplicationProfile {
  return Object.freeze({
    ...profile,
    plugins: Object.freeze([...profile.plugins]),
    ...(profile.providers === undefined
      ? {}
      : { providers: Object.freeze({ ...profile.providers }) }),
  });
}
