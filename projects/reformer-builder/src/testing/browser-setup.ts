/**
 * Подготовка браузерного прогона.
 *
 * Стили приложения грузятся целиком (`src/index.css` → tailwind + токены кита), потому что
 * половина того, ради чего этот прогон заведён, — вычисленный стиль: раскладка окна палитры,
 * предел высоты списка, `sr-only` у заголовка, тёмная тема. Без настоящего CSS проверялись бы
 * имена классов, то есть то же самое, что уже проверяет компилятор.
 *
 * @module testing/browser-setup
 */

import { afterEach } from 'vitest';
import '../index.css';
import { cleanupRendered } from './render';

afterEach(() => {
  cleanupRendered();
  // Тема — глобальное состояние документа: тест, включивший тёмную, обязан вернуть светлую,
  // иначе следующий получит её в наследство и «пройдёт» по чужой причине.
  document.documentElement.classList.remove('dark');
});
