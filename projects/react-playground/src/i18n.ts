/**
 * Локализация playground.
 *
 * Демо написаны по-русски, поэтому язык по умолчанию — русский: подписи кита (кнопки мастера,
 * плейсхолдеры, статусы), тексты ошибок валидации, для которых правило не задало своего сообщения,
 * размеры файлов и строки cdk берутся из русского словаря. Без провайдера компоненты говорили бы
 * встроенным английским.
 */

import { createLocaleLoader } from '@reformer/core/i18n';
import { loadKitLocale } from '@reformer/ui-kit/locale';

/** Язык playground при старте. */
export const DEFAULT_LANG = 'ru';

/**
 * Загрузчик локалей — один на приложение (константа модуля, иначе кэш терялся бы на каждый рендер).
 * Источник пока один: встроенные словари кита (они включают словари ядра и cdk), чанк нужного
 * языка по запросу.
 */
export const loadLocale = createLocaleLoader([loadKitLocale]);
