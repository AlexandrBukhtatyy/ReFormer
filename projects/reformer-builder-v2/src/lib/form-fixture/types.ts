/**
 * Что автор пишет в фикстуре формы.
 *
 * ## Почему это TypeScript, а не JSON
 *
 * Половина того, что нужно подставить форме, — функции, и JSON их не выражает. `itemLabel`
 * массива обязан быть функцией (массив на его месте даёт «is not a function» на первом же
 * элементе), `submitForm` — асинхронной, правило перехвата запроса — предикатом. Фикстура на JSON
 * заставила бы описывать всё это данными и оживлять их интерпретатором, который пришлось бы
 * написать и потом объяснять.
 *
 * Раз это TypeScript, он проходит ту же машинерию, что и сайдкары: читается из рабочей копии,
 * транспилируется, линкуется, исполняется. Отдельного пути для него нет.
 *
 * ## Три слоя, и каждый отвечает за свой класс зависимости
 *
 * 1. **Данные** — значения операторов схемы (`$dataSource`, `$fn`, `$locale`) и начальная модель.
 *    Это то, чего форме не хватает, когда её открыли без приложения.
 * 2. **Модули** — то, что форма импортирует у проекта: `./api`, `@/shared/dict`. Без подстановки
 *    линковщик отказывается их резолвить (и правильно делает — догрузка означала бы второй
 *    экземпляр пакета), и форма из чужого проекта не собирается вовсе.
 * 3. **Ambient** — то, что форма берёт из окружения, ни у кого не спрашивая: `fetch`, `Date.now`,
 *    `Math.random`. Подставляется лексически, параметрами модуля.
 *
 * Слои независимы: можно объявить только `dataSources` и не трогать остальное.
 *
 * @module reformer-builder/lib/form-fixture/types
 */

/** Значения модели формы. Форма приходит из схемы, и сузить её нечем. */
export type FixtureModel = Record<string, unknown>;

/** Ответ на перехваченный запрос. */
export interface FixtureHttpResponse {
  readonly status?: number;
  /** Тело как объект: уходит в `Response.json()`. */
  readonly json?: unknown;
  /** Тело как текст. Имеет смысл, когда форма читает не JSON. */
  readonly text?: string;
  readonly headers?: Readonly<Record<string, string>>;
  /**
   * Задержка ответа, мс. Ради этого правила перехват и заводят чаще всего: увидеть форму
   * в состоянии загрузки иначе можно только настоящей медленной сетью.
   */
  readonly delayMs?: number;
}

/** Правило перехвата запроса. */
export interface FixtureHttpRule {
  /** Метод; не указан — любой. */
  readonly method?: string;
  /**
   * Адрес: строка (совпадение по вхождению) либо регулярное выражение.
   *
   * Вхождение, а не точное равенство: форма собирает URL из базового адреса приложения,
   * которого в билдере нет, и требовать полного совпадения значило бы требовать знать чужой
   * `baseURL`.
   */
  readonly url: string | RegExp;
  readonly respond: FixtureHttpResponse;
}

/** Детерминизм времени и случайности. */
export interface FixtureClock {
  /** Что вернёт `Date.now()` и `new Date()` без аргументов. ISO-строка или миллисекунды. */
  readonly now?: string | number;
  /** Что вернёт `Math.random()`. Число из [0,1) либо последовательность по кругу. */
  readonly random?: number | readonly number[];
}

/**
 * Фикстура формы целиком. Все поля необязательны — слои независимы.
 */
export interface FormFixture {
  /* ── слой 1: данные ─────────────────────────────────────────────────────── */

  /** Начальные значения модели. Старше `model.ts`: фикстура пишется ради проверки. */
  readonly model?: FixtureModel;
  /** Значения `$dataSource`: списки опций, скаляры, функции подписи. */
  readonly dataSources?: Readonly<Record<string, unknown>>;
  /** Реализации `$fn`. */
  readonly fns?: Readonly<Record<string, (...args: never[]) => unknown>>;
  /** Резолвер `$locale`. Не задан — ключ отдаётся сам собой. */
  readonly locale?: (key: string) => string;

  /* ── слой 2: модули ─────────────────────────────────────────────────────── */

  /**
   * Подстановки импортов: спецификатор → готовые экспорты.
   *
   * Работает и для bare-имён, которых в оболочке нет (`@/shared/dict`), и для файлов, которые
   * в наборе ЕСТЬ (`./api`): второе — не обход, а суть проверки, когда настоящий `api.ts` ходит
   * в сеть, а посмотреть надо на форму.
   */
  readonly modules?: Readonly<Record<string, unknown>>;

  /* ── слой 3: ambient ────────────────────────────────────────────────────── */

  /** Правила перехвата сетевых запросов. Первое совпавшее выигрывает. */
  readonly http?: readonly FixtureHttpRule[];
  /** Подмена времени и случайности. */
  readonly clock?: FixtureClock;
}

/** Имя экспорта, по которому фикстура опознаётся в исполненном модуле. */
export const FIXTURE_EXPORT = 'fixture';
