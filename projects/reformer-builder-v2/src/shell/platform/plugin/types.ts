/**
 * Контракт плагина: что плагин обязан предъявить рантайму и что рантайм даёт плагину.
 *
 * Плагин — единица поставки возможностей. Он ничего не «инициализирует» и ничем не владеет
 * глобально: он **регистрирует** сервисы, вклады, команды и подписки, а рантайм умеет всё
 * это снять обратно. Отсюда два свойства, которые определяют весь модуль.
 *
 * ## `activate` синхронный
 *
 * Возвращаемый тип — `void`, и это не упущение, а решение (см. plugin-and-shell.md, «Решение:
 * `activate` синхронный»). Три причины:
 *
 * - **Ждать нечего.** Встроенные плагины уже в бандле, плагины каталога линкуются до вызова
 *   `activate`. Промис здесь был бы обещанием без содержания.
 * - **Асинхронная активация делает набор вкладов недетерминированным.** Оболочка отрисовалась бы
 *   раньше, чем часть панелей зарегистрировалась, и «панели нет» стало бы неотличимо от
 *   «панель ещё грузится» — то есть отказ выглядел бы как медленный старт.
 * - **Асинхронная работа никуда не девается, она просто не блокирует регистрацию.** Плагин,
 *   которому нужно восстановить состояние из хранилища, запускает это в `activate`, но
 *   **не ждёт**: вклады уже внесены, а состояние подтянется позже и обновит сервис, за которым
 *   оно живёт.
 *
 * Правило формулируется так: **`activate` только регистрирует.** Всё, что требует ожидания,
 * живёт за сервисом с асинхронными методами или за вкладом, который сам рисует своё состояние
 * загрузки. Тип `void` (а не `void | Promise<void>`) выбран, чтобы у API не было соблазна:
 * `async activate` даст ошибку компиляции в месте объявления плагина, а не странность
 * в поведении запуска через полгода.
 *
 * ## Порядок активации ничего не значит
 *
 * Плагины нуждаются в сервисах друг друга, но **сервис ищется в момент использования, а не
 * в момент активации**. Поэтому графа зависимостей с топологической сортировкой нет вовсе,
 * а вместе с ним нет и класса ошибок «активировался слишком рано». Правило приёмки —
 * активация в обратном порядке даёт то же поведение — проверяется тестом
 * `registry.test.ts` («порядок активации ничего не значит»).
 *
 * Следствие для автора плагина: в `activate` нельзя вызывать `services.require(...)` чужого
 * сервиса и нельзя читать чужие вклады. Можно только регистрировать своё и **захватывать
 * контекст в замыкание**, чтобы обратиться к чужому сервису тогда, когда команда действительно
 * выполняется.
 *
 * @module host/plugin/types
 */

import type { PluginCommandRegistry } from '@/shell/platform/primitives/command';
import type { Disposable } from '@/shell/platform/primitives/disposable';
import type { EventBus } from '@/shell/platform/primitives/event';
import type { ExtensionRegistry } from '@/shell/platform/primitives/extension-point';
import type { ServiceRegistry } from '@/shell/platform/primitives/service';
import type { PluginStorage, SecretStorage } from './storage';

/**
 * Всё, что плагин получает от платформы. Другого способа дотянуться до Host у него нет.
 *
 * Контекст создаётся рантаймом на каждую активацию заново (см. `createPluginContext`)
 * и перестаёт быть действительным после деактивации: подписки из него сняты, вклады убраны.
 * Держать контекст в модульной переменной плагина и пользоваться им после выключения —
 * ошибка, которую рантайм не в состоянии предотвратить, но которая проявится сразу:
 * зарегистрированное после деактивации уже никто не снимет.
 */
export interface PluginContext {
  /** Идентификатор плагина, которому принадлежит контекст. Совпадает с `Plugin.id`. */
  readonly id: string;

  /**
   * Реестр сервисов — общий, не вид на него.
   *
   * Регистрация чужого токена не запрещена технически (изоляция здесь — гигиена, а не граница
   * безопасности), но занят токен может быть только один раз: повторная регистрация бросает.
   */
  readonly services: ServiceRegistry;

  /**
   * Точки расширения — **вид реестра для этого плагина** (`RootExtensionRegistry.forPlugin`),
   * а не корневой реестр.
   *
   * Разница несущая: в виде нет ни параметра `pluginId`, ни метода `forPlugin`, поэтому плагин
   * физически не располагает способом внести вклад анонимно или от чужого имени. Ответ
   * на вопрос «откуда здесь эта панель» гарантирован строением API, а не дисциплиной.
   */
  readonly extensions: ExtensionRegistry;

  /** Реестр команд. Снятие команды — через `dispose()` регистрации, то есть через `subscriptions`. */
  /**
   * Реестр команд — ВИД на него для этого плагина: `register` проставляет владельца сам.
   *
   * Владелец нужен не реестру, а палитре: заголовок команды разрешается словарём того,
   * кто её внёс. Без этого `titleKey` команды плагина искался бы в словаре Host и всегда
   * промахивался. Метода `forPlugin` в виде нет — зарегистрировать команду от чужого
   * имени не получится, потому что пути к этому не существует.
   */
  readonly commands: PluginCommandRegistry;

  /** Шина событий. Доставка синхронная, ошибка подписчика не касается отправителя. */
  readonly events: EventBus;

  /** Изолированное хранилище плагина. Пространство имён — идентификатор плагина. */
  readonly storage: PluginStorage;

  /** Секреты плагина. По умолчанию — только память сессии, см. {@link SecretStorage}. */
  readonly secrets: SecretStorage;

  /**
   * Всё, что сюда положено, освобождается при деактивации.
   *
   * Массив, а не реестр: плагин пишет в него `push`, и это единственная операция, которая
   * от него требуется. Рантайм освобождает список сам — этим снимается целый класс утечек
   * «выключили плагин, а его панель и команда остались навсегда».
   *
   * Обратная сторона: вклад, **не** положенный в `subscriptions`, при деактивации не снимется.
   * Рантайм не в состоянии это обнаружить: он не знает, что именно плагин зарегистрировал.
   */
  readonly subscriptions: Disposable[];
}

/**
 * Контракт плагина.
 *
 * `id` — пространство имён владельца во всех реестрах (`editor-schema`, `ai`): по нему
 * подписаны вклады, по нему изолированы хранилище и секреты, по нему плагин включается
 * и выключается.
 */
export interface Plugin {
  readonly id: string;

  /**
   * Регистрирует всё, что даёт плагин. Вызывается рантаймом один раз на активацию.
   *
   * Синхронный по решению выше. Асинхронную работу запускать можно и нужно, но **не ждать**:
   * `void activate` не даёт вернуть промис, поэтому запущенное обязано само доложить о себе
   * через сервис или вклад.
   *
   * Исключение отсюда не роняет запуск: рантайм ловит его, помечает плагин отказавшим
   * и продолжает активировать остальные (см. `createPluginRegistry`).
   */
  activate(ctx: PluginContext): void;

  /**
   * Необязательный обратный вызов при выключении.
   *
   * Нужен только для того, что не выражается через `subscriptions`: остановить таймер, отменить
   * запрос, закрыть соединение. Снимать вклады руками здесь не надо — это делает рантайм,
   * освобождая `subscriptions` сразу после `deactivate`.
   */
  deactivate?(): void;
}

/**
 * Объявляет плагин.
 *
 * Функция выглядит тождественной и почти ею является — её ценность в трёх вещах:
 * вывод типов на `ctx` в месте объявления (без неё автор пишет аннотацию руками или теряет
 * типы), проверка `id` в момент объявления, а не в момент регистрации, и единственное имя,
 * которое загрузчик подставляет плагину каталога как `@builder/sdk`.
 *
 * Результат заморожен: `id` — ключ во всех реестрах, и его изменение после регистрации
 * означало бы вклады, найденные по одному имени и снимаемые по другому. Состояние плагина
 * живёт в замыкании `activate`, а не на объекте, поэтому заморозка ничего не отнимает.
 */
export function definePlugin(p: Plugin): Plugin {
  if (p.id.trim() === '') {
    throw new Error('definePlugin: идентификатор плагина не может быть пустым');
  }
  return Object.freeze(p);
}
