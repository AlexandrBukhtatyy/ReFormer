/**
 * Форма диагностики: во что валидатор облекает найденную проблему.
 *
 * Два свойства, из которых следует всё остальное:
 *
 * **У диагностики ровно одна цель.** Не «и диапазон, и узел». Синтаксическая ошибка адресуется
 * диапазоном, потому что узла ещё нет — текст не разобрался. Структурная адресуется
 * идентификатором узла, потому что он не съезжает при вставке соседей, а путь съезжает.
 * Двойная адресация означала бы, что валидатор обязан посчитать оба адреса, и один из них
 * (диапазон структурной ошибки) он вычислял бы симуляцией печати — то есть врал бы.
 * Перевод «узел → диапазон» делает тот, кто рисует, по тексту, который сейчас в редакторе.
 *
 * **Сообщение — это код и параметры, а не готовая строка.** По коду ассистент чинится сам,
 * по переведённой фразе не может. И одна ошибка выглядит одинаково в интерфейсе, в логе
 * и в тесте, потому что переводится в момент показа, а не в момент возникновения.
 *
 * @module shell/platform/services/diagnostics/types
 */

/**
 * Полуинтервал `[start, end)` в тексте ресурса, **в кодовых единицах UTF-16**.
 *
 * Единицы названы намеренно и совпадают с `TextEdit.offset` из журнала изменений: JavaScript
 * и Monaco считают именно так, и потребитель, решивший, что это байты или кодовые точки,
 * сломается на первом эмодзи. Смещения, а не «строка/колонка», потому что смещение — это то,
 * что отдаёт разбор с позициями, и то, что Monaco переводит в позицию одним вызовом;
 * обратный перевод потребовал бы считать начала строк и разъезжался бы на разных переводах
 * строки.
 */
export interface TextRange {
  readonly start: number;
  readonly end: number;
}

/** Куда показывает диагностика. Ровно один вариант — см. заголовок модуля. */
export type DiagnosticTarget =
  | { readonly kind: 'node'; readonly nodeId: string }
  | { readonly kind: 'range'; readonly range: TextRange }
  /** Проблема всего ресурса: файл не читается, схема не того вида. */
  | { readonly kind: 'resource' };

/**
 * Готовое исправление: ассистент получает не только «что не так», но и «чем чинить»,
 * и чинит той же командой, что и человек.
 */
export interface QuickFix {
  /** Ключ i18n подписи. */
  readonly titleKey: string;
  readonly commandId: string;
  readonly args?: unknown;
}

export type DiagnosticSeverity = 'error' | 'warning' | 'info';

/**
 * Порядок строгости: чем больше, тем строже.
 *
 * Живёт рядом со словарём, а не у каждого потребителя. Сравнивать строгости нужно всем,
 * кто показывает диагностику — дереву (какой тон у значка), канвасу (метка на узле),
 * панели проблем (что показать первым), — а плагины не видят друг друга и завели бы по
 * копии. Копии совпадали бы «по договорённости», то есть до первой правки словаря.
 */
export const SEVERITY_RANK: Readonly<Record<DiagnosticSeverity, number>> = Object.freeze({
  error: 3,
  warning: 2,
  info: 1,
});

export interface Diagnostic {
  /** Идентификатор валидатора. По нему `publish` замещает прошлый результат. */
  readonly source: string;
  readonly severity: DiagnosticSeverity;
  /** Ключ i18n: `errors.<code>`. Не текст. */
  readonly code: string;
  readonly params?: Record<string, unknown>;
  readonly target: DiagnosticTarget;
  readonly fixes?: readonly QuickFix[];
}
