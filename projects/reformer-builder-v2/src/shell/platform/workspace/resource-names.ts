/**
 * Правила имён и целевых путей для операций над ресурсами — всё, что проверяется без источника.
 *
 * Отделено от исполнения ({@link import('./resource-ops')}) по той же причине, по которой
 * правила дерева отделены от его отрисовки: имя, которое браузер не примет, и каталог,
 * вставляемый в самого себя, — это ошибки РЕШЕНИЯ, а не ввода-вывода, и проверять их
 * обращением к файловой системе значило бы узнавать о них последними.
 *
 * ## Почему подбор уникального имени берёт готовый список
 *
 * В v1 `uniqueName` (`io/fs-ops.ts:275-285`) спрашивал файловую систему до тысячи раз подряд,
 * причём каждая проверка стоила ДВУХ обращений (`existsIn` пробовал имя сначала как файл,
 * потом как каталог). На локальном диске это незаметно, по сети — минуты. Здесь имя
 * подбирается ПО СПИСКУ уровня, который вызывающий и так прочитал одним `list`, поэтому
 * цена подбора — ноль обращений, и правило проверяется без файловой системы вовсе.
 *
 * @module shell/platform/workspace/resource-names
 */

/**
 * Почему имя не годится. Код, а не фраза: по коду интерфейс строит текст на своём языке,
 * а тест сравнивает решение, а не перевод.
 */
export type NameRejection =
  /** Пустое имя или одни пробелы. */
  | 'empty'
  /** Разделитель пути внутри имени: создаём ОДНУ запись, а не дерево. */
  | 'separator'
  /** `.` или `..` — переход по дереву, а не имя. */
  | 'dots'
  /** Символ, запрещённый файловыми системами (`\ / : * ? " < > |`) или управляющий. */
  | 'forbidden-character'
  /** Имя, зарезервированное Windows (`CON`, `PRN`, `NUL`, `COM1`…). */
  | 'reserved'
  /** Точка или пробел в конце: Windows молча их срежет, и имя окажется не тем. */
  | 'trailing'
  /** Длиннее предела одного сегмента пути. */
  | 'too-long';

/**
 * Предел длины сегмента.
 *
 * 255 — общий знаменатель ext4, APFS и NTFS. Ограничение проверяется по кодовым единицам
 * UTF-16, а не по байтам: точная байтовая длина зависит от кодировки файловой системы,
 * а завышенный запас здесь безопаснее заниженного.
 */
export const MAX_NAME_LENGTH = 255;

/** Символы, которые не примет хотя бы одна из целевых файловых систем. */
const FORBIDDEN = /[\\/:*?"<>|]/;

/** Управляющие символы: в имя попадают только вставкой из буфера и всегда по ошибке. */
// eslint-disable-next-line no-control-regex -- проверка именно управляющих символов
const CONTROL = /[\u0000-\u001f\u007f]/;

/**
 * Имена устройств DOS, которые Windows не даёт занять ни файлу, ни каталогу — с расширением
 * или без него (`nul.txt` тоже отказ).
 */
const RESERVED = new Set([
  'con',
  'prn',
  'aux',
  'nul',
  'com1',
  'com2',
  'com3',
  'com4',
  'com5',
  'com6',
  'com7',
  'com8',
  'com9',
  'lpt1',
  'lpt2',
  'lpt3',
  'lpt4',
  'lpt5',
  'lpt6',
  'lpt7',
  'lpt8',
  'lpt9',
]);

/**
 * Проверяет имя одной записи. `null` — имя годится.
 *
 * Проверка идёт по правилам САМОЙ СТРОГОЙ из целевых систем, а не текущей: проект,
 * созданный в Linux, открывают в Windows, и имя `aux.ts` там не создастся вовсе. Отказать
 * при вводе честнее, чем отдать проект, который у соседа не разворачивается.
 */
export function validateResourceName(name: string): NameRejection | null {
  if (name.trim() === '') return 'empty';
  if (name.includes('/')) return 'separator';
  if (name === '.' || name === '..') return 'dots';
  if (CONTROL.test(name) || FORBIDDEN.test(name)) return 'forbidden-character';
  if (name.endsWith('.') || name.endsWith(' ')) return 'trailing';
  if (name.length > MAX_NAME_LENGTH) return 'too-long';

  const stem = name.split('.')[0] ?? '';
  if (RESERVED.has(stem.toLowerCase())) return 'reserved';
  return null;
}

/**
 * Делит имя на основу и расширение так, как этого ждёт человек, разводящий копии.
 *
 * Точка ищется ПОСЛЕДНЯЯ, а не первая: у `schema.form.json` расширением человек считает
 * `.json`, и копия обязана называться `schema.form-2.json`, а не `schema-2.form.json`
 * (v1 брала первую точку и делала именно второе). Ведущая точка расширением не считается:
 * `.gitignore` — это имя целиком, и `-2.gitignore` было бы другим файлом.
 */
export function splitName(name: string): { readonly stem: string; readonly ext: string } {
  const dot = name.lastIndexOf('.');
  if (dot <= 0) return { stem: name, ext: '' };
  return { stem: name.slice(0, dot), ext: name.slice(dot) };
}

/**
 * Свободное имя в уровне: `name`, иначе `name-2`, `name-3`…
 *
 * `taken` — имена, уже занятые в каталоге (обычно результат одного `list`). Сравнение
 * без учёта регистра: на APFS и NTFS `Schema.json` и `schema.json` — одна запись, и копия,
 * различающаяся только регистром, затёрла бы оригинал на половине машин команды.
 *
 * Предел подбора — {@link MAX_UNIQUE_ATTEMPTS}; дальше к основе приписывается переданный
 * `salt`. Соль параметром, а не `Date.now()` внутри: правило обязано быть проверяемым,
 * а функция, чей ответ зависит от часов, проверяется только приблизительно.
 */
export function uniqueName(taken: Iterable<string>, name: string, salt = 'copy'): string {
  const used = new Set<string>();
  for (const item of taken) used.add(item.toLowerCase());
  if (!used.has(name.toLowerCase())) return name;

  const { stem, ext } = splitName(name);
  for (let n = 2; n <= MAX_UNIQUE_ATTEMPTS; n++) {
    const candidate = `${stem}-${n}${ext}`;
    if (!used.has(candidate.toLowerCase())) return candidate;
  }
  return `${stem}-${salt}${ext}`;
}

/**
 * Сколько номеров перебирается, прежде чем имя разводится солью.
 *
 * Тысяча копий одного файла в одном каталоге — это не работа, а авария, и продолжать
 * перебор дальше означало бы её маскировать.
 */
export const MAX_UNIQUE_ATTEMPTS = 999;

/**
 * Лежит ли путь внутри каталога (или является им самим) — по строкам, без обращения к источнику.
 *
 * Нужна ровно одному правилу, зато несущему: каталог нельзя скопировать или перенести
 * внутрь самого себя, иначе обход не завершится вовсе.
 */
export function isInside(path: string, dir: string): boolean {
  if (dir === '') return true;
  return path === dir || path.startsWith(`${dir}/`);
}
