/**
 * Документ — открытый ресурс с текстовым буфером.
 *
 * **Это заготовка, а не полный контракт.** Полный документ — Э6: там появляются провайдер
 * модели, разбор, два вида документа (`TextDocument` против `ModelDocument`), состояние
 * расхождения буфера и модели, история и состояние вида. Здесь ровно тот минимум, без
 * которого Workspace не может выполнить `open`: буфер, признак изменённости и уведомление
 * о смене буфера.
 *
 * **Точка расширения для Э6, подписанная заранее.** Всё, что придёт, надстраивается НАД
 * буфером, а не вместо него:
 *
 * - `DocumentModelProvider` регистрируется на тип ресурса (не на редактор — иначе два вида
 *   на один файл разойдутся в двух представлениях) и даёт `parse`/`print`/`apply`;
 * - у документа с моделью истина — модель, а буфер становится её сериализацией; у документа
 *   без провайдера истина — буфер, и это определение `TextDocument`;
 * - сохранение в состоянии расхождения пишет БУФЕР, а не модель: пользователь сохраняет то,
 *   что видит, и незавершённый код — законное содержимое файла.
 *
 * Из этого следует единственное требование к сегодняшнему коду: {@link Document.getText}
 * обязан оставаться «тем, что уйдёт в файл при сохранении». Workspace пишет и сохраняет
 * именно его, и при появлении модели это правило не меняется.
 *
 * **Надстройка пришла в `model/`** и это правило не нарушила: провайдер, модель, расхождение
 * и история живут там, а здесь появился ровно один новый элемент — {@link DocumentKind},
 * дискриминант союза. Всё остальное по-прежнему буфер.
 *
 * @module host/workspace/document
 */

import { toDisposable, type Disposable } from '../primitives/disposable';
import type { ResourceId, ResourceRef } from '../primitives/resource';

/**
 * Вид документа — дискриминант союза `TextDocument | ModelDocument`.
 *
 * Он объявлен ЗДЕСЬ, а не в `model/`, потому что документ без провайдера модели должен
 * оставаться текстовым, ничем себя для этого не оборачивая: «остаётся текстовым» —
 * это и есть определение `TextDocument`, и обёртка вокруг него означала бы две ссылки
 * на один документ, из которых свежая только одна.
 *
 * Сам буфер о видах не знает: {@link createDocument} всегда делает `'text'`, а `'model'`
 * появляется у документа, которому провайдер модели дал вторую истину (`model/model-document.ts`).
 */
export type DocumentKind = 'text' | 'model';

/** Открытый ресурс: вкладка. Живёт, пока открыт, — в отличие от ресурса, который живёт в источнике. */
export interface Document {
  /**
   * Различает два вида документа. Поле, а не метод: оно не меняется за жизнь документа,
   * и сужение союза обязано работать без вызова.
   */
  readonly kind: DocumentKind;
  readonly id: ResourceId;
  /** Ссылка на ресурс: путь, вид, медиатип. Стабильна на всё время жизни документа. */
  readonly ref: ResourceRef;

  /**
   * Текущий текст буфера — то, что уйдёт в файл при сохранении.
   *
   * Метод, а не поле: буфер меняется, а `useSyncExternalStore` подписывается на
   * {@link Document.onDidChangeContent} и читает снимок — поле заставило бы держать
   * ссылку на документ и следить за мутацией самому.
   */
  getText(): string;

  /** Расходится ли буфер с BASE — тем, что отдал источник. */
  isDirty(): boolean;

  /**
   * Буфер сменился: правкой через Workspace, откатом или слиянием.
   *
   * Обработчик обязан быть дешёвым: уведомление синхронно относительно смены буфера,
   * и тяжёлую работу (разбор, валидацию, перерисовку) планирует себе сам подписчик.
   */
  onDidChangeContent(cb: (text: string) => void): Disposable;
}

/**
 * Документ вместе с ручками управления им.
 *
 * Разведение намеренное: наружу (в редакторы, панели, ассистента) уходит {@link Document},
 * который менять нельзя иначе как через Workspace, а мутаторы остаются у того, кто документ
 * создал. Без разведения любой держатель ссылки мог бы записать в буфер мимо рабочей копии —
 * и `save` начал бы писать не то, что лежит в OPFS.
 */
export interface DocumentHandle {
  readonly document: Document;
  /** Заменяет буфер целиком и уведомляет подписчиков, если текст действительно другой. */
  setText(text: string): void;
  /** Отмечает расхождение с BASE. Считает его Workspace: сравнение требует чтения обоих слоёв. */
  setDirty(dirty: boolean): void;
}

/**
 * Создаёт документ поверх уже прочитанного текста.
 *
 * Текст передаётся, а не читается здесь: документ не знает ни про источник, ни про хранилище —
 * это знание Workspace, и протечь оно не должно ни в редактор, ни в модель.
 */
export function createDocument(ref: ResourceRef, text: string, dirty: boolean): DocumentHandle {
  let content = text;
  let isDirty = dirty;
  const listeners = new Set<(text: string) => void>();

  const document: Document = {
    // Всегда `'text'`: провайдера модели буфер не знает и знать не должен. Документ становится
    // модельным не здесь, а надстройкой над этим буфером — см. `model/model-document.ts`.
    kind: 'text',
    id: ref.id,
    ref,
    getText: () => content,
    isDirty: () => isDirty,
    onDidChangeContent(cb) {
      listeners.add(cb);
      return toDisposable(() => {
        listeners.delete(cb);
      });
    },
  };

  return {
    document,
    setText(next) {
      // Равный текст — не событие: `writeText` дебаунсится и приходит повторно с тем же
      // содержимым, а перерисовка редактора на каждый такой вызов сбрасывала бы выделение.
      if (next === content) return;
      content = next;
      // Снимок: подписка, снятая обработчиком, не должна получить это же уведомление.
      for (const listener of [...listeners]) {
        try {
          listener(content);
        } catch (err) {
          // Упавший подписчик не рвёт правку, которая уже состоялась, — см. `event.ts`.
          console.error('[workspace] подписчик документа упал; правка не отменена', err);
        }
      }
    },
    setDirty(next) {
      isDirty = next;
    },
  };
}
