/**
 * Контракт источника: откуда берутся файлы проекта и куда они возвращаются.
 *
 * **Контракт выведен из потребителя, а не из адаптера.** Workspace (Э2) написан раньше
 * источника специально ради этого и объявил свою потребность сам —
 * `host/workspace/source.ts`. Здесь она не переизобретается: {@link Source} обязан быть
 * НАДМНОЖЕСТВОМ `WorkspaceSource` по типам, чтобы любой источник подходил Workspace как есть,
 * без переходника. Совместимость структурная, поэтому имена членов совпадать не обязаны —
 * обязаны совпадать формы. Проверяется это компиляцией в `contract.test.ts`.
 *
 * **Чего здесь намеренно нет.**
 *
 * - Предметного знания. Источник не знает, что такое форма: он отдаёт файлы и записи каталога.
 *   В v1 обход каталога читал КАЖДЫЙ `.json`-кандидат, чтобы решить, форма ли это, — и это
 *   не промах оптимизации, а чужая ответственность внутри транспорта: локально она стоит
 *   лишнего чтения, по сети — N+1 на каждый каталог. Классификация — чистая функция уровня
 *   домена; {@link Source.listForms} лишь позволяет источнику ответить самому, если он умеет.
 * - Нормализации путей. Ею владеет ядро (`primitives/resource`), иначе два адаптера разойдутся
 *   в трактовке `..` и это вскроется на третьем.
 * - Таблицы расширений. Она там же; адаптер только зовёт `mediaTypeFor`, добавляя подсказку
 *   транспорта, если она у него есть.
 *
 * @module host/source/types
 */

import type { Disposable } from '../primitives/disposable';

/**
 * Ответ источника на чтение текста.
 *
 * `revision` — НЕПРОЗРАЧНЫЙ маркер версии: сравнивается только на равенство. «Новее»
 * не вычисляется никогда: у одного источника это время модификации, у другого — ETag,
 * у третьего — счётчик, и код, научившийся сравнивать их порядком, сломается на втором же.
 *
 * `mediaType` уже разрешён источником: подсказка транспорта (`Content-Type` или его аналог)
 * имеет приоритет, при её отсутствии берётся таблица расширений ядра. Вопрос «что это
 * за документ» тут не решается вовсе — только «текст или байты» и подсветка.
 */
export interface SourceContent {
  readonly text: string;
  readonly revision?: string;
  readonly mediaType?: string;
}

/** Ответ источника на чтение байтов. Поля те же, что у {@link SourceContent}. */
export interface SourceBytes {
  readonly bytes: Uint8Array;
  readonly revision?: string;
  readonly mediaType?: string;
}

/**
 * Запись одного уровня каталога.
 *
 * Уровень отдаётся ОДНИМ обращением и без чтения содержимого: `list` — это листинг,
 * а не обход. Рекурсию и любые решения о содержимом строит вызывающий.
 */
export interface Entry {
  readonly name: string;
  /** Путь внутри источника: разделитель `/`, без ведущего слэша, нормализован. */
  readonly path: string;
  readonly kind: 'file' | 'directory';
}

/**
 * Свойства ресурса. `null` вместо {@link Stat} означает «этого там нет».
 *
 * Заменяет собой проверку существования: она стоит ровно столько же, а отвечает меньше.
 * В v1 существование выяснялось ДВУМЯ обращениями — сначала как к файлу, потом как
 * к каталогу, — и вид ресурса при этом всё равно терялся.
 *
 * `kind: 'directory'` обязателен и для каталогов: резолвер импортов проверяет именно вид,
 * а не наличие, и источник, отвечающий про каталог `null`, ломает сборку формы.
 */
export interface Stat {
  readonly kind: 'file' | 'directory';
  readonly revision?: string;
  /** Размер в БАЙТАХ, а не в символах: у не-ASCII текста это разные числа. */
  readonly size?: number;
  readonly mediaType?: string;
}

/** Что источник сообщает после записи. Новая ревизия нужна, чтобы следующая запись не конфликтовала. */
export interface Written {
  readonly revision?: string;
}

/**
 * Ссылка на форму, которую источник умеет назвать сам.
 *
 * Существует ради {@link Source.listForms}: плоский источник, раздающий формы по
 * идентификатору, знает свой перечень и без обхода дерева. Это ССЫЛКА, а не разбор:
 * «форма ли это» по содержимому решает домен, источник лишь показывает, где смотреть.
 */
export interface FormRef {
  /** Путь входного файла формы внутри источника. */
  readonly path: string;
  /** Человекочитаемое имя, если источник его знает. */
  readonly title?: string;
}

/**
 * Что источник умеет — ОПИСАНИЕ НАМЕРЕНИЙ ДЛЯ ИНТЕРФЕЙСА, а не предусловие вызова.
 *
 * Проверять возможность перед вызовом нельзя: это два источника правды об одном и том же,
 * и они разъедутся на первом источнике, где право на запись зависит от пути, а не от адаптера.
 * Вызывающий вызывает и получает отказ — реализация Workspace не спросила возможности ни разу.
 * Поле нужно интерфейсу: показывать ли кнопку «Сохранить», предлагать ли создание каталога.
 *
 * Отсюда единственное обязательство реализации: возможности не должны РАСХОДИТЬСЯ с методами.
 * Заявил `write: true` — объяви `write`; не умеешь — не объявляй метод либо откажи
 * `unsupported`: для вызывающего это один и тот же ответ.
 */
export interface SourceCapabilities {
  readonly write: boolean;
  /** Есть каталоги — или это плоское пространство имён. НЕ «есть ли пути»: пути есть всегда. */
  readonly tree: boolean;
  /** Возможен ли детект конфликта, то есть отдаёт ли источник ревизии. */
  readonly revisions: boolean;
  /**
   * Можно ли компилировать и исполнять сайдкары этого источника.
   *
   * Умолчание — `false` для всего, кроме локальной файловой системы: до решения о политике
   * live-превью система не исполняет код, пришедший по сети. Умолчание ничего не предрешает
   * и снимается одним изменением возможности.
   */
  readonly executesCode: boolean;
  readonly auth: 'none' | 'session' | 'persistent';
}

/** Локальный каталог, выбранный через File System Access. Сам хэндл — в IndexedDB по ключу. */
export interface FsSourceDescriptor {
  readonly kind: 'fs';
  readonly handleKey: string;
}

/** Тестовый двойник. `label` — то, по чему его находит фабрика. */
export interface MemorySourceDescriptor {
  readonly kind: 'memory';
  readonly label: string;
}

/**
 * Сериализуемое описание источника — то, что переживает перезагрузку вкладки.
 *
 * Живой объект не переживает: у File System Access это хэндл каталога, который клонируется
 * структурно, но не сериализуется в JSON, у источника с аутентификацией — ещё и токен.
 * Поэтому в хранилище едет дескриптор, а источник поднимается по нему через
 * {@link SourceFactory}.
 */
export type SourceDescriptor = FsSourceDescriptor | MemorySourceDescriptor;

/**
 * Источник — транспорт до файлов проекта.
 *
 * Обязательны четыре метода чтения; всё остальное необязательно, и его отсутствие —
 * законный ответ «не умею». Пути на входе нормализует сам источник (ядром), путь,
 * уводящий за корень, — отказ `forbidden`, а не тихое схлопывание к корню.
 */
export interface Source {
  /** Идентификатор источника: первая половина `ResourceId` (`<sourceId>:<path>`). */
  readonly id: string;
  /** Чем источник переоткрывается после перезагрузки. */
  readonly descriptor: SourceDescriptor;
  readonly capabilities: SourceCapabilities;

  /**
   * Читает текст. Отсутствие ресурса — отказ `not-found`, а не пустой ответ: «пустой файл»
   * и «файла нет» обязаны различать и вызывающий, и догрузка.
   */
  read(path: string): Promise<SourceContent>;
  /** Читает байты. Необязателен: источник, отдающий только текст, просто не объявляет метод. */
  readBytes?(path: string): Promise<SourceBytes>;
  /**
   * Один уровень каталога одним обращением.
   *
   * Отсутствующий каталог — отказ `not-found`, и это НЕ то же самое, что пустой список:
   * Workspace реагирует на них противоположно, и склеивание их превращает «каталога нет»
   * в «проект пуст».
   */
  list(dir: string): Promise<readonly Entry[]>;
  /** Свойства или `null`. Одно обращение вместо двух проверок существования. */
  stat(path: string): Promise<Stat | null>;

  /**
   * Пишет текст.
   *
   * `expected` — ревизия, которую вызывающий считает текущей. При РАСХОЖДЕНИИ (сравнение
   * на равенство, не на «новее») источник обязан отказать `conflict` и вернуть в отказе свою
   * текущую ревизию: без неё диалогу слияния нечего показать в колонке «версия источника».
   * Без `expected` — перезапись.
   */
  write?(path: string, text: string, expected?: string): Promise<Written>;
  /**
   * Пишет байты — тем же контрактом, что {@link Source.write}, но без прохода через строку.
   *
   * Существует ради ОДНОГО сценария, зато обязательного: копирование записи дерева. Файл
   * проекта не обязан быть текстом (картинка в markdown, шрифт, `.ico`), а копия, прошедшая
   * через `read`/`write`, портится молча — декодирование как UTF-8 и обратное кодирование
   * не является тождественным преобразованием для произвольных байтов.
   *
   * Необязателен по той же причине, что и `readBytes`: источник, хранящий только текст,
   * просто не объявляет метод, и копирование честно деградирует до текстового.
   */
  writeBytes?(path: string, bytes: Uint8Array, expected?: string): Promise<Written>;
  mkdir?(path: string): Promise<void>;
  remove?(path: string): Promise<void>;
  move?(from: string, to: string): Promise<void>;

  /** Отменяет обход дерева целиком, если источник умеет отдать список форм сам. */
  listForms?(): Promise<readonly FormRef[]>;
  /**
   * Наблюдение за изменениями. В первой версии не реализует никто: File System Access
   * наблюдения не даёт вовсе, а вместо него — перепроверка `stat` у открытых ресурсов
   * при возврате фокуса в окно.
   */
  watch?(glob: string, cb: (path: string) => void): Disposable;
}

/**
 * Почему источник не поднялся.
 *
 * Различать обязательно, и не ради полноты: **в интерфейсе этим двум случаям соответствуют
 * разные кнопки**. «Источника больше нет» лечится только выбором проекта заново — диалогом
 * выбора каталога, то есть новым дескриптором. «Доступ не подтверждён» лечится одним
 * нажатием «разрешить»: дескриптор на месте, хэндл на месте, не хватает жеста пользователя,
 * без которого браузер не отдаёт разрешение. Свести их в один ответ — значит показать
 * человеку кнопку, которая либо просит лишнего, либо не просит нужного.
 */
export type SourceUnavailableReason =
  /**
   * Описанного источника больше нет: хэндл не пережил хранилище, базу почистили, проект
   * открывали на другой машине, каталог удалили.
   */
  | 'missing'
  /**
   * Источник на месте, но доступ к нему не подтверждён: разрешение не выдавали, отозвали,
   * либо его не у чего было спросить — запрос требует жеста пользователя, а восстановление
   * идёт на старте, без жеста.
   */
  | 'denied';

/** Ответ фабрики, когда источника нет. Не ошибка: приложение обязано открыться без проекта. */
export interface SourceUnavailable {
  readonly unavailable: SourceUnavailableReason;
}

/**
 * Что отвечает фабрика: живой источник либо причина, по которой его нет.
 *
 * Прежде здесь был `Source | null`, и `null` схлопывал оба случая. Разведение сделано типом,
 * а не отдельным «спроси потом, что случилось»: причина известна ровно тому, кто отказал,
 * и ровно в тот момент; хранить её сбоку значило бы завести второе состояние, которое
 * разъедется с первым.
 */
export type RestoredSource = Source | SourceUnavailable;

/**
 * Не поднялся ли источник — и если да, то по какой причине.
 *
 * Различение по полю, а не по `instanceof` или по отсутствию методов: тот же приём и по той же
 * причине, что у `SourceErrorLike` в `./errors` — источник может приехать из другого бандла
 * или быть подставлен в тесте, и признание по структуре работает во всех случаях одинаково.
 */
export function isSourceUnavailable(result: RestoredSource): result is SourceUnavailable {
  return typeof (result as Partial<SourceUnavailable>).unavailable === 'string';
}

/**
 * Восстановление источника по дескриптору.
 *
 * Ответ «не смогли» — обычный ход событий, а не авария: пользователь закрыл диалог разрешения,
 * и приложение обязано открыться без проекта. Но он обязан быть РАЗЛИЧИМ — см.
 * {@link SourceUnavailableReason}.
 */
export interface SourceFactory {
  readonly kind: string;
  restore(descriptor: SourceDescriptor): Promise<RestoredSource>;
}

/**
 * Потолок листинга одного уровня.
 *
 * Превышение — отказ `budget`, а не усечение: молчаливо усечённый листинг выглядит как
 * «всё на месте», а потом файл «необъяснимо» не находится. Значение того же порядка,
 * что потолок обхода рабочей области: каталог на десятки тысяч записей — это `node_modules`,
 * то есть ошибка выбора каталога, а не большой проект.
 */
export const SOURCE_LIST_LIMIT = 5000;
