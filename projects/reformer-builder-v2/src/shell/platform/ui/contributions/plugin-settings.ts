/**
 * Точка расширения «настройки плагина каталога».
 *
 * Плагин объявляет, что у него есть настраиваемое, и отдаёт ОПИСАНИЕ формы. Рисует эту форму
 * раздел «Плагины» окна настроек, значения кладутся в службу настроек под ключом плагина
 * (`platform/services/plugin-settings`).
 *
 * ## Почему полезная нагрузка непрозрачна для платформы
 *
 * `schema` объявлена как `unknown`, хотя на деле это `JsonFormSchema`. Сузить тип здесь значило
 * бы, что ПЛАТФОРМА узнала про формы, — а она не знает предметных сущностей вовсе (правило
 * слоёв, `eslint.config.js`). Сужение делает тот, кому предметное знание разрешено:
 * композиция, когда собирает тело раздела. Платформа же переносит вклад, не заглядывая внутрь,
 * ровно как переносит `Body` раздела настроек.
 *
 * ## Точка КАТАЛОЖНАЯ, и это сказано в имени
 *
 * Форма рисуется только в строке плагина каталога — у встроенных плагинов строки нет, и вклад
 * от встроенного никто не покажет. Имя точки и этот абзац существуют, чтобы автор встроенного
 * плагина узнал об этом отсюда, а не из пустого места в интерфейсе. Понадобятся настройки
 * встроенному — это отдельное решение: у него есть свой раздел или своё место в чужом.
 *
 * @module shell/platform/ui/contributions/plugin-settings
 */

import { defineExtensionPoint } from '@/shell/platform/primitives/extension-point';

/**
 * Что плагин рассказывает о своих настройках.
 *
 * Умолчаний здесь НЕТ намеренно: их объявляет сам плагин через `settings.registerDefault`
 * в `activate` — тем же вызовом, каким это делает плагин китов. Второе поле с умолчаниями
 * во вкладе дало бы два источника одной сущности и правило приоритета между ними.
 */
export interface CatalogPluginSettingsContribution {
  /**
   * Чьи это настройки. Обязателен: точка глобальная, а строка в списке — конкретного плагина.
   *
   * Проверяется на совпадение с `pluginId` вклада (его проставляет реестр, а не вносящий):
   * плагин не настраивает соседа.
   */
  readonly pluginId: string;
  /**
   * Описание формы — `JsonFormSchema` пакета `@reformer/renderer-json`.
   *
   * Тип намеренно широкий: см. шапку модуля. Разбирает и проверяет схему композиция,
   * непригодная показывается человеку как отказ, а не роняет раздел.
   */
  readonly schema: unknown;
  /**
   * Заголовок формы в карточке. Ключ СЛОВАРЯ ПЛАГИНА либо готовая строка — плагин решает сам,
   * потому что его словарь знает только он.
   */
  readonly titleKey?: string;
}

/** Точка расширения. Вносят плагины каталога, читает раздел «Плагины» окна настроек. */
export const CatalogPluginSettingsPoint =
  defineExtensionPoint<CatalogPluginSettingsContribution>('catalog-plugin.settings');
