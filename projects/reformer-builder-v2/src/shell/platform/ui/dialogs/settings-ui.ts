/**
 * Модель окна настроек: разделы и поля.
 *
 * ## Поле знает, как читать и писать СЕБЯ
 *
 * Соблазн описать настройку одним ключом (`host.theme`) и дать окну писать его через
 * `SettingsService` велик — и неверен: у темы за записью стоит применение к корню документа,
 * у локали — догрузка словаря, и оба шага делают СЛУЖБЫ, а не хранилище. Окно, знающее про
 * ключ, обязано было бы знать и про эти шаги, то есть про каждую службу приложения.
 *
 * Поэтому поле — пара `read`/`write` поверх того, кто настройкой владеет. Окно рисует список
 * и зовёт `write`; что при этом происходит, знает тот, кто поле собрал (`app/settings-sections`).
 *
 * ## Почему только выбор из списка
 *
 * Обе настройки, которые сегодня есть, — выбор из перечисления. Ввод строки, число и флажок
 * добавятся вместе с первой настройкой, которой они нужны: вид поля, у которого нет ни одного
 * пользователя, невозможно проверить, и он расходится с действительностью молча.
 *
 * @module shell/platform/ui/dialogs/settings-ui
 */

/** Один вариант выбора: значение и ключ его подписи. */
export interface SettingChoice {
  readonly value: string;
  readonly titleKey: string;
}

/** Одна настройка: подпись, пояснение, варианты и доступ к значению. */
export interface SettingField {
  /** Уникален в пределах раздела. Годится React-ключом и адресом в тесте. */
  readonly id: string;
  readonly titleKey: string;
  /** Пояснение под подписью: чем этот выбор отличается. Необязательно. */
  readonly descriptionKey?: string;
  readonly choices: readonly SettingChoice[];
  /** Действующее значение. Синхронно: окно рисует его на каждый кадр. */
  read(): string;
  /** Применяет выбор. Ошибку показывает окно, а не глотает вызывающий. */
  write(value: string): Promise<void>;
}

/** Раздел — то, что в окне стоит слева. */
export interface SettingsSection {
  readonly id: string;
  readonly titleKey: string;
  readonly fields: readonly SettingField[];
}
