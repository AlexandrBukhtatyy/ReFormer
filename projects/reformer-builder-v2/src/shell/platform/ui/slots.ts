/**
 * Слоты оболочки и точка расширения панелей.
 *
 * Область раскладки — понятие платформенное, а не предметное, поэтому Host вправе её знать.
 * Набор фиксирован: если плагину нужна новая область, это правка Host — и пусть будет заметной.
 * Обратное («слот заводится вкладом») означало бы, что раскладка приложения зависит от того,
 * какие плагины включены, и два одинаковых слота от двух плагинов были бы неразличимы.
 *
 * ## Регистрация панелей глобальная, `when` управляет только видимостью
 *
 * Это главное решение модуля, и оно не про удобство. Если панель регистрировать на время
 * активности редактора, рейл мигает при каждом переключении вкладки: вклад снимается
 * и вносится заново, а вместе с ним пересоздаётся React-поддерево. Здесь вклад вносится один
 * раз при активации плагина и живёт до его выключения, а `when` каждый кадр отвечает только
 * на вопрос «показывать ли сейчас».
 *
 * Тем же чинится дефект v1, где палитра компонентов видна на вкладке с markdown, а инспектор
 * при этом пуст: там видимость панели была зашита в раскладку, здесь — в предикат вклада,
 * то есть у того, кто про содержимое панели знает.
 *
 * @module host/ui/slots
 */

import type { ComponentType } from 'react';
import { defineExtensionPoint } from '@/shell/platform/primitives/extension-point';
import type { WhenContext } from '@/shell/platform/primitives/when-context';

/**
 * Область оболочки, в которую можно внести панель.
 *
 * - `rail.left` — вертикальные вкладки слева: переключатель левой панели и мелкие кнопки;
 * - `panel.left` / `panel.right` / `panel.bottom` — доки вокруг центра;
 * - `toolbar` / `statusbar` — горизонтальные полосы сверху и снизу;
 * - `editor.main` — центр.
 *
 * Вкладки документов Host держит сам: вкладка — это открытый ресурс, а открытые ресурсы
 * принадлежат Workspace, поэтому слота под них нет.
 */
export type SlotId =
  | 'rail.left'
  | 'panel.left'
  | 'panel.right'
  | 'panel.bottom'
  | 'toolbar'
  | 'statusbar'
  | 'editor.main';

/** Все слоты в порядке обхода. Нужен диагностике и тестам, а не раскладке. */
export const SLOT_IDS: readonly SlotId[] = Object.freeze([
  'rail.left',
  'panel.left',
  'panel.right',
  'panel.bottom',
  'toolbar',
  'statusbar',
  'editor.main',
] as const);

/** Проверка непрозрачной строки (настройки, диагностика) на принадлежность набору слотов. */
export function isSlotId(value: unknown): value is SlotId {
  return typeof value === 'string' && (SLOT_IDS as readonly string[]).includes(value);
}

/**
 * Панель — единица содержимого слота.
 *
 * `titleKey`, а не готовая строка: панель регистрируется один раз при активации плагина,
 * а локаль меняется потом, и переведённый в момент регистрации заголовок остался бы
 * на языке, который был активен тогда. Ключ разрешается в пространстве имён внёсшего
 * плагина — см. panelTitle в ./panels.
 */
export interface PanelContribution {
  /**
   * Идентификатор панели. Приходит в `Body` как `panelId` и служит адресом в настройках
   * (какая вкладка дока активна).
   *
   * Уникальность в пределах точки расширения им **не** гарантируется: реестр проверяет
   * только явный `meta.id` вклада. Поэтому React-ключом служит идентификатор вклада,
   * а не этот.
   */
  readonly id: string;
  readonly slot: SlotId;
  /** Ключ i18n заголовка — в пространстве имён плагина, внёсшего панель. */
  readonly titleKey: string;
  /** Значок для рейла и шапки дока. Без него рейл покажет первые буквы заголовка. */
  readonly icon?: ComponentType;
  readonly Body: ComponentType<{ panelId: string }>;
  /**
   * Показывать ли панель сейчас. Отсутствие предиката означает «всегда».
   *
   * Предикат обязан быть чистым и быстрым: он вычисляется на каждое изменение
   * {@link WhenContext} для каждой панели каждого слота.
   */
  readonly when?: (ctx: WhenContext) => boolean;
  /**
   * Порядок внутри слота; меньше — раньше. Без значения берётся `order` вклада.
   *
   * Два источника порядка — не дублирование: `order` вклада принадлежит регистрации
   * (им плагин расставляет свои вклады между собой), а этот — самой панели, и он
   * переживает перерегистрацию.
   */
  readonly order?: number;
  /**
   * Где стоит вкладка панели на рейле: в основной группе или прижатой к низу.
   *
   * Не то же, что {@link PanelContribution.order}. Порядок расставляет панели ВНУТРИ
   * группы; эта пара говорит, к какому краю рейла панель принадлежит. Выразить прижатие
   * к низу через большой порядок нельзя: «последняя в списке» и «у нижнего края»
   * совпадают только пока рейл заполнен целиком.
   *
   * Нижняя группа — для того, что человек зовёт, а не просматривает: помощь, ассистент,
   * настройки. Их место на краю постоянно, поэтому рука находит их не глядя, сколько бы
   * панелей ни добавили сверху.
   */
  readonly railPlacement?: 'top' | 'bottom';
  /**
   * Значок на вкладке панели: число находок, точка «есть новое» и подобное.
   *
   * КОМПОНЕНТ, а не число: панель сама знает, на что подписаться и как часто это меняется,
   * а оболочка не должна ни того ни другого. Верни он число — оболочке пришлось бы
   * перевычислять его на каждый свой кадр либо завести отдельный канал уведомлений
   * ради одной цифры.
   *
   * Значок — единственное, что видно у панели в свёрнутом доке, и ради него свёрнутое
   * состояние и существует: полоса вкладок остаётся, чтобы ошибку было видно, не разворачивая.
   */
  readonly Badge?: ComponentType<{ panelId: string }>;
  /**
   * Действия панели — то, что стоит в шапке дока справа от заголовка.
   *
   * КОМПОНЕНТ по той же причине, что {@link PanelContribution.Badge}: доступность действия
   * зависит от состояния, которое знает панель («перечитать» имеет смысл всегда, «сохранить»
   * — только когда есть что), а оболочка ни этого состояния, ни поводов перерисоваться
   * не имеет.
   *
   * Почему не в теле панели: кнопка, стоящая первой строкой содержимого, уезжает вместе
   * с ним при прокрутке и занимает высоту у списка — а шапка дока уже нарисована и пуста
   * справа. Тело панели — про содержимое; постоянные действия над ним — про шапку.
   *
   * Рисуется только там, где шапка есть, — в левом и правом доках. У нижнего её нет вовсе:
   * его роль играет полоса вкладок.
   */
  readonly Actions?: ComponentType<{ panelId: string }>;
}

/**
 * Точка расширения панелей.
 *
 * Заполняется только через `PluginContext.extensions`: у корневого реестра метода
 * `contribute` нет вовсе, поэтому «панель, внесённая самим Host» невыразима, и вопрос
 * «откуда здесь эта панель» всегда имеет ответ.
 */
export const PanelPoint = defineExtensionPoint<PanelContribution>('panel');
