/**
 * Быстрые исправления, которым есть чем исполниться: отбор по реестру команд.
 *
 * {@link QuickFix} называет команду СТРОКОЙ, и это правильно — валидатор не обязан видеть
 * реализацию того, чем чинят. Но у строки нет владельца: ничто не мешает опечататься в
 * идентификаторе или назвать команду плагина, который выключен. Такой `QuickFix` сегодня
 * неотличим от рабочего до самого нажатия, а нажатие даёт `CommandError('not-found')` —
 * человеку в виде «кнопка есть, ничего не произошло», ассистенту в виде отказа посреди хода,
 * когда половина правки уже применена.
 *
 * ## Проверяем В МОМЕНТ ПОКАЗА, а не при регистрации вклада
 *
 * Соблазн проверить раньше — на активации плагина-валидатора — обязан быть отвергнут, и не из
 * осторожности, а из уже принятого решения: **порядок активации плагинов объявлен незначимым
 * и закреплён тестом** (правило приёмки Э4). Валидатор вправе активироваться до редактора,
 * который владеет командой правки; проверка на активации объявила бы законный порядок ошибкой
 * и погасила бы исправления, которые через миг станут рабочими.
 *
 * Момент показа отвечает точно. Реестр команд спрашивают тогда, когда исправление предъявляют
 * потребителю: у публикации диагностики — на каждой правке текста, у панели проблем и канваса —
 * на отрисовке, у ассистента — перед вызовом. К этому времени все плагины, которые вообще
 * поднимутся, уже подняты, а те, что выключили руками, уже сняли свои команды.
 *
 * ## Отбрасываем молча только для пользователя, но не для автора
 *
 * Исчезнувшая кнопка — это правильный ответ человеку (обещать он ничего не должен), но
 * никудышный ответ автору валидатора: опечатка в идентификаторе стала бы неотличима от
 * «плагин выключен». Поэтому отбор сообщает о каждом отброшенном исправлении вызывающему
 * ({@link FixesOptions.onUnavailable}), а тот решает, что с этим делать — обычно предупредить
 * в консоли по одному разу на идентификатор.
 *
 * @module shell/platform/diagnostics/fixes
 */

import type { Diagnostic, QuickFix } from './types';

/**
 * Есть ли сейчас команда с таким идентификатором.
 *
 * Предикат, а не сам реестр команд: диагностика не должна знать про `CommandRegistry` (он ей
 * не нужен ни для чего другого), а вызывающему проще всего отдать `(id) => commands.get(id)
 * !== undefined`. Заодно это делает отбор проверяемым без единого реестра.
 *
 * **Применимость (`enabled`) здесь НЕ спрашивается.** «Команды нет» и «команда сейчас
 * недоступна» — разные ответы: первое означает, что исправление неисполнимо в принципе,
 * второе — что не в этом контексте, и второе обязано проверяться там же, где у человека, —
 * в момент вызова. Смешать их значило бы прятать исправление на время, пока фокус стоит
 * не в том месте.
 */
export type CommandLookup = (commandId: string) => boolean;

export interface FixesOptions {
  /**
   * Куда сообщить об отброшенном исправлении. Необязателен, но нужен почти всем: без него
   * опечатка в идентификаторе команды исчезает вместе с кнопкой.
   */
  readonly onUnavailable?: (fix: QuickFix, diagnostic: Diagnostic) => void;
}

/** Общий пустой список: одна ссылка вместо нового массива на каждый вызов. */
const NO_FIXES: readonly QuickFix[] = Object.freeze([]);

/**
 * Исправления диагностики, чью команду сейчас можно выполнить.
 *
 * Возвращает **ту же ссылку**, если отбрасывать нечего: список читают из отрисовки, и новый
 * массив на каждый вызов ломал бы сравнение по ссылке ровно там, где на него рассчитывают
 * (`useSyncExternalStore`, мемоизация строки панели).
 */
export function usableFixes(
  diagnostic: Diagnostic,
  isRegistered: CommandLookup,
  options: FixesOptions = {}
): readonly QuickFix[] {
  const fixes = diagnostic.fixes;
  if (fixes === undefined || fixes.length === 0) return NO_FIXES;

  let dropped = false;
  const kept: QuickFix[] = [];
  for (const fix of fixes) {
    if (isRegistered(fix.commandId)) {
      kept.push(fix);
      continue;
    }
    dropped = true;
    options.onUnavailable?.(fix, diagnostic);
  }
  return dropped ? kept : fixes;
}

/**
 * Копия записи без поля `fixes`.
 *
 * Пустое поле не заводится: `fixes: []` и отсутствие поля читаются одинаково, но первое тянется
 * в каждое сравнение снимков и в каждый сериализованный лог. Копирование через `delete`, а не
 * перечислением полей: перечисление молча теряло бы поле, добавленное к диагностике завтра.
 */
function withoutFixes(item: Diagnostic): Diagnostic {
  const copy: { -readonly [K in keyof Diagnostic]: Diagnostic[K] } = { ...item };
  delete copy.fixes;
  return copy;
}

/**
 * Тот же отбор для целого свода: диагностики с неисполнимыми исправлениями пересобираются,
 * остальные остаются собой.
 *
 * Ссылки сохраняются по той же причине, что и в {@link usableFixes}, и на двух уровнях сразу:
 * не изменившийся список отдаётся как есть, не изменившаяся запись — тоже. Свод диагностик
 * читает панель проблем через подписку, и «всё новое на каждой правке» означало бы перерисовку
 * всего списка на каждый набранный символ.
 */
export function withUsableFixes(
  items: readonly Diagnostic[],
  isRegistered: CommandLookup,
  options: FixesOptions = {}
): readonly Diagnostic[] {
  let changed = false;
  const out: Diagnostic[] = [];

  for (const item of items) {
    const fixes = usableFixes(item, isRegistered, options);
    if (fixes === item.fixes || (fixes.length === 0 && item.fixes === undefined)) {
      out.push(item);
      continue;
    }
    changed = true;
    out.push(fixes.length === 0 ? withoutFixes(item) : { ...item, fixes });
  }

  return changed ? out : items;
}
