/**
 * Путевая арифметика над адресами ресурсов — для портов, которым нужно «рядом с этим файлом».
 *
 * Живёт в композиции, а не у плагинов, по правилу самого контракта: разбирать адрес ресурса
 * позволено только `parseResourceId`, и то лишь потому, что резолвер импортов, дерево и листинг
 * без этого невозможны. Плагину адрес непрозрачен — иначе он начнёт различать источники,
 * у которых внутри путь, и источники, у которых внутри то, что вернул сервер.
 *
 * Общий модуль, а не по копии в каждом порту: сегодня это нужно генерации кода и шаблонам,
 * и обе делают с адресом ровно одно и то же — поднимаются к каталогу и приписывают имена.
 *
 * @module app/resource-paths
 */

import {
  joinPath,
  makeResourceId,
  parseResourceId,
  type ResourceId,
} from '@/shell/platform/primitives/resource';

/**
 * Каталог, в котором лежит ресурс.
 *
 * Для ресурса в корне источника отдаёт **сам корень**, а не поднимается выше: подниматься
 * из корня некуда, и попытка была бы выходом за пределы источника.
 */
export function parentOf(id: ResourceId): ResourceId {
  const { sourceId, path } = parseResourceId(id);
  const at = path.lastIndexOf('/');
  return makeResourceId(sourceId, at <= 0 ? '' : path.slice(0, at));
}

/**
 * Адрес внутри каталога.
 *
 * Выйти за корень источника нельзя: нормализация на `..` из корня **бросает**, а не
 * схлопывает молча до корня. Отказ здесь правильнее тишины — молчаливое схлопывание
 * превратило бы «запиши на два уровня выше» в «запиши в корень проекта», то есть
 * промах адресации стал бы записью не туда без единого признака.
 */
export function resolve(dir: ResourceId, ...segments: readonly string[]): ResourceId {
  const { sourceId, path } = parseResourceId(dir);
  return makeResourceId(sourceId, joinPath(path, ...segments));
}

/**
 * Адрес по пути от КОРНЯ того же источника, которому принадлежит `anchor`.
 *
 * Нужен тем, у кого на руках путь ОТ КОРНЯ, а не смещение от текущего каталога: так адресуется
 * фикстура формы — её путь выводится из пути документа схемы (`fixturePathOf`) целиком, и
 * разбирать его обратно на сегменты ради `resolve` значило бы считать одно и то же дважды.
 *
 * Источник берётся у якоря, а не запрашивается отдельно: «корень проекта» вне источника
 * не определён, а якорем всегда служит ресурс, ради которого адрес и строят.
 */
export function fromRoot(anchor: ResourceId, path: string): ResourceId {
  const { sourceId } = parseResourceId(anchor);
  return makeResourceId(sourceId, joinPath('', path));
}
