/**
 * Ленивая загрузка пространства имён кита — единственной части превью, которая тянет кит целиком.
 *
 * ## Почему лениво
 *
 * `@reformer/ui-kit` — самый крупный чанк приложения, и нужен он только тому, кто рисует форму
 * по-настоящему. Билдер открывается, показывает дерево проекта и правит схему, ни разу его
 * не затронув, — грузить кит на старте значило бы платить за него всегда.
 *
 * ## Уведомление обязательно, а не удобно
 *
 * Загрузка начинается при ПЕРВОМ обращении, то есть уже во время сборки формы, и вернуть готовое
 * пространство имён этому вызову невозможно — он синхронный. Значит первая форма всегда собирается
 * без кита, и все его компоненты уходят в подписанные стабы («не резолвится в @reformer/ui-kit»).
 * Без уведомления пересобрать её было некому: заглушки оставались на экране до тех пор, пока
 * человек не переключал вид туда-обратно — перемонтирование поверхности собирало форму заново,
 * теперь уже с загруженным китом.
 *
 * `onDidLoad` не заменяет `KitsService.onDidChange` (тот про СМЕНУ активного кита), а дополняет
 * его: «кит тот же, но теперь он есть» — отдельное событие.
 *
 * ## Опоздавший подписчик тоже узнаёт — но ровно один раз
 *
 * Загрузку начинает отрисовка, а подписывается эффект: уведомление может уйти раньше, чем его
 * станет кому слушать (импорт из прогретого кэша разрешается микротаском). Тогда стабы застряли бы
 * точно так же, только реже и невоспроизводимо — худший сорт дефекта. Поэтому загрузчик помнит,
 * дошло ли уведомление хоть до кого-нибудь, и первому же опоздавшему сообщает лично.
 *
 * Именно «первому», а не каждому: сообщать всякому подписчику после загрузки значило бы
 * пересобирать форму лишний раз при каждом открытии вида — с уже правильным китом.
 *
 * ## Отказ загрузки — не авария
 *
 * Кит мог не собраться, не доехать по сети, отсутствовать в этой сборке. Форма при этом рисуется
 * подписанными стабами и остаётся понятной, поэтому отказ логируется и на этом заканчивается.
 * Повторная попытка разрешена: `loading` снимается в любом случае.
 *
 * @module app/kit-namespace
 */

import type { Disposable } from '@/shell/platform/primitives/disposable';
import type { KitNamespace } from '@/lib/kits/types';

export interface KitNamespaceLoader {
  /** Пространство имён либо `null`, если ещё не загружено. Первый вызов начинает загрузку. */
  get(): KitNamespace | null;
  /** Загрузка завершилась — тем, кто уже собрал форму без кита. */
  onDidLoad(cb: () => void): Disposable;
}

/**
 * Собирает загрузчик.
 *
 * Импорт приходит параметром: динамический `import('@reformer/ui-kit')` в теле модуля сделал бы
 * поведение непроверяемым — тест обязан наблюдать переход «нет кита → есть кит», а не ждать,
 * пока соберётся настоящий чанк на несколько сотен килобайт.
 */
export function createKitNamespaceLoader(load: () => Promise<KitNamespace>): KitNamespaceLoader {
  let loaded: KitNamespace | null = null;
  let loading: Promise<void> | null = null;
  const listeners = new Set<() => void>();
  /** Дошло ли уведомление о загрузке хоть до одного слушателя. */
  let announced = false;

  const notify = (): void => {
    for (const listener of [...listeners]) {
      try {
        listener();
      } catch (error) {
        // Политика всех хранилищ оболочки: упавший подписчик не мешает остальным узнать.
        console.error('[preview] подписчик загрузки кита отказал', error);
      }
    }
  };

  return {
    get: () => {
      if (loaded === null && loading === null) {
        loading = load()
          .then((namespace) => {
            loaded = namespace;
            announced = listeners.size > 0;
            notify();
          })
          .catch((error: unknown) => {
            console.error('[preview] кит не загрузился: рисуем заглушки', error);
          })
          .finally(() => {
            loading = null;
          });
      }
      return loaded;
    },

    onDidLoad(cb: () => void): Disposable {
      listeners.add(cb);
      if (loaded !== null && !announced) {
        announced = true;
        // Микротаском, а не сразу: подписка ставится из эффекта React, и вызвать оттуда
        // обновление состояния синхронно значило бы перерисовку внутри коммита.
        queueMicrotask(cb);
      }
      return {
        dispose(): void {
          listeners.delete(cb);
        },
      };
    },
  };
}
