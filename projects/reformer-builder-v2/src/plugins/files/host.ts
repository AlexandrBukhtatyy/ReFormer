/**
 * Порт платформы для плагина файлов: ровно то, чем он пользуется, и ничего сверх.
 *
 * ## Почему порт, а не импорт
 *
 * Плагин видит платформу только через `@/sdk` (проверяется линтером), а `@/sdk` — сданная
 * поверхность: панелей, редакторов и рабочей области в ней нет. Расширять её ради одного
 * плагина нельзя, поэтому недостающее приходит ПАРАМЕТРОМ — тем же приёмом, которым
 * `host/workspace/source.ts` объявляет свою потребность в источнике, а `host/ui/tabs.ts` —
 * в рабочей области: потребность объявляет потребитель, а удовлетворяет её композиция.
 *
 * Типы здесь СТРУКТУРНЫЕ копии платформенных, и это не дублирование контракта, а его сужение:
 * каждая из них должна быть НАДМНОЖЕСТВОМ настоящей (`PanelContribution` присваивается
 * в {@link FilesPanelSpec}, `EditorContribution` — в {@link FilesEditorSpec}). Совместимость
 * проверяется компиляцией в одном-единственном месте — там, где `app/boot` подставляет
 * настоящие точки расширения.
 *
 * ## Чего в порту нет
 *
 * Реестров, рабочей области, оболочки: плагин не должен уметь открыть чужой документ или
 * прочитать чужой вклад. Всё, что он делает с рабочей областью, выражено четырьмя глаголами —
 * открыть проект, сохранить, прочитать буфер документа, записать в него.
 *
 * @module plugins/files/host
 */

import type { ComponentType } from 'react';
import type { Disposable, ResourceId, ResourceRef } from '@/sdk';

/**
 * Типизированное имя точки расширения — структурная копия `host/primitives/extension-point`.
 *
 * `__type` существует только для вывода типов и в рантайме отсутствует; ключом служит `id`.
 */
export interface ExtensionPointRef<T> {
  readonly id: string;
  readonly __type?: T;
}

/**
 * Панель — в объёме, который вносит этот плагин.
 *
 * `slot` объявлен строкой, а не набором слотов: набор принадлежит оболочке, и копия его
 * перечисления здесь разошлась бы с оригиналом на первом же новом слоте. Что строка обязана
 * быть слотом, проверяет подстановка настоящей точки расширения в `app/boot`.
 */
export interface FilesPanelSpec {
  readonly id: string;
  readonly slot: string;
  readonly titleKey: string;
  readonly icon?: ComponentType;
  readonly Body: ComponentType<{ panelId: string }>;
  /** Значок на вкладке: число находок. Копия поля `PanelContribution.Badge`. */
  readonly Badge?: ComponentType<{ panelId: string }>;
  readonly order?: number;
}

/** Проба содержимого: то же, что `EditorProbe` платформы. Читает ОДИН раз на всех кандидатов. */
export interface FilesEditorProbe {
  text(): Promise<string>;
}

/** Редактор — в объёме, который вносит этот плагин. */
export interface FilesEditorSpec {
  readonly id: string;
  canOpen(ref: ResourceRef, probe: FilesEditorProbe): number | false;
  readonly Body: ComponentType<{ documentId: ResourceId }>;
}

/**
 * Открытый документ — в объёме, нужном текстовому редактору.
 *
 * `getText` — то, что уйдёт в файл при сохранении; писать в него можно только через
 * {@link FilesHost.writeText}, то есть через рабочую область. Отдельного канала записи
 * у плагина нет, и это граница прав, а не неудобство.
 */
export interface FilesDocument {
  readonly ref: ResourceRef;
  getText(): string;
  isDirty(): boolean;
  onDidChangeContent(cb: (text: string) => void): Disposable;
}

/** Перевод в пространстве имён плагина. */
export type Translate = (key: string, params?: Record<string, unknown>) => string;

/** Всё, что плагин файлов получает от композиции. */
export interface FilesHost {
  /**
   * Тело панели с деревом ресурсов.
   *
   * Компонент платформенный (`host/ui/ResourceTree`) — навигация по ресурсам не предметна
   * и живёт в Host целиком. А вот МЕСТО для неё — решение предметное, и принимает его этот
   * плагин: он же может его и не вносить.
   */
  readonly ResourceTreePanel: ComponentType<{ panelId: string }>;

  /**
   * Реактивный перевод. Хук, а не функция: локаль меняется, и компонент обязан
   * перерисоваться — подписку на смену локали держит композиция.
   */
  useTranslate(): Translate;

  /**
   * Перевод кода диагностики словарём **Host**, а не плагина.
   *
   * То же разделение, что в порту Monaco (`plugins/editor-monaco/host`), и по той же
   * причине: строку рисует панель проблем, но владеет ею тот, кто завёл код, — а коды
   * диагностик лежат общим списком (`errors.<code>` в словаре Host), потому что одна
   * и та же ошибка обязана выглядеть одинаково в редакторе, в панели проблем и в подсказке
   * на файле в дереве. **Ключ передаётся голым кодом**, без приставки: её ставит композиция.
   *
   * Необязателен, и это цена того, что порт объявляет потребитель: без него панель проблем
   * покажет сам код (`schema.unknown-component`). Читаемо для разработчика, но не для
   * человека, поэтому композиции стоит его дать — одной строкой, той же, что у Monaco.
   */
  useDiagnosticMessage?(): Translate;

  /**
   * Перевод ключа словарём **Host** БЕЗ приставки — для подписей быстрых исправлений.
   *
   * Отдельно от {@link useDiagnosticMessage}, хотя словарь тот же: тот приписывает `errors.`,
   * потому что получает голый код находки, а `QuickFix.titleKey` — уже полный ключ
   * (`quickfix.remove-orphan-rule`). Приписать ему приставку значило бы промахнуться мимо
   * словаря, а завести подписи в словаре плагина — получить две разные фразы для одного
   * исправления: здесь и на канвасе редактора схемы.
   *
   * Необязателен: без него на кнопке виден сам ключ — читаемо для разработчика, но не для
   * человека, поэтому композиции стоит его дать.
   */
  useQuickFixTitle?(): Translate;

  /** Умеет ли движок выбрать каталог вообще. Ответ не меняется за время жизни вкладки. */
  canOpenProject(): boolean;
  /** Открыт ли проект прямо сейчас. */
  hasProject(): boolean;
  /** Показывает выбор каталога и открывает проект. `false` — не открыли. */
  openProject(): Promise<boolean>;

  /** Сохраняет один ресурс в источник. `false` — не сохранилось (конфликт, отказ источника). */
  save(id: ResourceId): Promise<boolean>;
  /** Сохраняет всё изменённое. */
  saveAll(): Promise<boolean>;
  /** Идентификатор активной вкладки или `null`. */
  activeResource(): ResourceId | null;
  /**
   * Показать ресурс: открыть вкладку или сделать активной уже открытую.
   *
   * Нужен ровно панели проблем — «переход к месту» начинается с перехода к файлу. Дерево
   * ресурсов обходится без него, потому что открытие ему даёт композиция пропом
   * (`ResourceTree.onOpen`), а панель проблем — вклад плагина, и пропа у неё нет.
   *
   * Необязателен: пока композиция его не даёт, строки панели остаются списком, а не
   * навигацией. Это видно на глаз и потому не выглядит поломкой.
   */
  openResource?(id: ResourceId): void;
  /** Есть ли несохранённые правки — во всей рабочей области. */
  isDirty(): boolean;

  /** Документ открытой вкладки или `null`, если она ещё открывается. */
  documentOf(id: ResourceId): FilesDocument | null;
  /** Пишет в рабочую копию. В источник не пишет ничего и никогда — для этого есть `save`. */
  writeText(id: ResourceId, text: string): Promise<void>;

  /** Читается ли такой ресурс текстом. Правило платформенное — таблица медиатипов у неё. */
  isTextual(mediaType: string): boolean;

  /**
   * Операции над записями проекта. `null` — проект не открыт, и делать их не над чем.
   *
   * Портом, а не службой из `@/sdk`, в отличие от запросов к человеку и буфера: операции
   * живут и умирают вместе с ОТКРЫТЫМ ПРОЕКТОМ (они пишут в его источник и чинят его
   * дерево), а служба в реестре пережила бы закрытие проекта и продолжала бы указывать
   * на исчезнувший источник.
   */
  resources(): FilesResourceOperations | null;

  /**
   * Что выделено в дереве проекта — набор, если щёлкнули по его строке, иначе одна строка.
   *
   * Нужен командам, вызванным С КЛАВИШИ: у пункта меню цель приходит аргументом, а у клавиши
   * аргументов нет вовсе, и «к чему применить» знает только дерево.
   */
  treeSelection(): readonly ResourceRef[];

  /** Корень дерева проекта; `null` — проект не открыт. */
  treeRoot(): ResourceId | null;
}

/**
 * Операции над записями проекта — структурная копия платформенных.
 *
 * Копия, а не импорт: `plugins/**` не видит `@/host`, и это правило слоёв, а не неудобство.
 * Совместимость проверяется компиляцией в одном месте — там, где композиция подставляет
 * настоящие операции.
 */
export interface FilesResourceOperations {
  createFile(dir: ResourceId, name: string, text?: string): Promise<ResourceId>;
  createDirectory(dir: ResourceId, name: string): Promise<ResourceId>;
  rename(id: ResourceId, name: string): Promise<ResourceId>;
  move(id: ResourceId, dir: ResourceId): Promise<ResourceId>;
  remove(ids: readonly ResourceId[]): Promise<FilesBatchResult>;
  copy(ids: readonly ResourceId[], dir: ResourceId): Promise<FilesBatchResult>;
  /** Перечитать уровень каталога: содержимое изменилось не нами. */
  refresh(dir: ResourceId): Promise<void>;
}

/** Итог пакетной операции: что получилось и что нет. */
export interface FilesBatchResult {
  readonly done: readonly ResourceId[];
  readonly failed: readonly { readonly id: ResourceId; readonly error: unknown }[];
}
