/**
 * Повод перечитать список шаблонов — один на плагин.
 *
 * ## Зачем отдельный канал, если панель умеет перечитывать сама
 *
 * Кнопка «Обновить» уехала из тела панели в шапку дока, а шапку рисует оболочка: это ДВА
 * разных React-поддерева, и общего состояния у них нет. Поднимать список шаблонов в общий
 * стор ради одной кнопки — менять место хранения из-за расположения кнопки; вместо этого
 * наверх поднят ПОВОД: «перечитай», а что именно перечитывать и чем, знает по-прежнему
 * только панель.
 *
 * ## Почему это не событие платформы
 *
 * Событие в общей шине пришлось бы кому-то объявить и кому-то отфильтровать, а слушатель
 * здесь ровно один и живёт в том же плагине. Своя шина на такое — это подписка ценой в чужой
 * реестр; здесь достаточно множества слушателей и вызова.
 *
 * @module plugins/templates/content/refresh
 */

import type { Disposable } from '@/sdk';

export interface TemplatesRefresh {
  /** Позвать перечитывание. Без слушателей — ничего не делает и не копится. */
  request(): void;
  /** Подписаться. Освобождение снимает подписку; повторное безвредно. */
  subscribe(listener: () => void): Disposable;
}

export function createTemplatesRefresh(): TemplatesRefresh {
  const listeners = new Set<() => void>();
  return {
    request: () => {
      // Копия набора: слушатель вправе отписаться прямо в обработчике, а обход живого
      // множества при этом пропустил бы соседа.
      for (const listener of [...listeners]) listener();
    },
    subscribe: (listener) => {
      listeners.add(listener);
      return {
        dispose: () => {
          listeners.delete(listener);
        },
      };
    },
  };
}
