/**
 * Порт платформы для генерации кода: ровно то, чем она пользуется, и ничего сверх.
 *
 * ## Почему порт, а не импорт
 *
 * Плагин видит платформу только через `@/sdk` (проверяется линтером), а в `@/sdk` нет ни рабочей
 * области, ни возможностей источника, ни сервиса китов. Недостающее приходит ПАРАМЕТРОМ — тем же
 * приёмом, каким объявляют свою потребность `plugins/preview/host` и `plugins/editor-monaco/host`.
 *
 * ## Записи «мимо всех» здесь нет и быть не может
 *
 * Главное отличие от v1. Там `codegen/deliver.ts` звал СВОЙ `showDirectoryPicker()` и писал файлы
 * в произвольный каталог — мимо рабочей копии и мимо источника. Из этого следовало три вещи, и все
 * плохие: записанное не попадало ни в журнал, ни в дерево ресурсов; конфликт с чужой правкой был
 * невыразим; а «куда пишем» решал браузерный диалог, а не открытый проект.
 *
 * В v2 запись идёт ТОЛЬКО через рабочую область ({@link CodegenHost.writeText}), а КУДА —
 * решает источник: адреса строит {@link CodegenHost.resolve}, и выйти за пределы открытого
 * проекта ими нельзя. Своего диалога выбора каталога у плагина нет вовсе, и это граница прав,
 * а не недоделка.
 *
 * ## Кит приходит портом, а не импортом
 *
 * Три разные вещи, как и у превью: каталог отвечает «какие имена бывают», дескриптор — «как их
 * резолвить и откуда импортировать». Namespace (`чем рисовать`) кодогену не нужен вовсе: он
 * печатает ИМЕНА, а не рисует компоненты, — и это самая узкая часть порта по сравнению с превью.
 *
 * Обе — ФУНКЦИИ, а не значения: кит переключают без перезагрузки, и захваченный в замыкание
 * дескриптор дал бы импорты от предыдущего кита.
 *
 * @module plugins/codegen/host
 */

import type { CatalogEntry } from '@/lib/catalog/types';
import type { FormRules } from '@/lib/form-model/rules';
import type { KitDescriptor } from '@/lib/kits/types';
import type { Disposable, DocumentKind, ResourceId, ResourceRef } from '@/sdk';

/** Перевод: ключ и параметры. Совпадает по форме с `I18nService.t`. */
export type Translate = (key: string, params?: Record<string, unknown>) => string;

/** Приёмник словаря: `PluginI18n.contribute` в объёме, которым пользуется плагин. */
export interface MessageSink {
  contribute(locale: string, messages: Readonly<Record<string, string>>): void;
}

/**
 * Открытый документ — в объёме, нужном генерации.
 *
 * `model()` отдаёт модель, СОГЛАСОВАННУЮ с буфером, либо `undefined`. Устаревшая модель хуже
 * отсутствующей: сгенерировали бы форму, которой в тексте перед человеком уже нет.
 */
export interface CodegenDocument {
  readonly id: ResourceId;
  readonly ref: ResourceRef;
  /** Вид документа: генерация применима только к модельному документу схемы. */
  readonly kind: DocumentKind;
  getText(): string;
  model(): unknown;
  onDidChangeContent(cb: (text: string) => void): Disposable;
}

/**
 * Возможности источника — в объёме одного вопроса: можно ли в него вообще писать.
 *
 * Ширина порта равна ширине принимаемого решения, поэтому «а можно ли ещё вот это» в плагине
 * даже не выразимо.
 */
export interface CodegenSourceCapabilities {
  readonly write: boolean;
}

/** Всё, что генерация получает от композиции. */
export interface CodegenHost {
  /**
   * Реактивный перевод в пространстве имён плагина. Хук, а не функция: локаль меняется,
   * и компонент обязан перерисоваться — подписку держит композиция.
   */
  useTranslate(): Translate;

  /**
   * Документ активной вкладки или `null`. Хук: вкладки переключают, и панель обязана
   * перерисоваться. Своего способа узнать активную вкладку у плагина нет.
   */
  useActiveDocument(): ResourceId | null;

  /** Документ открытой вкладки или `null`, если её уже закрыли. */
  documentOf(id: ResourceId): CodegenDocument | null;

  /** Возможности источника, которому принадлежит ресурс. `null` — источника нет, писать некуда. */
  sourceOf(id: ResourceId): CodegenSourceCapabilities | null;

  /** Каталог активного кита: из него берутся символы экспорта для `registry.ts`. */
  catalog(): readonly CatalogEntry[];

  /**
   * Дескриптор активного кита. `null` — кита нет, и генерация отказывается работать.
   *
   * Отказ намеренный и по нему проходит вся ценность задачи: умолчание «нет кита — пиши
   * `@reformer/ui-kit`» вернуло бы ровно тот дефект, ради которого дескриптор и заводился,
   * только молча.
   */
  kit(): KitDescriptor | null;

  /** Кит сменился: сгенерированное перестало соответствовать активному киту. */
  onDidChangeKit(cb: () => void): Disposable;

  /**
   * Правила формы — сайдкар рядом со схемой.
   *
   * Необязателен, и это честно названное сегодняшнее состояние: плумбинга сайдкара в v2 нет
   * вовсе (`plugins/ai/bridge` держит правила В ПАМЯТИ СЕССИИ и говорит об этом вслух).
   * Без него `validation.ts` и `form.behavior.ts` уезжают заготовками — то есть форма, которую
   * ассистент считает описанной правилами, у пользователя не проверяет ничего. Это ЗАМЕТНАЯ
   * деградация, и композиции стоит закрыть её первой.
   */
  rulesOf?(id: ResourceId): FormRules | null;

  /* ── адреса и запись: только через рабочую область ─────────────────────────── */

  /**
   * Каталог ресурса — место, рядом с которым появится модуль формы.
   *
   * Арифметику путей делает платформа (`dirname`/`joinPath` живут в `host/primitives/resource`
   * и плагину недоступны), а РЕШЕНИЕ, куда класть модуль, принимает плагин.
   */
  parentOf(id: ResourceId): ResourceId;

  /** Собрать адрес внутри каталога. Сегменты нормализуются платформой. */
  resolve(dir: ResourceId, ...segments: readonly string[]): ResourceId;

  /** Есть ли такой ресурс. Дешевле чтения и не материализует содержимое. */
  exists(id: ResourceId): Promise<boolean>;

  /** Текст рабочей копии либо `null`, если ресурса нет. В источник не ходит. */
  readText(id: ResourceId): Promise<string | null>;

  /** Пишет в рабочую копию. В источник не пишет ничего и никогда — для этого есть `save`. */
  writeText(id: ResourceId, text: string): Promise<void>;

  /**
   * Отправляет записанное в источник.
   *
   * Необязателен: без него сгенерированные файлы остаются рабочей копией, помеченной как
   * несохранённая, и на диск их отправит обычное «Сохранить всё». Деградация видна человеку
   * в дереве и потому не выглядит поломкой.
   */
  save?(ids: readonly ResourceId[]): Promise<boolean>;

  /**
   * Показать ресурс: открыть вкладку или сделать активной уже открытую.
   *
   * Необязателен. Без него после генерации ничего не открывается — список файлов в панели
   * остаётся списком, а не навигацией.
   */
  openResource?(id: ResourceId): void;

  /**
   * Форматирование сгенерированного текста.
   *
   * Необязателен, и это НАЗВАННЫЙ пробел: в v1 форматирование делал `prettier/standalone`,
   * а в зависимостях v2 prettier не объявлен (в этом монорепо «импорт работает» не означает
   * «зависимость объявлена» — правило записано в журнале решений). Без форматтера файлы
   * уезжают такими, как их напечатали эмиттеры: собираются и читаются, но отличаются от
   * `prettier --write` по переносам. Форматировать ОБЯЗАНА генерация, а не доставка, иначе
   * маркер происхождения считался бы не от того текста, что лежит на диске.
   */
  format?(files: readonly { path: string; content: string }[]): Promise<readonly string[]>;
}
