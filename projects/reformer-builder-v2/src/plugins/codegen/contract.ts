/**
 * Контракт генерации: точка расширения целей и то, что цель обязана про себя рассказать.
 *
 * ## Почему цель — вклад, а не строка в модуле
 *
 * В v1 состав модуля формы был литеральным массивом вызовов внутри `codegen/index.ts`. Это одно
 * из четырёх мест, ради которых заводилась точка расширения (см. шапку
 * `host/primitives/extension-point`): массив в модуле означает, что добавить файл может только
 * правка этого модуля, а снять его нельзя вовсе.
 *
 * Цена массива была не теоретической. Три раза подряд один и тот же список приходилось держать
 * синхронным в четырёх местах: сам массив, набор «user-файлов, которые всё-таки регенерируются»
 * в `deliver.ts`, его же копия в `regenerate.ts` и перечисление файлов в тексте README. Здесь
 * все четыре ответа даёт одна запись цели: `cls`, `regenerable` и `path`, а README читает
 * фактический состав из контекста.
 *
 * ## Точка объявлена здесь, но принадлежит не нам
 *
 * `codegen.target` — точка ПЛАТФОРМЫ ровно в том же смысле, что `preview.surface`: `@/sdk` её
 * пока не отдаёт, а `defineExtensionPoint` оттуда не экспортируется вовсе. Поэтому здесь
 * структурная копия, и она сделана МИНИМАЛЬНОЙ — один замороженный объект с `id` и фантомным
 * типом. Урок записан в журнале решений: копия, описывающая ПРЕДМЕТНУЮ область, разъезжается
 * с оригиналом (копия точки моделей сузила `DocumentModelProvider<unknown>` до своей модели,
 * и поймал это компилятор на композиции). Копия работает потому, что реестр ключуется по `id`,
 * а не по идентичности объекта.
 *
 * Как только `@/sdk` начнёт отдавать точку, этот модуль обязан РЕЭКСПОРТИРОВАТЬ её, а не
 * объявлять свою. Пока — она передаётся плагину параметром, и подстановка настоящей точки
 * не изменит ни строки в целях.
 *
 * @module plugins/codegen/contract
 */

import type { EmitContext, FileClass } from '@/lib/codegen';

/**
 * Типизированное имя точки расширения — структурная копия `host/primitives/extension-point`.
 *
 * Описывает не предметную область, а САМ реестр, поэтому разойтись по смыслу не может:
 * `__type` существует только для вывода типов, а ключом служит `id`.
 */
export interface ExtensionPointRef<T> {
  readonly id: string;
  readonly __type?: T;
}

/**
 * Одна цель генерации — один файл модуля формы.
 *
 * Цель ЧИСТАЯ: у неё нет доступа ни к рабочей области, ни к источнику, ни к оболочке. Всё, что
 * она видит, — контекст эмиссии, и всё, что она делает, — возвращает текст. Записью занимается
 * доставка, и это граница прав: чужая цель не может ни прочитать соседний файл, ни записать
 * что-нибудь мимо каталога модуля.
 */
export interface CodegenTarget {
  /** Уникален в пределах точки; он же адрес цели в отчёте о генерации. */
  readonly id: string;
  /** Имя файла ОТНОСИТЕЛЬНО каталога модуля. Абсолютные пути и `..` отвергаются доставкой. */
  readonly path: string;
  /** `derived` перезаписывается всегда, `user` пишется один раз. */
  readonly cls: FileClass;
  /**
   * `user`-файл, который всё-таки производится из правил и потому несёт маркер происхождения:
   * перезаписывается, только если его не правили руками.
   *
   * В v1 это был отдельный набор имён в модуле доставки — четвёртая копия списка файлов.
   * Здесь свойство принадлежит цели, поэтому чужая цель объявляет его сама и не нуждается
   * в правке чужого модуля.
   */
  readonly regenerable?: boolean;
  /**
   * Применима ли цель к этой форме. Без ответа — применима всегда.
   *
   * Контекст на этот вопрос отвечает БЕЗ состава модуля (`ctx.files` пуст): применимость
   * обязана зависеть от формы и кита, а не от того, кто ещё вносил цели.
   */
  applies?(ctx: EmitContext): boolean;
  /** Текст файла. Бросок не роняет генерацию: он превращается в запись отчёта. */
  emit(ctx: EmitContext): string;
}

/**
 * Точка расширения целей генерации.
 *
 * Умолчание для плагина, работающего до переезда точки в `@/sdk`. Композиция вправе подставить
 * настоящую — вклады найдут её по `id`.
 */
export const CodegenTargetPoint: ExtensionPointRef<CodegenTarget> = Object.freeze({
  id: 'codegen.target',
});

/** Реестр целей в объёме, которым пользуется плагин: читать и знать об изменениях. */
export interface TargetCatalog {
  list(): readonly CodegenTarget[];
}
