/**
 * Контракт превью: точка расширения поверхностей и то, что поверхность про документ знает.
 *
 * ## Почему объявление здесь, а не в `@/sdk`
 *
 * `PreviewSurfacePoint` — СТРУКТУРНАЯ КОПИЯ точки расширения, ровно того же сорта, что
 * `KitsServiceToken` в плагине китов: `@/sdk` сдан и точки превью не отдаёт, а `defineExtensionPoint`
 * оттуда не экспортируется вовсе. Копия работает, потому что реестр вкладов ключуется по `id`,
 * а не по идентичности объекта (см. `host/primitives/extension-point`), — то есть две копии
 * объявления находят ОДНУ точку.
 *
 * Это временное место, и его надо назвать вслух: как только `@/sdk` начнёт отдавать
 * `PreviewSurfacePoint`, этот модуль обязан РЕЭКСПОРТИРОВАТЬ точку оттуда, а не объявлять свою.
 * Урок Э6 записан в журнале решений: копия, описывающая ПРЕДМЕТНУЮ область, разъезжается
 * с оригиналом (там копия сузила `DocumentModelProvider<unknown>` до своей модели). Здесь риск
 * тот же — `PreviewSurface` описывает предметное, — поэтому копия сделана максимально узкой:
 * один замороженный объект с `id` и типом.
 *
 * ## Ось — realm, а не «нужен ли компилятор»
 *
 * Возможности поверхности перечислены так, как записано в контракте Э8, и порядок полей значения
 * не имеет, а вот `sameRealm` имеет: рендер в iframe при компиляторе в оболочке даёт второй
 * экземпляр ядра, поэтому исполняющая поверхность обязана быть в том же realm. Правило проверки
 * живёт не здесь, а в {@link './schema/source-guard'} — оно про источник, а не про поверхность.
 *
 * ## Состояние превью живёт вне поверхности
 *
 * Отсюда форма {@link PreviewContext}: схема, выделение, мок-данные и приёмник диагностик
 * приходят поверхности ИЗВНЕ, методами. Поверхность не владеет ничем, что должно пережить её
 * размонтирование, — и потому переключение поверхностей свободно, а смонтированной держим одну
 * (docs/editors-and-preview.md, «Состояние превью живёт вне поверхности»).
 *
 * @module plugins/preview/contract
 */

import type { JsonFormSchema } from '@reformer/renderer-json';
import type { Disposable, DocumentRef, NodeId } from '@/sdk';

/**
 * Типизированное имя точки расширения — структурная копия `host/primitives/extension-point`.
 *
 * Та же копия, что оставлена намеренно в `plugins/editor-schema/host`: она описывает не предметную
 * область, а САМ реестр, поэтому разойтись по смыслу не может — `__type` существует только для
 * вывода типов, а ключом служит `id`.
 */
export interface ExtensionPointRef<T> {
  readonly id: string;
  readonly __type?: T;
}

/**
 * Что поверхность умеет. Ровно пять признаков контракта Э8, и каждый отвечает на вопрос,
 * который оболочка обязана задать ДО монтирования.
 */
export interface PreviewCapabilities {
  /** Можно ли трогать форму: вводить значения, нажимать кнопки. */
  readonly interactive: boolean;
  /** Выбор узла кликом. Требует аннотированной копии схемы — см. {@link './schema/node-token'}. */
  readonly hitTest: boolean;
  /** Принимает ли дроп с палитры. */
  readonly dragSource: boolean;
  /** Исполняет ли код документа. Только по этому признаку работает запрет по источнику. */
  readonly executesCode: boolean;
  /** Тот же realm, что у оболочки. Исполняющая поверхность обязана отвечать `true`. */
  readonly sameRealm: boolean;
}

/** На чём споткнулись. Надмножество `LinkPhase` платформы: у превью есть свои две фазы. */
export type PreviewProblemPhase =
  /** Документ не разобрался в схему формы. */
  | 'schema'
  /** Импорт не привязался. */
  | 'resolve'
  /** Движок транспиляции отказался. */
  | 'transpile'
  /** Модуль исполнился и бросил. */
  | 'evaluate'
  /** Сборка формы или отрисовка. */
  | 'render';

/**
 * Сбой превью — данные, а не исключение.
 *
 * Плоская структура с именем файла: «на чём споткнулись» и «где чинить» — два разных вопроса,
 * и панель сборки показывает оба. Файл пустой, если сбой ни к какому файлу не относится.
 */
export interface PreviewProblem {
  readonly file: string;
  readonly phase: PreviewProblemPhase;
  readonly message: string;
}

/**
 * Значения модели формы. Форма приходит из схемы, и сузить её нечем.
 */
export type PreviewValues = Record<string, unknown>;

/**
 * Мок-данные формы: значения модели и значения источников.
 *
 * Авторский артефакт, а не производное состояние: человек написал его руками и вправе забрать
 * с собой, поэтому по контракту он живёт в OPFS рядом с рабочей копией. Поверхность его только
 * ЧИТАЕТ — владеет им тот, кто дал контекст.
 */
export interface PreviewMock {
  readonly model: Record<string, unknown>;
  readonly dataSources: Record<string, unknown>;
}

/**
 * Собранная форма в объёме, нужном наблюдателю.
 *
 * Не `JsonForm` целиком, а ровно два поля: модель (значения и путь к узлам через `signalAt`)
 * и реестр (опции для редакторов панели). Шире — значит дать панели пересобирать форму,
 * а этим занята поверхность.
 */
export interface PreviewFormHandle {
  readonly model: unknown;
  readonly registry?: unknown;
}

/**
 * Что поверхность получает на монтирование.
 *
 * Схема — метод, а не поле: документ правят, пока превью открыто, и поверхность обязана читать
 * то, что есть СЕЙЧАС. `null` означает «документ не разобрался»; это законное состояние
 * (расхождение буфера и модели), а не ошибка контекста.
 */
export interface PreviewContext {
  readonly doc: DocumentRef;

  /** Разобранная схема документа либо `null`, если буфер не разбирается. */
  schema(): JsonFormSchema | null;
  onDidChangeSchema(cb: () => void): Disposable;

  /** Выделенные узлы — те же адреса, которыми оперирует редактор схемы (`$nodeId`). */
  selection(): readonly NodeId[];
  onDidChangeSelection(cb: () => void): Disposable;
  /** Обратная связь хит-теста: поверхность сообщает, куда ткнули. */
  select(ids: readonly NodeId[]): void;

  /** Мок-данные или `null`, если автор их не задавал (тогда поверхность синтезирует свои). */
  mock(): PreviewMock | null;

  /**
   * Что человек успел ввести в прежнюю сборку этой формы; `undefined` — вводить не начинали.
   *
   * Отдельно от {@link PreviewContext.mock}: мок — авторский артефакт, живущий рядом с рабочей
   * копией, а это эфемерное состояние сеанса. Общее у них одно — поверхность ими не владеет.
   */
  values(): PreviewValues | undefined;

  /**
   * Отдать значения на хранение: перед пересборкой формы и при размонтировании.
   *
   * Поверхность обязана звать это САМА, потому что только она знает, когда её модель ещё жива.
   * Не позовёт — потеряет ровно то, что человек набрал, и никто, кроме него, этого не заметит.
   */
  keepValues(values: PreviewValues): void;

  /**
   * Отдать собранную форму наблюдателям; `null` — формы сейчас нет.
   *
   * Симметрично {@link PreviewContext.keepValues} по месту хранения и противоположно по смыслу:
   * там снимок значений для переноса между сборками, здесь ЖИВОЙ объект, по которому панель
   * модели читает значения и состояние узлов — и через который их правят.
   *
   * Необязателен: поверхность, которой нечего показать наблюдателю (каркас, чужая), просто
   * не зовёт его, и панель говорит, что формы нет.
   */
  publishForm?(form: PreviewFormHandle | null): void;

  /**
   * Куда уходят находки сборки.
   *
   * `source` — имя поверхности: список ЗАМЕЩАЕТСЯ целиком, как в службе диагностик, иначе
   * исправленная ошибка осталась бы висеть после пересборки.
   */
  report(source: string, problems: readonly PreviewProblem[]): void;
}

/**
 * Поверхность превью — вклад в точку `preview.surface`.
 *
 * `mount` возвращает `Disposable`, а не пару «смонтировать/размонтировать»: превью держит
 * смонтированной ровно одну поверхность, и симметрия здесь важнее выразительности.
 */
export interface PreviewSurface {
  /** Уникален среди поверхностей: он же адрес в настройках и имя источника диагностик. */
  readonly id: string;

  /**
   * Берётся ли поверхность за такой документ.
   *
   * Синхронная и дешёвая, решает по адресу и виду — ровно как `ValidatorContribution.applies`.
   * Содержимого здесь нет намеренно: выбор поверхности не должен стоить разбора текста.
   */
  applies(doc: DocumentRef): boolean;

  readonly capabilities: PreviewCapabilities;

  mount(host: HTMLElement, ctx: PreviewContext): Disposable;

  /**
   * Ключ заголовка для переключателя — СВЕРХ контракта Э8, и это стоит назвать.
   *
   * Контракт не говорит, как поверхность называется в интерфейсе. Ключ разрешается в пространстве
   * имён ПЛАГИНА ПРЕВЬЮ (переключатель живёт здесь), поэтому чужая поверхность его не ставит —
   * ей переключатель покажет `id`. Полноценное решение — `titleKey` плюс идентификатор внёсшего
   * плагина, но это правка контракта, а не плагина.
   */
  readonly titleKey?: string;
}

/**
 * Точка расширения поверхностей превью.
 *
 * Заполняется только вкладами: «какое превью у этого документа» — предметное знание, и в Host
 * оно означало бы, что второй вид превью вносится правкой ядра.
 */
export const PreviewSurfacePoint: ExtensionPointRef<PreviewSurface> = Object.freeze({
  id: 'preview.surface',
});

/**
 * Вид на точку расширения для тех, кто поверхности ЧИТАЕТ.
 *
 * Панель не имеет доступа к `PluginContext` — она получает его срез. Отдельный тип нужен,
 * чтобы панель нельзя было заставить читать реестр напрямую: у неё есть ровно два вопроса —
 * «какие поверхности есть» и «когда список изменился».
 */
export interface SurfaceCatalog {
  list(): readonly PreviewSurface[];
  observe(cb: () => void): Disposable;
}
