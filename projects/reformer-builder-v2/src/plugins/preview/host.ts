/**
 * Порт платформы для превью: ровно то, чем оно пользуется, и ничего сверх.
 *
 * ## Почему порт, а не импорт
 *
 * Плагин видит платформу только через `@/sdk` (проверяется линтером), а в `@/sdk` нет ни рабочей
 * области, ни возможностей источника, ни загрузчика модулей, ни сервиса китов. Недостающее
 * приходит ПАРАМЕТРОМ — тем же приёмом, каким объявляют свою потребность `plugins/files/host`,
 * `plugins/editor-monaco/host` и `plugins/editor-schema/host`: потребность объявляет потребитель,
 * а удовлетворяет её композиция.
 *
 * Типы здесь СТРУКТУРНЫЕ копии платформенных и обязаны быть их НАДмножествами по сигнатуре: в
 * {@link PreviewModules} присваивается настоящий `ModuleLoader`, в {@link PreviewDocument} —
 * настоящий `Document`, в {@link PreviewSourceCapabilities} — настоящие `SourceCapabilities`.
 * Совместимость проверяется компиляцией в одном месте — там, где `app/boot` подставляет
 * настоящие объекты.
 *
 * ## Кит приходит портом, а не импортом
 *
 * Каталог, дескриптор и namespace активного кита — три РАЗНЫЕ вещи, и это не дробление:
 * каталог отвечает «какие имена бывают» (данные, `lib/catalog`), дескриптор — «как их резолвить»
 * (данные, `lib/kits`), namespace — «чем рисовать» (значения, React-компоненты). Первые два
 * сегодня отдаёт сервис китов; третьего в v2 нет ни у кого — `lib/kits` намеренно не тянет
 * React-адаптеры, — поэтому namespace объявлен необязательным, а рантайм-поверхность без него
 * штатно деградирует в подписанные стабы.
 *
 * Все три — ФУНКЦИИ, а не значения: кит переключают без перезагрузки, и захваченный в замыкание
 * каталог означал бы превью от предыдущего кита.
 *
 * ## Чего в порту нет
 *
 * Реестров, оболочки, источника, сохранения. Превью ничего не пишет: оно читает рабочую копию
 * и исполняет её. Записи здесь нет вовсе, и это граница прав, а не недоделка.
 *
 * @module plugins/preview/host
 */

import type { CatalogEntry } from '@/lib/catalog/types';
import type { KitDescriptor, KitNamespace } from '@/lib/kits/types';
import type { Disposable, DocumentKind, ResourceId, ResourceRef, TextRange } from '@/sdk';

/** Перевод: ключ и параметры. Совпадает по форме с `I18nService.t`. */
export type Translate = (key: string, params?: Record<string, unknown>) => string;

/** Приёмник словаря: `PluginI18n.contribute` в объёме, которым пользуется плагин. */
export interface MessageSink {
  contribute(locale: string, messages: Readonly<Record<string, string>>): void;
}

/**
 * Открытый документ — в объёме, нужном превью.
 *
 * `model()` отдаёт модель, СОГЛАСОВАННУЮ с буфером, либо `undefined` — ровно как
 * `ValidateContext.model`. Устаревшая модель хуже отсутствующей: превью показывало бы форму,
 * которой в тексте перед человеком уже нет.
 */
export interface PreviewDocument {
  readonly id: ResourceId;
  readonly ref: ResourceRef;
  /**
   * Вид документа. Нужен, чтобы собрать `DocumentRef` для `PreviewSurface.applies`: поверхность
   * решает применимость по виду и адресу, а не по содержимому, и второй способ узнать вид
   * разошёлся бы с платформенным.
   */
  readonly kind: DocumentKind;
  getText(): string;
  model(): unknown;
  onDidChangeContent(cb: (text: string) => void): Disposable;
}

/**
 * Возможности источника — в объёме одного вопроса: можно ли исполнять его код.
 *
 * Больше превью и не нужно. Ширина порта здесь равна ширине принимаемого решения, поэтому
 * «а можно ли ещё вот это» в плагине даже не выразимо.
 */
export interface PreviewSourceCapabilities {
  readonly executesCode: boolean;
}

/** Сбой загрузки одного файла. Надмножество `ModuleLoadError` платформы по полю `phase`. */
export interface PreviewModuleError {
  readonly file: string;
  readonly phase: 'resolve' | 'transpile' | 'evaluate';
  readonly message: string;
  /** Место в исходнике файла, если фаза его знает (транспиляция — знает). */
  readonly range?: TextRange;
}

/** Результат загрузки графа модулей. Структурная копия `LoadResult`. */
export interface PreviewModuleGraph {
  readonly entry: unknown;
  readonly modules: ReadonlyMap<string, unknown>;
  readonly errors: readonly PreviewModuleError[];
  /** Что пришлось транспилировать: путь → JS. Уходит обратно в кэш сборки. */
  readonly compiled?: ReadonlyMap<string, string>;
}

/**
 * Прогретая компиляция набора — структурная копия `PrimedCompile` платформы.
 *
 * Превью не знает ни про OPFS, ни про ключи: его дело — отдать прогретое в `load` и вернуть
 * назад то, что пришлось собрать самому.
 */
export interface PreviewPrimedCompile {
  /** Готовый JS, взятый из кэша: путь → код. */
  readonly ready: ReadonlyMap<string, string>;
  /** Нашлось ли всё. `false` означает, что движок транспиляции уже разбужен. */
  readonly complete: boolean;
  /** Отдать на хранение то, что собралось. Зовётся после линковки — до неё состав неизвестен. */
  commit(compiled: ReadonlyMap<string, string>): Promise<void>;
}

/**
 * Загрузчик модулей платформы — тот же, которым пользуется загрузчик плагинов.
 *
 * Второго транспилятора у превью нет и быть не должно: механизм один и живёт в Host службой
 * (`host/modules/loader`), а разные у потребителей только входные данные — у плагина это его
 * каталог, у формы её файлы из рабочей копии.
 */
export interface PreviewModules {
  /**
   * Прогрев перед линковкой. ОБЯЗАН завершиться до `load`: внутри `require` асинхронного шага
   * быть не может, поэтому и ленивая загрузка `typescript`, и чтение кэша вынесены отдельной фазой.
   *
   * Принимает ФАЙЛЫ, а не имена, и это не мелочь: ответить «движок не нужен, всё уже собрано»
   * можно, только зная содержимое, — ключ кэша считается от исходника. Прежняя форма (имена)
   * заставляла будить движок всегда, то есть платить 3.5 МБ за форму, которую не меняли.
   *
   * Необязателен: композиция вправе его не давать, и тогда компиляция идёт без кэша.
   */
  prepare?(files: ReadonlyMap<string, string>): Promise<PreviewPrimedCompile>;

  load(
    files: ReadonlyMap<string, string>,
    entry: string,
    options?: {
      /** Готовый JS из кэша: путь → код. */
      readonly ready?: ReadonlyMap<string, string>;
      /** Подстановки импортов из фикстуры: спецификатор → готовые экспорты. */
      readonly overrides?: ReadonlyMap<string, unknown>;
      /** Лексически подставляемое окружение: `fetch`, `Date`, `Math`. */
      readonly ambient?: Readonly<Record<string, unknown>>;
    }
  ): Promise<PreviewModuleGraph>;
}

/** Всё, что превью получает от композиции. */
export interface PreviewHost {
  /**
   * Реактивный перевод в пространстве имён плагина. Хук, а не функция: локаль меняется,
   * и компонент обязан перерисоваться — подписку на смену локали держит композиция.
   */
  useTranslate(): Translate;

  /** Документ открытой вкладки или `null`, если её уже закрыли. */
  documentOf(id: ResourceId): PreviewDocument | null;

  /**
   * Документ активной вкладки — на него и смотрит панель превью.
   *
   * Хук, потому что вкладки переключают, и панель обязана перерисоваться. Своего способа узнать
   * активную вкладку у плагина нет: вкладки принадлежат рабочей области, а её `@/sdk` не отдаёт.
   */
  useActiveDocument(): ResourceId | null;

  /**
   * Возможности источника, которому принадлежит документ, или `null`, если источник неизвестен.
   *
   * `null` трактуется как запрет (см. {@link './schema/source-guard'}): «источника нет» — не повод
   * исполнять код, а повод сказать, что исполнять его пока нельзя.
   */
  sourceOf(id: ResourceId): PreviewSourceCapabilities | null;

  /** Каталог активного кита: то, из чего строится реестр компонентов рантайм-поверхности. */
  catalog(): readonly CatalogEntry[];

  /** Дескриптор активного кита: инфра-имена, политика превью, листья. `null` — кита нет. */
  kit(): KitDescriptor | null;

  /**
   * Namespace активного кита: имя экспорта → значение.
   *
   * `null` — рантайма кита нет (никто не поставил его композиции). Поверхность при этом
   * рисуется, но каждым компонентом становится подписанный стаб: сказать «кит недоступен»
   * честнее, чем показать пустоту.
   */
  kitNamespace(): KitNamespace | null;

  /** Кит сменился: реестр компонентов надо пересобрать. */
  onDidChangeKit(cb: () => void): Disposable;

  /**
   * Соседи документа — один уровень его каталога.
   *
   * Арифметику путей делает платформа (`dirname`/`joinPath` живут в `host/primitives/resource`,
   * и плагину они недоступны), а РЕШЕНИЕ, какие из этих файлов составляют форму и что считать
   * точкой входа, принимает плагин — это предметное знание, ради которого `plugins/preview`
   * и существует отдельно от `host/modules`.
   */
  siblings(id: ResourceId): Promise<readonly ResourceRef[]>;

  /** Текст рабочей копии. В источник не ходит: компиляция читает Workspace, а не Source. */
  readText(id: ResourceId): Promise<string>;

  /**
   * Адрес по пути от корня проекта, которому принадлежит документ.
   *
   * Нужен фикстурам: их адрес выводится из пути документа схемы от корня проекта
   * (`fixturePathOf`) целиком, а не как смещение от каталога. Арифметику по-прежнему делает
   * платформа — плагин лишь называет путь.
   *
   * Необязателен: без него фикстура не читается, и форма наполняется синтезом из схемы,
   * то есть ведёт себя ровно как до появления фикстур.
   */
  resolveFromRoot?(anchor: ResourceId, path: string): ResourceId;

  /**
   * Правка ЛЮБОЙ рабочей копии.
   *
   * Нужен компилирующей поверхности: сайдкары формы правят в соседних вкладках, а подписка
   * на документ схемы про них ничего не знает. Без него превью пересобирается только на смене
   * самой схемы — это работает, но «поменял валидацию, ничего не изменилось» возвращается.
   *
   * `changed` — адреса, чей ТЕКСТ изменился или исчез (не «загрузился» и не «сохранился»):
   * по ним снимаются находки сборки этих файлов до следующей сборки — подчёркивание относится
   * к тексту, которого после правки уже нет.
   *
   * Необязателен: композиция вправе его не давать, и тогда деградация именно такая.
   */
  onDidChangeFiles?(cb: (changed: readonly ResourceId[]) => void): Disposable;

  /**
   * Загрузчик модулей. Необязателен: без него компилирующая поверхность объявляет себя
   * недоступной, а рантайм и каркас работают как обычно.
   */
  readonly modules?: PreviewModules;
}
