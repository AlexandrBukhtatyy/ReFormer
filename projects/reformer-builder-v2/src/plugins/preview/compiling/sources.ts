/**
 * Какие файлы составляют форму — то самое ПРЕДМЕТНОЕ знание, ради которого `plugins/preview`
 * существует отдельно от `host/modules`.
 *
 * Платформа умеет транспилировать и линковать любой набор «путь → исходник» и не знает, что
 * такое форма. Здесь — знание: сайдкары лежат прямыми детьми каталога схемы, исполняются только
 * `.ts`/`.tsx`, страница-обёртка и тесты не исполняются никогда.
 *
 * ## Читается рабочая КОПИЯ, а не источник
 *
 * Это то, ради чего рабочая копия вообще существует. Буфер редактора и есть файл: правка,
 * не сохранённая на диск, обязана попасть в превью — иначе «поменял валидацию, ничего
 * не изменилось» становится нормой. В v1 путей чтения было два, с правилом приоритета,
 * и форма, собранная в билдере, живого превью не получала вовсе, потому что файлов у неё
 * не существовало.
 *
 * ## Почему `index.tsx` исключён
 *
 * Это страница-обёртка примера: она монтирует форму в приложение, тянет роутер и layout.
 * Исполнить её в превью значит смонтировать приложение внутрь приложения. Сайдкары, которые
 * она импортирует, превью и так найдёт — они лежат рядом.
 *
 * @module plugins/preview/compiling/sources
 */

import type { ResourceRef } from '@/sdk';

/** Расширения, которые превью исполняет. */
const EXECUTABLE = /\.tsx?$/;
/** Объявления типов: исполнять нечего, а транспилятор на них ругаться права не имеет. */
const DECLARATION = /\.d\.tsx?$/;
/** Тесты и спеки: они про сайдкары, а не сайдкары. */
const TESTS = /\.(test|spec)\.tsx?$/;
/** Страница-обёртка примера. */
const PAGE_ENTRY: ReadonlySet<string> = new Set(['index.ts', 'index.tsx']);

/**
 * Исполняется ли этот файл каталога формы.
 *
 * Решение по ИМЕНИ, а не по содержимому: список файлов известен раньше, чем их текст, и читать
 * весь каталог ради отбора значило бы платить чтением за файлы, которые всё равно отбросим.
 */
export function isExecutableSidecar(name: string): boolean {
  if (!EXECUTABLE.test(name)) return false;
  if (DECLARATION.test(name)) return false;
  if (TESTS.test(name)) return false;
  return !PAGE_ENTRY.has(name);
}

/**
 * Сайдкары среди соседей документа.
 *
 * Каталоги отбрасываются целиком: каталог формы ПЛОСКИЙ, и вложенность здесь означала бы,
 * что превью исполняет соседний пример. Импорт вглубь при этом работает — его резолвит
 * линковщик внутри уже отобранного набора, если файл в набор попал.
 */
export function selectSidecars(refs: readonly ResourceRef[]): readonly ResourceRef[] {
  return refs.filter((ref) => ref.kind === 'file' && isExecutableSidecar(ref.name));
}
