/**
 * Схема формы как ТЕКСТ: разбор буфера документа и печать результата хода.
 *
 * ## Почему это здесь, а не берётся у редактора схемы
 *
 * Разбор и печать того же формата уже написаны в `plugins/editor-schema/provider`, но плагины
 * не импортируют друг друга — и это не формальность: сегодня схему открывает структурный
 * редактор, завтра её может не быть в списке включённых вовсе, а ассистент обязан работать и
 * тогда. Общее у обоих не код провайдера, а домен (`@/lib/form-model`), и оба зовут именно его.
 *
 * ## Идентификаторы узлов НЕ выдаются
 *
 * Редактор схемы при открытии дописывает каждому узлу `$nodeId` — ему это нужно для адресации
 * и выделения. Ассистент адресует узлы JSON Pointer'ом (`core/node-ref`), поэтому выдавать
 * идентификаторы ему не за чем, а выдать — значит записать в файл правку, которой пользователь
 * не просил, ещё до первого хода. Уже стоящие идентификаторы при этом сохраняются: разбор и
 * печать не трогают неизвестных ключей, поэтому круг «прочитать → напечатать» возвращает
 * тот же текст.
 *
 * ## Печать совпадает с печатью редактора
 *
 * Два пробела отступа и перевод строки в конце — то же, что делает `printFormSchema`
 * провайдера. Разойдись форматирование, и ход ассистента давал бы diff на весь файл там, где
 * поменялось одно свойство.
 *
 * @module plugins/ai/schema-text
 */

import type { JsonFormSchema } from '@reformer/renderer-json';
import { ensureSchema, isFormSchema } from '@/lib/form-model/normalize';

/** Отступ печати. Два пробела — то, чем набраны схемы в репозитории. */
const INDENT = 2;

/**
 * Разобрать текст буфера в схему формы.
 *
 * @throws Если текст не разбирается как JSON или не похож на схему формы.
 */
export function parseSchemaText(text: string): JsonFormSchema {
  return ensureSchema(JSON.parse(text));
}

/** Печатает схему. Детерминированна: одна и та же модель даёт байт в байт один текст. */
export function printSchemaText(schema: JsonFormSchema): string {
  return `${JSON.stringify(schema, null, INDENT)}\n`;
}

/**
 * Похож ли текст на схему формы.
 *
 * Ошибка разбора здесь не диагностика, а ответ «не моё»: про синтаксис скажет валидатор того,
 * кто за файл взялся, а ассистенту достаточно знать, что править нечего.
 */
export function looksLikeSchemaText(text: string): boolean {
  try {
    return isFormSchema(JSON.parse(text));
  } catch {
    return false;
  }
}
