/**
 * Сборка текстового ответа инструмента в пределах бюджета.
 *
 * Почему отдельный помощник, а не обрезка строки в реестре: обрезать «по символам» безопасно для
 * прозы, но не для дайджеста — модель получит оборванный адрес узла и обратится по нему. Здесь
 * обрезка идёт по ЦЕЛЫМ строкам, а факт неполноты сообщается явно, чтобы модель дозапросила
 * недостающее вместо того, чтобы считать обрезанное полным.
 *
 * Длина проверяется по фактически собранному тексту, а не по накопительному счётчику: счётчик легко
 * разъезжается с реальностью на разделителях, и тогда бюджет тихо превышается.
 *
 * @module plugins/ai/core/render-budget
 */

/**
 * Собрать `head` + столько строк `items`, сколько влезает, добавив строку-уведомление при обрезке.
 *
 * @param head - Строки, которые выводятся всегда (заголовок).
 * @param items - Строки-кандидаты в порядке важности.
 * @param budget - Бюджет итогового текста в символах.
 * @param notice - Текст уведомления по числу показанных и общему числу.
 * @returns Готовый текст в пределах `budget`. Гарантия не действует, если бюджета не хватает даже
 *   на `head` с первым элементом и уведомлением: тогда бюджет превышается сознательно — молча
 *   обрезанный вывод модель приняла бы за полный, и это хуже, чем перерасход.
 */
export function joinWithinBudget(
  head: readonly string[],
  items: readonly string[],
  budget: number,
  notice: (shown: number, total: number) => string
): string {
  const lines = [...head];
  for (const [i, item] of items.entries()) {
    const withItem = [...lines, item];
    const tail = notice(i, items.length);
    const fits = withItem.join('\n').length <= budget;
    const fitsWithTail = [...withItem, tail].join('\n').length <= budget;
    // Последний элемент уведомления не потребует — его пускаем по более мягкому условию.
    if (i === items.length - 1 ? fits : fitsWithTail) {
      lines.push(item);
      continue;
    }
    if (i > 0) lines.push(tail);
    break;
  }
  return lines.join('\n');
}
