/**
 * Словарь плагина: локаль → ключ → сообщение.
 *
 * **Словари везёт плагин** (project-structure.md, «Устройство плагина»). Заголовок панели
 * разрешается в пространстве имён ВНЁСШЕГО плагина, поэтому `panel.title` двух разных
 * плагинов — два разных сообщения, и словарь Host для них невыразим.
 *
 * Файлы JSON, а не литералы в `.ts`: словарь правит переводчик, а не автор кода, и формат,
 * в котором нельзя случайно написать выражение, для этого лучше. Разбирает их сервис
 * локализации на регистрации — сообщение с ошибкой формата валит активацию, а не всплывает
 * у пользователя на редкой панели.
 *
 * Регистрирует словарь тот, у кого есть сервис: `PluginContext` его не содержит, поэтому
 * приёмник приходит параметром плагина ({@link '../host'.MessageSink}). Без приёмника плагин
 * работает, а строки показываются маркерами промаха — ровно так, как задумано в i18n.
 *
 * @module plugins/editor-schema/messages
 */

import en from './locales/en.json';
import ru from './locales/ru.json';

/** Локаль → ключ (без пространства имён) → сообщение. */
export const SCHEMA_EDITOR_MESSAGES: Readonly<Record<string, Readonly<Record<string, string>>>> =
  Object.freeze({ ru, en });
