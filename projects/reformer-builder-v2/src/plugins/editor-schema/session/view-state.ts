/**
 * Состояние вида канваса: свёрнутые ветки. И ничего больше.
 *
 * Выделение сюда **не входит** — так требует контракт (`host/ui/editors.ts` и
 * `docs/editors-and-preview.md`): оно часть модели правки, переезжает на `focus` после операции
 * и входит в снимок отмены. Здесь только то, что человек видит: какие ветки он свернул.
 *
 * ## Почему снимок записывается заранее, а не снимается по требованию
 *
 * Тонкость перенесена из порта Monaco (`plugins/editor-monaco/view-state`), потому что она
 * принадлежит не Monaco, а самому контракту: `viewState.capture(id)` оболочка зовёт в уборке
 * эффекта раскладки — то есть когда тело редактора уже могло быть размонтировано. Спрашивать
 * состояние у снятого с дерева React-компонента нечем. Поэтому канвас пишет снимок в реестр
 * ПО ХОДУ ДЕЛА (каждое сворачивание), а `capture` только достаёт последний записанный.
 *
 * Симметрично `restore` кладёт снимок обратно, а применяет его СЛЕДУЮЩИЙ экземпляр при
 * монтировании: тело пересоздаётся на пару «редактор + документ» (`key` в `EditorArea`),
 * и другого момента у него нет.
 *
 * ## Почему значение проверяется на чтении
 *
 * Хранилище оболочки держит непрозрачные значения и никогда в них не заглядывает — туда может
 * прийти что угодно, включая снимок прошлой версии редактора. Поэтому {@link readCollapsedState} —
 * не приведение типа, а проверка: непонятное значение равносильно отсутствию снимка, и канвас
 * просто открывается развёрнутым.
 *
 * Снимок наружу отдаётся МАССИВОМ, а не `Set`: хранилище состояния вида переживает сериализацию,
 * а `Set` в JSON превращается в `{}` — то есть снимок молча стал бы пустым.
 *
 * @module plugins/editor-schema/session/view-state
 */

import { isNodeId } from '@/lib/form-model/node-id';
import type { ResourceId } from '@/sdk';
import type { NodeId } from '../host';

/**
 * Проверяет непрозрачное значение из хранилища.
 *
 * `null` вместо исключения: невнятный снимок — обычное дело (другая версия редактора, ручная
 * правка хранилища), и падать из-за него означало бы не открыть файл вовсе. Элементы не формы
 * адреса отбрасываются поштучно: чужая строка в списке не повод потерять остальные, а свернуть
 * по ней всё равно нечего — такого узла в модели не бывает.
 */
export function readCollapsedState(value: unknown): readonly NodeId[] | null {
  if (!Array.isArray(value)) return null;
  return value.filter((item): item is NodeId => isNodeId(item));
}

/**
 * Реестр снимков по документам.
 *
 * Ключ — документ, а не пара «редактор + документ»: пару различает уже хранилище оболочки,
 * а этот реестр принадлежит одному редактору и второго различия не несёт.
 */
export interface CollapseRegistry {
  record(id: ResourceId, collapsed: ReadonlySet<NodeId>): void;
  /** Последний записанный снимок или `null`. */
  peek(id: ResourceId): readonly NodeId[] | null;
  forget(id: ResourceId): void;
}

export function createCollapseRegistry(): CollapseRegistry {
  const states = new Map<ResourceId, readonly NodeId[]>();
  return {
    record(id, collapsed) {
      // Пустой набор хранится наравне с непустым: «всё развёрнуто» — такое же состояние вида,
      // как и «свёрнуты две ветки», и терять его значило бы восстанавливать позапрошлое.
      states.set(id, [...collapsed]);
    },
    peek: (id) => states.get(id) ?? null,
    forget(id) {
      states.delete(id);
    },
  };
}
