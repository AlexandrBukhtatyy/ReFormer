/**
 * Схема санитайзера предпросмотра.
 *
 * ## Почему HTML в markdown вообще рендерится
 *
 * В README он встречается постоянно — `<details>`, `<br>`, `<img>`, таблицы выравнивания, —
 * и без `rehype-raw` текст выглядел бы пропавшим. Раз так, HTML обязан пройти санитайзер:
 * файл открыт из чужого каталога, а оболочка держит доступ к файловой системе проекта.
 * Исполнение чего-либо из markdown недопустимо, и это не осторожность, а условие того,
 * что предпросмотр вообще можно показывать.
 *
 * За основу берётся `defaultSchema` (GitHub-совместимая: уже разрешает `details`, чек-боксы
 * GFM и `className` вида `language-*` на `<code>`), и правятся ровно три вещи.
 *
 * @module plugins/editor-markdown/render/sanitize
 */

import { defaultSchema, type Options } from 'rehype-sanitize';

const base = defaultSchema;
const anyAttributes = base.attributes?.['*'] ?? [];

export const sanitizeSchema: Options = {
  ...base,
  attributes: {
    ...base.attributes,
    // `data-line` — привязка узла к строке исходника: по ней предпросмотр умеет отвечать
    // на вопрос «где это в тексте». Без разрешения её вырезал бы санитайзер.
    '*': [...anyAttributes, 'dataLine'],
    // Размеры пишут в HTML-вставках картинок, и без них широкая картинка ломает колонку.
    img: [...(base.attributes?.img ?? []), 'width', 'height'],
  },
  protocols: {
    ...base.protocols,
    // Инлайновые `data:image/...` — обычное дело в самодостаточных README.
    src: [...(base.protocols?.src ?? []), 'data'],
  },
  /**
   * Префикс `user-content-` у идентификаторов снимается осознанно.
   *
   * Он существует, чтобы разметка страницы не переопределила свойства документа. Здесь он
   * ломает главное — якоря: `rehype-slug` кладёт в `id` тот самый slug, на который ссылается
   * оглавление самого файла, и с префиксом ни одна ссылка вида `#установка` не сработает.
   * Риск снят иначе: якорь ищется ВНУТРИ контейнера предпросмотра, а не по документу.
   */
  clobberPrefix: '',
};
