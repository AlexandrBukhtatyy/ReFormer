/**
 * Ввод принадлежит редактору — правило и его единственная проверяемая часть.
 *
 * ## Как разведены слои
 *
 * Диспетчер сочетаний Host стоит **на `document`, в фазе всплытия** (`host/ui/keybindings.ts`).
 * Из этого следует всё остальное: событие, которое Monaco обработал, обязано до `document`
 * не дойти — тогда глобальный слой о нём не узнает вовсе, и никакого реестра приоритетов
 * не нужно. Выигрывает тот, кто ближе к фокусу, потому что так устроено всплытие.
 *
 * Два уровня защиты, и оба нужны:
 *
 * 1. **Фокус.** Ввод Monaco идёт через скрытый `<textarea>`, поэтому `classifyFocus`
 *    (`host/ui/focus.ts`) отвечает `editable`, и диспетчер пропускает все сочетания, кроме
 *    помеченных `allowInEditable`. Набор текста глобальных команд не запускает уже поэтому.
 * 2. **Остановка распространения.** А вот `mod+s` помечен `allowInEditable` — и это правильно
 *    (сохранять надо ровно тогда, когда курсор в тексте). Но так же помечена будет любая
 *    следующая команда, и если Monaco уже что-то сделал по этому сочетанию, выполнить его
 *    ВТОРОЙ раз глобально — это ровно та двойная обработка, из-за которой в v1 обработчик
 *    клавиш разросся до двухсот строк условий.
 *
 * ## Почему признак — `defaultPrevented`
 *
 * Спросить Monaco «ты обработал?» нечем: список его сочетаний закрыт, меняется от версии
 * к версии и зависит от того, какие вклады собраны в бандл. Зато обработанное он помечает
 * сам — его служба сочетаний зовёт `preventDefault()` на событии, которое исполнило команду.
 * Слушатель на корневом узле редактора в фазе ВСПЛЫТИЯ видит событие уже после этой пометки,
 * и `defaultPrevented` — честный ответ на вопрос «это уже чей-то ввод».
 *
 * Набор обычных символов пометки не получает (Monaco нужен `input`), поэтому `mod+s` и прочее
 * непонятное Monaco проходит наверх, как и должно.
 *
 * ## Композиция IME
 *
 * Во время набора через IME нажатия принадлежат вводу целиком: Enter там подтверждает выбор
 * иероглифа, а не сохраняет файл. Диспетчер это и сам знает, но останавливать такое событие
 * на границе редактора честнее — оно физически не про команду.
 *
 * @module plugins/editor-monaco/sync/input
 */

/** Поля события, по которым принимается решение. Не `KeyboardEvent`: правило проверяется в `node`. */
export interface EditorKeyEvent {
  /** Пометил ли кто-то ниже событие как обработанное. */
  readonly defaultPrevented: boolean;
  /** Идёт ли набор через IME. */
  readonly isComposing?: boolean;
}

/** Останавливать ли распространение — то есть скрывать ли событие от глобального слоя. */
export function shouldStopPropagation(event: EditorKeyEvent): boolean {
  if (event.isComposing === true) return true;
  return event.defaultPrevented;
}
