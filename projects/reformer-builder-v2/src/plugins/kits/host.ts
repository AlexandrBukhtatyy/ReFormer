/**
 * Порт платформы для плагина китов: ровно то, чем он пользуется, и ничего сверх.
 *
 * ## Почему порт, а не импорт
 *
 * Плагин видит платформу только через `@/sdk` (проверяется линтером), а `@/sdk` — сданная
 * поверхность: службы настроек в ней нет, как нет и `PluginContext.settings`. Расширять её
 * ради одного плагина нельзя, поэтому недостающее приходит ПАРАМЕТРОМ — тем же приёмом,
 * которым это делает плагин файлов (`plugins/files/host.ts`): потребность объявляет
 * потребитель, а удовлетворяет её композиция.
 *
 * Типы здесь СТРУКТУРНЫЕ копии платформенных, и каждая обязана быть ПОДмножеством настоящей:
 * `SettingsService` присваивается в {@link KitsSettings}, `PluginI18n.t` — в {@link Translate}.
 * Совместимость проверяется компиляцией в одном-единственном месте — там, где `app/boot`
 * подставляет настоящие службы.
 *
 * @module plugins/kits/host
 */

import type { Disposable } from '@/sdk';

/**
 * Перевод в пространстве имён плагина.
 *
 * Функция, а не хук: пункты палитры собираются в момент запроса, а не в отрисовке, и
 * `PluginI18n.t` читает действующую локаль на каждый вызов — то есть перевод и так свежий.
 */
export type Translate = (key: string, params?: Record<string, unknown>) => string;

/**
 * Настройки — в объёме, нужном выбору кита.
 *
 * Четыре метода, и каждый по делу: `get` — прочитать выбор на старте (к моменту активации
 * плагина хранилище уже загружено, см. последовательность запуска в `app/boot`), `set` —
 * сохранить новый, `registerDefault` — объявить умолчание один раз и снять его вместе
 * с плагином, `onDidChange` — узнать о правке настройки МИМО службы (панель настроек,
 * второе окно), иначе выбор разъехался бы с тем, что записано.
 *
 * `localStorage` здесь не появляется намеренно: у выбора кита есть владелец — служба
 * настроек, которая знает про области видимости и умеет откатить неудачную запись.
 */
export interface KitsSettings {
  get<T>(key: string): T | undefined;
  set<T>(key: string, value: T): Promise<void>;
  registerDefault<T>(key: string, value: T): Disposable;
  onDidChange(cb: (key: string) => void): Disposable;
}
