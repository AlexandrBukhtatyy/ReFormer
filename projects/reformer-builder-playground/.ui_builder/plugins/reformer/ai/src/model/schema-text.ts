/**
 * Схема формы как ТЕКСТ: разбор буфера документа и печать результата хода.
 *
 * ## Почему это здесь, а не берётся у редактора схемы
 *
 * Разбор и печать того же формата уже написаны в `plugins/reformer/editor/provider`, но плагины
 * не импортируют друг друга — и это не формальность: сегодня схему открывает структурный
 * редактор, завтра её может не быть в списке включённых вовсе, а ассистент обязан работать и
 * тогда. Общее у обоих не код провайдера, а домен (`@/plugins/reformer/core/form-model`), и оба зовут именно его.
 *
 * ## Идентификаторы узлов НЕ выдаются
 *
 * Редактор схемы при открытии дописывает каждому узлу `$nodeId` — ему это нужно для адресации
 * и выделения. Ассистент адресует узлы JSON Pointer'ом (`core/node-ref`), поэтому выдавать
 * идентификаторы ему не за чем, а выдать — значит записать в файл правку, которой пользователь
 * не просил, ещё до первого хода. Уже стоящие идентификаторы при этом сохраняются: разбор и
 * печать не трогают неизвестных ключей, поэтому круг «прочитать → напечатать» возвращает
 * тот же текст.
 *
 * ## Модель — всегда формата 2
 *
 * Файл на диске может быть прежнего формата (привязка в `value` / `array`, шаги визарда в
 * `componentProps.steps`). Разбор переводит его в формат 2 (`ensureSchema`), и дальше ассистент
 * прежних ключей не знает: карта формы, адреса узлов и правки инструментов описывают формат 2.
 * Круг «прочитать → напечатать» для такого файла текст поэтому МЕНЯЕТ — но печатается он только
 * при применении хода, а ход без правок в буфер не пишет (`hasChanges`). Открыть прежний файл
 * и что-то в нём поправить значит перевести его; открыть и не тронуть — ничего не записать.
 * Файл формата 2 разбор возвращает как есть.
 *
 * ## Печать совпадает с печатью редактора и кодогена
 *
 * Принтер у всех троих один — `printJson` ядра: им кодоген пишет `schema/form.schema.json`, им же
 * печатает `printFormSchema` провайдера редактора. Раскладка — как у форматтера репозитория:
 * объекты развёрнуты, массив без объектов — в строку, если помещается; два пробела отступа и
 * перевод строки в конце. Разойдись форматирование, и ход ассистента давал бы diff на весь файл
 * там, где поменялось одно свойство, а записанный им документ переставал бы проходить
 * `prettier --check`. Прежде здесь стоял свой `JSON.stringify(…, null, 2)` — он расходился с
 * кодогеном ровно на массивах. Совпадение держит `./schema-text-parity.test`.
 *
 * Общее у плагинов по-прежнему не код провайдера, а ядро домена: принтер берётся из его модуля
 * (`core/codegen/print/js`), а не из входа `core/codegen` — тот тянет шаблоны модуля формы и мост
 * к билдерам `@reformer/mcp`, которые ассистенту не нужны.
 *
 * @module plugins/reformer/ai/model/schema-text
 */

import type { JsonFormSchema } from '@reformer/renderer-json';
import { printJson } from '../../../core/codegen/print/js';
import { ensureSchema, isFormSchema } from '../../../core/form-model';

/**
 * Разобрать текст буфера в схему формы. Документ прежнего формата переводится в формат 2
 * (см. шапку модуля).
 *
 * @throws Если текст не разбирается как JSON или не похож на схему формы.
 */
export function parseSchemaText(text: string): JsonFormSchema {
  return ensureSchema(JSON.parse(text));
}

/**
 * Печатает схему — принтером документа формы, общим с редактором и кодогеном (см. шапку модуля).
 * Детерминированна: одна и та же модель даёт байт в байт один текст; завершается переводом строки.
 */
export function printSchemaText(schema: JsonFormSchema): string {
  return printJson(schema);
}

/**
 * Похож ли текст на схему формы.
 *
 * Ошибка разбора здесь не диагностика, а ответ «не моё»: про синтаксис скажет валидатор того,
 * кто за файл взялся, а ассистенту достаточно знать, что править нечего.
 */
export function looksLikeSchemaText(text: string): boolean {
  try {
    return isFormSchema(JSON.parse(text));
  } catch {
    return false;
  }
}
