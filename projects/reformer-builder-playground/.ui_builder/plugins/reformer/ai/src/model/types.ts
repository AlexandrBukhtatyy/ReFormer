/** Результат вызова инструмента. */
export interface ToolOutcome extends FormToolOutcome {
  /** Новая схема черновика. Есть только у write-инструментов при `ok: true`. */
  schema?: JsonFormSchema;
  /** Новые правила формы. Есть только у инструментов, правящих правила, при `ok: true`. */
  rules?: FormRules;
}

/**
 * Одна операция редактора, описанная машиночитаемо.
 *
 * `C` — контекст вызова. Структурные инструменты работают над {@link ToolContext}; инструменты
 * файлового режима получают его расширение (`files/turn`). Инструмент, объявленный над базовым
 * контекстом, входит в реестр расширенного без правок: ему просто передают больше, чем он читает.
 */
export interface AgentTool<P = never, C extends ToolContext = ToolContext> extends FormAgentTool<
  P,
  C
> {
  /**
   * Выполнить операцию.
   *
   * Возвращать промис разрешено, но нежелательно: ответ инструмента уходит в контекст модели
   * на каждом шаге, и асинхронный шаг задерживает весь ход. Асинхронность оправдана там, где
   * данные физически не в памяти — например, справка по библиотеке грузит корпус лениво.
   */
  run(params: P, ctx: C): ToolOutcome | Promise<ToolOutcome>;
}

/** Успешный ответ read-only инструмента. */
export function ok(text: string): ToolOutcome {
  return formToolOk(text);
}

/** Ответ с ошибкой. */
export function fail(code: ToolErrorCode, message: string, suggestions?: string[]): ToolOutcome {
  return formToolFail(code, message, suggestions);
}
