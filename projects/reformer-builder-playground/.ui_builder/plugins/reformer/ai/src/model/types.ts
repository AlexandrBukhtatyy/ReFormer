/** Вход инструмента: черновик хода и база, от которой считается diff. */
export interface ToolContext extends FormToolContext {
  /** Схема черновика — то, что инструмент читает и правит. НЕ схема активной вкладки. */
  readonly draft: JsonFormSchema;
  /** Схема на начало хода: база для diff и для проверки конфликта при применении. */
  readonly base: JsonFormSchema;
  /**
   * Правила формы черновика (валидация, поведение, видимость).
   *
   * Отдельно от схемы, а не внутри неё, потому что контракт `@reformer/renderer-json` закрыт:
   * `additionalProperties: false` и на корне, и в `meta`. См. `@/plugins/reformer/core/form-model`.
   */
  readonly rules: FormRules;
  /**
   * Каталог активного кита: единственный легальный словарь имён компонентов для агента.
   *
   * В v1 он читался модульным синглтоном (`getCatalog()`), и это было ошибкой ровно того же рода,
   * что ключ в `localStorage`: кит переключают, а застывшее значение молча продолжает описывать
   * прежний. В v2 каталог — состояние приложения, домену не видное (`@/plugins/reformer/core/catalog` умеет собрать
   * его из любого источника, но не решает, из какого), поэтому он приходит ВХОДОМ вызова — тем же
   * приёмом, что `MakeNodeKit` у `makeNodeFor` и `catalog: () => entries` у валидатора схемы.
   *
   * Вместе с записями приходят и факты о ките: фабрика узла у записи (`makeNode`) собрана уже с
   * `MakeNodeKit` — листьями кита и компонентом, которым он рисует массив. Поэтому узел для
   * вставки инструменты берут у ЗАПИСИ, как палитра, а не зовут `makeNodeFor` без кита: иначе
   * массив от ассистента оставался без `component`, в отличие от массива из палитры.
   */
  readonly catalog: readonly CatalogEntry[];
  /**
   * Проверка по мета-схеме form-DSL — то, на чём стоит гейт качества (`./gate`).
   *
   * Здесь она по той же причине, что и каталог: это не знание домена, а ЗАГРУЖЕННЫЙ РЕСУРС,
   * и решать, когда его грузить, обязан владелец (плагин), а не тот, кто им пользуется.
   * Статический импорт в `./validate` возвращал 120,93 кБ raw в главный чанк — измерено
   * сборкой, см. шапку `./validate`.
   *
   * Один канал на три места вызова (`./gate` дважды и `./tools/validate-form`) — потому что
   * все три уже получают контекст: отдельный параметр каждому означал бы три подписи вместо
   * одного поля и не дал бы ничего сверх.
   */
  readonly validateForm: ValidateFormSchema;
  /**
   * Ход, внутри которого идёт вызов: сигнал остановки, дверь записи и чтение ресурсов.
   *
   * Необязателен, потому что встроенные инструменты его не читают — они правят черновик или
   * пишут своей дверью (`files/turn`). Нужен инструментам плагинов и `read_resource`; без него
   * (тест ядра) они отвечают `UNAVAILABLE`.
   */
  readonly turn?: TurnScope;
}

