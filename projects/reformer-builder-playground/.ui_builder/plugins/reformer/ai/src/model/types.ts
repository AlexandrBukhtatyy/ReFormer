/**
 * Бюджет ВСЕЙ поверхности инструментов: имена, описания и схемы аргументов вместе (символы).
 *
 * Отдельно от {@link TOOL_DESCRIPTION_BUDGET} потому, что дорого не отдельное описание, а сумма:
 * поверхность уходит в запрос ЦЕЛИКОМ на каждом шаге, а шагов за ход десятки. Тринадцать
 * инструментов, каждый из которых честно уложился в свои 500 символов, вместе стоят дороже
 * системного промпта вчетверо.
 *
 * Число — храповик, а не цель: оно равно достигнутому размеру и его СНИЖАЮТ по мере сжатия схем.
 * Поднимать нельзя — рост поверхности обязан быть осознанным решением, а не побочным эффектом
 * очередного уточнения в описании.
 *
 * Второй случай, когда число не изменилось при добавлении инструмента: справка по библиотеке
 * (`ask_reformer`, 368 символов) вошла за счёт сжатия остальных описаний на 366 — убрано то,
 * что модель уже знает из системного промпта или из описания самого инструмента. Потолок при
 * этом опустился с 7700 до фактического размера: место, освобождённое один раз, не должно
 * молча превратиться в запас под следующую правку.
 *
 * В v1 храповик держался договорённостью — число сравнивали глазами. Здесь он ПРОВЕРЯЕТСЯ:
 * `core/tool-surface.test.ts` складывает длины имён, описаний и схем аргументов всех инструментов
 * и падает при превышении. Поднять потолок по-прежнему можно, но теперь это отдельная строка в
 * diff'е рядом с обоснованием, а не незаметный побочный эффект уточнения в описании.
 *
 * Осознанных повышений за всю историю три.
 *
 * Первое — пакетные аргументы (`nodes[]`, `refs[]`, `props{}`): прибавили около трёхсот
 * символов КАЖДОМУ запросу, но убрали из эталонной задачи одиннадцать обращений к модели, а
 * каждое обращение несёт весь контекст целиком. Размен выгоден примерно на два порядка.
 *
 * Второе — правила формы (`set_form_rules`, 1259 символов, потолок 7686 → 8946). Здесь размен
 * не в шагах, а в том, что происходит БЕЗ инструмента, и это измерено живым прогоном
 * (gemma4:26b, отчёт — docs/mcp-eval/builder-rules.md). На просьбу «сделай email обязательным»
 * агент без него зовёт `set_node_prop`, ход завершается как успешный, форма выглядит
 * изменённой — а валидации нет. Отказ был бы дешевле: ложное «готово» пользователь обнаружит
 * у себя, а не в редакторе. С инструментом выбор верен 4/4, включая две задачи, где правила
 * трогать НЕ надо, — то есть плата за него не растеклась на соседние ходы.
 *
 * Третье — поведение UI (`set_render_rules`, 971 символ, потолок 8946 → 9917). Размен снова не в
 * шагах: без инструмента у агента НЕТ способа задать условную видимость, событие узла или
 * динамический проп — правил render-слоя не принимал ни один инструмент, потому что селектором
 * никто не управлял. Замер на `qwen3.8:27b` (`core/render-rules-eval.test.ts`, отчёт —
 * docs/mcp-eval/builder-render-rules.md): выбор верен 4/4, причём в обеих НЕцелевых задачах новый
 * инструмент не вызывался вовсе — то есть плата за поверхность не растеклась на соседние ходы.
 *
 * Первое снижение — при переносе в v2: 9917 → 9914. Описание `validate_form` перестало обещать
 * проверку связей между узлами (вкладка ↔ панель, шаги мастера) — структурный линт живёт
 * диагностикой валидатора схемы, то есть в другом плагине, и придёт мостом. Освободившиеся три
 * символа опущены вместе с потолком: место, освобождённое один раз, не должно молча превратиться
 * в запас под следующую правку.
 *
 * Второе снижение — 9914 → 9908: `set_render_rules` называет файл по новой раскладке модуля
 * (`form.render.ts` вместо `renderer.behavior.ts`). Шесть символов опущены вместе с потолком
 * по тому же правилу.
 *
 * Третье снижение — 9908 → 9884: модуль формы разложен по папкам ролей, и отдельного файла
 * render-слоя в нём нет. `set_form_rules` называет папки `validation/` и `behavior/` вместо
 * файлов, `set_render_rules` — `behavior/`, а условия его правил читают модель
 * (`model.pickup === true`), а не ноды формы (`form.pickup.value.value === true`): правила узлов
 * печатаются в то же поведение, где модель под рукой. Двадцать четыре символа опущены вместе с
 * потолком.
 *
 * Повышение — 9884 → 10060: `set_node_prop` получил `edits` — свои свойства каждому узлу
 * (ReFormer-kuj). `props` одни на все `refs`, поэтому семь разных заголовков шагов шли семью
 * вызовами: модель упиралась в форму инструмента, а не нарушала просьбу промпта править пачкой.
 * 176 символов в каждом запросе против шести лишних шагов хода, каждый из которых заново
 * отправляет модели весь контекст.
 *
 * Повышение — 10060 → 10165: `describe_component` принимает `names` — сводку по нескольким
 * компонентам одним вызовом (ReFormer-6sj). По замеру на спеке кредитной заявки разведка шла
 * девятью вызовами `describe_component` подряд — больше половины хода до первой правки. 105
 * символов в каждом запросе против восьми лишних шагов.
 *
 * **Потолок — только встроенным.** У поверхности есть второе слагаемое — вклады плагинов:
 * инструменты точки `reformer.assistant.tool`, команды с блоком `agent` и `read_resource`, который
 * появляется вместе с провайдером ресурсов. У них свой потолок,
 * {@link CONTRIBUTED_TOOL_SURFACE_BUDGET}: состав вкладов зависит от включённых плагинов и известен
 * только в рантайме, а храповик встроенных — тест, и смешать их значило бы, что первый же вклад
 * ломает тест, которого его автор даже не видит. Обе стороны считает одна функция
 * `measureToolSurface`.
 */
export const TOOL_SURFACE_BUDGET = 10165;

