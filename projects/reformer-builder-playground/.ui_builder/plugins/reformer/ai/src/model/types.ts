/**
 * Контракты ядра ассистента — машиночитаемая поверхность операций редактора.
 *
 * Слой намеренно НЕ знает ни про React, ни про состояние приложения: инструмент получает схему во
 * входе и возвращает новую схему в выходе. Это даёт два свойства, ради которых слой и разделён:
 *  - его можно покрыть юнитами принятыми в проекте средствами (`environment: 'node'`,
 *    `include: ['src/**\/*.test.ts']`);
 *  - ход агента правит ЧЕРНОВИК, а не открытый документ, поэтому применение результата — одна
 *    запись отмены, а не по одной на каждую правку.
 *
 * Адресация узлов — JSON Pointer (RFC 6901) поверх `toPointer`/`fromPointer`
 * (`@/plugins/reformer/core/form-model`), см. {@link module:plugins/ai/core/node-ref}.
 *
 * @module plugins/reformer/ai/model/types
 */

