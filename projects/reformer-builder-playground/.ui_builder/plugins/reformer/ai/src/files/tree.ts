/**
 * Дерево модуля формы — что лежит в модуле и что значит правка каждого файла.
 *
 * Роль печатается рядом с файлом намеренно: «этот файл производный» модель должна узнать ДО
 * правки, а не из замечания после неё. Обход — как у чтения модуля превью
 * (`render/src/compiling/read.ts`): без чужого кода и скрытых каталогов.
 *
 * Файлы, созданные в этом ходе, подмешиваются из журнала: рабочая область показывает новый
 * файл в листинге не всегда (файл в новом подкаталоге не виден до сохранения), а модель обязана
 * видеть то, что сама же только что создала.
 *
 * @module plugins/reformer/ai/files/tree
 */

import type { ResourceId } from '@reformer/builder-plugin-api';
import { fileRoleOf, type ModuleFileRole } from '../../../core/codegen/layout';
import type { AiFiles, FileScope } from '../host';
import type { FileJournal } from './journal';

/**
 * Глубина обхода в каталогах. На единицу глубже, чем у чтения модуля превью: превью нужен
 * только код, а модели — ещё и файлы шагов разбитого визарда, которые лежат на четвёртом
 * уровне (`schema/steps/<шаг>/form.schema.json`).
 */
const MAX_DEPTH = 4;

/** Каталоги, в которые обход не заходит. */
function skipped(name: string): boolean {
  return name.startsWith('.') || name === 'node_modules';
}

/** Метка роли в листинге; у авторских и прочих файлов метки нет. */
const ROLE_TAG: Partial<Record<ModuleFileRole, string>> = {
  form: '[form]',
  step: '[step]',
  regenerable: '[rules]',
  rules: '[rules data — codegen prints validation/ and behavior/ from it]',
  derived: '[derived — regenerated by codegen]',
  legacy: '[legacy layout]',
};

/** Файлы модуля — пути от корня, по алфавиту. */
export async function moduleFiles(
  files: Pick<AiFiles, 'list'>,
  scope: FileScope,
  journal?: FileJournal
): Promise<string[]> {
  const found = new Set<string>();
  const walk = async (dir: ResourceId, prefix: string, depth: number): Promise<void> => {
    const entries = await files.list(dir).catch(() => []);
    for (const entry of entries) {
      const rel = `${prefix}${entry.name}`;
      if (entry.kind === 'file') found.add(rel);
      else if (depth < MAX_DEPTH && !skipped(entry.name)) {
        await walk(entry.id, `${rel}/`, depth + 1);
      }
    }
  };
  await walk(scope.root, '', 1);
  for (const entry of journal?.entries().values() ?? []) found.add(entry.rel);
  return [...found].sort();
}

/** Листинг для модели: строка на файл, роль меткой. */
export function renderTree(paths: readonly string[], scope: FileScope): string {
  return paths
    .map((rel) => {
      const tag = ROLE_TAG[fileRoleOf(rel, scope.schemaPath)];
      return tag ? `${rel} ${tag}` : rel;
    })
    .join('\n');
}
