/**
 * Справка по библиотеке и проверка кода — возможность, которой стек форм ReFormer даёт себя заменить.
 *
 * Стек отвечает модели на вопросы о библиотеке (`ask_reformer`, `./tools/reformer-docs`) и
 * проверяет TS-код, который модель пишет в режиме файлов (`./files/gate`). Встроенная реализация —
 * `@reformer/mcp` (`./knowledge/mcp-reference`): корпус из `node_modules` открытого проекта либо
 * вшитый в сборку. Другой плагин может дать свою — удалённый MCP-сервер, свой поиск по
 * документации, — не трогая стек: зарегистрировать службу по {@link LibraryReferenceCapability}
 * в `activate` и объявить её в `provides` своего манифеста.
 *
 * ## Почему стек не регистрирует её сам
 *
 * Слот службы держит одну реализацию, повторная регистрация бросает. Займи стек слот встроенной
 * реализацией — плагин проекта со своей падал бы на активации. Поэтому встроенная — запасной
 * вариант ВНУТРИ стека (`./knowledge/builtin`), а слот свободен для поставщика. Спрашивается он на
 * каждый вызов: поставщик вправе подняться позже стека или исчезнуть вместе со своим плагином.
 *
 * ## Почему копия, а не импорт
 *
 * Плагины друг друга не импортируют, а в SDK этому контракту не место: справка по ReFormer —
 * знание домена, и другому стеку она не нужна. Поставщик держит у себя копию этого файла.
 * Совпадать обязаны идентификатор и форма: служба находится по идентификатору, а форму сверяет
 * стек при каждом вызове (`chooseReference`) — версии в рантайме нет, её проверяет только резолвер
 * по манифестам. Несовместимая правка — это `2.0.0` здесь и `^2` в `requires` манифеста стека.
 *
 * @module plugins/reformer/ai/reference
 */

import { defineCapability } from '@reformer/builder-plugin-api';

/** Находка проверки кода. Строка — в переданном тексте, с единицы. */
export interface CodeFinding {
  readonly code: string;
  readonly severity: 'error' | 'warning';
  readonly message: string;
  readonly line?: number;
  /** Что сделать — действием, а не описанием проблемы. */
  readonly suggestion?: string;
}

/** Чем стек снабжает запрос к справке. */
export interface ReferenceRequest {
  /** Срабатывает, когда ход остановили: удалённому поставщику незачем дожидаться ответа. */
  readonly signal?: AbortSignal;
}

export interface LibraryReferenceService {
  /**
   * Ответ на вопрос модели о библиотеке; `null` — справки нет, и модель узнает об этом словами.
   *
   * Ответ обязан уложиться в `maxChars` ВМЕСТЕ с припиской об источнике, если она есть: лишнее
   * срежет реестр инструментов, и срежет с конца — то есть саму приписку.
   */
  ask(
    question: string,
    request: ReferenceRequest & { readonly maxChars: number }
  ): Promise<{ readonly text: string } | null>;
  /**
   * Находки по TS-коду модуля формы; `null` — проверить нечем, запись пройдёт с замечанием.
   *
   * Метода нет — стек проверит код встроенной проверкой: барьер записи режима файлов держится на
   * ней, и поставщик справки не обязан его снимать. Сравнение «до и после» делает стек сам —
   * поставщик только возвращает находки по тексту.
   */
  checkCode?(
    code: string,
    request: ReferenceRequest & { readonly path?: string }
  ): Promise<{ readonly findings: readonly CodeFinding[] } | null>;
}

/** Версия `1.0.0` — исходная. */
export const LibraryReferenceCapability = defineCapability<LibraryReferenceService>({
  id: 'reformer.ai-schema.reference',
  version: '1.0.0',
});

/**
 * Какая справка действует сейчас; `undefined` — никакой.
 *
 * Функция, а не значение: набор инструментов собирается один раз, а поставщик приходит и уходит
 * вместе со своим плагином.
 */
export type ResolveLibraryReference = () => LibraryReferenceService | undefined;
