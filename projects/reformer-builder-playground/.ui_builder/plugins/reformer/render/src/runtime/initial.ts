/**
 * Начальные значения модуля формы, подогнанные под ЖИВУЮ схему.
 *
 * ## Зачем подгонять
 *
 * `createInitialValues` модуля — производный код: кодоген печатает его по схеме в момент
 * генерации. Схему же в редакторе правят непрерывно, а код перегенерируют по требованию — и
 * между этими двумя событиями значения модуля описывают вчерашнюю форму: поля, которых уже нет,
 * строку на месте, где теперь группа.
 *
 * Положенные поверх мока как есть, они сломали бы сборку именно там, где форму только что
 * поправили: лист на месте группы не даёт вырастить сигналы её полей, и рендерер рисует пустоту.
 * Поэтому форма данных берётся у синтеза по живой схеме — он покрывает каждый её путь, — а
 * значения модуля ложатся только туда, где у этой формы есть для них место.
 *
 * ## Правила, и чем они отличаются от переноса введённого
 *
 * - **ключ есть только у схемы** — берётся синтез: поле добавили, у модуля о нём ничего нет;
 * - **ключ есть только у модуля** — отбрасывается: поле из схемы убрали;
 * - **оба объекта** — рекурсия; **оба массива** — массив модуля целиком;
 * - **группа, массив и лист не взаимозаменяемы** — при расхождении берётся синтез;
 * - **лист на лист** — значение модуля, каким бы оно ни было.
 *
 * Последнее — отличие от переноса введённого (`./carry`): там «поле переделали из строки в число»
 * значит, что набранная строка стала мусором, и род листа сверяется. Здесь сверять нечего: синтез
 * у числа без нижней границы, даты и мультивыбора даёт `null`, и значение модуля на таком месте
 * — не смена рода, а ровно то, ради чего начальные значения объявляют.
 *
 * @module plugins/reformer/render/runtime/initial
 */

/** Форма данных модели превью: она приходит из схемы, и сузить её нечем. */
type Shape = Record<string, unknown>;

function isPlainObject(value: unknown): value is Shape {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * Значения модуля в форме данных живой схемы.
 *
 * Функция чистая: ни `base`, ни `declared` не мутируются.
 *
 * @param base - Синтез по живой схеме: его ключи и есть форма данных.
 * @param declared - Начальные значения модуля; `undefined` — модуль их не объявил.
 * @returns Значения для слияния поверх синтеза; `undefined`, если подгонять нечего.
 */
export function fitInitialValues(base: Shape, declared: Shape | undefined): Shape | undefined {
  if (declared === undefined) return undefined;

  const out: Shape = {};
  for (const [key, own] of Object.entries(base)) {
    if (!Object.hasOwn(declared, key)) continue;
    const value = declared[key];
    if (isPlainObject(own)) {
      if (isPlainObject(value)) out[key] = fitInitialValues(own, value);
    } else if (Array.isArray(own)) {
      if (Array.isArray(value)) out[key] = value;
    } else if (!isPlainObject(value) && !Array.isArray(value)) {
      out[key] = value;
    }
  }
  return out;
}
