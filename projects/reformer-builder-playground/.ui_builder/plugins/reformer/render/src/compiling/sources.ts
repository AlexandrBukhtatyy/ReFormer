/**
 * Какие файлы составляют форму — то самое ПРЕДМЕТНОЕ знание, ради которого `plugins/forms/preview`
 * существует отдельно от `host/modules`.
 *
 * Платформа умеет транспилировать и линковать любой набор «путь → исходник» и не знает, что
 * такое форма. Здесь — знание о НАБОРЕ: файлы модуля лежат в его каталоге и папках ролей
 * (`model/`, `validation/`, `schema/steps/<шаг>/`…), исполняются только `.ts`/`.tsx`, данные
 * (`.json`) в набор входят, а страница-обёртка, фикстура и тесты не исполняются никогда. Где
 * корень модуля и какие файлы набора требует точка входа, решает `./module`.
 *
 * ## Почему `fixture.ts` исключена
 *
 * Она лежит в каталоге модуля, но сайдкаром не является: фикстура ПОДСТАВЛЯЕТ модули формы
 * (`../api`), а сайдкары их импортируют. В одном графе `api/index.ts` исполнился бы дважды — раз
 * как импорт фикстуры, раз как импорт сайдкара, — и форма получила бы два разных объекта под
 * одним именем (разбор — в `./fixture`). Графы собираются врозь, и разделяет их только имя файла.
 *
 * ## Читается рабочая КОПИЯ, а не источник
 *
 * Это то, ради чего рабочая копия вообще существует. Буфер редактора и есть файл: правка,
 * не сохранённая на диск, обязана попасть в превью — иначе «поменял валидацию, ничего
 * не изменилось» становится нормой. В v1 путей чтения было два, с правилом приоритета,
 * и форма, собранная в билдере, живого превью не получала вовсе, потому что файлов у неё
 * не существовало.
 *
 * ## Почему корневой `index.ts(x)` исключён
 *
 * Это вход модуля для приложения: он реэкспортирует страницу (у модуля прежней раскладки
 * `index.tsx` и есть страница), а страница монтирует форму в приложение, тянет роутер и layout.
 * Исполнить её в превью значило бы смонтировать приложение внутрь приложения. Из набора он
 * убран целиком, а не просто не затребован: случайный импорт `..` из файла роли обязан
 * оказаться отказом линковки, а не тихим исполнением страницы.
 *
 * Исключается только КОРНЕВОЙ `index.ts(x)`: `behavior/index.ts` и `api/index.ts` — файлы ролей,
 * а `steps/index.ts` модуля прежней раскладки — агрегатор шагов.
 *
 * @module plugins/reformer/render/compiling/sources
 */

import { isFixturePath } from '../../../core/form-fixture';
import type { ResourceRef } from '@reformer/builder-plugin-api';

/** Расширения, которые превью исполняет. */
const EXECUTABLE = /\.tsx?$/;
/** Объявления типов: исполнять нечего, а транспилятор на них ругаться права не имеет. */
const DECLARATION = /\.d\.tsx?$/;
/** Тесты и спеки: они про сайдкары, а не сайдкары. */
const TESTS = /\.(test|spec)\.tsx?$/;
/** Вход модуля для приложения (страница либо её реэкспорт) — только в корне модуля. */
const PAGE_ENTRY: ReadonlySet<string> = new Set(['index.ts', 'index.tsx']);

/** Последний сегмент пути. */
function baseName(path: string): string {
  return path.slice(path.lastIndexOf('/') + 1);
}

/**
 * Входит ли этот файл модуля в набор, который видит линковщик.
 *
 * Принимает путь ОТ КОРНЯ МОДУЛЯ (`validation/form.ts`, `schema/steps/kontakty/form.schema.json`).
 * Фильтры расширений, тестов и фикстуры — по базовому имени: тест в папке роли такой же тест.
 * Вход модуля — только в корне (см. модуль).
 *
 * «В наборе» не значит «исполнится»: точка входа требует файлы ролей (`./module`), остальное
 * исполняется, только если его импортировали.
 *
 * Решение по ИМЕНИ, а не по содержимому: список файлов известен раньше, чем их текст, и читать
 * весь каталог ради отбора значило бы платить чтением за файлы, которые всё равно отбросим.
 */
export function isExecutableSidecar(path: string): boolean {
  const name = baseName(path);
  const nested = path.includes('/');
  // Данные в папках ролей — схема шага разбитого визарда, справочник рядом с константами — их
  // импортирует код модуля. Файл данных в корне — нет: в корне прежней раскладки лежит сам
  // документ формы, а его превью берёт из модели редактора. Документ, лежащий в `schema/`,
  // отсекает чтение (`./read`): здесь его путь неизвестен.
  if (nested && name.endsWith('.json')) return true;
  if (!EXECUTABLE.test(name)) return false;
  if (DECLARATION.test(name)) return false;
  if (TESTS.test(name)) return false;
  if (isFixturePath(name)) return false;
  return nested || !PAGE_ENTRY.has(name);
}

/**
 * Сайдкары среди соседей документа — один уровень, без обхода.
 *
 * Каталоги отбрасываются: обход вглубь делает `readSidecars` (`./read`), когда порт
 * умеет листинг, а этот отбор — запасной путь для порта, у которого есть только соседи.
 */
export function selectSidecars(refs: readonly ResourceRef[]): readonly ResourceRef[] {
  return refs.filter((ref) => ref.kind === 'file' && isExecutableSidecar(ref.name));
}
