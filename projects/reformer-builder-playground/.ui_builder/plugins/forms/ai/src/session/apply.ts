/**
 * Расхождение документа с базой хода — проверка, которую ассистент делает сам, до стека.
 *
 * Сравнивается ТЕКСТ: истина — буфер рабочей области, и единственное сравнение, которое ничего не
 * выдумывает, — текст на начало хода против текста сейчас. Оно ловит и правку руками в Monaco, и
 * правку структурным редактором, и правку командой, которую ассистент сам же и вызвал по ходу.
 * Записывает набор стек (у ReFormer — `../stack/land`); молча перезаписать расхождение нельзя —
 * `force` приходит только от кнопки, которую нажал человек, увидев предупреждение.
 *
 * @module plugins/forms/ai/session/apply
 */

import type { ResourceId } from '@reformer/builder-plugin-api';

/**
 * Разошёлся ли буфер с базой хода.
 *
 * Отдельно от применения, потому что спрашивает об этом ещё и панель: кнопка обязана называться
 * «Применить всё равно» ДО того, как её нажали, а не после отказа. Просит ТОЛЬКО дверь документа:
 * вопрос «разошёлся ли текст» решается сравнением строк.
 */
export function isStale(
  deps: { readonly host: { documentOf(id: ResourceId): { getText(): string } | null } },
  base: { readonly resource: ResourceId; readonly text: string }
): boolean {
  const document = deps.host.documentOf(base.resource);
  return document === null || document.getText() !== base.text;
}
