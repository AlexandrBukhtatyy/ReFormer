/**
 * Значения `${VAR}` удалённых серверов — в секретах плагина, а не в настройках проекта.
 *
 * Настройки плагина уходят в `.ui_builder/settings.json`, а он лежит в git: токен в нём оказался
 * бы в истории репозитория. Секреты плагина (`ctx.secrets`) по умолчанию живут сессию — как ключ
 * канала ассистента; «Запомнить» в панели просит хранилище сохранить значение дольше.
 *
 * @module plugins/forms/mcp/secrets
 */

/** Ключ секрета для переменной: одно пространство на все серверы — одна переменная, один ввод. */
export function secretKeyOf(variable: string): string {
  return `var:${variable}`;
}
