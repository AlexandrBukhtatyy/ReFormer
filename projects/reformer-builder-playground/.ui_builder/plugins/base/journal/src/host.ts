/**
 * Порт плагина журнала: ровно то, чем пользуется панель, и ничего сверх.
 *
 * Панель пишется против ЭТОГО интерфейса, а не против десятка служб: тест подставляет порт
 * целиком, а компонент не знает, из чего он собран. Собирает его сам плагин — из служб SDK
 * (`./host-from-context`).
 *
 * Службы диагностик и журнала в порт не входят: обе объявлены в `@reformer/builder-plugin-api`
 * и приходят телу панели как есть — подменять их в тесте проще настоящими реализациями.
 *
 * @module plugins/base/journal/host
 */

import type { ResourceId } from '@reformer/builder-plugin-api';

/** Перевод: ключ и параметры сообщения. */
export type Translate = (key: string, params?: Record<string, unknown>) => string;

/** Имя ресурса для человека и путь для подсказки. */
export interface ResourceName {
  readonly name: string;
  readonly path: string;
}

/** Всё, что журнал получает от оболочки. Собирает порт сам плагин — `./host-from-context`. */
export interface JournalHost {
  /**
   * Реактивный перевод словарём ЭТОГО плагина: заголовок, переключатель, пустые состояния.
   * Хук, а не функция: локаль меняется, и компонент обязан перерисоваться.
   */
  useTranslate(): Translate;

  /**
   * Перевод кода находки словарём того, кто код завёл.
   *
   * Одна ошибка обязана звучать одинаково в журнале, в подчёркивании редактора кода и на узле
   * канваса, поэтому журнал не переводит сам. **Ключ передаётся голым кодом**, без приставки
   * `errors.`: её ставит служба словаря.
   *
   * Необязателен: без него строка покажет сам код — читаемо для разработчика, но не для человека.
   */
  useDiagnosticMessage?(): Translate;

  /**
   * Перевод ГОТОВОГО ключа словарём оболочки: голый ключ — её словарём, ключ с владельцем
   * (`<plugin-id>:<ключ>`) — словарём владельца.
   *
   * Им переводятся подписи быстрых исправлений (`QuickFix.titleKey`) и сообщения записей
   * журнала (`LogEntry.messageKey`): и то и другое приходит полным ключом от того, кто его
   * завёл. Необязателен: без него виден сам ключ.
   */
  useHostMessage?(): Translate;

  /**
   * Время записи — строкой в текущей локали. Хук по той же причине, что перевод: смена языка
   * меняет и формат времени.
   */
  useFormatTime(): (time: number) => string;

  /**
   * Показать ресурс: открыть вкладку или сделать активной уже открытую.
   *
   * Необязателен: без него строки журнала остаются списком, а не навигацией. Это видно на глаз
   * и потому не выглядит поломкой.
   */
  openResource?(id: ResourceId): void;

  /**
   * Имя и путь ресурса по адресу. Открытый документ называет себя сам, закрытый (сайдкар формы
   * с ошибкой сборки) называет платформа разбором адреса — путевая арифметика принадлежит ей.
   *
   * `null` — назвать нечем: ресурс подписывается своим адресом.
   */
  nameOf(id: ResourceId): ResourceName | null;
}
