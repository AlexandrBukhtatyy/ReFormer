/**
 * Порт плагина файлов: ровно то, чем пользуются его панели и команды, и ничего сверх.
 *
 * ## Зачем порт, если всё есть в контексте
 *
 * Текстовый редактор и операции над записями пишутся против ЭТОГО интерфейса,
 * а не против десятка служб: тест подставляет порт целиком, а компонент не знает, из чего он
 * собран. Собирает его сам плагин — из служб SDK (`./host-from-context`). Раньше порт собирала
 * оболочка и ради этого импортировала плагин; теперь оболочка о плагине не знает.
 *
 * Типы документа, панели и редактора — сужения контрактов SDK до того, что нужно плагину:
 * настоящий `Document` присваивается в {@link FilesDocument}. Совместимость проверяется
 * компиляцией там, где порт собирается.
 *
 * ## Чего в порту нет
 *
 * Открытия проекта и сохранения: это дело встроенного плагина «Проект». Плагин файлов правит
 * рабочую копию и записи проекта, а наружу, в источник, не сохраняет ничего.
 *
 * @module plugins/base/files/host
 */

import type { ComponentType } from 'react';
import type { Disposable, ResourceId, ResourceRef } from '@reformer/builder-plugin-api';

/**
 * Открытый документ — в объёме, нужном текстовому редактору.
 *
 * `getText` — то, что уйдёт в файл при сохранении; писать в него можно только через
 * {@link FilesHost.writeText}, то есть через рабочую область. Отдельного канала записи
 * у плагина нет, и это граница прав, а не неудобство.
 */
export interface FilesDocument {
  readonly ref: ResourceRef;
  getText(): string;
  isDirty(): boolean;
  onDidChangeContent(cb: (text: string) => void): Disposable;
}

/** Перевод в пространстве имён плагина. */
export type Translate = (key: string, params?: Record<string, unknown>) => string;

/** Всё, что плагин файлов получает от оболочки. Собирает порт сам плагин — `./host-from-context`. */
export interface FilesHost {
  /**
   * Тело панели с деревом ресурсов.
   *
   * Компонент платформенный — навигация по ресурсам не предметна и живёт в оболочке целиком
   * (возможность `reformer.workspace.tree`). А вот МЕСТО для неё — решение предметное,
   * и принимает его этот плагин: он же может его и не вносить.
   *
   * Необязателен: оболочка, не дающая дерева, оставляет плагин без панели проекта — текстовый
   * редактор и операции при этом работают.
   */
  readonly ResourceTreePanel?: ComponentType<{ panelId: string }>;

  /**
   * Реактивный перевод. Хук, а не функция: локаль меняется, и компонент обязан
   * перерисоваться — подписку на смену локали держит композиция.
   */
  useTranslate(): Translate;

  /** Открыт ли проект прямо сейчас. */
  hasProject(): boolean;
  /** Документ открытой вкладки или `null`, если она ещё открывается. */
  documentOf(id: ResourceId): FilesDocument | null;
  /** Пишет в рабочую копию. В источник не пишет ничего и никогда — сохраняет плагин «Проект». */
  writeText(id: ResourceId, text: string): Promise<void>;

  /** Читается ли такой ресурс текстом. Правило платформенное — таблица медиатипов у неё. */
  isTextual(mediaType: string): boolean;

  /**
   * Что выделено в дереве проекта — набор, если щёлкнули по его строке, иначе одна строка.
   *
   * Нужен командам, вызванным С КЛАВИШИ: у пункта меню цель приходит аргументом, а у клавиши
   * аргументов нет вовсе, и «к чему применить» знает только дерево.
   */
  treeSelection(): readonly ResourceRef[];

  /** Корень дерева проекта; `null` — проект не открыт. */
  treeRoot(): ResourceId | null;
}

/**
 * Операции над записями проекта ушли из порта в привилегированную службу.
 *
 * `reformer.workspace.resources` (`@reformer/builder-plugin-api`): создать, переименовать,
 * перенести, удалить, скопировать, открыть каталог проекта. Портом они существовали только
 * для встроенного плагина — внешнему такой порт не собрал бы никто, — а службой их видит
 * любой, кто объявил право `workspace.resources` и получил подтверждение человека.
 *
 * `refresh` в переезд не попал: он уже был у соседней, НЕпривилегированной службы записей
 * (`WorkspaceFilesService.refresh`), и второй его адрес означал бы два ответа на один вопрос.
 */
