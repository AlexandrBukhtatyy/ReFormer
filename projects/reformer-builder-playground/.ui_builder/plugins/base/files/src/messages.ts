/**
 * Словарь плагина файлов.
 *
 * **Почему он здесь, а не в словаре оболочки.** Заголовок панели разрешается в пространстве
 * имён ВНЁСШЕГО плагина, а не словарём оболочки: `panel.title` двух разных плагинов — два
 * разных сообщения. Заголовки команд — тоже: и палитра, и меню разрешают `titleKey` словарём
 * ВЛАДЕЛЬЦА команды. Тексты уведомлений об операциях над записями раньше лежали в словаре
 * оболочки (`files.notify.*`) — и это была последняя причина, по которой оболочка знала о плагине.
 *
 * Строки везёт и вносит сам плагин — `ctx.i18n.contribute` при активации.
 *
 * Ключи команд не переименованы (`files.command.copy`, а не `command.copy`): пространство имён
 * добавляется и при регистрации словаря, и при чтении, поэтому менять имя было незачем.
 *
 * Сами тексты лежат в `locales/{ru,en}.json`: словарь — данные, и держать его в JSON значит
 * уметь отдать файл переводчику, не показывая ему TypeScript.
 *
 * @module plugins/base/files/messages
 */

import en from './locales/en.json';
import ru from './locales/ru.json';

/** Локаль → ключ (без пространства имён) → сообщение. */
export const FILES_MESSAGES: Readonly<Record<string, Readonly<Record<string, string>>>> =
  Object.freeze({ ru, en });
