/**
 * Что показывает превью приложением — решения без React и без рамки.
 *
 * У плагина два вида, и оба — рамка с адресом приложения:
 *
 * - **форма** — вид открытой вкладки (`./form-surface`): модуль формы, которому принадлежит
 *   документ, на стенде приложения;
 * - **приложение** — панель в правом доке (`./ui/PreviewPanel`): страница целиком, по которой
 *   ходят адресной строкой.
 *
 * Здесь — то, что решается без рамки: где лежит модуль формы и какой адрес принять из адресной
 * строки. Всё это — чистые функции: рамке остаётся только открыть адрес.
 *
 * ## Точка входа модуля — `index.ts` либо `index.tsx`
 *
 * Тот самый файл, по которому приложение импортирует форму каталогом: компонент формы в нём
 * экспортирован по умолчанию (сам или реэкспортом страницы), и приложение рисует его на стенде.
 * Что внутри, билдер не знает и знать не должен — он передаёт путь, а рисует приложение.
 *
 * ## Где её искать: рядом с документом либо уровнем выше
 *
 * Точка входа лежит рядом с документом, а если документ лежит в папке `schema` — в её родителе.
 * Так раскладывают модуль, когда данные отделены от кода: схема — в `schema/`, вход — в корне
 * модуля. Правило знает только об имени папки, а не о том, что в ней за документ: чей это
 * формат и чей кодоген, плагину безразлично.
 *
 * @module plugins/base/app-preview/model
 */

import type { ResourceId, ResourceRef, WorkspaceFilesService } from '@reformer/builder-plugin-api';

/**
 * Имена точки входа модуля формы — в порядке, в котором их разрешает импорт каталога: сборщик и
 * компилятор сначала пробуют `.ts`. В модуле, где лежат оба файла, приложение импортирует
 * первый — его же показывает и стенд.
 */
export const FORM_MODULE_NAMES: readonly string[] = Object.freeze(['index.ts', 'index.tsx']);

/** Папка, в которой документ лежит ВНУТРИ модуля: точка входа тогда — уровнем выше. */
export const DOCUMENT_FOLDER = 'schema';

/**
 * Сколько ждать после записи файла, прежде чем перезагрузить рамку.
 *
 * Запись закончилась раньше, чем dev-сервер приложения её заметил: он следит за файлами
 * и узнаёт о правке с задержкой. Перезагрузка в тот же миг показала бы прежнее.
 */
export const RELOAD_DELAY_MS = 300;

/** Адресная арифметика в объёме правила: каталог ресурса и адрес внутри каталога. */
export type ModuleDirectoryFiles = Pick<WorkspaceFilesService, 'parentOf' | 'resolve'>;

/**
 * Каталог модуля, которому принадлежит документ: каталог документа, а если он зовётся
 * {@link DOCUMENT_FOLDER} — его родитель.
 *
 * Имя каталога узнаётся у службы, а не разбором адреса: адрес ресурса для плагина непрозрачен.
 * «Каталог зовётся `schema`» — это «адрес `schema` внутри его родителя и есть он сам».
 */
export function moduleDirectoryOf(files: ModuleDirectoryFiles, document: ResourceId): ResourceId {
  const directory = files.parentOf(document);
  const parent = files.parentOf(directory);
  return files.resolve(parent, DOCUMENT_FOLDER) === directory ? parent : directory;
}

/**
 * Путь точки входа модуля от корня проекта среди записей его каталога; `null` — её там нет.
 *
 * Из нескольких подходящих файлов берётся первый по {@link FORM_MODULE_NAMES}, а не первый по
 * порядку листинга: порядок записей каталога источник не обещает.
 */
export function formModulePath(entries: readonly ResourceRef[]): string | null {
  for (const name of FORM_MODULE_NAMES) {
    const module = entries.find((entry) => entry.kind === 'file' && entry.name === name);
    if (module !== undefined) return module.path;
  }
  return null;
}

/**
 * Адрес из адресной строки панели — адресом ЭТОГО приложения либо `null`.
 *
 * Человек вправе написать и полный адрес, и путь (`/contacts`): путь достраивается от текущего
 * адреса. Адрес другого источника не принимается: рамка превью показывает запущенное
 * приложение, а не произвольный сайт, и компонент билдера в чужом документе рамку не узнает.
 */
export function resolveAddress(input: string, current: string): string | null {
  const text = input.trim();
  if (text === '') return null;
  let url: URL;
  let base: URL;
  try {
    base = new URL(current);
    url = new URL(text, base);
  } catch {
    return null;
  }
  return url.origin === base.origin ? url.href : null;
}
