/**
 * Плагин-образец приложения: одна команда билдера.
 *
 * Лежит в `.ui_builder/plugins/` приложения и поднимается, когда приложение открыто в билдере
 * как проект, — так же, как плагин любого проекта в билдере, открытом своей вкладкой. Сборки
 * у него нет: один файл без зависимостей билдер читает и переводит в JavaScript сам. Плагину
 * с зависимостями или несколькими каталогами нужна сборка (`reformer-plugin build`).
 *
 * Чтобы править его и видеть результат без перезагрузки, плагин помечают «в разработке»
 * (палитра команд → «Плагины: наблюдать…»): билдер перечитывает его, когда файл изменился.
 */

import { definePlugin } from '@reformer/builder-plugin-api';

export default definePlugin({
  id: 'delivery-hello',
  activate(ctx) {
    ctx.subscriptions.push(
      ctx.commands.register({
        id: 'delivery-hello.hello',
        // Ключ словаря плагина, а не текст: строки лежат в locales/*.json.
        titleKey: 'command.hello',
        run: () => true,
      })
    );
  },
});
