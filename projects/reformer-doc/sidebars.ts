import type { SidebarsConfig } from '@docusaurus/plugin-content-docs';
import { existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

// Разделы Core API Reference — только непустые каталоги typedoc: их состав следует за
// публичными экспортами ядра (классов нод в нём нет), а пустая категория роняет сборку.
const API_SECTIONS = [
  ['Classes', 'classes'],
  ['Enumerations', 'enumerations'],
  ['Functions', 'functions'],
  ['Interfaces', 'interfaces'],
  ['Type Aliases', 'type-aliases'],
  ['Variables', 'variables'],
] as const;

/** Категории typedoc (функции, интерфейсы…) внутри каталога `docs/api/<base>`. */
function apiSections(base: string) {
  return API_SECTIONS.filter(([, dir]) => {
    const path = join(__dirname, 'docs', 'api', base, dir);
    return existsSync(path) && readdirSync(path).length > 0;
  }).map(([label, dir]) => ({
    type: 'category' as const,
    label,
    // Одинаковые подписи (Functions, Interfaces…) у разных модулей — свой ключ перевода у каждой.
    key: `api-${base || 'core'}-${dir}`,
    items: [
      { type: 'autogenerated' as const, dirName: ['api', base, dir].filter(Boolean).join('/') },
    ],
  }));
}

